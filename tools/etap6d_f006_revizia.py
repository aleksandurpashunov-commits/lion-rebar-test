def _редове(файл: pathlib.Path) -> dict[str, dict]:
    д = json.loads(файл.read_text(encoding="utf-8"))
    о = _отчет(str(д.get("copy") or ""))
    изход: dict[str, dict] = {}
    if о is not None:
        for ред in json.loads(о.read_text(encoding="utf-8")).get("rows") or ():
            ръчка = str(ред.get("annotation_handle") or "")
            if ръчка:
                изход[ръчка] = ред
    return изход


def _шумови(файл: pathlib.Path) -> set[str]:
    д = json.loads(файл.read_text(encoding="utf-8"))
    return set((д.get("import") or {}).get("noise_layers") or ())


def _освободените() -> list[tuple[str, str]]:
    """156-те: присъдата пада от MANUAL на CONTROL заради потвърждението.

    Сравнява се точно това, което е измерено на етап 5: `chisti_progoni`
    (преди) срещу `progoni_f006` (само промяната за F006, без откриването на
    слоеве). Така броят е d-1 35, s-10 35, s-11 53, тест-004 33.
    """

    преди = КОРЕН / "etap_4" / "chisti_progoni"
    сега = КОРЕН / "etap_5" / "progoni_f006"
    изход: list[tuple[str, str]] = []
    for файл in sorted(сега.glob("*.json")):
        if файл.name.startswith("_"):
            continue
        стар = преди / файл.name
        if not стар.is_file():
            continue
        а, б = _редове(стар), _редове(файл)
        for ръчка, ред in б.items():
            предишен = а.get(ръчка)
            if предишен is None:
                continue
            if (str(предишен.get("matcher_disposition")) == "MANUAL"
                    and str(ред.get("matcher_disposition")) == "CONTROL"):
                изход.append((файл.stem, ръчка))
    return изход


