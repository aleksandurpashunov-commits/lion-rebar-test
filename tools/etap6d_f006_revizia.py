# ------------------------------------------------------------------ геометрия

def _точка(стойност):
    if not стойност or len(стойност) < 2:
        return None
    return (float(стойност[0]), float(стойност[1]))


def _върхове(обект) -> list[tuple[float, float]]:
    точки = (обект.get("geometry") or {}).get("points") or []
    изход = []
    for т in точки:
        ако = _точка(т)
        if ако is not None:
            изход.append(ако)
    return изход


def _най_близък_връх(точка, върхове):
    """(разстояние, индекс) до най-близкия връх."""

    if not върхове:
        return math.inf, -1
    най = math.inf
    индекс = -1
    for i, (x, y) in enumerate(върхове):
        d = math.hypot(точка[0] - x, точка[1] - y)
        if d < най:
            най, индекс = d, i
    return най, индекс


def _привеждане(стойност: float) -> float:
    """`vertical_shape_resolver.snap` — преизчислено тук, за да е независимо."""

    цяло = round(стойност)
    if abs(стойност - цяло) <= 0.4:
        return float(цяло)
    return round(стойност * 2) / 2


def _добавка(сбор: float, обявена: float, допуск: float = 0.51) -> tuple[bool, float]:
    """Затваря ли се уравнението за F006 (`bend_allowance.segments_match_total`).

    Допустимият НЕДОСТИГ при затворено стреме е 8 cm
    (``BEND_ALLOWANCE_LIMITS_CM["F006"]``); НАДВИШАВАНЕТО над допуска остава
    отказ. Преизчислено тук, за да не зависи проверката от модула, който
    проверява. Измерените 156 дават недостиг 2, 4 и 5 cm — далеч под тавана,
    затова числата не се менят и при по-тясна граница.
    """

    разлика = сбор - обявена
    if разлика > допуск:
        return False, разлика
    if -(допуск + 8.0) <= разлика:
        return True, разлика
    # Проектантът закръгля НАГОРЕ до 5 cm (`BEND_ROUNDING_STEP_CM`).
    цел = math.ceil((сбор - допуск) / 5.0) * 5.0
    return abs(цел - обявена) <= допуск, разлика


def _чети_стреме(стойности, предпочитана_кука):
    """`vertical_shape_resolver.read_owned_stirrup` — преизчислено независимо."""

    различни = sorted({с for с in стойности if с >= МИН_УЧАСТЪК}, reverse=True)
    if len(различни) == 3:
        return [различни[0], различни[1], различни[2]], "ТРИ РАЗЛИЧНИ КОТИ"
    if len(различни) == 2:
        широчина, кука = различни
        if предпочитана_кука is not None and кука != предпочитана_кука:
            return None, "ДВЕ КОТИ, НО КУКАТА НЕ Е ОБИЧАЙНАТА ЗА ЧЕРТЕЖА"
        return [широчина, широчина, кука], "ДВЕ КОТИ — ДОПУСКА СЕ КВАДРАТНО"
    return None, "БРОЯТ РАЗЛИЧНИ КОТИ НЕ Е 2 ИЛИ 3"


def _вектор(широчина, височина, кука):
    return [кука, височина, широчина, височина, широчина, кука]


