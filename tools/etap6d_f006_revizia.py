def _прегледай(проект, ръчка, ред, обекти_по_ръчка, контури, принадлежност,
               предпочитана_кука, шум, центрове, заети_контури):
    находка = {
        "проект": проект,
        "надпис": ръчка,
        "текст": str(ред.get("annotation_text") or ""),
        "обявена_L_cm": ред.get("declared_length_cm"),
        "диаметър_mm": ред.get("diameter_mm"),
        "бройка": ред.get("annotation_count"),
        "форма": ред.get("master_shape_code"),
        "кандидат": list(ред.get("candidate_handles") or ()),
        "слой_на_кандидата": ред.get("candidate_layer"),
        "участъци_в_реда_cm": list(ред.get("production_segments_cm") or ()),
        "присъда_на_програмата": ред.get("matcher_disposition"),
        "причини_за_преглед": list(ред.get("review_reason_codes") or ()),
        "оставащи_спирачки": list(ред.get("matcher_blocker_codes") or ()),
        "забележки": [],
    }
    присъда = ред.get("f006_owned_dimension_confirmation")
    находка["присъда_на_модула"] = (присъда or {}).get("status") if isinstance(присъда, dict) else None
    обявени_коти = list((присъда or {}).get("dimension_handles") or ()) if isinstance(присъда, dict) else []

    кандидати = [str(х) for х in (ред.get("candidate_handles") or ())]
    if len(кандидати) != 1:
        находка["клас"] = СЪМНИТЕЛНО
        находка["причина"] = ("кандидатът не е един DXF обект (%d), затова "
                              "принадлежността на котите не е еднозначна"
                              % len(кандидати))
        return находка
    контур = кандидати[0]
    върхове = контури.get(контур)
    if not върхове:
        находка["клас"] = ОПРОВЕРГАНО
        находка["причина"] = "кандидатът %s не е LWPOLYLINE с върхове в оригиналните обекти" % контур
        return находка
    находка["брой_върхове"] = len(върхове)

    # --- кои коти са НЕГОВИ (собствено измерване) ---
    мои = []
    for кота, класация in принадлежност.items():
        сбор, собственик, d2, i2, d3, i3 = класация[0]
        if собственик != контур or сбор > ДОПУСК_ПРИНАДЛЕЖНОСТ:
            continue
        обект = обекти_по_ръчка[кота]
        г = обект.get("geometry") or {}
        мярка = float(г["measurement"])
        съперник = класация[1] if len(класация) > 1 else None
        разтег = (math.hypot(върхове[i2][0] - върхове[i3][0],
                             върхове[i2][1] - върхове[i3][1])
                  if i2 >= 0 and i3 >= 0 else None)
        мои.append({
            "кота": кота,
            "слой": обект.get("layer"),
            "вид": обект.get("entity_type"),
            "мярка_сурова": round(мярка, 4),
            "мярка_привед_cm": _привеждане(мярка),
            "текст_на_котата": г.get("display_text"),
            "defpoint2_до_връх": round(d2, 4),
            "връх2": i2,
            "defpoint3_до_връх": round(d3, 4),
            "връх3": i3,
            "сбор": round(сбор, 4),
            "разтег_между_върховете": round(разтег, 4) if разтег is not None else None,
            "разтег_минус_мярка": round(разтег - мярка, 4) if разтег is not None else None,
            "втори_контур": съперник[1] if съперник else None,
            "втори_сбор": round(съперник[0], 4) if съперник else None,
            "преднина": round(съперник[0] - сбор, 4) if съперник else None,
        })
    мои.sort(key=lambda з: -з["мярка_привед_cm"])
    находка["коти"] = мои
    находка["коти_по_отчета"] = обявени_коти

    if not мои:
        находка["клас"] = ОПРОВЕРГАНО
        находка["причина"] = "независимото измерване не намира НИТО ЕДНА собствена кота на контура"
        return находка

    # --- същите ли са, които отчита програмата ---
    ако_съвпада = sorted(з["кота"] for з in мои) == sorted(str(х) for х in обявени_коти)
    находка["котите_съвпадат_с_отчета"] = ако_съвпада
    if not ако_съвпада:
        находка["забележки"].append(
            "независимото измерване дава друг набор коти от отчета: мои=%s, отчет=%s"
            % (sorted(з["кота"] for з in мои), sorted(str(х) for х in обявени_коти)))

    # --- съпоставяне с участъците ---
    стойности = [з["мярка_привед_cm"] for з in мои]
    прочетено, правило = _чети_стреме(стойности, предпочитана_кука)
    находка["правило_за_четене"] = правило
    находка["предпочитана_кука_в_чертежа"] = предпочитана_кука
    if прочетено is None:
        находка["клас"] = ОПРОВЕРГАНО
        находка["причина"] = "собствените коти не се четат като стреме (%s)" % правило
        return находка
    широчина, височина, кука = прочетено
    от_коти = _вектор(широчина, височина, кука)
    находка["вектор_от_котите_cm"] = от_коти
    находка["съпоставяне"] = {
        "широчина": широчина, "височина": височина, "кука": кука,
        "коти_за_широчина": [з["кота"] for з in мои
                             if abs(з["мярка_привед_cm"] - широчина) < 1e-9],
        "коти_за_височина": [з["кота"] for з in мои
                             if abs(з["мярка_привед_cm"] - височина) < 1e-9],
        "коти_за_кука": [з["кота"] for з in мои
                         if abs(з["мярка_привед_cm"] - кука) < 1e-9],
        "ред_на_вектора": "кука, височина, широчина, височина, широчина, кука",
    }

    # --- уравнението ---
    обявена = float(ред.get("declared_length_cm") or 0.0)
    затваря, разлика = _добавка(sum(от_коти), обявена)
    находка["сбор_на_котите_cm"] = round(sum(от_коти), 4)
    находка["уравнението_се_затваря"] = затваря
    находка["сбор_минус_обявена_cm"] = round(разлика, 4)

    # --- съвпада ли с вече доказания вектор ---
    в_реда = [float(с) for с in (ред.get("production_segments_cm") or ())]
    едно_и_също = (len(в_реда) == 6
                   and all(abs(х - у) <= ДОПУСК_СЪВПАДЕНИЕ
                           for х, у in zip(sorted(от_коти), sorted(в_реда))))
    различна_наредба = (len(в_реда) == 6 and any(
        abs(х - у) > ДОПУСК_СЪВПАДЕНИЕ for х, у in zip(от_коти, в_реда)))
    находка["съвпада_с_измерената_геометрия"] = едно_и_също
    находка["различна_наредба"] = различна_наредба

    # --- котите описват ли РЕАЛЕН размер НА ТОЗИ контур ---
    # Проверката е „има ли двойка върхове на точно това разстояние". Тя е
    # по-силна от „най-близкият връх е близо": казва, че котата мери нещо
    # СЪЩЕСТВУВАЩО в контура, а не просто стои до него.
    разстояния = sorted({round(math.hypot(а[0] - б[0], а[1] - б[1]), 3)
                         for i, а in enumerate(върхове)
                         for б in върхове[i + 1:]})
    находка["нормализирани_участъци_на_контура_cm"] = [
        round(с, 3) for с in _нормализирани_участъци(обекти_по_ръчка[контур])]
    находка["начертани_прави_участъци_cm"] = [
        round(math.hypot(върхове[i + 1][0] - върхове[i][0],
                         върхове[i + 1][1] - върхове[i][1]), 3)
        for i in range(len(върхове) - 1)]
    невписани = [з["кота"] for з in мои
                 if not any(abs(з["мярка_привед_cm"] - d) <= ДОПУСК_СЪВПАДЕНИЕ
                            for d in разстояния)]
    находка["коти_без_двойка_върхове_на_това_разстояние"] = невписани

    # --- съседното стреме (без предварително отрязване по обхват) ---
    мой_център = _център(върхове)
    близки = sorted(
        ((math.hypot(мой_център[0] - ц[0], мой_център[1] - ц[1]), р)
         for р, ц in центрове.items() if р != контур),
        key=lambda е: е[0])[:20]
    съседи = [(_разстояние_между_контури(върхове, контури[р]), р,
               str((обекти_по_ръчка[р].get("layer"))), len(контури[р]))
              for _, р in близки]
    съседи.sort()
    находка["съседни_контури"] = [
        {"контур": р, "слой": сл, "разстояние_връх_до_връх": round(d, 3),
         "върхове": n, "негов_ред": заети_контури.get(р)}
        for d, р, сл, n in съседи[:4]
    ]
    същ_слой = [е for е in съседи if е[2] == str(обекти_по_ръчка[контур].get("layer"))]
    моите_прави = sorted(находка["начертани_прави_участъци_cm"])
    if същ_слой:
        съсед = същ_слой[0][1]
        негови = контури[съсед]
        негови_прави = sorted(
            round(math.hypot(негови[i + 1][0] - негови[i][0],
                             негови[i + 1][1] - негови[i][1]), 3)
            for i in range(len(негови) - 1))
        еднакво = (len(негови_прави) == len(моите_прави)
                   and all(abs(а - б) <= ДОПУСК_СЪВПАДЕНИЕ
                           for а, б in zip(негови_прави, моите_прави)))
        находка["най_близко_друго_стреме"] = {
            "контур": съсед, "разстояние": round(същ_слой[0][0], 3),
            "негов_ред": заети_контури.get(съсед),
            "еднакво_с_моето": еднакво,
            "негови_прави_участъци": негови_прави,
        }
    else:
        находка["най_близко_друго_стреме"] = None
    находка["контурът_е_кандидат_и_на"] = [
        х for х in заети_контури.get(контур, []) if х != ръчка]
    най_малка_преднина = min((з["преднина"] for з in мои
                              if з["преднина"] is not None), default=None)
    находка["най_малка_преднина_пред_втория_контур"] = най_малка_преднина
    спорни = [з["кота"] for з in мои
              if з["преднина"] is not None and з["преднина"] <= ДОПУСК_ПРИНАДЛЕЖНОСТ]
    находка["коти_със_спорна_принадлежност"] = спорни

    # чужди коти, чиито опорни точки падат ВЪРХУ моите върхове (обратната грешка)
    чужди_близо = []
    най_близка_чужда = math.inf
    for кота, класация in принадлежност.items():
        сбор, собственик, *_ = класация[0]
        if собственик == контур:
            continue
        мой = next((е for е in класация if е[1] == контур), None)
        if мой is None:
            continue
        най_близка_чужда = min(най_близка_чужда, мой[0])
        if мой[0] <= ДОПУСК_ПРИНАДЛЕЖНОСТ:
            чужди_близо.append({"кота": кота, "истински_собственик": собственик,
                                "сбор_при_мен": round(мой[0], 4),
                                "сбор_при_него": round(сбор, 4)})
    находка["чужди_коти_близо_до_моите_върхове"] = чужди_близо
    находка["най_близка_чужда_кота_до_моите_върхове"] = (
        round(най_близка_чужда, 3) if най_близка_чужда < math.inf else None)

    # слой на котите: трябва да е един и същ слой за всички
    слоеве = sorted({з["слой"] for з in мои})
    находка["слоеве_на_котите"] = слоеве
    шумови_коти = [з["кота"] for з in мои if з["слой"] in шум]
    if шумови_коти:
        находка["забележки"].append("коти на шумов слой: %s" % шумови_коти)

    # --- класификация ---
    if not едно_и_също:
        находка["клас"] = ОПРОВЕРГАНО
        находка["причина"] = ("котите дават %s, а вече доказаната геометрия %s"
                              % (от_коти, в_реда))
    elif not затваря:
        находка["клас"] = ОПРОВЕРГАНО
        находка["причина"] = ("уравнението не се затваря: сбор %.4g cm срещу "
                              "обявена %.4g cm" % (sum(от_коти), обявена))
    elif not ако_съвпада:
        находка["клас"] = СЪМНИТЕЛНО
        находка["причина"] = "независимото измерване дава друг набор коти от отчета"
    elif спорни:
        находка["клас"] = СЪМНИТЕЛНО
        находка["причина"] = ("коти %s имат втори контур на по-малко от един "
                              "пълен допуск (%s cm преднина)"
                              % (спорни, най_малка_преднина))
    elif чужди_близо:
        находка["клас"] = СЪМНИТЕЛНО
        находка["причина"] = ("чужди коти %s лежат и върху моите върхове — има "
                              "къде да се сбърка"
                              % [з["кота"] for з in чужди_близо])
    elif невписани:
        находка["клас"] = СЪМНИТЕЛНО
        находка["причина"] = ("коти %s не мерят никое разстояние между два "
                              "върха на контура" % невписани)
    elif находка["контурът_е_кандидат_и_на"]:
        находка["клас"] = СЪМНИТЕЛНО
        находка["причина"] = ("същият контур е кандидат и на надпис %s"
                              % находка["контурът_е_кандидат_и_на"])
    elif правило.startswith("ДВЕ КОТИ"):
        находка["клас"] = СЪМНИТЕЛНО
        находка["причина"] = ("само 2 различни коти: втората страна е ПРИЕТА за "
                              "равна на първата, не е измерена")
    elif различна_наредба:
        находка["клас"] = СЪМНИТЕЛНО
        находка["причина"] = ("същите размери, но ДРУГА наредба на участъците — "
                              "посоката на обхождане не е потвърдена")
    else:
        находка["клас"] = ПОТВЪРДЕНО
        находка["причина"] = ("%d собствени коти (%s) лежат на 0–%.2f cm от "
                              "върховете на контура и дават същия вектор"
                              % (len(мои), ", ".join(з["кота"] for з in мои),
                                 max(з["сбор"] for з in мои)))
    return находка


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--izhod", type=pathlib.Path, default=ИЗХОД)
    args = parser.parse_args()

    освободени = _освободените()
    по_проекти: dict[str, list[str]] = {}
    for проект, ръчка in освободени:
        по_проекти.setdefault(проект, []).append(ръчка)

    срез = КОРЕН / "etap_6" / "progoni_B"
    находки = []
    класове = Counter()
    причини = Counter()
    for проект in sorted(по_проекти):
        файл = срез / ("%s.json" % проект)
        редове = _редове(файл)
        шум = _шумови(файл)
        път = ЧИСТИ / проект / "working" / "extracted_entities.json"
        обекти = json.loads(път.read_text(encoding="utf-8"))["entities"]
        обекти = [о for о in обекти if str(о.get("layer")) not in шум]
        обекти_по_ръчка = {str(о.get("handle")): о for о in обекти}
        контури = {}
        for о in обекти:
            if о.get("entity_type") == "LWPOLYLINE":
                в = _върхове(о)
                if в:
                    контури[str(о.get("handle"))] = в
        принадлежност = _принадлежност(обекти, контури)
        центрове = {р: _център(в) for р, в in контури.items()}
        заети: dict[str, list[str]] = {}
        for р in редове.values():
            for к in (р.get("candidate_handles") or ()):
                заети.setdefault(str(к), []).append(
                    str(р.get("annotation_handle")))
        измервания = [float((о.get("geometry") or {}).get("measurement"))
                      for о in обекти
                      if о.get("entity_type") == "DIMENSION"
                      and (о.get("geometry") or {}).get("measurement")]
        брояч = Counter(с for с in измервания if 4.0 <= с <= 20.0)
        предпочитана = брояч.most_common(1)[0][0] if брояч else None

        for ръчка in по_проекти[проект]:
            ред = редове.get(ръчка)
            if ред is None:
                находки.append({"проект": проект, "надпис": ръчка,
                                "клас": ОПРОВЕРГАНО,
                                "причина": "редът липсва в среза на етап 6"})
                класове[ОПРОВЕРГАНО] += 1
                continue
            находка = _прегледай(проект, ръчка, ред, обекти_по_ръчка, контури,
                                 принадлежност, предпочитана, шум, центрове,
                                 заети)
            находки.append(находка)
            класове[находка["клас"]] += 1
            причини[находка["причина"][:70]] += 1

    изход = {
        "какво": ("ревизия на освободените ръчни проверки при F006 — "
                  "измерено наново от оригиналните обекти"),
        "срез": str(срез),
        "оригинали": str(ЧИСТИ),
        "как_са_намерени_156": ("присъда MANUAL -> CONTROL между "
                                "etap_4/chisti_progoni и etap_5/progoni_f006"),
        "общо": len(находки),
        "по_проекти": {к: len(в) for к, в in sorted(по_проекти.items())},
        "класове": dict(класове),
        "причини": dict(причини.most_common()),
        "позиции": находки,
    }
    args.izhod.parent.mkdir(parents=True, exist_ok=True)
    args.izhod.write_text(json.dumps(изход, ensure_ascii=False, indent=1),
                          encoding="utf-8")
    print("освободени позиции:", len(находки), dict(по_проекти and
          {к: len(в) for к, в in sorted(по_проекти.items())}))
    for к, в in класове.most_common():
        print("  %-14s %d" % (к, в))
    print("\nпричини:")
    for к, в in причини.most_common(20):
        print("  %4d  %s" % (в, к))
    print("\nзаписано:", args.izhod)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
