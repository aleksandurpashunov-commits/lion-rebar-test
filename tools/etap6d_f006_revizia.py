def _принадлежност(обекти, контури):
    """За всяка кота: подреждане на контурите по сбор от двете опорни точки.

    Връща `{handle_на_котата: [(сбор, handle_на_контура, d2, i2, d3, i3), ...]}`
    подредено по сбор. Това е СОБСТВЕНО измерване, не отчетът на програмата.
    """

    изход = {}
    for обект in обекти:
        if обект.get("entity_type") != "DIMENSION":
            continue
        г = обект.get("geometry") or {}
        мярка = г.get("measurement")
        първа, втора = _точка(г.get("defpoint2")), _точка(г.get("defpoint3"))
        if not мярка or първа is None or втора is None:
            continue
        класация = []
        for ръчка, върхове in контури.items():
            d2, i2 = _най_близък_връх(първа, върхове)
            d3, i3 = _най_близък_връх(втора, върхове)
            класация.append((d2 + d3, ръчка, d2, i2, d3, i3))
        класация.sort(key=lambda е: (е[0], е[1]))
        изход[str(обект.get("handle"))] = класация
    return изход


def _обхват(върхове):
    xs = [x for x, _ in върхове]
    ys = [y for _, y in върхове]
    return min(xs), min(ys), max(xs), max(ys)


def _център(върхове):
    о = _обхват(върхове)
    return ((о[0] + о[2]) / 2.0, (о[1] + о[3]) / 2.0)


def _разстояние_между_контури(а, б) -> float:
    най = math.inf
    for x1, y1 in а:
        for x2, y2 in б:
            d = math.hypot(x1 - x2, y1 - y2)
            if d < най:
                най = d
    return най


def _нормализирани_участъци(обект) -> list[float]:
    """Начертаните прави участъци, ПРОДЪЛЖЕНИ до пресечните точки на допирателните.

    Радиусът на огъване съкращава правата част. При дъга с централен ъгъл
    ``θ`` и радиус ``r`` допирателната отсечка е ``r*tan(θ/2)``; тя се връща
    на двата съседни прави участъка. Така се получава семантичната
    (нормализирана) геометрия, с която програмата сравнява.

    ``bulge`` е ``tan(θ/4)``; хордата дава ``r = хорда / (2*sin(θ/2))``.
    """

    г = обект.get("geometry") or {}
    точки = г.get("points") or []
    ако_затворен = bool(г.get("closed"))
    върхове = [_точка(т) for т in точки]
    издутини = [float(т[2]) if len(т) > 2 else 0.0 for т in точки]
    n = len(върхове)
    if n < 2:
        return []
    брой = n if ако_затворен else n - 1
    прави: list[float] = []
    допирателни: list[float] = []
    for i in range(брой):
        а = върхове[i]
        б = върхове[(i + 1) % n]
        хорда = math.hypot(б[0] - а[0], б[1] - а[1])
        b = издутини[i]
        if abs(b) < 1e-9:
            прави.append(хорда)
            допирателни.append(0.0)
        else:
            ъгъл = 4.0 * math.atan(abs(b))
            радиус = хорда / (2.0 * math.sin(ъгъл / 2.0)) if ъгъл > 1e-9 else 0.0
            прави.append(0.0)
            допирателни.append(радиус * math.tan(ъгъл / 2.0))
    изход: list[float] = []
    for i in range(брой):
        if допирателни[i] > 0.0:
            continue
        дължина = прави[i]
        преди = (i - 1) % брой
        след = (i + 1) % брой
        if ако_затворен or i > 0:
            дължина += допирателни[преди]
        if ако_затворен or i < брой - 1:
            дължина += допирателни[след]
        изход.append(дължина)
    return изход


