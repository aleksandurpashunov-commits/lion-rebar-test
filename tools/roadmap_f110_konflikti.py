# -*- coding: utf-8 -*-
"""F1.10: има ли НЕРАЗРЕШЕН конфликт, представен като проверено производство.

## Критерият беше сгрешен и е променен — ето защо

Първата редакция броеше за конфликт всяка позиция, която едновременно влиза в
производството и носи ``proven_form.state == UNRESOLVED``. Измерването показа,
че това е **точно правилното поведение**, а не конфликт: такава позиция излиза
с доказани от отпечатаните размери участъци, **без нито един ъгъл**
(``canonical_turn_angles_deg == []``) и с бележка ``FORMA_ZA_PREGLED: ъглите НЕ
са доказани и не се произвеждат``. Тоест програмата прави каквото е поискано —
не произвежда предполагаем ъгъл и праща формата за преглед.

Проверено върху всичките 48 такива позиции: **начертаният завой съвпада с
шаблона на заключената форма до 5° в 48 от 48** (F003 21, F004 24, F005 3).
Няма нито един случай, в който изнесеното твърди ъгъл, който чертежът
опровергава. Сверено срещу engine 0.3.14 — този, който проектите носят
замразен — а не срещу активния 0.3.15; двете се различават само по състоянията
на F009 и F010, геометрията на F003/F004/F005/F007 е една и съща.

Затова конфликт тук значи нещо по-тясно и по-опасно: **изнесеното твърди нещо,
което доказателството не поддържа.** Три случая:

1. изнесените ъгли се разминават с НАЧЕРТАНИТЕ с повече от 5° и това НЕ е
   записано в бележките — тиха подмяна на геометрията;
2. формата е неразрешена, но въпреки това се изнасят ъгли — нарушава „не
   произвеждай предполагаеми ъгли";
3. старият вектор ``[7,5; 25; 7,5]`` (случаят от F1.5).

Отделно се ОТЧИТА, без да е конфликт, класът „неудостоверен, но съвпадащ":
участъците са доказани, начертаният ъгъл съвпада с шаблона, но съседното рамо е
извън мащаб, затова чертежът не е меродавен на това място. Това е открито
ограничение, не скрито твърдение.

Само чете отчетите на прогона.
"""
from __future__ import annotations

import argparse
import glob
import json
import pathlib
from collections import Counter

from lion_rebar.export.auto_gate import AUTO_EXPORT_BATCH_STATUSES

ПРОГОНИ = pathlib.Path(r"C:\lr_exp\data\full_path_runs")
ПРОЕКТИ = ("d-1", "d-2", "s-10", "s-11", "s-7", "s-8", "s-9",
           "Тест-002", "Тест-003", "тест-004", "тест-006")

#: Статусите, с които позицията влиза в производствения изход.
#:
#: ВНАСЯ СЕ, не се преписва. По-ранна редакция ги изписа на ръка и сгреши в
#: четири от шест: пропусна ``СИЛЕН`` и ``СИЛНО СТРЕМЕ F006`` (351 позиции,
#: отчетени като спрени, а всъщност излизащи) и измисли ``ОДОБРЕНА ВРЪЗКА`` и
#: ``СИЛЕН ПО ГЕОМЕТРИЯ — Ø ОТ НАДПИСА``, каквито в кода няма.
ПРОИЗВОДСТВЕНИ = AUTO_EXPORT_BATCH_STATUSES

#: Над този допуск две посоки са различни посоки. Същото число, с което
#: ``shape_image._turns_contradict_shape`` решава дали да рисува друго.
ДОПУСК_DEG = 5.0


def последен(проект: str) -> pathlib.Path | None:
    к = sorted(glob.glob(str(
        ПРОГОНИ / ("%s_*/output/04_REVIEW_REPORTS/*/*_geometry_batch.json" % проект))))
    return pathlib.Path(к[-1]) if к else None


def _числа(стойност) -> list[float]:
    изход = []
    for с in (стойност or ()):
        try:
            изход.append(float(с))
        except (TypeError, ValueError):
            continue
    return изход


def недоказан_необходим_параметър(ред: dict) -> str:
    """ВТОРАТА проверка: необходим ъгъл без доказателство и без правило.

    Позицията влиза в производствения изход, формата ѝ е ``UNRESOLVED`` и няма
    одобрено правило в обхват. Тогава изображението ѝ се рисува по шаблона на
    MASTER формата — тоест показва ъгъл, който записът не поддържа.

    Бележка не е достатъчна: тя обяснява липсата, но изходът пак носи ъгъла.

    Измерено: 24 позиции F004 в `s-8`, `s-9` и `тест-006` — куки, чието късо
    рамо е начертано 26 при отпечатани 35. Начертаният им завой съвпада с
    шаблона, но чертежът не е меродавен на това място, а правило няма.
    """

    пф = ред.get("proven_form")
    if not isinstance(пф, dict) or пф.get("state") != "UNRESOLVED":
        return ""
    if not ред.get("production_segments_cm"):
        return ""
    if str(ред.get("contextual_rule_code") or "").strip():
        return ""                      # правилото го покрива — не е находка
    начертани = [о.get("drawn_turn_deg") for о in (пф.get("bends") or ())
                 if isinstance(о, dict) and о.get("drawn_turn_deg") is not None]
    if not начертани:
        return ""                      # няма завой — няма какво да се доказва
    return ("необходим производствен ъгъл без независимо доказателство и без "
            "одобрено правило: форма %s, начертани завои %s, рамена в мащаб %s"
            % (ред.get("master_shape_code"),
               [round(float(а), 1) for а in начертани],
               list(пф.get("legs_to_scale") or ())))


def прегледай(ред: dict) -> tuple[list[str], str]:
    """Връща (причини за конфликт, етикет на открито ограничение)."""

    причини: list[str] = []
    пф = ред.get("proven_form")
    пф = пф if isinstance(пф, dict) else {}
    изнесени = _числа(ред.get("canonical_turn_angles_deg"))
    начертани = [
        float(о["drawn_turn_deg"]) for о in (пф.get("bends") or ())
        if isinstance(о, dict) and о.get("drawn_turn_deg") is not None
    ]
    записано = any("SHABLONAT_NE_SAVPADA" in str(б) or "FORMA_OT_PROEKTA" in str(б)
                   for б in (пф.get("notes") or ()))

    # 1. тиха подмяна на геометрията
    if (изнесени and начертани and len(изнесени) == len(начертани)
            and any(abs(abs(а) - abs(б)) > ДОПУСК_DEG
                    for а, б in zip(изнесени, начертани))
            and not записано):
        причини.append("изнесените ъгли %s се разминават с начертаните %s без записана бележка"
                       % ([round(а, 1) for а in изнесени], [round(б, 1) for б in начертани]))

    # 2. неразрешена форма, но въпреки това изнесени ъгли
    if пф.get("state") == "UNRESOLVED" and изнесени:
        причини.append("формата е НЕРАЗРЕШЕНА, но се изнасят ъгли %s"
                       % [round(а, 1) for а in изнесени])

    # 3. старият вектор
    вектор = _числа(ред.get("production_segments_cm"))
    if вектор == [7.5, 25.0, 7.5]:
        причини.append("старият вектор [7,5; 25; 7,5]")

    # 4. ВТОРАТА проверка — недоказан необходим параметър
    втора = недоказан_необходим_параметър(ред)
    if втора:
        причини.append(втора)

    # открито ограничение, НЕ конфликт: параметърът е покрит от правило
    ограничение = ""
    if (пф.get("state") == "UNRESOLVED" and not изнесени
            and ред.get("production_segments_cm") and not втора):
        ограничение = "участъци доказани, ъгълът следва от одобрено правило"
    return причини, ограничение


def main() -> int:
    ап = argparse.ArgumentParser()
    ап.add_argument("--izhod", type=pathlib.Path, default=pathlib.Path(
        r"C:\lr_exp\rezultat\roadmap_completion\F1_KONFLIKTI.json"))
    арг = ап.parse_args()

    брой = Counter()
    находки: list[dict] = []
    ограничения: list[dict] = []
    for проект in ПРОЕКТИ:
        о = последен(проект)
        if о is None:
            брой["без отчет"] += 1
            continue
        for ред in (json.loads(о.read_text(encoding="utf-8")).get("rows") or []):
            статус = str(ред.get("batch_status") or "")
            ако_излиза = статус in ПРОИЗВОДСТВЕНИ and not ред.get("production_export_blocked")
            if not (ако_излиза or ред.get("production_segments_cm")):
                continue
            брой["производствени позиции"] += 1
            пф = ред.get("proven_form")
            if isinstance(пф, dict):
                брой["с присъда за форма: %s" % пф.get("state")] += 1
            причини, ограничение = прегледай(ред)
            запис = {"проект": проект, "позиция": ред.get("annotation_handle"),
                     "текст": ред.get("annotation_text"), "статус": статус,
                     "форма": ред.get("master_shape_code"),
                     "вектор": ред.get("production_segments_cm"),
                     "ъгли": ред.get("canonical_turn_angles_deg")}
            if причини:
                брой["КОНФЛИКТИ"] += 1
                вид = ("2 — недоказан необходим параметър"
                       if any("необходим производствен ъгъл" in п for п in причини)
                       else "1 — неправомерна подмяна на формата")
                брой["вид %s" % вид] += 1
                находки.append({**запис, "вид": вид, "причини": причини})
            elif ограничение:
                брой["открито ограничение"] += 1
                ограничения.append({**запис, "ограничение": ограничение})

    изход = {"схема": "roadmap-f110/v2", "броеве": dict(брой),
             "конфликти": находки, "открити ограничения": ограничения}
    арг.izhod.parent.mkdir(parents=True, exist_ok=True)
    арг.izhod.write_text(json.dumps(изход, ensure_ascii=False, indent=1), encoding="utf-8")

    for к, v in sorted(брой.items()):
        print("   %-52s %d" % (к, v))
    print()
    if находки:
        print("F1.10 ПАДА — конфликти, представени като проверено производство: %d" % len(находки))
        for н in находки[:15]:
            print("   %-10s %-16s %s" % (н["проект"], str(н["позиция"])[:16],
                                         "; ".join(н["причини"])[:92]))
    else:
        print("F1.10 МИНАВА — и по двете проверки:")
        print("   1. няма неправомерна подмяна на проектната форма;")
        print("   2. няма недоказан необходим производствен параметър.")
    print("открити ограничения (НЕ конфликт): %d позиции с доказани участъци и "
          "неудостоверен ъгъл" % len(ограничения))
    print("записано:", арг.izhod)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
