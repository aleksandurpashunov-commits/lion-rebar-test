"""ЕКСПЕРИМЕНТ 3: противоречи ли резултатът на НЕЗАВИСИМОТО доказателство.

Най-опасната грешка по CLAUDE.md не е блокирана позиция, а **силна и грешна**.
Затова тук не се мери процент разпознаване, а обратното: колко ОДОБРЕНИ позиции
се разминават с доказателство, което не идва от самата програма.

Източникът на проверките е ``dxf/disagreement_report.py``, вграден в пакетния
отчет:

  R2 — надписаните от проектанта коти A–E срещу измерените участъци;
  R4 — две позиции, които твърдят една и съща геометрия;
  R5 — броят участъци срещу определението на формата в активния MASTER.

Чете ЗАПИСАНИТЕ отчети; нищо не се пуска наново и нищо не се пипа.

ВАЖНО за отчитането: `УЧАСТЪК_БЕЗ_КОТА` НЕ е противоречие. То значи, че
проектантът не е котирал този участък — липса на доказателство, не спор.
Двете се броят отделно, защото смесването им би преувеличило и в двете посоки.
"""
from __future__ import annotations

import argparse
import json
import pathlib
from collections import Counter

ПРОГОНИ = pathlib.Path(r"C:\lr_exp\data\full_path_runs")

СЕМЕЙСТВО = {
    "т-1": "т-1", "s-9": "s-9", "s-11": "s-11", "s-8": "s-8", "s-10": "s-10",
    "s-7": "s-7", "s-1": "s-1..s-6/а-1", "d-1": "d-1", "d-2": "d-2",
    "Тест-003": "тест-001/Тест-003", "Тест-002": "Тест-002",
    "тест-004": "тест-004/005", "тест-006": "тест-006",
}
ЗАКЛЮЧЕНИ = {"т-1", "Тест-002", "s-7", "s-1..s-6/а-1"}

#: Видове, които значат „проектантът не е дал кота", а не „числата се разминават".
ЛИПСА_НЕ_СПОР = {"УЧАСТЪК_БЕЗ_КОТА", "БЕЗ_КОТИ", "НЯМА_КОТИ"}
#: Кои състояния на позицията значат, че тя би стигнала до спецификацията.
СИЛНИ_СЪСТОЯНИЯ = {"СИЛЕН", "СИЛЕН ПО ГЕОМЕТРИЯ", "ОДОБРЕНА"}


def _най_нови_отчети() -> dict[str, pathlib.Path]:
    намерени: dict[str, tuple[float, pathlib.Path]] = {}
    for п in ПРОГОНИ.rglob("*_geometry_batch.json"):
        части = п.parent.parent.parent.parent.name
        име = части.split("_2026")[0]
        време = п.stat().st_mtime
        ако = намерени.get(име)
        if ако is None or време > ако[0]:
            намерени[име] = (време, п)
    return {и: п for и, (_, п) in намерени.items()}


def main() -> int:
    parser = argparse.ArgumentParser(description="Противоречия срещу независимо доказателство")
    parser.add_argument("--json", type=pathlib.Path, default=None)
    args = parser.parse_args()

    отчети = _най_нови_отчети()
    print("%-10s %-4s %7s %8s %8s %8s  %s" % (
        "проект", "набор", "ПОЗИЦ", "СПОРОВЕ", "БЕЗ_КОТА", "R4+R5", "видове на споровете"))
    print("-" * 100)

    спорове_общо: Counter = Counter()
    спорове_развоен: Counter = Counter()
    примери: list = []
    сбор = Counter()
    сбор_р = Counter()
    редове = {}

    for име, път in sorted(отчети.items()):
        try:
            д = json.loads(път.read_text(encoding="utf-8-sig"))
        except (OSError, ValueError) as грешка:
            print("%-10s ГРЕШКА: %s" % (име, грешка))
            continue
        раз = д.get("disagreements") or {}
        if not раз:
            print("%-10s няма раздел за разминавания" % име)
            continue
        заключен = СЕМЕЙСТВО.get(име, име) in ЗАКЛЮЧЕНИ
        позиции = int(раз.get("scope_positions") or 0)

        спорове, липси, r4r5 = 0, 0, 0
        видове: Counter = Counter()
        for находка in раз.get("findings") or []:
            вид = str(находка.get("kind") or "")
            проверка = str(находка.get("check") or "")
            силна = str(находка.get("batch_status") or "").upper() in СИЛНИ_СЪСТОЯНИЯ
            if вид in ЛИПСА_НЕ_СПОР:
                липси += 1
                continue
            спорове += 1
            видове[вид] += 1
            спорове_общо[проверка + " / " + вид] += 1
            if not заключен:
                спорове_развоен[проверка + " / " + вид] += 1
            if проверка.startswith(("R4", "R5")):
                r4r5 += 1
            if len(примери) < 40:
                примери.append({
                    "проект": име, "проверка": проверка, "вид": вид,
                    "надпис": находка.get("annotation_text"),
                    "handle": находка.get("annotation_handle"),
                    "състояние": находка.get("batch_status"),
                    "силна": силна,
                    "обяснение": находка.get("explanation"),
                })

        редове[име] = {"набор": "ЗАКЛ" if заключен else "РАЗВ",
                       "позиции": позиции, "спорове": спорове,
                       "без_кота": липси, "r4_r5": r4r5,
                       "видове": dict(видове),
                       "проверки": раз.get("checks")}
        for ключ, стойност in (("позиции", позиции), ("спорове", спорове),
                               ("без_кота", липси), ("r4r5", r4r5)):
            сбор[ключ] += стойност
            if not заключен:
                сбор_р[ключ] += стойност

        print("%-10s %-4s %7d %8d %8d %8d  %s" % (
            име, "ЗАКЛ" if заключен else "РАЗВ", позиции, спорове, липси, r4r5,
            ", ".join("%s×%d" % (к, v) for к, v in видове.most_common(3)) or "—"))

    for етикет, с, брояч in (("ЦЯЛ КОРПУС", сбор, спорове_общо),
                             ("РАЗВОЕН НАБОР", сбор_р, спорове_развоен)):
        print("\n=== %s" % етикет)
        print("  позиции в обхвата на проверките   %6d" % с["позиции"])
        print("  ПРОТИВОРЕЧИЯ с доказателството    %6d" % с["спорове"])
        print("  от тях R4 (спор за геометрия) +R5 %6d" % с["r4r5"])
        print("  участъци БЕЗ кота (липса, не спор)%6d" % с["без_кота"])
        if брояч:
            print("  видове:")
            for к, брой in брояч.most_common(10):
                print("      %5d  %s" % (брой, к))

    if args.json:
        args.json.parent.mkdir(parents=True, exist_ok=True)
        args.json.write_text(json.dumps({
            "по_проект": редове,
            "сборове_цял_корпус": dict(сбор),
            "сборове_развоен": dict(сбор_р),
            "видове_цял_корпус": dict(спорове_общо),
            "видове_развоен": dict(спорове_развоен),
            "примери": примери,
        }, ensure_ascii=False, indent=1), encoding="utf-8")
        print("\nзаписан:", args.json)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
