def карта_на_краищата(ент: list[dict], слой: str = "ARM_Bars"):
    карта = collections.defaultdict(list)
    for з in ент:
        if з.get("entity_type") != "LINE" or str(з.get("layer")) != слой:
            continue
        т = върхове(з)
        if len(т) != 2:
            continue
        for п in т:
            карта[(round(п[0], 2), round(п[1], 2))].append(str(з["handle"]))
    return карта


def дължина(з: dict) -> float:
    return float(sum(участъци(върхове(з))))


def подреден_път(ръчки: list[str], обектите: dict) -> list[tuple[float, float]]:
    """Върховете в реда на обхождане на веригата.

    Отделните DXF отсечки не идват подредени и често делят НАЧАЛНАТА си точка.
    Без подреждане завоят се мери между несъседни посоки и излиза 151° вместо
    28° — точно това скри две от четирите позиции при първото броене.
    """

    отсечки = []
    for h in ръчки:
        в = върхове(обектите.get(h) or {})
        for и in range(len(в) - 1):
            отсечки.append((в[и], в[и + 1]))
    if not отсечки:
        return []
    ключ = lambda п: (round(п[0], 2), round(п[1], 2))  # noqa: E731
    съседи: dict = collections.defaultdict(list)
    for и, (a, b) in enumerate(отсечки):
        съседи[ключ(a)].append(и)
        съседи[ключ(b)].append(и)
    край = [к for к, с in съседи.items() if len(с) == 1]
    ако_затворено = not край
    старт = край[0] if край else ключ(отсечки[0][0])
    текуща = next(п for отс in отсечки for п in отс if ключ(п) == старт)
    използвани: set[int] = set()
    път = [текуща]
    while True:
        нататък = [и for и in съседи[ключ(текуща)] if и not in използвани]
        if not нататък:
            break
        и = нататък[0]
        използвани.add(и)
        a, b = отсечки[и]
        текуща = b if ключ(a) == ключ(текуща) else a
        път.append(текуща)
        if ако_затворено and len(използвани) == len(отсечки):
            break
    return път


def завои(път: list[tuple[float, float]]) -> list[float]:
    """Отклонението от правата във всеки вътрешен връх (0 = право напред)."""

    изх = []
    for и in range(1, len(път) - 1):
        a = ъгъл(път[и - 1], път[и])
        b = ъгъл(път[и], път[и + 1])
        изх.append(round((b - a + 540) % 360 - 180, 3))
    return изх


def пълна_верига(ръчки: list[str], обектите: dict, карта) -> list[str]:
    """Транзитивното затваряне по общи крайни точки — Закон 3 без прекъсване."""

    видени = set(ръчки)
    стек = list(ръчки)
    while стек:
        h = стек.pop()
        з = обектите.get(h)
        if з is None:
            continue
        for п in върхове(з):
            for друг in карта[(round(п[0], 2), round(п[1], 2))]:
                if друг not in видени:
                    видени.add(друг)
                    стек.append(друг)
    return sorted(видени, key=lambda h: (-дължина(обектите[h]), h))


def надписи_по_участъци(верига: list[str], обектите: dict,
                        текстове: list[dict]) -> dict[str, list[dict]]:
    """Всеки числов надпис се приписва на НАЙ-БЛИЗКИЯ участък от веригата."""

    отсечки = []
    for h in верига:
        в = върхове(обектите[h])
        for и in range(len(в) - 1):
            отсечки.append((h, в[и], в[и + 1]))
    прик: dict[str, list[dict]] = {h: [] for h in верига}
    if not отсечки:
        return прик
    for тх in текстове:
        опори = опорни_точки(тх)
        if not опори:
            continue
        най = min(((min(разстояние_до_отсечка(п, a, b) for п in опори), h)
                   for h, a, b in отсечки))
        if най[0] > РАДИУС_НАДПИС:
            continue
        прик[най[1]].append({
            "handle": str(тх["handle"]),
            "текст": текст_на(тх),
            "стойност": числа_в(текст_на(тх))[0],
            "ротация": round(float((тх.get("geometry") or {}).get("rotation") or 0.0), 1),
            "разстояние": round(най[0], 3),
        })
    return прик


def числови_надписи(ент: list[dict]) -> list[dict]:
    return [з for з in ент
            if z_вид(з) in ("TEXT", "MTEXT")
            and str(з.get("layer") or "").upper().startswith("ARM_TXT")
            and САМО_ЧИСЛО.match(str(з.get("text") or "").strip())]


def z_вид(з: dict) -> str:
    return str(з.get("entity_type") or "").upper()


# ------------------------------------------------------------------- околност
def околност(ент, отсечки, радиус, без: set[str]) -> list[dict]:
    намерени = []
    for з in ент:
        h = str(з.get("handle"))
        if h in без or z_вид(з) not in {"TEXT", "MTEXT", "DIMENSION",
                                        "BLOCK_ATTR_TEXT", "INSERT", "ATTRIB"}:
            continue
        точки = опорни_точки(з)
        if not точки:
            continue
        по_участък = [round(min(разстояние_до_отсечка(п, a, b) for п in точки), 3)
                      for a, b in отсечки]
        d = min(по_участък)
        if d > радиус:
            continue
        текст = текст_на(з)
        г = з.get("geometry") or {}
        ред = {"handle": h, "вид": z_вид(з), "слой": str(з.get("layer") or ""),
               "текст": текст, "числа": числа_в(текст), "разстояние_мин": d,
               "разстояние_по_участък": по_участък, "ротация": г.get("rotation")}
        if z_вид(з) == "DIMENSION":
            ред["измерено"] = round(float(г.get("measurement") or 0.0), 4)
            ред["стил"] = г.get("dimension_style")
            d2, d3 = г.get("defpoint2"), г.get("defpoint3")
            if d2 and d3:
                ред["ориентация_на_котата"] = ъгъл((float(d3[0]), float(d3[1])),
                                                   (float(d2[0]), float(d2[1])))
        намерени.append(ред)
    намерени.sort(key=lambda р: р["разстояние_мин"])
    return намерени


# ------------------------------------------------------------------ ведомости
def ведомост(проект: str, ент: list[dict]) -> dict:
    дxf = ЧИСТИ / проект / "source" / "original.dxf"
    итог: dict = {"dxf": str(дxf)}
    try:
        документи = ole_schedule.read_embedded_documents(дxf)
    except Exception as e:  # noqa: BLE001
        документи = []
        итог["ole_грешка"] = repr(e)
    описание = []
    for д in документи:
        опис = {"клас": getattr(д, "root_class", None),
                "грешка": getattr(д, "error", None), "листове": []}
        wb = getattr(д, "workbook", None)
        for лист in (getattr(wb, "sheets", ()) or ()) if wb else ():
            т = ole_schedule.detect_schedule_table(лист)
            опис["листове"].append({"име": getattr(лист, "name", None),
                                    "колони": list(getattr(т, "columns", ()) or ()),
                                    "редове": len(getattr(т, "rows", ()) or ())})
        описание.append(опис)
    итог["ole_документи"] = описание
    итог["ole_брой"] = len(документи)

    записи = [types.SimpleNamespace(**з) for з in ент]
    итог["asd_има_слой"] = bool(asd_schedule.has_schedule(записи))
    итог["asd_редове"] = (len(getattr(asd_schedule.read_schedule(записи), "rows", ()) or ())
                          if итог["asd_има_слой"] else 0)
    слоеве = sorted({str(з.get("layer") or "") for з in ент})
    подобни = [с for с in слоеве if any(k in с.upper() for k in
                                        ("TABLE", "ТАБЛ", "VEDOM", "ВЕДОМ",
                                         "SCHED", "SPEC", "СПЕЦИФ"))]
    итог["слоеве_с_таблица_в_името"] = подобни
    итог["съдържание_на_тези_слоеве"] = [
        {"handle": str(з["handle"]), "вид": z_вид(з), "слой": str(з.get("layer")),
         "текст": текст_на(з)[:90]}
        for з in ент if str(з.get("layer")) in подобни][:10]
    return итог


