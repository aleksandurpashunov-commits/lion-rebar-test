def подготви(проект: str, кеш: dict) -> dict:
    if проект in кеш:
        return кеш[проект]
    обектите, ент = обекти(проект)
    кеш[проект] = {
        "обекти": обектите, "ент": ент,
        "карта": карта_на_краищата(ент),
        "текстове": числови_надписи(ент),
        "А": отчет(проект, ПРОГОН_А), "Б": отчет(проект, ПРОГОН_Б),
        "ведомост": ведомост(проект, ент),
    }
    return кеш[проект]


def случай(сл: dict, кеш: dict) -> dict:
    проект = сл["проект"]
    к = подготви(проект, кеш)
    обектите, ент = к["обекти"], к["ент"]
    ред_а = к["А"].get(сл["надпис"]) or {}
    ред_б = к["Б"].get(сл["надпис"]) or {}

    итог: dict = {
        "проект": проект, "надпис": сл["надпис"],
        "текст": str(ред_а.get("annotation_text") or ""),
        "обявена": ред_а.get("declared_length_cm"),
        "рамка": str(ред_а.get("frame_title") or ""),
        "рамка_категория": str(ред_а.get("frame_category_code") or ""),
        "геометрия_сурова": round(float(ред_а.get("geometry_length_raw") or 0.0), 4),
        "прогон_А": {
            "статус": str(ред_а.get("batch_status") or ""),
            "форма": str(ред_а.get("master_shape_code") or ""),
            "каноничен": [float(x) for x in (ред_а.get("canonical_segment_lengths_cm") or ())],
            "ъгли": [float(x) for x in (ред_а.get("canonical_turn_angles_deg") or ())],
            "стратегия": str(ред_а.get("dimension_resolution_strategy") or ""),
            "размерни_текстове": list(ред_а.get("dimension_text_handles") or ()),
            "правило": str(ред_а.get("contextual_rule_code") or ""),
            "бележка": str(ред_а.get("contextual_rule_note") or ""),
        },
        "прогон_Б": {
            "статус": str(ред_б.get("batch_status") or ""),
            "форма": str(ред_б.get("master_shape_code") or ""),
            "каноничен": [float(x) for x in (ред_б.get("canonical_segment_lengths_cm") or ())],
            "причини": list(ред_б.get("review_reason_codes") or ()),
            "стратегия": str(ред_б.get("dimension_resolution_strategy") or ""),
            "правило": str(ред_б.get("contextual_rule_code") or ""),
        },
        "близки_коти_cm": list(ред_б.get("nearby_dimensions_cm") or ()),
    }

    # 1. кандидатът, както го е взела програмата
    ръчки = [str(h) for h in (ред_б.get("candidate_handles") or ())]
    кандидати, отсечки = [], []
    for h in ръчки:
        з = обектите.get(h)
        if з is None:
            кандидати.append({"handle": h, "липсва": True})
            continue
        в = върхове(з)
        сем, как = семантични(з)
        г = з.get("geometry") or {}
        кандидати.append({
            "handle": h, "вид": z_вид(з), "слой": str(з.get("layer") or ""),
            "върхове": [[round(p[0], 4), round(p[1], 4)] for p in в],
            "сурови_участъци": участъци(в),
            "ъгли": [ъгъл(в[i], в[i + 1]) for i in range(len(в) - 1)],
            "семантични_участъци": сем, "как_семантично": как,
            "дъги": bool(г.get("bulges")) or z_вид(з) == "ARC",
            "радиус": г.get("radius"),
        })
        отсечки.extend((в[i], в[i + 1]) for i in range(len(в) - 1))
    итог["кандидат"] = {
        "обекти": кандидати,
        "участъци": [x for k in кандидати for x in (k.get("сурови_участъци") or ())],
        "сбор": round(sum(x for k in кандидати for x in (k.get("сурови_участъци") or ())), 4),
        "има_дъги": any(k.get("дъги") for k in кандидати),
    }
    път = подреден_път(ръчки, обектите)
    if len(път) >= 3:
        итог["кандидат"]["подреден_път"] = [[round(p[0], 4), round(p[1], 4)] for p in път]
        итог["кандидат"]["подредени_участъци"] = участъци(път)
        итог["кандидат"]["завои"] = завои(път)
        къс = път[-2], път[-1]
        if math.dist(*къс) > math.dist(път[0], път[1]):
            къс = път[0], път[1]
        итог["кандидат"]["проекции_на_късата"] = [round(къс[1][0] - къс[0][0], 4),
                                                  round(къс[1][1] - къс[0][1], 4)]

    # 7. пълната свързана верига и надписът на всеки участък
    верига = пълна_верига(ръчки, обектите, к["карта"])
    прик = надписи_по_участъци(верига, обектите, к["текстове"])
    участъци_верига = []
    вектор, пълно = [], True
    for h in верига:
        в = върхове(обектите[h])
        n = прик.get(h, [])
        участъци_верига.append({
            "handle": h, "дължина": round(дължина(обектите[h]), 4),
            "ъгъл": ъгъл(в[0], в[-1]), "надписи": n})
        if len(n) == 1:
            вектор.append(n[0]["стойност"])
        else:
            пълно = False
    сбор = sum(вектор)
    обявена = float(итог["обявена"] or 0.0)
    итог["пълна_верига"] = {
        "взети_от_програмата": ръчки,
        "изпуснати": [h for h in верига if h not in ръчки],
        "участъци": участъци_верига,
        "отпечатан_вектор": вектор,
        "всеки_участък_с_надпис": пълно,
        "сбор_на_отпечатаните": round(сбор, 3),
        "равен_на_обявената": bool(пълно and abs(сбор - обявена) < 0.01),
    }

    # 2. околност
    итог["околност"] = околност(ент, отсечки, РАДИУС, без=set(ръчки))

    # 3. откъде идва отпечатаното
    цел = float(сл["отпечатано"])
    итог["източник_на_отпечатаното"] = {
        "търсено": цел,
        "намерени": [р for р in итог["околност"]
                     if any(abs(ч - цел) < 0.51 for ч in р["числа"])]}

    # 4. написано ли е 30 / 23 / 22 някъде до пръта
    търси = {}
    for стойност in (30.0, 23.0, 22.0):
        търси["%g" % стойност] = [
            {"handle": р["handle"], "слой": р["слой"], "текст": р["текст"],
             "разстояние": р["разстояние_мин"], "вид": р["вид"]}
            for р in итог["околност"]
            if any(abs(ч - стойност) < 0.51 for ч in р["числа"])]
    # и най-близкото „30" в целия чертеж, независимо от радиуса
    най_близко_30 = None
    for з in ент:
        if 30.0 not in числа_в(текст_на(з)):
            continue
        опори = опорни_точки(з)
        if not опори:
            continue
        d = min(разстояние_до_отсечка(п, a, b) for п in опори for a, b in отсечки)
        if най_близко_30 is None or d < най_близко_30["разстояние"]:
            най_близко_30 = {"handle": str(з["handle"]), "вид": z_вид(з),
                             "слой": str(з.get("layer")), "текст": текст_на(з)[:40],
                             "разстояние": round(d, 2)}
    търси["най-близко_30_в_целия_чертеж"] = най_близко_30
    итог["написано_ли_е"] = търси

    # 5. ведомост
    итог["ведомост"] = к["ведомост"]

    # 6. еднотипните в същата рамка
    итог["еднотипни_в_рамката"] = еднотипни(к, итог["рамка"])
    return итог


def еднотипни(к: dict, рамка: str) -> dict:
    """Двусегментните пръти от същата рамка — с пълната верига и надписите."""

    ключ = "еднотипни::" + рамка
    if ключ in к:
        return к[ключ]
    обектите = к["обекти"]
    сбор = []
    for надпис, ред in к["Б"].items():
        if str(ред.get("frame_title") or "") != рамка:
            continue
        ръчки = [str(h) for h in (ред.get("candidate_handles") or ())]
        if not ръчки or any(h not in обектите for h in ръчки):
            continue
        обявена = ред.get("declared_length_cm")
        if обявена is None:
            continue
        верига = пълна_верига(ръчки, обектите, к["карта"])
        прик = надписи_по_участъци(верига, обектите, к["текстове"])
        вектор, пълно = [], True
        дълж = []
        for h in верига:
            дълж.append(round(дължина(обектите[h]), 3))
            n = прик.get(h, [])
            if len(n) == 1:
                вектор.append(n[0]["стойност"])
            else:
                пълно = False
        взети = [round(x, 3) for h in ръчки for x in участъци(върхове(обектите[h]))]
        if len(взети) != 2:
            continue
        сбор.append({
            "надпис": надпис, "текст": str(ред.get("annotation_text") or ""),
            "обявена": float(обявена),
            "взети_участъци": взети,
            "верига": дълж, "изпуснати": len(верига) - len(ръчки),
            "отпечатан_вектор": вектор,
            "сбор": round(sum(вектор), 3) if пълно else None,
            "затваря": bool(пълно and abs(sum(вектор) - float(обявена)) < 0.01),
            "форма": str(ред.get("master_shape_code") or ""),
            "каноничен": [float(x) for x in (ред.get("canonical_segment_lengths_cm") or ())],
            "правило": str(ред.get("contextual_rule_code") or ""),
            "статус": str(ред.get("batch_status") or ""),
        })
    сбор.sort(key=lambda р: (р["надпис"]))
    к[ключ] = {"рамка": рамка, "брой": len(сбор), "позиции": сбор}
    return к[ключ]


# -------------------------------------------------------------------- обхват
def обхват(кеш: dict) -> dict:
    """Колко позиции в целия корпус би засегнало правилото с ДВЕ куки.

    Условието е точно това на `BEAM_MIDDLE_N8_15CM_90`, но с
    `expected_long = declared − 2 × 15` вместо `− 15`, И изрично изискване
    втората кука да е НАЧЕРТАНА (свързан участък в другия край на дългото
    рамо) и НАДПИСАНА с „15".
    """

    редове = []
    за_проект: dict[str, dict] = {}
    for проект in ВСИЧКИ_ПРОЕКТИ:
        try:
            к = подготви(проект, кеш)
        except FileNotFoundError:
            continue
        обектите = к["обекти"]
        броячи = collections.Counter()
        for надпис, ред in к["Б"].items():
            ръчки = [str(h) for h in (ред.get("candidate_handles") or ())]
            if not ръчки or any(h not in обектите for h in ръчки):
                continue
            диаметър = ред.get("diameter_mm")
            слой = str(ред.get("candidate_layer") or "").upper().replace("-", "_")
            обявена = ред.get("declared_length_cm")
            if обявена is None:
                continue
            взети = [x for h in ръчки for x in участъци(върхове(обектите[h]))]
            if len(взети) != 2:
                continue
            дълга, къса = max(взети), min(взети)
            път = подреден_път(ръчки, обектите)
            завой = max((abs(з) for з in завои(път)), default=None)
            подходящ_слой = "ARM_BARS" in слой
            n8 = диаметър is not None and abs(float(диаметър) - 8.0) <= 0.01
            for k in (1, 2):
                очаквана = float(обявена) - k * КУКА
                if очаквана <= 0:
                    continue
                допуск = max(ДОПУСК_ДЪЛГА, очаквана * 0.01)
                ако = (abs(дълга - очаквана) <= допуск
                       and къса <= очаквана * МАКС_ДЯЛ_КЪСА
                       and завой is not None and МИН_ЗАВОЙ <= завой <= МАКС_ЗАВОЙ
                       and подходящ_слой and n8)
                if not ако:
                    continue
                верига = пълна_верига(ръчки, обектите, к["карта"])
                прик = надписи_по_участъци(верига, обектите, к["текстове"])
                куки = [h for h in верига
                        if дължина(обектите[h]) <= очаквана * МАКС_ДЯЛ_КЪСА]
                надписани = sum(1 for h in куки
                                if len(прик.get(h, [])) == 1
                                and abs(прик[h][0]["стойност"] - КУКА) < 0.51)
                запис = {
                    "проект": проект, "надпис": надпис,
                    "текст": str(ред.get("annotation_text") or ""),
                    "обявена": float(обявена), "куки": k,
                    "взети": [round(дълга, 3), round(къса, 3)],
                    "верига": len(верига), "начертани_куки": len(куки),
                    "куки_с_надпис_15": надписани,
                    "рамка": str(ред.get("frame_category_code") or ""),
                    "правило_сега": str(ред.get("contextual_rule_code") or ""),
                    "статус_сега": str(ред.get("batch_status") or ""),
                    "доказана": bool(len(куки) == k and надписани == k),
                }
                редове.append(запис)
                броячи["k=%d" % k] += 1
                if k == 2:
                    броячи["k=2_доказана" if запис["доказана"] else "k=2_недоказана"] += 1
                break
        за_проект[проект] = dict(броячи)
    return {"по_проект": за_проект, "позиции": редове,
            "общо_k1": sum(1 for р in редове if р["куки"] == 1),
            "общо_k2": sum(1 for р in редове if р["куки"] == 2),
            "общо_k2_доказани": sum(1 for р in редове
                                    if р["куки"] == 2 and р["доказана"])}


