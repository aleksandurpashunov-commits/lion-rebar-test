def върхове(з: dict) -> list[tuple[float, float]]:
    г = з.get("geometry") or {}
    т = г.get("points")
    if т:
        return [(float(п[0]), float(п[1])) for п in т]
    за, до = г.get("start"), г.get("end")
    if за and до:
        return [(float(за[0]), float(за[1])), (float(до[0]), float(до[1]))]
    return []


def участъци(т: list[tuple[float, float]]) -> list[float]:
    return [round(math.dist(т[и], т[и + 1]), 4) for и in range(len(т) - 1)]


def ъгъл(a: tuple[float, float], b: tuple[float, float]) -> float:
    return round(math.degrees(math.atan2(b[1] - a[1], b[0] - a[0])), 3)


def семантични(з: dict) -> tuple[list[float], str]:
    вид = str(з.get("entity_type") or "").upper()
    т = върхове(з)
    if вид == "LINE":
        return участъци(т), "LINE — няма дъги, семантичното е равно на суровото"
    if вид in {"LWPOLYLINE", "POLYLINE"}:
        път = polyline_path_from_geometry(з.get("geometry") or {})
        if път is None:
            return [], "полилинията не се чете"
        сем = semantic_path_from_polyline(път)
        как = ("semantic_path_from_polyline: сгънати %d допирателни дъги от %d; "
               "представяне %s" % (сем.collapsed_arc_count, път.curve_count,
                                   getattr(сем.representation, "value", сем.representation)))
        точки = [(п.x, п.y) for п in сем.points]
        return участъци(точки), как
    if вид == "ARC":
        return [], "ARC r=%s" % (з.get("geometry") or {}).get("radius")
    return [], "вид %s не се нормализира" % вид


def разстояние_до_отсечка(п, a, b) -> float:
    dx, dy = b[0] - a[0], b[1] - a[1]
    дд = dx * dx + dy * dy
    if дд <= 1e-12:
        return math.dist(п, a)
    t = max(0.0, min(1.0, ((п[0] - a[0]) * dx + (п[1] - a[1]) * dy) / дд))
    return math.dist(п, (a[0] + t * dx, a[1] + t * dy))


def опорни_точки(з: dict) -> list[tuple[float, float]]:
    г = з.get("geometry") or {}
    точки: list[tuple[float, float]] = []
    for ключ in ("insert", "align_point", "defpoint", "defpoint2", "defpoint3",
                 "text_midpoint", "center", "start", "end", "visual_anchor"):
        с = г.get(ключ)
        if с:
            точки.append((float(с[0]), float(с[1])))
    for с in (г.get("visual_bbox") or ()):
        точки.append((float(с[0]), float(с[1])))
    for с in (г.get("points") or ()):
        точки.append((float(с[0]), float(с[1])))
    for пр in (г.get("render_primitives") or ()):
        for ключ in ("start", "end", "insert", "center"):
            с = пр.get(ключ)
            if с:
                точки.append((float(с[0]), float(с[1])))
    for атр in (г.get("attributes") or ()):
        с = атр.get("insert")
        if с:
            точки.append((float(с[0]), float(с[1])))
    return точки


def текст_на(з: dict) -> str:
    т = з.get("text")
    if т:
        return str(т)
    return str((з.get("geometry") or {}).get("display_text") or "")


def числа_в(текст: str) -> list[float]:
    изх = []
    for м in ЧИСЛО.findall(текст or ""):
        try:
            изх.append(float(м.replace(",", ".")))
        except ValueError:
            pass
    return изх


