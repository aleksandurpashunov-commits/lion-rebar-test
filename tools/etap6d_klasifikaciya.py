def _числа_в_чертежа(обекти):
    """Индекс на числата, които стоят НАПИСАНИ в чертежа.

    Ползва се, за да се докаже откъде идва число, което не се потвърждава от
    нито един начертан участък: съседен прът, бройка или позиционен номер.
    """

    индекс = []
    for о in обекти:
        вид = str(о.get("entity_type") or "")
        г = о.get("geometry") or {}
        текст = о.get("text")
        стойност = None
        if вид == "DIMENSION":
            стойност = г.get("measurement")
            текст = г.get("display_text")
        elif вид in {"TEXT", "MTEXT", "BLOCK_ATTR_TEXT"}:
            сурово = str(текст or "").strip().replace(",", ".")
            try:
                стойност = float(сурово)
            except ValueError:
                стойност = None
        if стойност is None:
            continue
        точка = (г.get("insert") or г.get("position") or г.get("defpoint")
                 or г.get("visual_anchor"))
        т = _точка(точка) if точка else None
        индекс.append({"handle": str(о.get("handle")), "layer": str(о.get("layer")),
                       "type": вид, "value": float(стойност),
                       "text": str(текст or ""), "point": т})
    return индекс


def _точки_на_кандидата(обекти_по_ръчка, кандидати):
    точки = []
    for h in кандидати:
        о = обекти_по_ръчка.get(h)
        if о is None:
            continue
        г = о.get("geometry") or {}
        for т in (г.get("points") or ()):
            ако = _точка(т)
            if ако:
                точки.append(ако)
        краища = _краища(о)
        if краища:
            точки.extend([т for т in краища if т])
    return точки


def _едно_семейство(а, б):
    """Един и същ слой ли са по семейство: ``ARMTXT`` и ``ARMTXT1``.

    Проектантът държи позиционния надпис и размерния текст на два слоя от
    един корен. Точното съвпадение се отчита отделно.
    """

    а, б = str(а or ""), str(б or "")
    if not а or not б:
        return False
    корен = lambda с: с.rstrip("0123456789").rstrip("_-. ").upper()
    return корен(а) == корен(б)


def _център_на_кандидата(обекти_по_ръчка, кандидати):
    точки = []
    for h in кандидати:
        о = обекти_по_ръчка.get(h)
        if о is None:
            continue
        г = о.get("geometry") or {}
        for ключ in ("points",):
            for т in (г.get(ключ) or ()):
                ако = _точка(т)
                if ако:
                    точки.append(ако)
        for ключ in ("start", "end", "center", "insert"):
            ако = _точка(г.get(ключ)) if г.get(ключ) else None
            if ако:
                точки.append(ако)
    if not точки:
        return None
    return (sum(т[0] for т in точки) / len(точки),
            sum(т[1] for т in точки) / len(точки))


def _отклонение(а, б):
    """Най-малкото максимално отклонение между два реда, с обърната посока.

    Обратната посока не е разлика: `recognition_policy.allow_reversed_direction`.
    """

    if not а or not б or len(а) != len(б):
        return None
    напред = max(abs(х - у) for х, у in zip(а, б))
    назад = max(abs(х - у) for х, у in zip(а, list(reversed(б))))
    return min(напред, назад)


