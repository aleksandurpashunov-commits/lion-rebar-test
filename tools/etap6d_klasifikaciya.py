def _точка(с):
    return (float(с[0]), float(с[1])) if с and len(с) >= 2 else None


def _дъга_от_издутина(а, б, издутина):
    """(дължина_на_дъгата, радиус, ъгъл_в_радиани) за DXF ``bulge``.

    ``bulge = tan(θ/4)``; хордата дава ``r = хорда / (2*sin(θ/2))``.
    """

    хорда = math.hypot(б[0] - а[0], б[1] - а[1])
    ъгъл = 4.0 * math.atan(abs(издутина))
    if ъгъл <= 1e-9 or хорда <= 1e-12:
        return хорда, None, 0.0
    радиус = хорда / (2.0 * math.sin(ъгъл / 2.0))
    return радиус * ъгъл, радиус, ъгъл


def _елементи(обект):
    """Пътят на един обект като (вид, дължина, радиус, ъгъл).

    ``вид`` е ``"П"`` за права и ``"Д"`` за дъга.
    """

    вид = str(обект.get("entity_type") or "")
    г = обект.get("geometry") or {}
    if вид in {"LWPOLYLINE", "POLYLINE"}:
        точки = [_точка(т) for т in (г.get("points") or [])]
        точки = [т for т in точки if т is not None]
        издутини = г.get("bulges")
        if not издутини:
            издутини = [float(т[2]) if len(т) > 2 else 0.0
                        for т in (г.get("points") or [])]
        издутини = [float(с) for с in издутини]
        if len(точки) < 2:
            return []
        затворен = bool(г.get("closed"))
        брой = len(точки) if затворен else len(точки) - 1
        изход = []
        for i in range(брой):
            а, б = точки[i], точки[(i + 1) % len(точки)]
            b = издутини[i] if i < len(издутини) else 0.0
            if abs(b) < 1e-9:
                изход.append(("П", math.hypot(б[0] - а[0], б[1] - а[1]), None, 0.0))
            else:
                д, r, θ = _дъга_от_издутина(а, б, b)
                изход.append(("Д", д, r, θ))
        return изход
    if вид == "LINE":
        а, б = _точка(г.get("start")), _точка(г.get("end"))
        if а is None or б is None:
            return []
        return [("П", math.hypot(б[0] - а[0], б[1] - а[1]), None, 0.0)]
    if вид == "ARC":
        r = г.get("radius")
        нач, кр = г.get("start_angle"), г.get("end_angle")
        if r is None or нач is None or кр is None:
            return []
        θ = math.radians((float(кр) - float(нач)) % 360.0)
        return [("Д", float(r) * θ, float(r), θ)]
    if вид == "CIRCLE":
        r = г.get("radius")
        if r is None:
            return []
        return [("Д", 2.0 * math.pi * float(r), float(r), 2.0 * math.pi)]
    return []


def _краища(обект):
    """Началната и крайната точка на един обект, или ``None``."""

    вид = str(обект.get("entity_type") or "")
    г = обект.get("geometry") or {}
    if вид in {"LWPOLYLINE", "POLYLINE"}:
        точки = [_точка(т) for т in (г.get("points") or [])]
        точки = [т for т in точки if т is not None]
        if len(точки) < 2:
            return None
        return точки[0], точки[-1]
    if вид == "LINE":
        а, б = _точка(г.get("start")), _точка(г.get("end"))
        return (а, б) if а and б else None
    if вид == "ARC":
        ц, r = _точка(г.get("center")), г.get("radius")
        нач, кр = г.get("start_angle"), г.get("end_angle")
        if ц is None or r is None or нач is None or кр is None:
            return None
        r = float(r)
        а = (ц[0] + r * math.cos(math.radians(float(нач))),
             ц[1] + r * math.sin(math.radians(float(нач))))
        б = (ц[0] + r * math.cos(math.radians(float(кр))),
             ц[1] + r * math.sin(math.radians(float(кр))))
        return а, б
    return None


#: Допускът за обща крайна точка (`recognition_policy.endpoint_tolerance_raw`).
ДОПУСК_КРАЙНА_ТОЧКА = 0.75


def _верига(обекти):
    """Подрежда обектите на кандидата ПО ПЪТЯ и връща елементите в този ред.

    Връща ``(елементи, подредено_ли_е)``. Без подреждане сравнението по ред е
    безсмислено: `geometry_handles` е реда на записа, не на обхождането.
    """

    ако = [(о, _краища(о)) for о in обекти]
    if any(к is None for _о, к in ако):
        return None, False
    if len(ако) == 1:
        return list(_елементи(ако[0][0])), True

    def близо(а, б):
        return math.hypot(а[0] - б[0], а[1] - б[1]) <= ДОПУСК_КРАЙНА_ТОЧКА

    остатък = list(ако)
    верига = [остатък.pop(0)]
    обърнат = {id(верига[0][0]): False}
    while остатък:
        начало = верига[0][1][1] if обърнат[id(верига[0][0])] else верига[0][1][0]
        край = верига[-1][1][0] if обърнат[id(верига[-1][0])] else верига[-1][1][1]
        за_добавяне = None
        for i, (о, (а, б)) in enumerate(остатък):
            if близо(край, а):
                за_добавяне = (i, "край", False)
            elif близо(край, б):
                за_добавяне = (i, "край", True)
            elif близо(начало, б):
                за_добавяне = (i, "начало", False)
            elif близо(начало, а):
                за_добавяне = (i, "начало", True)
            if за_добавяне:
                break
        if за_добавяне is None:
            return None, False
        i, къде, обр = за_добавяне
        о, к = остатък.pop(i)
        обърнат[id(о)] = обр
        if къде == "край":
            верига.append((о, к))
        else:
            верига.insert(0, (о, к))
    елементи = []
    for о, _к in верига:
        част = list(_елементи(о))
        if обърнат[id(о)]:
            част.reverse()
        елементи.extend(част)
    return елементи, True


def _трите_дължини(елементи):
    """(L_сур, L_дот, L_цех) от списъка елементи на целия кандидат."""

    сур = дот = цех = 0.0
    for вид, дължина, радиус, ъгъл in елементи:
        сур += дължина
        if вид == "П" or радиус is None or ъгъл <= 1e-9:
            дот += дължина
            цех += дължина
            continue
        дот += 2.0 * радиус * math.tan(min(ъгъл, math.pi - 1e-6) / 2.0)
        цех += (2.0 * радиус if abs(ъгъл - math.pi / 2.0) <= math.radians(1.0)
                else дължина)
    return сур, дот, цех


def _участъци_цех(елементи):
    """Участъците по цеховата уговорка: правите, разтегнати с ``r`` на огъвка.

    Правилото е изведено от ``curved_centreline_proof`` (не е предположено):

    * F003 ``(L0+r, L1+2r, L2+r)`` — КРАЙНАТА права също се разтяга, защото
      съседната ѝ огъвка е на 90°;
    * F006 ``(L0, L1+2r, L2+2r, L3+2r, L4+2r, L5)`` — крайните прави са
      КУКИТЕ и не се разтягат, защото съседната им огъвка е по-остра от 90°
      и свободният ѝ край няма до какво да се продължи.

    Общото правило: всяка огъвка дава ``r`` на двете си съседни прави; краят
    на пътя получава ``r`` само когато огъвката му е правоъгълна.
    """

    n = len(елементи)
    изход = []
    for i, (вид, дължина, _r, _θ) in enumerate(елементи):
        if вид != "П":
            continue
        край = (i == 0 or i == n - 1)
        д = дължина
        for съсед in (i - 1, i + 1):
            if not (0 <= съсед < n):
                continue
            с_вид, _с_д, с_r, с_θ = елементи[съсед]
            if с_вид != "Д" or not с_r:
                continue
            правоъгълна = abs(с_θ - math.pi / 2.0) <= math.radians(1.0)
            if край and not правоъгълна:
                continue
            д += с_r
        изход.append(д)
    return изход


def _затваря(форма, сбор, обявена, допуск=ДОПУСК_УРАВНЕНИЕ):
    """`bend_allowance.segments_match_total` — преизчислено тук.

    ``допуск`` е симетричната част. За производствените участъци тя е 0,51 cm
    (допускът на самия Engine). За ИЗМЕРЕНА геометрия се подава допускът на
    разпознаването ``max(1.0, 0.5 %)``, защото начертаното носи и грешка от
    чертежа, не само от закръгляне.

    Асиметрията не се мени: надвишаване над допуска е отказ при всяка форма.
    """

    код = str(форма or "").strip().upper()
    разлика = float(сбор) - float(обявена)
    if разлика > допуск:
        return False
    добавка = ДОБАВКА.get(код, ДОБАВКА_ПО_ПОДРАЗБИРАНЕ)
    if -(допуск + добавка) <= разлика:
        return True
    if not код or код in ПРАВИ_ФОРМИ or float(сбор) <= 0:
        return False
    цел = math.ceil((float(сбор) - abs(допуск)) / СТЪПКА_ЗАКРЪГЛЯНЕ) * СТЪПКА_ЗАКРЪГЛЯНЕ
    return abs(цел - float(обявена)) <= допуск


def _допуск_геометрия(обявена: float) -> float:
    return max(ДОПУСК_ГЕОМЕТРИЯ_ABS, float(обявена) * ДОПУСК_ГЕОМЕТРИЯ_ОТН)


