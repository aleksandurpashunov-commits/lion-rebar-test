def _дъга(x0, y0, x1, y1, bulge):
    """SVG дъга през bulge на DXF."""

    theta = 4.0 * math.atan(bulge)
    chord = math.hypot(x1 - x0, y1 - y0)
    r = abs(chord / (2.0 * math.sin(theta / 2.0))) if theta else 0.0
    голяма = 1 if abs(theta) > math.pi else 0
    посока = 0 if theta > 0 else 1
    return "A %.4f %.4f 0 %d %d %.4f %.4f" % (r, r, голяма, посока, x1, y1)


