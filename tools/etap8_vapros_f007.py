def _мащабирай(точки, ширина, височина, отстъп=28.0):
    xs = [т[0] for т in точки]
    ys = [т[1] for т in точки]
    dx, dy = max(xs) - min(xs) or 1.0, max(ys) - min(ys) or 1.0
    к = min((ширина - 2 * отстъп) / dx, (височина - 2 * отстъп) / dy)
    return [((т[0] - min(xs)) * к + отстъп,
             височина - ((т[1] - min(ys)) * к + отстъп),
             т[2] if len(т) > 2 else 0.0) for т in точки]


def _път(точки):
    d = ["M %.3f %.3f" % (точки[0][0], точки[0][1])]
    for и in range(len(точки) - 1):
        x0, y0, b = точки[и]
        x1, y1 = точки[и + 1][0], точки[и + 1][1]
        d.append(_дъга(x0, y0, x1, y1, b) if abs(b) > 1e-9
                 else "L %.3f %.3f" % (x1, y1))
    return " ".join(d)


def _master_f007(L1=10.0, L2=20.0):
    """Шаблонът на заключената F007: нагоре L1, завой 90° надясно, L2, завой
    135° надясно, L1 (дъгов). Точно това се изнася в Excel-а."""

    посока = 90.0
    точка = (0.0, 0.0)
    точки = [(точка[0], точка[1], 0.0)]
    for дължина, завой, bulge in ((L1, -90.0, 0.0), (L2, -135.0, 0.0), (L1, None, 0.55)):
        рад = math.radians(посока)
        точка = (точка[0] + дължина * math.cos(рад), точка[1] + дължина * math.sin(рад))
        точки[-1] = (точки[-1][0], точки[-1][1], bulge if завой is None else 0.0)
        точки.append((точка[0], точка[1], 0.0))
        if завой is not None:
            посока += завой
    return точки


