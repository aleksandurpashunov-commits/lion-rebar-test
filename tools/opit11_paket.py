def position_diff(резултати: pathlib.Path) -> list[dict]:
    етикети = (
        "приложим_А", "приложим_Б", "приложим_В",
        "неприложим_А", "неприложим_Б", "неприложим_В",
    )
    по_етикет = {
        етикет: _по_позиция(_редове_на_режима(
            _сводка_на_режима(резултати, етикет)))
        for етикет in етикети
    }
    редове: list[dict] = []
    for роля, група in (
        ("приложим", ("приложим_А", "приложим_Б", "приложим_В")),
        ("неприложим", ("неприложим_А", "неприложим_Б", "неприложим_В")),
    ):
        основа_етикет = група[0]
        основа = по_етикет.get(основа_етикет) or {}
        for етикет in група[1:]:
            друго = по_етикет.get(етикет) or {}
            for ключ in sorted(set(основа) | set(друго)):
                ако_в_основата = ключ in основа
                ако_в_другото = ключ in друго
                if not (ако_в_основата and ако_в_другото):
                    редове.append({
                        "роля": роля,
                        "позиция": ключ,
                        "поле": "(наличие на позицията)",
                        "режим": етикет,
                        "очаквана стойност": "налична" if ако_в_основата else "липсва",
                        "действителна стойност": "налична" if ако_в_другото else "липсва",
                        "източник на очакваната": "режим %s" % основа_етикет,
                        "еднакви": False,
                    })
                    continue
                for поле in ИНЖЕНЕРНИ:
                    очаквано = основа[ключ].get(поле)
                    действително = друго[ключ].get(поле)
                    if очаквано != действително:
                        редове.append({
                            "роля": роля,
                            "позиция": ключ,
                            "поле": поле,
                            "режим": етикет,
                            "очаквана стойност": json.dumps(
                                очаквано, ensure_ascii=False),
                            "действителна стойност": json.dumps(
                                действително, ensure_ascii=False),
                            "източник на очакваната": "режим %s" % основа_етикет,
                            "еднакви": False,
                        })
    if not редове:
        редове.append({
            "роля": "всички",
            "позиция": "(няма)",
            "поле": "(няма)",
            "режим": "А срещу Б срещу В",
            "очаквана стойност": "нула разлики",
            "действителна стойност": "нула разлики",
            "източник на очакваната": "режим А — паметта изключена",
            "еднакви": True,
        })
    return редове


