def _csv(път: pathlib.Path, редове: list[dict], полета: list[str]) -> None:
    път.parent.mkdir(parents=True, exist_ok=True)
    with път.open("w", encoding="utf-8-sig", newline="") as поток:
        писач = csv.DictWriter(поток, fieldnames=полета, extrasaction="ignore")
        писач.writeheader()
        for ред in редове:
            писач.writerow(ред)


def _сумите(корен: pathlib.Path, име_на_файла: str) -> str:
    редове = []
    for файл in sorted(корен.rglob("*")):
        if not файл.is_file():
            continue
        относителен = файл.relative_to(корен).as_posix()
        if относителен == име_на_файла:
            continue
        редове.append("%s  %s" % (_sha(файл), относителен))
    return "\n".join(редове) + "\n"


def _zip(източник: pathlib.Path, цел: pathlib.Path) -> None:
    цел.parent.mkdir(parents=True, exist_ok=True)
    if цел.exists():
        цел.unlink()
    with zipfile.ZipFile(цел, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as архив:
        for файл in sorted(източник.rglob("*")):
            if файл.is_file():
                архив.write(файл, файл.relative_to(източник).as_posix())


