def _ogled_na_excela(папка: pathlib.Path) -> list[str]:
    """Отваря произведения Excel и описва ДАННИТЕ и ОФОРМЛЕНИЕТО му.

    „Има файл" не е проверка. Тук се чете колко листа има, колко реда и колони,
    колко обединени области и колко РИСУНКИ на форми носи книгата — последното
    през архива на самия .xlsx, защото openpyxl не ги връща при повторно
    отваряне.
    """

    import zipfile

    редове = ["", "## Данните и оформлението, прочетени от самия файл", ""]
    книги = sorted(папка.glob("excel_*.xlsx"))
    if not книги:
        return редове + ["Няма Excel файл в тази папка."]
    for книга in книги:
        try:
            from openpyxl import load_workbook

            wb = load_workbook(книга)
        except Exception as грешка:  # noqa: BLE001
            редове.append("* `%s` — НЕ СЕ ЧЕТЕ: %s" % (книга.name, грешка))
            continue
        with zipfile.ZipFile(книга) as архив:
            рисунки = sum(1 for име in архив.namelist() if "/media/" in име)
        редове.append(
            "* `%s` — листове: %s" % (книга.name, ", ".join(wb.sheetnames))
        )
        for ws in wb.worksheets:
            редове.append(
                "  * `%s` — %d реда, %d колони, %d обединени области"
                % (ws.title, ws.max_row, ws.max_column,
                   len(ws.merged_cells.ranges))
            )
        редове.append("  * рисунки на форми в книгата: **%d**" % рисунки)
        първи = wb.worksheets[0]
        заглавия = []
        for ред in първи.iter_rows(min_row=1, max_row=8, values_only=True):
            стойности = [str(к).strip() for к in ред if к not in (None, "")]
            if стойности:
                заглавия.append(" | ".join(стойности[:10]))
        редове.append("  * първите непразни редове на първия лист:")
        for заглавие in заглавия[:4]:
            редове.append("    * `%s`" % заглавие)
    return редове


