def _sha(път: pathlib.Path) -> str:
    смес = hashlib.sha256()
    with път.open("rb") as поток:
        for парче in iter(lambda: поток.read(1 << 20), b""):
            смес.update(парче)
    return смес.hexdigest()


def _чети(път: pathlib.Path) -> dict:
    try:
        return json.loads(път.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError):
        return {}


def _сводка_на_режима(резултати: pathlib.Path, етикет: str) -> dict:
    """Отчетът на ``full_path`` за един режим; името му е по името на копието."""

    папка = резултати / "opit11" / етикет
    if not папка.is_dir():
        return {}
    for файл in sorted(папка.glob("*.json")):
        if файл.name == "INZHENERNI_POLETA.json":
            continue
        return _чети(файл)
    return {}


def _редове_на_режима(сводка: dict) -> list[dict]:
    копие = str(сводка.get("copy") or "")
    относителен = str(((сводка.get("analysis") or {}).get("report")) or "")
    if not копие or not относителен:
        return []
    път = pathlib.Path(копие) / относителен
    if not път.is_file():
        return []
    данни = _чети(път)
    редове = данни.get("rows")
    return [р for р in редове if isinstance(р, dict)] if isinstance(редове, list) else []


def _по_позиция(редове: list[dict]) -> dict[str, dict]:
    изход: dict[str, dict] = {}
    for ред in редове:
        ключ = str(ред.get("annotation_handle") or "")
        if ключ:
            изход[ключ] = {име: ред.get(име) for име in ИНЖЕНЕРНИ}
    return изход


def _ред_по_надпис(редове: list[dict], надпис: str) -> dict:
    for ред in редове:
        if str(ред.get("annotation_text") or "").strip().upper() == надпис.upper():
            return ред
    return {}


def _изтекли_размери(запис: dict) -> list[str]:
    """Срещат ли се ДОНОРСКИТЕ размери в СТОЙНОСТ на поле."""

    ако = []
    стойности = [поле.get("стойност") for поле in (запис.get("полета") or [])]
    числа = []
    for стойност in стойности:
        if isinstance(стойност, list):
            числа.append(tuple(float(х) for х in стойност if _число(х)))
    for забранено in ЗАБРАНЕНИ_РАЗМЕРИ:
        if забранено in числа:
            ако.append("/".join(str(х) for х in забранено))
    return ако


def _число(стойност) -> bool:
    try:
        float(стойност)
    except (TypeError, ValueError):
        return False
    return True


