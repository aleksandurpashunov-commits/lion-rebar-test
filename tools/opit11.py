def _sha(път: pathlib.Path) -> str:
    смес = hashlib.sha256()
    with път.open("rb") as поток:
        for парче in iter(lambda: поток.read(1 << 20), b""):
            смес.update(парче)
    return смес.hexdigest()


def _sha_на_дърво(корен: pathlib.Path, шаблон: str) -> str:
    смес = hashlib.sha256()
    for файл in sorted(корен.rglob(шаблон)):
        if not файл.is_file():
            continue
        смес.update(файл.relative_to(корен).as_posix().encode("utf-8"))
        смес.update(_sha(файл).encode("ascii"))
    return смес.hexdigest()


def _dxf(проект: pathlib.Path) -> pathlib.Path | None:
    кандидати = sorted(проект.rglob("*.dxf"))
    return кандидати[0] if кандидати else None


def _среда(
    data_root: pathlib.Path, *, памет: bool, донори: "list[str] | None" = None,
) -> dict:
    среда = dict(os.environ)
    среда["LION_REBAR_DATA_ROOT"] = str(data_root)
    среда["QT_QPA_PLATFORM"] = "offscreen"
    среда["PYTHONPATH"] = str(КОРЕН)
    среда["PYTHONIOENCODING"] = "utf-8"
    # Научените ПРАВИЛА остават изключени през целия опит.
    среда["LION_REBAR_LEARNING"] = "off"
    среда["LION_REBAR_AUTOCYCLE"] = "off"
    среда["LION_REBAR_DECISION_MEMORY"] = "on" if памет else "off"
    # РАЗРЕШЕНИТЕ донорски проекти. Това е контролираната стъпка на режим В:
    # донорът се ОБЯВЯВА за разрешен източник, а журналите НЕ се смесват.
    среда["LION_REBAR_DECISION_REUSE_DONORS"] = ";".join(донори or [])
    return среда


def _копирай(източник: pathlib.Path, цел: pathlib.Path) -> pathlib.Path:
    if цел.exists():
        shutil.rmtree(цел, ignore_errors=True)
    shutil.copytree(източник, цел)
    return цел


def _изчисти_паметта(проект: pathlib.Path) -> list[str]:
    """Изходните копия може да носят дневници; „празна памет" иска чистене."""

    махнати: list[str] = []
    работна = проект / "working"
    if not работна.is_dir():
        return махнати
    for файл in sorted(работна.glob("decision_event*")):
        if файл.is_file():
            файл.unlink()
            махнати.append(файл.name)
    return махнати


def _памет_sha(проект: pathlib.Path) -> str:
    return _sha_на_дърво(проект / "working", "decision_event*")


def _снимка_на_паметта(проект: pathlib.Path, цел: pathlib.Path) -> dict:
    """Копие на файловете с решенията в ТОЗИ миг, с техните суми.

    Нужно е, защото журналът е дописващ: по-късно копие носи и събитията,
    случили се след мига, който искаме да опишем. Снимката се прави НА
    МОМЕНТА, а не се възстановява наум при сглобяването на пакета.
    """

    цел.mkdir(parents=True, exist_ok=True)
    записани: dict[str, str] = {}
    работна = проект / "working"
    if работна.is_dir():
        for файл in sorted(работна.glob("decision_event*")):
            if not файл.is_file() or файл.suffix == ".lock":
                continue
            shutil.copy2(файл, цел / файл.name)
            записани[файл.name] = _sha(цел / файл.name)
    return {"папка": str(цел), "файлове": записани,
            "sha на паметта": _памет_sha(проект)}


def _пусни_пътя(
    проект: pathlib.Path,
    изход: pathlib.Path,
    среда: dict,
    *,
    work_root: pathlib.Path,
) -> dict:
    """Целият път в ОТДЕЛЕН процес — това е и рестартът, който опитът иска."""

    изход.mkdir(parents=True, exist_ok=True)
    отчет = изход / ("%s.json" % проект.name)
    команда = [
        sys.executable,
        str(FULL_PATH),
        str(проект),
        "--json",
        str(отчет),
        "--work-root",
        str(work_root),
    ]
    процес = subprocess.run(команда, env=среда, capture_output=True)
    данни: dict = {}
    if отчет.is_file():
        try:
            данни = json.loads(отчет.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            данни = {}
    данни["exit_code"] = процес.returncode
    данни["stderr_tail"] = процес.stderr.decode("utf-8", "replace")[-1200:]
    return данни


def _отчетът(резултат: dict) -> pathlib.Path | None:
    относителен = str(((резултат.get("analysis") or {}).get("report")) or "")
    копие = str(резултат.get("copy") or "")
    if not относителен or not копие:
        return None
    път = pathlib.Path(копие) / относителен
    return път if път.is_file() else None


def _редове(отчет: pathlib.Path | None) -> list[dict]:
    if отчет is None:
        return []
    try:
        данни = json.loads(отчет.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError):
        return []
    редове = данни.get("rows")
    return [р for р in редове if isinstance(р, dict)] if isinstance(редове, list) else []


