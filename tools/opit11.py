def _ui(
    проект: pathlib.Path,
    *,
    действие: str,
    изход: pathlib.Path,
    среда: dict,
    отчет: pathlib.Path | None = None,
    надпис: str = "",
    етикет: str = "",
    handle: str = "",
    форма: str = "",
    участъци: "list[float] | None" = None,
    причина: str = "",
    с_геометрия: bool = False,
) -> dict:
    команда = [
        sys.executable, str(UI),
        "--proekt", str(проект),
        "--deystvie", действие,
        "--izhod", str(изход),
        "--etiket", етикет or действие,
    ]
    if отчет is not None:
        команда += ["--otchet", str(отчет)]
    if надпис:
        команда += ["--nadpis", надпис]
    if handle:
        команда += ["--otteglyay-handle", handle]
    if форма:
        команда += ["--forma", форма]
    if участъци:
        команда += ["--uchastatsi", ";".join(str(ст) for ст in участъци)]
    if причина:
        команда += ["--prichina", причина]
    if с_геометрия:
        команда += ["--s-geometriya"]
    процес = subprocess.run(команда, env=среда, capture_output=True)
    файл = изход / ("UI_%s.json" % (етикет or действие))
    данни: dict = {}
    if файл.is_file():
        try:
            данни = json.loads(файл.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            данни = {}
    данни["exit_code"] = процес.returncode
    данни["stderr_tail"] = процес.stderr.decode("utf-8", "replace")[-1200:]
    return данни


