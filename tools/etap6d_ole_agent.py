def надписи_от_чертежа(път: pathlib.Path, блок: str = "MLCircle") -> dict:
    данни = json.loads(път.read_text(encoding="utf-8"))
    обекти = данни["entities"]
    вмъквания = [
        e for e in обекти
        if e.get("entity_type") == "INSERT" and e.get("block_name") == блок
    ]
    надписи = []
    без_номер = []
    for e in вмъквания:
        геом = e.get("geometry") or {}
        poz = [
            a for a in (геом.get("attributes") or [])
            if (a.get("tag") or "").upper() == "POZ"
        ]
        текст = (poz[0].get("text") or "").strip() if poz else ""
        точка = геом.get("insert") or [None, None, None]
        ако = {
            "handle": e.get("handle"),
            "слой": e.get("layer"),
            "номер": текст or None,
            "x": точка[0],
            "y": точка[1],
            "има_ATTRIB_POZ": bool(poz),
        }
        (надписи if текст else без_номер).append(ако)
    брояч = collections.Counter(н["номер"] for н in надписи)
    return {
        "блок": блок,
        "вмъквания": len(вмъквания),
        "с_ATTRIB_POZ": sum(1 for e in вмъквания if any(
            (a.get("tag") or "").upper() == "POZ"
            for a in ((e.get("geometry") or {}).get("attributes") or [])
        )),
        "с_непразен_номер": len(надписи),
        "без_номер": без_номер,
        "различни_номера": len(брояч),
        "нечислови_номера": sorted(n for n in брояч if n and not n.isdigit()),
        "номерът_е_уникален": all(v == 1 for v in брояч.values()),
        "повторения": dict(sorted(брояч.items(), key=lambda kv: int(kv[0]))),
        "надписи": надписи,
    }


def свържи_с_ведомостите(надписи: dict, ведомости: list[dict]) -> dict:
    """Кои надписи се свързват ЕДНОЗНАЧНО с точно един ред от точно една ведомост.

    Номерата на позициите се повтарят между отделните ведомости (етапите).
    Затова еднозначна е само връзката за номер, който се среща в ТОЧНО ЕДНА
    ведомост. За останалите не се избира „най-близката" ведомост — това би
    било близост, приета за принадлежност.
    """
    по_номер: dict[str, list[dict]] = collections.defaultdict(list)
    for в in ведомости:
        за_рамка = в["рамка"]["handle"]
        for лист in в["листове"]:
            for ред in лист["редове_позиции"]:
                по_номер[ред["поз"]].append(
                    {"рамка": за_рамка, "лист": лист["лист"], "ред": ред["ред_в_листа"],
                     "заглавие": лист["заглавие_на_листа"]}
                )

    еднозначни = {n: v[0] for n, v in по_номер.items() if len(v) == 1}
    многозначни = {n: v for n, v in по_номер.items() if len(v) > 1}

    надписи_еднозначни = [н for н in надписи["надписи"] if н["номер"] in еднозначни]
    надписи_многозначни = [н for н in надписи["надписи"] if н["номер"] in многозначни]
    надписи_без_ред = [
        н for н in надписи["надписи"] if н["номер"] not in по_номер
    ]
    номера_без_надпис = sorted(
        (n for n in по_номер if n not in {х["номер"] for х in надписи["надписи"]}),
        key=int,
    )
    return {
        "правило": (
            "Еднозначна е връзката само когато номерът на позицията се среща в "
            "точно една от прочетените ведомости. Не се прави избор по близост."
        ),
        "редове_позиции_общо": sum(len(v) for v in по_номер.values()),
        "различни_номера_във_ведомостите": len(по_номер),
        "номера_в_точно_една_ведомост": sorted(еднозначни, key=int),
        "номера_в_повече_от_една": {
            n: len(v) for n, v in sorted(многозначни.items(), key=lambda kv: int(kv[0]))
        },
        "надписи_еднозначни": len(надписи_еднозначни),
        "надписи_многозначни": len(надписи_многозначни),
        "надписи_без_ред_във_ведомост": [н["номер"] for н in надписи_без_ред],
        "номера_във_ведомост_без_надпис": номера_без_надпис,
    }


