# Как се разпознават колоните: по заглавния им текст, нормализиран. Това е
# диалектът на тази ведомост, не общо правило — записано е като ограничение.
КОЛОНИ = (
    ("поз", "поз"),
    ("брой", "брой"),
    ("тип", "тип"),
    ("обща", "обща_дълж_m"),
    ("дълж", "дължина_cm"),
    ("тегло", "тегло_kg"),
)


def _норм(текст: str) -> str:
    return re.sub(r"[\s.,:;]+", "", (текст or "").strip().lower())


def свържи_колони(колони: dict[int, str]) -> dict[str, int]:
    """Заглавие на колона → роля. Първото съвпадение печели, редът има значение."""
    роли: dict[str, int] = {}
    for индекс, заглавие in sorted(колони.items()):
        н = _норм(заглавие)
        if н in {"ø", "o", "d"} or н.startswith("ø"):
            роли.setdefault("диаметър", индекс)
            continue
        for ключ, роля in КОЛОНИ:
            if ключ in н:
                роли.setdefault(роля, индекс)
                break
    return роли


def _число(стойност) -> float | None:
    if isinstance(стойност, bool):
        return None
    if isinstance(стойност, (int, float)):
        return float(стойност)
    if isinstance(стойност, str):
        т = стойност.strip().replace(",", ".")
        try:
            return float(т)
        except ValueError:
            return None
    return None


def _текст(стойност) -> str:
    if стойност is None:
        return ""
    if isinstance(стойност, float) and стойност.is_integer():
        return str(int(стойност))
    return str(стойност).strip()


def рамена_от_тип(текст: str) -> list[int]:
    """Числата в колоната ТИП — дължините на рамената, както са изписани."""
    return [int(x) for x in re.findall(r"\d+", текст or "")]


def прочети_единичните(sheet: Sheet) -> dict[str, float]:
    """Таблицата с единични тегла, която проектантът е оставил в самия лист."""
    единични: dict[str, float] = {}
    for (ред, кол), клетка in sheet.cells.items():
        текст = _текст(клетка.value)
        if клетка.kind == "text" and re.fullmatch(r"N\d+", текст):
            под = sheet.cells.get((ред + 1, кол))
            стойност = _число(под.value) if под else None
            if стойност and 0.1 < стойност < 10:
                единични.setdefault(текст, стойност)
    return единични


def разгледай_лист(sheet: Sheet, заглавие_лист: str) -> dict:
    таблица = detect_schedule_table(sheet)
    роли = свържи_колони(таблица.columns)
    единични_в_листа = прочети_единичните(sheet)

    редове_позиции: list[dict] = []
    редове_други: list[dict] = []

    for запис in таблица.rows:
        ред = запис["_row"]
        сурови = {
            име: запис.get(заглавие)
            for име, индекс in роли.items()
            for заглавие in [таблица.columns.get(индекс, f"col{индекс}")]
        }
        поз = _текст(сурови.get("поз"))
        брой = _число(сурови.get("брой"))
        диаметър = _текст(сурови.get("диаметър"))
        дължина = _число(сурови.get("дължина_cm"))
        обща = _число(сурови.get("обща_дълж_m"))
        тегло = _число(сурови.get("тегло_kg"))

        # Критерий за ред-позиция, обявен изрично: номер (цяло число), бройка
        # (число) и диаметър (текст от вида N<число>). Всичко друго отива в
        # „други редове" СУРОВО — не се тълкува и не се мълчи за него.
        е_позиция = bool(
            поз.isdigit()
            and брой is not None
            and re.fullmatch(r"N\s*\d+", диаметър or "")
        )
        общ = {
            "ред_в_листа": ред,
            "поз": поз or None,
            "брой": брой,
            "диаметър": диаметър or None,
            "тип_сурово": _текст(сурови.get("тип")) or None,
            "тип_числа": рамена_от_тип(_текст(сурови.get("тип"))),
            "дължина_cm": дължина,
            "обща_дълж_m": обща,
            "тегло_kg": тегло,
            "източници": {
                име: запис.get(f"{таблица.columns.get(индекс, f'col{индекс}')}__source")
                for име, индекс in роли.items()
            },
        }
        if not е_позиция:
            общ["всички_клетки"] = {
                к: v for к, v in запис.items() if not к.endswith("__source")
            }
            редове_други.append(общ)
            continue

        # --- независими проверки -------------------------------------------
        д_норм = диаметър.replace(" ", "")
        мярка = None
        ако_тегло = None
        if обща and тегло and обща > 0:
            мярка = тегло / обща
            близки = sorted(
                ЕДИНИЧНИ_ТЕГЛА.items(), key=lambda kv: abs(kv[1] - мярка)
            )
            ако_тегло = {
                "тегло_на_метър": round(мярка, 6),
                "най-близък_Ø": близки[0][0],
                "отклонение": round(abs(близки[0][1] - мярка), 6),
                "относително": round(abs(близки[0][1] - мярка) / близки[0][1], 6),
                "съвпада_с_обявения": близки[0][0] == д_норм,
                "втори_по_близост": близки[1][0] if len(близки) > 1 else None,
            }
        проверка_дължина = None
        if брой and дължина and обща:
            очаквано = брой * дължина / 100.0
            проверка_дължина = {
                "брой×дължина/100": round(очаквано, 6),
                "обявена_обща": обща,
                "съвпада": math.isclose(очаквано, обща, rel_tol=1e-6, abs_tol=1e-6),
            }
        общ["проверки"] = {
            "по_тегло": ако_тегло,
            "по_дължина": проверка_дължина,
            "единично_тегло_в_листа": единични_в_листа.get(д_норм),
            "единично_тегло_справочно": ЕДИНИЧНИ_ТЕГЛА.get(д_норм),
        }
        редове_позиции.append(общ)

    return {
        "лист": sheet.name,
        "заглавие_на_листа": заглавие_лист,
        "dimensions": list(sheet.dimensions) if sheet.dimensions else None,
        "брой_клетки": len(sheet.cells),
        "заглавен_ред": таблица.header_row,
        "колони": {str(k): v for k, v in таблица.columns.items()},
        "роли_на_колоните": {k: int(v) for k, v in роли.items()},
        "единични_тегла_в_листа": единични_в_листа,
        "единични_тегла_справочно": ЕДИНИЧНИ_ТЕГЛА,
        "единичните_съвпадат": {
            к: (abs(единични_в_листа[к] - ЕДИНИЧНИ_ТЕГЛА[к]) < 1e-9)
            for к in единични_в_листа
            if к in ЕДИНИЧНИ_ТЕГЛА
        },
        "редове_позиции": редове_позиции,
        "редове_други": редове_други,
    }


def заглавие_на_лист(sheet: Sheet) -> str:
    """Текстът над заглавния ред — как проектантът е нарекъл ведомостта."""
    таблица = detect_schedule_table(sheet)
    ако = таблица.header_row
    if ако is None:
        return ""
    for ред in sheet.rows():
        if ред >= ако:
            break
        за = [
            _текст(c.value)
            for _, c in sorted(sheet.row_values(ред).items())
            if c.kind == "text" and _текст(c.value)
        ]
        if за:
            return за[0]
    return ""


