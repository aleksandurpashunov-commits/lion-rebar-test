"""Добавка за огъване — ЕДИН източник на истина.

ПРАВИЛО (Product Owner, 2026-08-25)
-----------------------------------
В описа влиза това, което е НАДПИСАНО в чертежа. При затворено стреме
проектантът изписва страните, а общата дължина включва добавка за
огъвките. Затова сборът на страните е по-МАЛЪК от надписаната дължина:

    56N8x115 -> стреме 25 x 20, кука 10 -> 2*(25+20)+2*10 = 110 при L=115

Разликата е отговорност на проектанта и не е повод за отказ.

ЗАЩО Е ОТДЕЛЕН МОДУЛ
--------------------
Същата проверка съществуваше на ПЕТ различни места: диалога за инженерно
решение, пътя за запис, MASTER формулата, обвивката към Engine-а и Excel
експорта. Поправянето им едно по едно означаваше, че операторът удря
следваща преграда след всеки ъпдейт — седем поредни версии за един и същ
случай.

Всяко място вика ``segments_match_total``. Ново място задължително също.

ГРАНИЦИ (асиметрични, умишлено)
-------------------------------
* недостиг до 8 cm при F006 (затворено стреме) -> приема се;
* недостиг до 2.1 cm при F009 (отворено стреме с четири огъвки) -> приема се;
* недостиг при F004/F012 до следващото кратно на 5 cm -> приема се;
* недостиг над тавана за формата -> отказ (сгрешени размери);
* НАДВИШАВАНЕ -> отказ при всяка форма (не е добавка, а грешка).

Таваните са в ``BEND_ALLOWANCE_LIMITS_CM``; форма извън него няма добавка.
Закръглянето е отделно правило -- ``BEND_ROUNDING_SHAPES``.
"""
from __future__ import annotations

import math
from typing import Iterable

#: Максимална добавка за огъване при затворено стреме.
#: Измерена в реален чертеж: при 43 от 60 стремета точно 5 cm,
#: единични случаи 4 и 6.
BEND_ALLOWANCE_LIMIT_CM = 8.0

#: Добавка при ОТВОРЕНОТО стреме с четири огъвки (F009).
#:
#: Собственик, 19.09.2026, за борда ``1180N8x190``: „трябва да има как да се
#: зададе този механизъм да е 8/79/15/79/8, а не за 1 сантиметър да не …
#: защото по чертеж си е така, но нашата програма не дава."
#:
#: Основанието е физиката, не изключение: F009 се огъва ЧЕТИРИ пъти на 90°,
#: точно както затвореното стреме, и дължината, която проектантът надписва,
#: включва същата добавка. Правилото „при отворените форми сборът Е
#: дължината" важи за правия прът и за формите с една огъвка, не за
#: четирикратно огънатото стреме.
#:
#: Границата е нарочно МНОГО по-тясна от 8 cm на F006: измерен е един реален
#: случай — 8+79+15+79+8 = 189 при надписано L=190, тоест 1 cm при четири
#: огъвки. До повече измерени случаи 2.1 cm приема него с резерв: заедно с
#: симетричния допуск за закръгляне (0.51) минава недостиг до 2.61 cm, а
#: размер, сгрешен с 3 cm, се отказва. Същата стойност MASTER формулата
#: вече ползва като допуск за отклонение при F006.
OPEN_STIRRUP_BEND_ALLOWANCE_LIMIT_CM = 2.1

#: Форми, при които добавката е допустима, и нейният таван за всяка.
#: При останалите отворени форми сборът на сегментите Е производствената
#: дължина и разлика няма да бъде приета.
BEND_ALLOWANCE_LIMITS_CM: dict[str, float] = {
    "F006": BEND_ALLOWANCE_LIMIT_CM,
    "F009": OPEN_STIRRUP_BEND_ALLOWANCE_LIMIT_CM,
}

#: Запазено име за обратна съвместимост на вносителите.
BEND_ALLOWANCE_SHAPES = frozenset(BEND_ALLOWANCE_LIMITS_CM)

#: Стъпка, до която проектантът закръглява НАГОРЕ общата дължина на огъната
#: форма.
#:
#: Измерено на 21.09.2026 по запазените пакетни отчети (само най-новият отчет
#: за всеки проект, доверени съвпадения, без неразрешени криви):
#:
#: * прав прът F001 -- 177 позиции в "тест-001" и "d-2": недостиг НУЛА, нула
#:   изключения. Правият прът НЕ се закръгля;
#: * F004/F012 -- 36 позиции в същите два чертежа: всички с недостиг и всички
#:   точно ``ceil(сбор / 5) * 5``, нула изключения.
#:
#: Разликата между двете групи е доказателството: недостигът Е добавката за
#: огъване, а проектантът я изразява като закръгляне на общата дължина.
#: Стойностите в "тест-001" са 2, 3 и 4 cm; в "d-2" 0,91-1,70 cm. Затова
#: критерият е закръглянето, а не плосък таван: закръглянето приема 4,99 cm,
#: когато това е целта, и ОТКАЗВА 2 cm, когато надписаното не е кратно на 5.
#:
#: Собственик, 21.09.2026, за ``11N8x115`` (начертани 100 + 12 при надпис 115):
#: "задавайки правото и куката останалото да остава за огъвката".
BEND_ROUNDING_STEP_CM = 5.0

#: Форми БЕЗ добавка за огъване: правият прът няма какво да огъне.
#:
#: Измерено 21.09.2026: F001 дава недостиг НУЛА при 177 позиции в "тест-001" и
#: "d-2", с нула изключения. Всяка форма С огъвка дава недостиг и той е точно
#: закръгляне нагоре до кратно на 5 cm (42 от 42 при F004/F012/F003).
STRAIGHT_SHAPES = frozenset({"F001"})

#: Собственик, 22.09.2026: „оправи това с допуска +- няколко сантиметра при
#: огъвките да се показва така, както е на чертежа, нищо че не съвпада 100%
#: с общата дължина“.
#:
#: Дотук закръглянето важеше само за F004 и F012 — формите, за които имаше
#: широка измерена популация. Случаят, който отвори въпроса, е F008 СТОЛЧЕ:
#: надписаните 15 + 9 + 20 + 9 + 15 = 68 при обявени 70, а ``ceil(68/5)*5``
#: дава точно 70. Второто му столче: 15 + 13 + 20 + 13 + 15 = 76 при 80.
#:
#: Затова правилото се обръща: важи за ВСЯКА форма с огъвка, а изключението е
#: изброено. Асиметрията НЕ се мени — надвишаването си остава отказ при всяка
#: форма, а недостиг, който не е цел на закръгляне, също.
BEND_ROUNDING_SHAPES = frozenset({"F004", "F012"})


def _rounding_applies(shape_code: str | None) -> bool:
    """Има ли тази форма право на закръгляне.

    Празен код значи „не се знае каква е формата“ — тогава нищо не се приема.
    """

    code = str(shape_code or "").strip().upper()
    return bool(code) and code not in STRAIGHT_SHAPES


def rounded_production_total(
    shape_code: str | None,
    segments_total: float,
    *,
    tolerance: float = 0.51,
    rounding_step: float | None = None,
) -> float | None:
    """Дължината, която проектантът би написал при закръгляне нагоре до 5 cm.

    ``None`` -- формата няма такова правило. Сбор, който ВЕЧЕ е кратен на 5,
    сочи сам себе си: затова закръглянето не оправдава недостиг при кръгъл
    размер (450 -> 450, а не 455).

    ``rounding_step`` позволява формата да ОБЯВИ стъпката си, вместо да се
    търси по код. Нужно е за форма, родена от случай: нейният код се измисля
    при създаването ѝ и затова не може да стои в ``BEND_ROUNDING_SHAPES``.
    Правилото остава тук -- обявява се само ДАЛИ важи, не как работи.
    """

    if rounding_step is None:
        if not _rounding_applies(shape_code):
            return None
        step = BEND_ROUNDING_STEP_CM
    else:
        try:
            step = float(rounding_step)
        except (TypeError, ValueError):
            return None
        if step <= 0:
            return None
    try:
        total = float(segments_total)
    except (TypeError, ValueError):
        return None
    if total <= 0:
        return None
    return math.ceil((total - abs(float(tolerance))) / step) * step


def allowance_for(shape_code: str | None) -> float:
    """Допустимият НЕДОСТИГ за дадена форма."""

    code = str(shape_code or "").strip().upper()
    return BEND_ALLOWANCE_LIMITS_CM.get(code, 0.0)


def declared_allowance_closes(
    segments_total: float,
    production_total: float,
    declared_allowance_cm: float | None,
    *,
    tolerance: float = 0.51,
) -> bool:
    """Затваря ли ЗАЯВЕНОТО от инженера число уравнението.

    ЗАЩО СЪЩЕСТВУВА. Правилата по-горе са изведени от измерени популации и
    важат за цели групи форми. Има обаче отделни начертани детайли, при които
    нито плоският таван, нито закръглянето до 5 обясняват разликата. Измереният
    случай е F007 „S за продънване“: отпечатаните коти дават 10 + 21 + 13 = 44
    при надписана дължина 47, тоест точно 3 cm. ``segments_match_total`` отказва
    и е ПРАВ да отказва — закръглянето сочи 45, не 47, а да се въведе ново общо
    правило по един детайл би било догадка (виж и обратните 21 от 334 подменени
    коти в ``PROJECT_HANDOFF.md``, § 6н).

    Затова числото не се ПОГАЖДА, а се ЗАЯВЯВА: инженерът пише 3 и програмата
    проверява, че точно това число затваря уравнението. Не е таван („до 3“), а
    равенство: сбор + заявено = надписана дължина, в рамките на същия допуск.
    Сгрешено число не минава — 30 вместо 3 не затваря нищо.

    Това НЕ е ново общо правило и не се прилага никъде само по себе си: вика се
    единствено когато обикновените правила вече са отказали, и само там, където
    има записано решение на инженер с автор, време и самоличност на данните.
    Закръглянето до 5 остава правилото за всички останали.

    Само в посока НЕДОСТИГ: добавката за огъване е дължина, която изчезва в
    огъвките. Отрицателно или нулево заявено число не означава нищо и се
    отказва, както и надвишаването.
    """

    try:
        declared = float(declared_allowance_cm)
    except (TypeError, ValueError):
        return False
    if not math.isfinite(declared) or declared <= 0:
        return False
    try:
        difference = float(production_total) - float(segments_total)
    except (TypeError, ValueError):
        return False
    return abs(difference - declared) <= abs(float(tolerance))


def segments_match_total(
    shape_code: str | None,
    segments_total: float,
    production_total: float,
    *,
    tolerance: float = 0.51,
    rounding_step: float | None = None,
    declared_allowance_cm: float | None = None,
) -> bool:
    """Приемлив ли е сборът на сегментите спрямо производствената дължина.

    ``tolerance`` е симетричният допуск за закръгляне; добавката за огъване
    се прилага ОТГОРЕ на него и само в посока недостиг.

    ``rounding_step`` е за форма, родена от случай: тя обявява стъпката си в
    дефиницията си (данни, не код) и я подава оттам. Асиметрията не се мени --
    надвишаването остава отказ.

    ``declared_allowance_cm`` е число, ЗАЯВЕНО от инженера за ТАЗИ позиция.
    Пита се ПОСЛЕДНО — след таваните и след закръглянето — тоест не отслабва
    нито едно от измерените правила и не мени нищо, когато не е подадено.
    Виж ``declared_allowance_closes``.
    """

    try:
        difference = float(segments_total) - float(production_total)
    except (TypeError, ValueError):
        return False
    if difference > tolerance:
        return False
    if -(tolerance + allowance_for(shape_code)) <= difference:
        return True
    target = rounded_production_total(shape_code, segments_total,
                                      tolerance=tolerance,
                                      rounding_step=rounding_step)
    if target is not None and abs(target - float(production_total)) <= tolerance:
        return True
    return declared_allowance_closes(
        segments_total,
        production_total,
        declared_allowance_cm,
        tolerance=tolerance,
    )


def explain_mismatch(
    shape_code: str | None,
    segments_total: float,
    production_total: float,
    *,
    tolerance: float = 0.51,
    declared_allowance_cm: float | None = None,
) -> str:
    """Човешко обяснение защо сборът не е приемлив. Празно = приемлив е."""

    if segments_match_total(shape_code, segments_total, production_total,
                            tolerance=tolerance,
                            declared_allowance_cm=declared_allowance_cm):
        return ""
    difference = float(segments_total) - float(production_total)
    if difference > tolerance:
        return (
            f"Сборът на сегментите ({float(segments_total):g} cm) НАДВИШАВА "
            f"общата дължина ({float(production_total):g} cm) с "
            f"{difference:g} cm."
        )
    # Недостиг. Казват се ВСИЧКИ граници, които формата има: плоският таван
    # (F006 = 8 cm, F009 = 2,1) и целта на закръглянето. След 22.09.2026
    # закръглянето важи за почти всяка форма и ако то се изпишеше първо и
    # само̀, съобщението за F006 спираше да споменава осемте сантиметра —
    # точно това хвана ``test_explanation_names_the_real_problem``.
    начало = (
        f"Сборът на сегментите ({float(segments_total):g} cm) е по-малък от "
        f"общата дължина ({float(production_total):g} cm) с {-difference:g} cm"
    )
    части: list[str] = []
    allowance = allowance_for(shape_code)
    if allowance:
        части.append(
            f"допустимата добавка за огъване е {allowance:g} cm"
        )
    target = rounded_production_total(shape_code, segments_total,
                                      tolerance=tolerance)
    if target is not None:
        части.append(
            f"закръгляне нагоре до кратно на {BEND_ROUNDING_STEP_CM:g} cm сочи "
            f"{target:g} cm, а надписаната дължина е "
            f"{float(production_total):g} cm"
        )
    # Казва се и кое число БИ затворило уравнението, ако разликата наистина е
    # добавка за огъване. Не я прилага — само показва какво трябва да се заяви,
    # за да не гадае операторът. Сгрешено заявено число се назовава изрично.
    липсващо = float(production_total) - float(segments_total)
    if declared_allowance_cm is not None:
        части.append(
            f"заявената добавка {float(declared_allowance_cm):g} cm не затваря "
            f"уравнението — разликата е {липсващо:g} cm"
        )
    elif липсващо > 0:
        части.append(
            f"ако това е добавка за огъване по този детайл, заявеното число "
            f"трябва да е {липсващо:g} cm"
        )
    if части:
        return начало + " — " + "; ".join(части) + "."
    return (
        f"Сборът на сегментите ({float(segments_total):g} cm) не съвпада с "
        f"общата дължина ({float(production_total):g} cm)."
    )


def sum_of(values: Iterable) -> float:
    total = 0.0
    for value in values or ():
        try:
            total += float(value)
        except (TypeError, ValueError):
            continue
    return total
