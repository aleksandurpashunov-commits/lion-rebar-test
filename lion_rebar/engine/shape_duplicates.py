# -*- coding: utf-8 -*-
"""Проверка за ДУБЛИРАНЕ преди раждането на нова MASTER форма.

## Защо съществува

Нова форма няма право да ражда двусмислие точно там, където днес има
еднозначност. Днешната проверка обаче е **точна**: ``detect_shape_semantic_collisions``
сравнява канонични сигнатури, а те квантуват ъглите на 0,1°. Измерено с изпълнен
код (`rezultat/etap_9/proverka_dublikat.py`):

| случай | вижда ли се днес |
|---|---|
| точен дубликат | **ДА** |
| разлика 0,8° | не |
| разлика 3,8° | не |
| огледален | не (``shape_semantic_domains_overlap`` го вижда, но не се вика) |
| обърнат ред | не (същото) |

Тоест форма, различаваща се с един градус, минава за нова. За matcher-а обаче
двете са НЕРАЗЛИЧИМИ: той сравнява ъгли с допуск ``angle_match_tolerance_deg``
(8° по подразбиране). Две форми, които matcher-ът не може да различи, са
дубликат по последствие, независимо какво казва сигнатурата.

## Откъде идва допускът

**Не е избран тук.** Взима се от самата политика на разпознаването
(``RecognitionPolicy.angle_match_tolerance_deg``). Смисълът е точен: „ако
matcher-ът би приел геометрията на едната за другата, двете не са различни
форми". Промяна на политиката мени и тази проверка — без второ, скрито число.

## Какво връща

Степенувана присъда, а не да/не:

* ``ТОЧЕН`` — същата канонична сигнатура; днешната проверка също го вижда;
* ``БЛИЗЪК`` — еднакъв брой участъци, еднакъв ОБРАЗЕЦ на дължинните кодове и
  ъгли в границите на допуска, при някое от обхожданията (напред, назад,
  огледално). Това е дубликат по последствие;
* ``РАЗЛИЧИМ_ПО_ДЪЛЖИНИ`` — същите ъгли, но различен образец (``ABA`` срещу
  ``ABC``): едната налага равни рамена, другата не. НЕ е дубликат, но трябва да
  се види — без записано отношение двете стават неразличими;
* ``ПРИПОКРИВАЩ`` — ъглите не съвпадат, но домейните се припокриват
  (``shape_index.shape_semantic_domains_overlap``);
* ``НОВА`` — нищо от горните.

## Калибровка — срещу самия заключен MASTER

Пусната върху 15-те активни форми на `lion-rebar-master 0.3.15`
(`rezultat/etap_9/dublikati_master.py`):

| присъда | брой | кои |
|---|---:|---|
| ``НОВА`` | 11 | всички останали |
| ``ТОЧЕН`` | 2 | F003 „ПРЪТ С ДВА ВИНКЕЛА“ ↔ F005 „ФИБА“ |
| ``БЛИЗЪК`` | 2 | F009 „ОТВОРЕНА ФОРМА С ДВЕ РАМЕНА“ ↔ F011 (огледални; F009 е RETIRED) |

Тоест проверката намира ТОЧНО двете двойки, за които самият engine вече знае,
че са двусмислени, и нито една друга. Това е доказателството, че допускът не е
широк: 11 от 15 форми остават различими.

## Какво НЕ прави

* не публикува и не отхвърля сама — дава присъда и доказателство;
* не пипа съществуваща форма;
* не сравнява КОНКРЕТНИ РАЗМЕРИ — те са на позицията, не на формата. Сравнява
  само образеца на дължинните кодове, тоест кои участъци са задължително равни.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Iterable, Sequence

ТОЧЕН = "EXACT_DUPLICATE"
БЛИЗЪК = "NEAR_DUPLICATE"
ПРИПОКРИВАЩ = "OVERLAPPING"
#: Същата топология и същите ъгли, но домейните по ДЪЛЖИНИ не се припокриват —
#: формите се различават по отношенията между рамената, както F003 „ПРЪТ С ДВА
#: ВИНКЕЛА“ и F005 „ФИБА“. Това НЕ е дубликат, но операторът трябва да го знае:
#: без записано отношение двете стават неразличими.
РАЗЛИЧИМ_ПО_ДЪЛЖИНИ = "DISTINCT_BY_LENGTH_RELATIONS"
НОВА = "NEW"

#: Подредба по тежест — по-ранното бие по-късното.
ТЕЖЕСТ = (ТОЧЕН, БЛИЗЪК, ПРИПОКРИВАЩ, РАЗЛИЧИМ_ПО_ДЪЛЖИНИ, НОВА)

#: Допуск по подразбиране, ако не е подадена политика. Същата стойност, която
#: ``RecognitionPolicy`` дава на ``angle_match_tolerance_deg``.
ДОПУСК_ЪГЪЛ_DEG = 8.0


@dataclass(frozen=True)
class Находка:
    """Една съществуваща форма, с която кандидатът се сблъсква."""

    код: str
    име: str
    вид: str
    разлика_deg: float | None
    съвпадение: str
    обяснение: str

    def as_dict(self) -> dict[str, Any]:
        return {
            "code": self.код,
            "name": self.име,
            "kind": self.вид,
            "max_angle_difference_deg": (
                None if self.разлика_deg is None else round(self.разлика_deg, 3)
            ),
            "match": self.съвпадение,
            "explanation": self.обяснение,
        }


@dataclass(frozen=True)
class Присъда:
    вид: str
    находки: tuple[Находка, ...]
    допуск_deg: float

    @property
    def е_дубликат(self) -> bool:
        return self.вид in (ТОЧЕН, БЛИЗЪК)

    def as_dict(self) -> dict[str, Any]:
        return {
            "verdict": self.вид,
            "is_duplicate": self.е_дубликат,
            "angle_tolerance_deg": self.допуск_deg,
            "findings": [н.as_dict() for н in self.находки],
        }


def завои_на_формата(shape: Any) -> tuple[float, ...]:
    """Завоите на формата, със знак: положителен = наляво."""

    изход: list[float] = []
    for сегмент in sorted(getattr(shape, "segments", ()) or (),
                          key=lambda с: int(getattr(с, "index", 0))):
        ъгъл = getattr(сегмент, "bend_after_deg", None)
        if ъгъл is None:
            continue
        посока = str(getattr(сегмент, "bend_direction", "") or "").strip().upper()
        изход.append(float(ъгъл) if посока.startswith("L") else -float(ъгъл))
    return tuple(изход)


def образец_на_кодовете(shape: Any) -> str:
    """Структурата на дължинните кодове: ``L1,L2,L1`` → ``ABA``.

    Това е формата БЕЗ размерите: кои участъци са задължително равни.
    """

    азбука: dict[str, str] = {}
    изход: list[str] = []
    for сегмент in sorted(getattr(shape, "segments", ()) or (),
                          key=lambda с: int(getattr(с, "index", 0))):
        код = str(getattr(сегмент, "length_code", "") or "").strip().upper()
        if код not in азбука:
            азбука[код] = chr(ord("A") + len(азбука))
        изход.append(азбука[код])
    return "".join(изход)


def нормализирай_образеца(образец: str) -> str:
    """Преименува буквите по реда на първата им поява: ``CBA`` → ``ABC``.

    Буквите са само етикети; значение има КОИ участъци са задължително равни.
    Без това обърнатото обхождане на ``ABC`` изглежда като различна форма.
    """

    азбука: dict[str, str] = {}
    изход: list[str] = []
    for буква in образец:
        if буква not in азбука:
            азбука[буква] = chr(ord("A") + len(азбука))
        изход.append(азбука[буква])
    return "".join(изход)


def _варианти(завои: Sequence[float], образец: str) -> list[tuple[tuple[float, ...], str]]:
    """Обхожданията, при които формата е същата: напред, назад, огледално."""

    обърнат = нормализирай_образеца(образец[::-1])
    напред = (tuple(float(з) for з in завои), нормализирай_образеца(образец))
    назад = (tuple(-float(з) for з in reversed(завои)), обърнат)
    огледално = (tuple(-float(з) for з in завои), нормализирай_образеца(образец))
    огледално_назад = (tuple(float(з) for з in reversed(завои)), обърнат)
    видени: list[tuple[tuple[float, ...], str]] = []
    for вариант in (напред, назад, огледално, огледално_назад):
        if вариант not in видени:
            видени.append(вариант)
    return видени


def _най_малка_разлика(
    кандидат_завои: Sequence[float],
    кандидат_образец: str,
    съществуващи_завои: Sequence[float],
    съществуващ_образец: str,
) -> tuple[float | None, str, bool]:
    """Най-доброто съвпадение измежду обхожданията.

    Връща (най-малка разлика в завоите, кое обхождане, съвпада ли ОБРАЗЕЦЪТ на
    дължинните кодове при това обхождане). Образецът се връща отделно, защото
    той е другият въпрос: две форми с едни и същи ъгли, но различен образец
    (``ABA`` срещу ``ABC``) НЕ са дубликат — едната налага равни рамена.
    """

    ако = None
    как = ""
    образецът_съвпада = False
    имена = ("напред", "назад", "огледално", "огледално назад")
    for име, (завои, образец) in zip(имена, _варианти(кандидат_завои, кандидат_образец)):
        if len(завои) != len(съществуващи_завои):
            continue
        разлика = (
            0.0 if not завои
            else max(abs(a - b) for a, b in zip(завои, съществуващи_завои))
        )
        if ако is None or разлика < ако:
            ако, как = разлика, име
            образецът_съвпада = образец == съществуващ_образец
    return ако, как, образецът_съвпада


def провери(
    кандидат: Any,
    съществуващи: Iterable[Any],
    *,
    policy: Any | None = None,
    допуск_deg: float | None = None,
) -> Присъда:
    """Сблъсква ли се кандидатът със съществуваща форма — и как."""

    from lion_rebar.engine.shape_index import (
        canonical_semantic_signature_from_shape, shape_semantic_domains_overlap,
    )

    допуск = float(
        допуск_deg
        if допуск_deg is not None
        else getattr(policy, "angle_match_tolerance_deg", ДОПУСК_ЪГЪЛ_DEG)
    )
    к_завои = завои_на_формата(кандидат)
    к_образец = нормализирай_образеца(образец_на_кодовете(кандидат))
    к_код = str(getattr(кандидат, "code", "") or "").strip().upper()
    к_сигнатура = canonical_semantic_signature_from_shape(кандидат)

    находки: list[Находка] = []
    for форма in съществуващи:
        код = str(getattr(форма, "code", "") or "").strip().upper()
        if not код or код == к_код:
            continue
        if not getattr(форма, "active", True):
            continue
        if bool(getattr(форма, "closed", False)) != bool(getattr(кандидат, "closed", False)):
            continue
        # Еднакъв БРОЙ УЧАСТЪЦИ е предварително условие. Без него „прав прът“
        # (1 участък, нула завои) и „прав прът с редукция“ (3 участъка, чиито
        # завои се задават чрез проекции, не чрез ъгъл) излизаха с нула завои
        # и се сравняваха като една и съща форма.
        if len(getattr(форма, "segments", ()) or ()) != len(
                getattr(кандидат, "segments", ()) or ()):
            continue

        сигнатура = canonical_semantic_signature_from_shape(форма)
        if (к_сигнатура is not None and сигнатура is not None
                and к_сигнатура.value == сигнатура.value):
            находки.append(Находка(
                код, str(getattr(форма, "name", "") or ""), ТОЧЕН, 0.0, "сигнатура",
                "същата канонична сигнатура — това е същата форма",
            ))
            continue

        try:
            припокрива = shape_semantic_domains_overlap(кандидат, форма)
        except Exception:  # noqa: BLE001 — проверката не бива да вали раждането
            припокрива = False

        разлика, как, образецът_съвпада = _най_малка_разлика(
            к_завои, к_образец, завои_на_формата(форма),
            нормализирай_образеца(образец_на_кодовете(форма)))
        if разлика is not None and разлика <= допуск:
            # Съвпадащите ъгли сами по себе си не правят дубликат. Решава
            # ОБРАЗЕЦЪТ на дължинните кодове: ``ABA`` налага две равни рамена,
            # ``ABC`` не налага нищо. Различен образец значи различна форма.
            if not образецът_съвпада:
                находки.append(Находка(
                    код, str(getattr(форма, "name", "") or ""),
                    РАЗЛИЧИМ_ПО_ДЪЛЖИНИ, разлика, как,
                    "същите ъгли (разлика %.2f° при допуск %.2f°), но различен "
                    "образец на дължините: %r срещу %r — различава се САМО по "
                    "отношенията между рамената и те трябва да са записани"
                    % (разлика, допуск, к_образец,
                       нормализирай_образеца(образец_на_кодовете(форма))),
                ))
                continue
            находки.append(Находка(
                код, str(getattr(форма, "name", "") or ""), БЛИЗЪК, разлика, как,
                "същата топология и същият образец %r; най-голямата разлика в "
                "завоите е %.2f° при допуск %.2f° на matcher-а — двете форми са "
                "неразличими за разпознаването" % (к_образец, разлика, допуск),
            ))
            continue

        if припокрива:
            находки.append(Находка(
                код, str(getattr(форма, "name", "") or ""), ПРИПОКРИВАЩ, разлика,
                как or "домейн",
                "домейните се припокриват (огледално, обърнато или специализация)",
            ))

    if not находки:
        return Присъда(НОВА, (), допуск)
    находки.sort(key=lambda н: (ТЕЖЕСТ.index(н.вид), н.код))
    return Присъда(находки[0].вид, tuple(находки), допуск)
