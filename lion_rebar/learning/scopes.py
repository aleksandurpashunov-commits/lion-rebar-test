# -*- coding: utf-8 -*-
"""ЧЕТИРИТЕ ОБХВАТА на едно твърдение — в кода, не само в документацията.

Изискване на собственика (задание от 30.09.2026, § 5):

> Разграничи решение за конкретна позиция, проектна конвенция, проверена
> конвенция за семейство и общо приложимо правило. Избирай най-тесния доказан
> обхват. Извън него давай предложение или отказ.

Затова обхватът НЕ е свободен текст, а стълба, чието стъпало се ИЗЧИСЛЯВА от
доказателството:

``POSITION_DECISION``   решение за КОНКРЕТНА позиция (количество, дължина,
                       изключение). Не се учи никога. Конкретно количество в един
                       проект не става общо правило; подобен надпис не доказва
                       еднаква принадлежност.
``PROJECT_CONVENTION``  конвенция, доказана в ЕДИН независим източник. Остава
                       ``CANDIDATE`` — не се прилага върху друг чертеж.
``FAMILY_CONVENTION``   доказана в ДВА независими източника, за които НЕ е
                       доказано, че са от различни стилови семейства. Прилага се
                       САМО върху чертеж, чийто диалект съвпада с диалекта на
                       поне един донор. Това е АДАПТАЦИЯ В СЕМЕЙСТВО.
``GENERAL_RULE``        доказана в два независими източника, за които е доказано,
                       че са от РАЗЛИЧНИ семейства. Това е ПРЕНОС МЕЖДУ
                       СЕМЕЙСТВА и единственият обхват без ограничение по диалект.

Защо „неопределено семейство" пада в ``FAMILY_CONVENTION``, а не в
``GENERAL_RULE``: двете стъпала се различават по това какво е ДОКАЗАНО. Когато
диалектът не решава, доказано е само „два независими чертежа" — най-тесният
обхват, който това позволява, е семейният. Тогава прилагането иска целевият
чертеж да съвпадне с донор; ако не съвпада, отговорът е отказ, не догадка.

Броенето е по НЕЗАВИСИМИ ИЗТОЧНИЦИ (``auto_cycle.independence_groups``), а не по
имена на семейства или файлове: различно име или различен хеш не доказва различен
източник (``source_identity``).
"""
from __future__ import annotations

from typing import Any, Iterable, Mapping

ОБХВАТ_ПОЗИЦИЯ = "POSITION_DECISION"
ОБХВАТ_ПРОЕКТ = "PROJECT_CONVENTION"
ОБХВАТ_СЕМЕЙСТВО = "FAMILY_CONVENTION"
ОБХВАТ_ОБЩ = "GENERAL_RULE"

#: Стълбата от тясно към широко. Редът е значещ: ``СТЪЛБА.index`` сравнява обхвати.
СТЪЛБА = (ОБХВАТ_ПОЗИЦИЯ, ОБХВАТ_ПРОЕКТ, ОБХВАТ_СЕМЕЙСТВО, ОБХВАТ_ОБЩ)

#: Колко НЕЗАВИСИМИ източника трябват, за да излезе твърдението от един проект.
#: Числото е същото, което кодът иска и досега (``MIN_FAMILIES_TO_ACCEPT``,
#: ``НУЖНИ_СЕМЕЙСТВА``) — променено е КАКВО се брои, не колко.
МИН_НЕЗАВИСИМИ = 2

#: Обхвати, които се ПРИЛАГАТ. Останалите се пазят с доказателствата си, но не
#: влизат в разпознаването.
ПРИЛОЖИМИ = frozenset({ОБХВАТ_СЕМЕЙСТВО, ОБХВАТ_ОБЩ})


def is_applicable(scope: str) -> bool:
    """Прилага ли се твърдение с този обхват върху нов чертеж."""

    return str(scope or "") in ПРИЛОЖИМИ


def crosses_families(scope: str) -> bool:
    """Важи ли твърдението ИЗВЪН семейството на донорите."""

    return str(scope or "") == ОБХВАТ_ОБЩ


def narrower(а: str, б: str) -> str:
    """По-тесният от два обхвата. Непознат обхват е най-тесният."""

    редове = [СТЪЛБА.index(с) if с in СТЪЛБА else 0 for с in (str(а), str(б))]
    return СТЪЛБА[min(редове)]


def scope_for(
    *,
    independent_sources: int,
    family_verdicts: Iterable[str] = (),
    per_position: bool = False,
) -> dict[str, Any]:
    """Най-тесният обхват, който доказателството позволява.

    ``independent_sources``  колко РАЗЛИЧНИ независими източника подкрепят;
    ``family_verdicts``      присъдите за семейство между донорите
                             (``source_identity.family_relation``);
    ``per_position``         доказателството е за конкретна позиция.
    """

    from lion_rebar.learning.source_identity import РАЗЛИЧНИ_СЕМЕЙСТВА

    присъди = [str(п) for п in family_verdicts]
    if per_position:
        return {
            "scope": ОБХВАТ_ПОЗИЦИЯ,
            "independent_sources": int(independent_sources),
            "family_verdicts": присъди,
            "verdict": "доказателството е за конкретна позиция — не се учи като "
                       "правило (конкретно количество не става общо правило)",
        }
    брой = int(independent_sources)
    if брой < МИН_НЕЗАВИСИМИ:
        return {
            "scope": ОБХВАТ_ПРОЕКТ,
            "independent_sources": брой,
            "family_verdicts": присъди,
            "verdict": "доказано в %d независим източник, а за излизане от проекта "
                       "трябват %d" % (брой, МИН_НЕЗАВИСИМИ),
        }
    if РАЗЛИЧНИ_СЕМЕЙСТВА in присъди:
        return {
            "scope": ОБХВАТ_ОБЩ,
            "independent_sources": брой,
            "family_verdicts": присъди,
            "verdict": "доказано в %d независими източника, от които поне двама са "
                       "в РАЗЛИЧНИ стилови семейства — пренос между семейства"
                       % брой,
        }
    return {
        "scope": ОБХВАТ_СЕМЕЙСТВО,
        "independent_sources": брой,
        "family_verdicts": присъди,
        "verdict": "доказано в %d независими източника, но НЕ е доказано, че са от "
                   "различни семейства — адаптация В семейството, прилага се само "
                   "върху чертеж със същия диалект" % брой,
    }


def rule_scope(правило: Any) -> str:
    """Обхватът, записан в правило. Липсващ обхват е СЕМЕЕН, не общ.

    ЗАЩО. Паметта е постоянна: правило, прието от предишна редакция на обучителя,
    няма поле ``learning_scope``. Да се чете като общо би му дало най-ШИРОКИЯ
    обхват на основание, че не е записан — точно обратното на „най-тесния
    доказан обхват". Затова липсващият обхват се чете като семеен, а правило без
    записан диалект на донорите не минава проверката за семейство и не се прилага.
    """

    обхват = getattr(правило, "scope", None) or {}
    ако = str((обхват or {}).get("learning_scope") or "")
    return ако if ако in СТЪЛБА else ОБХВАТ_СЕМЕЙСТВО


def target_in_scope(
    правило: Any,
    *,
    target_style: Mapping[str, Any] | None,
) -> tuple[bool, str]:
    """Може ли правилото да се приложи върху ТОЗИ чертеж, при неговия диалект.

    Връща ``(да/не, обяснение)``. Обяснението влиза в отчета за проследимост —
    отказът също е резултат и се записва.
    """

    from lion_rebar.learning.source_identity import (
        ЕДНО_СЕМЕЙСТВО, family_relation,
    )

    обхват = rule_scope(правило)
    if not is_applicable(обхват):
        return False, "обхватът е %s — твърдението не се прилага върху друг чертеж" % обхват
    if crosses_families(обхват):
        return True, "обхватът е %s — доказан пренос между семейства" % обхват

    донори = list(((getattr(правило, "scope", None) or {}).get("donor_styles") or ()))
    if not донори:
        return False, (
            "обхватът е %s, но правилото не носи диалекта на донорите — "
            "принадлежността на целевия чертеж към семейството не е проверима"
            % обхват
        )
    if target_style is None:
        return False, (
            "обхватът е %s, а диалектът на целевия чертеж не е подаден — "
            "не се прилага без проверка на семейството" % обхват
        )
    присъди = []
    for донор in донори:
        присъда = family_relation(донор, target_style)
        присъди.append(присъда)
        if присъда["verdict"] == ЕДНО_СЕМЕЙСТВО:
            return True, (
                "обхватът е %s и целевият чертеж е в същото семейство (%s)"
                % (обхват, присъда["reason"])
            )
    причини = "; ".join(п["reason"] for п in присъди[:3])
    return False, (
        "обхватът е %s, а целевият чертеж не съвпада с диалекта на нито един "
        "донор: %s" % (обхват, причини)
    )
