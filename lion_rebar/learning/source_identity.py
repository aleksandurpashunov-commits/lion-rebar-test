# -*- coding: utf-8 -*-
"""Самоличност на ИЗТОЧНИКА по съдържание — кое наблюдение е ВТОРО свидетелство.

## Защо съществува този модул

``auto_cycle.record_observation`` пазеше дублирането по ``family`` **или**
``source_sha256``. И двете са ИМЕНА, не съдържание:

* ``family`` е името, което викащият подава — и двата реални викащи подават
  името на чертежа (``ui/main_window.py``, ``skills/lion-rebar-full-path``);
* ``source_sha256`` е отпечатък на БАЙТОВЕТЕ. Един и същ чертеж, записан втори
  път, има друг sha.

Измерено на 30.09.2026 (``rezultat/closure_final/agent_nezavisimost/PREDI.json``,
скрипт ``01_izmeri_predi.py``) върху истинските обекти на 11-те чертежа:

| двойка | какво е | sha | днешната порта | приети правила |
|---|---|---|---|---|
| ``d-1`` + ``s-10`` | ЕДИН чертеж | различни | пуска | **6** |
| ``s-8`` + ``s-9`` | ``s-8`` ⊂ ``s-9`` | различни | пуска | **3** |

Тоест шестте правила от режим „В" на предишния опит са приети от ЕДИН чертеж,
подаден двукратно. Затова независимостта тук се доказва по СЪДЪРЖАНИЕ.

## Мерките — същите, с които вече е мерено

Върху множеството от РАЗЛИЧНИ надписи ``Н`` на чертежа:

    J = |Н(а) ∩ Н(б)| / |Н(а) ∪ Н(б)|       покритие
    C = |Н(а) ∩ Н(б)| / min(|Н(а)|, |Н(б)|)  вложеност

``C`` е задължителна: тя хваща „същият чертеж, изнесен в по-малък обхват", при
което ``J`` пада, без файлът да е друг чертеж. Определенията са от
``rezultat/closure_final/agent_semeystva/izmereno.py`` (редове 50–65) и
``OPREDELENIA.md`` § 1 — не са избрани тук.

Стиловото СЕМЕЙСТВО се мери по ДИАЛЕКТА: същите надписи, но само от слоевете с
армировъчен признак и с всяко число заменено с ``#`` (``образец``). Правилото
``J_образци >= 0,50`` **или** ``C_образци >= 0,85`` е проверено двустранно в
``vlozhenost_dialekt.py`` (слепва 0 двойки, слага всички файлове на един чертеж
в едно семейство) и възпроизведено върху обектите, които програмата вижда:
шестте семейства излизат същите, с ров 0,1389 → 0,5758 по ``J``.

## Какво НЕ съдържа подписът

Нито един надпис, handle или координата. Пазят се само ОТПЕЧАТЪЦИ (по 32 бита
на надпис) и броеве. Отпечатъкът стига за ``J`` и ``C``, но не връща текста —
наблюдението остава „профил по съдържание", както казва докстрингът на
``auto_cycle``.
"""
from __future__ import annotations

import hashlib
import re
from typing import Any, Iterable, Mapping, Sequence

ПОДПИС_СХЕМА = "lion-rebar-content-signature/v1"

#: Колко отпечатъка се пазят най-много. Измереното в корпуса е 482 различни
#: надписа (``Тест-002``), тоест таванът е с осем пъти запас. Над него подписът
#: се отрязва и се БЕЛЕЖИ, а отрязан подпис не дава присъда „независими" —
#: случаят не е измерен и отказът е по-безопасен от оценка.
МАКС_ОТПЕЧАТЪЦИ = 4096

#: Дължина на отпечатъка в шестнадесетични знаци (32 бита). При 482 надписа
#: вероятността за сблъсък е 2,7e-5 — под всяка от измерените разлики.
ДЪЛЖИНА_ОТПЕЧАТЪК = 8

ВИДОВЕ_ТЕКСТ = frozenset({"TEXT", "MTEXT", "ATTRIB", "ATTDEF"})

#: Признакът за „слой с армировъчни надписи" при мярката за диалект. Преписан от
#: ``agent_semeystva/rolevi_sloeve.py`` и ``OPREDELENIA.md`` § 4, точка 1.
_АРМИРОВЪЧЕН_СЛОЙ = re.compile(
    r"ARM|TXT|TEXT|LEGEND|SPEC|NADPIS|NOMER|BAR|REINF", re.IGNORECASE)

_ЧИСЛА = re.compile(r"\d+(?:[.,]\d+)?")

# --------------------------------------------------------------------------- #
# Прагове
# --------------------------------------------------------------------------- #

#: Праг на ВЛОЖЕНОСТТА, над която второто наблюдение НЕ е второ свидетелство.
#:
#: Избран от измереното (``PREDI.json``, 55 двойки върху 11 чертежа):
#:
#:   ЕДИН чертеж:      ``s-8`` ⊂ ``s-9`` -> C = 1,0000; ``d-1``/``s-10`` -> 0,9469
#:   РАЗЛИЧНИ чертежи: най-високото C е 0,8011 (``s-8``/``тест-006``)
#:
#: Ровът е 0,8011 → 0,9469. Прагът стои В рова и по-близо до ДОЛНИЯ му край:
#: при съмнение наблюдението се брои за същия източник. Грешката в тази посока
#: коства научено правило, грешката в другата посока дава мнимо свидетелство.
ПРАГ_ВЛОЖЕНОСТ = 0.90

#: Същото по ПОКРИТИЕ: един чертеж дава J >= 0,5974 (``s-8``/``s-9``);
#: най-високото J между различни чертежи е 0,4393 (``s-9``/``тест-006``).
#: Ров 0,4393 → 0,5974.
ПРАГ_ПОКРИТИЕ = 0.50

#: Семейство по диалект — преписано от ``izmereno.py`` (J_СЕМЕЙСТВО, C_СЕМЕЙСТВО).
СЕМЕЙСТВО_ПОКРИТИЕ = 0.50
СЕМЕЙСТВО_ВЛОЖЕНОСТ = 0.85

#: Под колко образеца диалектът е твърде тънък за присъда. Измерено: най-тънкият
#: диалект, който мярката подрежда вярно, е 14 образеца (``s-8`` -> семейство Б);
#: множествата, които се провалиха в по-ранното измерване, са с 6 и 10
#: (``OPREDELENIA.md`` § 4, „кога данните не стигат"). Прагът стои между 10 и 14.
МИН_ОБРАЗЦИ = 12

# Присъди за самоличността на източника.
ЕДИН_ИЗТОЧНИК = "ЕДИН_ИЗТОЧНИК"
НЕЗАВИСИМИ = "НЕЗАВИСИМИ"
НЕДОКАЗАНО = "НЕДОКАЗАНО"

# Присъди за стиловото семейство.
ЕДНО_СЕМЕЙСТВО = "ЕДНО_СЕМЕЙСТВО"
РАЗЛИЧНИ_СЕМЕЙСТВА = "РАЗЛИЧНИ_СЕМЕЙСТВА"
НЕОПРЕДЕЛЕНО_СЕМЕЙСТВО = "НЕОПРЕДЕЛЕНО_СЕМЕЙСТВО"


# --------------------------------------------------------------------------- #
# Изграждане на подписа
# --------------------------------------------------------------------------- #

def _отпечатък(текст: str) -> str:
    return hashlib.blake2b(
        текст.encode("utf-8"), digest_size=ДЪЛЖИНА_ОТПЕЧАТЪК // 2
    ).hexdigest()


def _надпис(запис: Any) -> str:
    """Човешкият текст на един обект — през нормализатора на самата програма."""

    from lion_rebar.dxf.text_normalization import decode_dxf_text

    if str(getattr(запис, "entity_type", "") or "").upper() not in ВИДОВЕ_ТЕКСТ:
        return ""
    return " ".join(decode_dxf_text(getattr(запис, "text", "") or "").split()).strip()


def образец(текст: str) -> str:
    """Надписът с всяко число заменено с ``#`` — единицата на диалекта."""

    изход = _ЧИСЛА.sub("#", текст or "")
    return "" if изход.strip() in {"", "#"} else изход


def _подмножество(отпечатъци: set[str]) -> tuple[list[str], bool]:
    """Подредени отпечатъци с таван. Отрязва се по НАЙ-МАЛКИТЕ стойности.

    Отрязването по стойност (а не по ред на четене) е нарочно: така двата
    подписа гледат един и същ дял от пространството на отпечатъците и
    сравнението остава смислено. Дали е отрязано се пази отделно.
    """

    подредени = sorted(отпечатъци)
    if len(подредени) <= МАКС_ОТПЕЧАТЪЦИ:
        return подредени, False
    return подредени[:МАКС_ОТПЕЧАТЪЦИ], True


def content_signature(entities: Iterable[Any]) -> dict[str, Any]:
    """Подписът по съдържание на ЕДИН чертеж — от самите обекти.

    Не чете анализа и не ползва решенията му: само текстовете и слоевете.
    """

    надписи: set[str] = set()
    образци: set[str] = set()
    слоеве: set[str] = set()
    брой = 0
    for запис in entities:
        брой += 1
        слоеве.add(str(getattr(запис, "layer", "") or ""))
        текст = _надпис(запис)
        if not текст:
            continue
        надписи.add(_отпечатък(текст))
        if _АРМИРОВЪЧЕН_СЛОЙ.search(str(getattr(запис, "layer", "") or "")):
            обр = образец(текст)
            if обр:
                образци.add(_отпечатък(обр))

    отпечатъци, отрязано = _подмножество(надписи)
    образци_подредени, образци_отрязани = _подмножество(образци)
    return {
        "schema": ПОДПИС_СХЕМА,
        "labels": отпечатъци,
        "label_count": len(надписи),
        "labels_truncated": отрязано,
        "patterns": образци_подредени,
        "pattern_count": len(образци),
        "patterns_truncated": образци_отрязани,
        "layer_count": len(слоеве),
        "entity_count": брой,
    }


def signature_from_labels(labels: Iterable[str],
                          patterns: Iterable[str] | None = None,
                          *, layer_count: int = 0) -> dict[str, Any]:
    """Подпис от ГОТОВИ надписи — за проверки и еднократни скриптове.

    Ползва същото хеширане и същия ``образец``, за да няма втора реализация.
    """

    текстове = {" ".join(str(т).split()).strip() for т in labels}
    текстове.discard("")
    ако_образци = (
        {str(о) for о in patterns} if patterns is not None
        else {образец(т) for т in текстове}
    )
    ако_образци.discard("")
    отпечатъци, отрязано = _подмножество({_отпечатък(т) for т in текстове})
    обр, обр_отрязани = _подмножество({_отпечатък(о) for о in ако_образци})
    return {
        "schema": ПОДПИС_СХЕМА,
        "labels": отпечатъци, "label_count": len(текстове),
        "labels_truncated": отрязано,
        "patterns": обр, "pattern_count": len(ако_образци),
        "patterns_truncated": обр_отрязани,
        "layer_count": int(layer_count), "entity_count": len(текстове),
    }


