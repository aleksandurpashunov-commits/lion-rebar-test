# Мерките
# --------------------------------------------------------------------------- #

def jaccard(а: Sequence[str] | set[str], б: Sequence[str] | set[str]) -> float:
    А, Б = set(а), set(б)
    if not А and not Б:
        return 1.0
    return len(А & Б) / float(len(А | Б) or 1)


def containment(а: Sequence[str] | set[str], б: Sequence[str] | set[str]) -> float:
    А, Б = set(а), set(б)
    if not А or not Б:
        return 0.0
    return len(А & Б) / float(min(len(А), len(Б)))


def _подпис(стойност: Mapping[str, Any] | None) -> dict[str, Any]:
    return dict(стойност or {})


def has_content(signature: Mapping[str, Any] | None) -> bool:
    """Има ли подписът с какво да се мери. Празен подпис не доказва нищо."""

    подпис = _подпис(signature)
    return bool(подпис.get("labels"))


def labels_as_set(signature: Mapping[str, Any] | None) -> frozenset[str]:
    """Отпечатъците като множество — за да се строи ВЕДНЪЖ, не на всяка двойка.

    ``auto_cycle.assign_independence_groups`` сравнява всяко наблюдение с всяко;
    при тавана от 500 наблюдения това са 124 750 двойки. Построяването на
    множествата наново за всяка двойка струваше 7,2 s на анализ (измерено), с
    кеширане — под 1 s.
    """

    return frozenset(_подпис(signature).get("labels") or ())


def independent_sets(А: frozenset[str], Б: frozenset[str]) -> tuple[bool, float, float]:
    """Двете мерки наведнъж върху готови множества: ``(независими, J, C)``.

    Единственото място, където стоят формулите — ``independence`` вика него.
    """

    общи = len(А & Б)
    обединение = len(А) + len(Б) - общи
    J = общи / обединение if обединение else 1.0
    C = общи / min(len(А), len(Б)) if А and Б else 0.0
    return (J < ПРАГ_ПОКРИТИЕ and C < ПРАГ_ВЛОЖЕНОСТ), J, C


def independence(а: Mapping[str, Any] | None,
                 б: Mapping[str, Any] | None) -> dict[str, Any]:
    """Второ свидетелство ли е ``б`` спрямо ``а`` — по съдържание.

    ``НЕЗАВИСИМИ`` изисква ДВЕТЕ мерки да са под праговете си. ``НЕДОКАЗАНО``
    (липсващ или отрязан подпис) НЕ е независимост: непроверимото не се брои за
    свидетелство.
    """

    А, Б = _подпис(а), _подпис(б)
    if not has_content(А) or not has_content(Б):
        return {"verdict": НЕДОКАЗАНО, "jaccard": None, "containment": None,
                "reason": "липсва подпис по съдържание — независимостта не е доказана"}
    if А.get("labels_truncated") or Б.get("labels_truncated"):
        return {"verdict": НЕДОКАЗАНО, "jaccard": None, "containment": None,
                "reason": "подписът е отрязан на %d отпечатъка — случаят не е "
                          "измерен и не се решава" % МАКС_ОТПЕЧАТЪЦИ}
    независими, J, C = independent_sets(frozenset(А["labels"]),
                                        frozenset(Б["labels"]))
    return {
        "verdict": НЕЗАВИСИМИ if независими else ЕДИН_ИЗТОЧНИК,
        "jaccard": round(J, 4), "containment": round(C, 4),
        "reason": (
            "покритие %.4f (праг %.2f) и вложеност %.4f (праг %.2f)"
            % (J, ПРАГ_ПОКРИТИЕ, C, ПРАГ_ВЛОЖЕНОСТ)
        ),
    }


def family_relation(а: Mapping[str, Any] | None,
                    б: Mapping[str, Any] | None) -> dict[str, Any]:
    """Едно стилово семейство ли са двата чертежа — по диалекта на надписите."""

    А, Б = _подпис(а), _подпис(б)
    обр_а = list(А.get("patterns") or ())
    обр_б = list(Б.get("patterns") or ())
    if not обр_а or not обр_б:
        return {"verdict": НЕОПРЕДЕЛЕНО_СЕМЕЙСТВО, "jaccard": None,
                "containment": None,
                "reason": "няма записан диалект за поне единия чертеж"}
    if (int(А.get("pattern_count") or 0) < МИН_ОБРАЗЦИ
            or int(Б.get("pattern_count") or 0) < МИН_ОБРАЗЦИ):
        return {"verdict": НЕОПРЕДЕЛЕНО_СЕМЕЙСТВО, "jaccard": None,
                "containment": None,
                "reason": "диалект под %d образеца — мярката не е достатъчна "
                          "(измерено: 6 и 10 образеца не се разделят)" % МИН_ОБРАЗЦИ}
    J = jaccard(обр_а, обр_б)
    C = containment(обр_а, обр_б)
    едно = J >= СЕМЕЙСТВО_ПОКРИТИЕ or C >= СЕМЕЙСТВО_ВЛОЖЕНОСТ
    return {
        "verdict": ЕДНО_СЕМЕЙСТВО if едно else РАЗЛИЧНИ_СЕМЕЙСТВА,
        "jaccard": round(J, 4), "containment": round(C, 4),
        "reason": ("диалект: покритие %.4f (праг %.2f), вложеност %.4f (праг %.2f)"
                   % (J, СЕМЕЙСТВО_ПОКРИТИЕ, C, СЕМЕЙСТВО_ВЛОЖЕНОСТ)),
    }


def style_signature(signature: Mapping[str, Any] | None) -> dict[str, Any]:
    """Само диалектната част — тя е това, което се носи в правилото.

    Правилото пази диалекта на ДОНОРИТЕ, за да може при прилагане да се провери
    дали целевият чертеж е в същото семейство. Надписите не се носят: за обхвата
    е нужен диалектът, не съдържанието.
    """

    подпис = _подпис(signature)
    return {
        "schema": ПОДПИС_СХЕМА,
        "patterns": list(подпис.get("patterns") or ()),
        "pattern_count": int(подпис.get("pattern_count") or 0),
        "patterns_truncated": bool(подпис.get("patterns_truncated")),
        "labels": [], "label_count": 0, "labels_truncated": False,
    }
