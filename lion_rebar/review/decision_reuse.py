@dataclass(frozen=True)
class Предложение:
    състояние: str
    обяснение: str
    вход: "ВходниДоказателства | None" = None
    случай: "НамеренСлучай | None" = None
    полета: tuple[Поле, ...] = ()
    произход: tuple[Произход, ...] = ()
    варианти: tuple[НамеренСлучай, ...] = ()
    липсва: tuple[str, ...] = ()
    остава_за_оператора: tuple[str, ...] = ()
