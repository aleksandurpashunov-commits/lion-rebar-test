@dataclass(frozen=True)
class ВходниДоказателства:
    """Това, което ЧЕРТЕЖЪТ печата — и нищо от изхода на разпознаването.

    Нарочно НЕ съдържа ``batch_status``, ``candidate_*``, ``matcher_*``,
    ``problem_codes``, ``geometry_class``. Точно те обезсилваха стария ключ.
    """

    надпис: str
    бройка: int
    диаметър_mm: float
    обявена_дължина_cm: float

    @property
    def ключ(self) -> str:
        return _отпечатък({
            "надпис": self.надпис,
            "бройка": self.бройка,
            "диаметър_mm": _число(self.диаметър_mm),
            "обявена_дължина_cm": _число(self.обявена_дължина_cm),
        })

    def речник(self) -> dict[str, Any]:
        return {
            "надпис": self.надпис,
            "бройка": self.бройка,
            "диаметър_mm": self.диаметър_mm,
            "обявена_дължина_cm": self.обявена_дължина_cm,
            "ключ": self.ключ,
        }


def входни_доказателства(
    ред: Mapping[str, Any],
) -> tuple["ВходниДоказателства | None", tuple[str, ...]]:
    """Ключът за намиране — от ред на Review Center или от донорско ``original``."""

    надпис = _главни(
        ред.get("annotation_text")
        or ред.get("source_annotation_text")
        or ред.get("надпис")
    )
    бройка = _цяло(
        ред.get("annotation_count"),
        ред.get("count"),
        ред.get("original_count"),
    )
    диаметър = _положително(
        ред.get("diameter_mm"),
        ред.get("original_diameter_mm"),
    )
    дължина = _положително(
        ред.get("declared_length_cm"),
        ред.get("original_length_cm"),
    )
    липсва = [
        име
        for име, стойност in (
            ("надпис", надпис),
            ("бройка", бройка),
            ("диаметър_mm", диаметър),
            ("обявена_дължина_cm", дължина),
        )
        if not стойност
    ]
    if липсва:
        return None, tuple(липсва)
    assert бройка is not None and диаметър is not None and дължина is not None
    return ВходниДоказателства(надпис, бройка, диаметър, дължина), ()


