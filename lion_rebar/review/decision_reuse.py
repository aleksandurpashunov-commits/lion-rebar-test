def _поддържана_схема(стойност: Any) -> bool:
    return str(стойност or "") in {
        DECISION_CONTRACT_SCHEMA, DECISION_CONTRACT_SCHEMA_V2,
    }


def _jsonl(път: Path) -> list[dict[str, Any]]:
    if not път.is_file():
        return []
    редове: list[dict[str, Any]] = []
    for ред in път.read_text(encoding="utf-8-sig").splitlines():
        try:
            стойност = json.loads(ред)
        except (TypeError, ValueError):
            continue
        if isinstance(стойност, dict):
            редове.append(стойност)
    return редове


def _речник(стойност: Any) -> dict[str, Any]:
    return dict(стойност) if isinstance(стойност, Mapping) else {}


def _текст(стойност: Any) -> str:
    return " ".join(str(стойност if стойност is not None else "").split()).strip()


def _главни(стойност: Any) -> str:
    return _текст(стойност).upper()


def _отпечатък(стойност: Any) -> str:
    сурово = json.dumps(
        стойност, ensure_ascii=False, sort_keys=True, separators=(",", ":")
    )
    return hashlib.sha256(сурово.encode("utf-8")).hexdigest()


def _число(стойност: Any) -> str:
    число = _число_или_none(стойност)
    if число is None:
        return ""
    цяло = round(число)
    if abs(число - цяло) < 1e-9:
        return str(int(цяло))
    return ("%.4f" % число).rstrip("0").rstrip(".")


def _число_или_none(стойност: Any) -> "float | None":
    try:
        число = float(str(стойност).replace(",", "."))
    except (TypeError, ValueError):
        return None
    return число if math.isfinite(число) else None


def _положително(*стойности: Any) -> "float | None":
    for стойност in стойности:
        число = _число_или_none(стойност)
        if число is not None and число > 0:
            return число
    return None


def _цяло(*стойности: Any) -> "int | None":
    for стойност in стойности:
        число = _число_или_none(стойност)
        if число is not None and число > 0 and abs(число - round(число)) < 1e-6:
            return int(round(число))
    return None


def _числов_списък(стойност: Any) -> list[float]:
    if not isinstance(стойност, (list, tuple)):
        return []
    резултат: list[float] = []
    for елемент in стойност:
        число = _число_или_none(елемент)
        if число is None or число <= 0:
            return []
        резултат.append(число)
    return резултат


def _списък_текстове(стойност: Any) -> tuple[str, ...]:
    if isinstance(стойност, str):
        източник = стойност.split(",")
    elif isinstance(стойност, (list, tuple, set)):
        източник = list(стойност)
    else:
        return ()
    return tuple(sorted({_главни(елемент) for елемент in източник if _текст(елемент)}))


def _стойност(самоличност: Any, име: str) -> str:
    if самоличност is None:
        return ""
    if isinstance(самоличност, Mapping):
        return _текст(самоличност.get(име))
    return _текст(getattr(самоличност, име, ""))
