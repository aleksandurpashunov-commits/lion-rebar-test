@dataclass(frozen=True)
class НамеренСлучай:
    """Етап 1 + 2: намерен донор, разложен на слоеве. Още НЕ е предложение."""

    вход: ВходниДоказателства
    правило: str
    форма: ПараметричнаФорма
    донорски_размери_cm: tuple[float, ...]
    донорска_дължина_cm: float
    без_геометрия: bool
    произход: Произход

    @property
    def подпис_на_знанието(self) -> str:
        """Отпечатък на ПРЕНОСИМОТО. Размерите на донора нарочно НЕ влизат.

        Затова два донора с еднаква параметрична форма и различни конкретни
        размери не се броят за противоречие: размерите не се пренасят от
        никого, тоест по тях няма какво да си противоречи.
        """

        return _отпечатък({
            "правило": self.правило,
            "форма": self.форма.код,
            "ревизия": self.форма.ревизия,
            "рамена": self.форма.рамена,
            "завои": [_число(стойност) for стойност in self.форма.завои_deg],
        })

    def речник(self) -> dict[str, Any]:
        return {
            "вход": self.вход.речник(),
            "слоеве": {
                СЛОЙ_ПРАВИЛО: self.правило,
                СЛОЙ_ФОРМА: self.форма.речник(),
                СЛОЙ_РАЗМЕРИ: {
                    "стойности_cm": list(self.донорски_размери_cm),
                    "преносими": False,
                    "защо": "конкретните размери на донора не се пренасят",
                },
                СЛОЙ_ПРИНАДЛЕЖНОСТ: {
                    "преносима": False,
                    "защо": "принадлежността към елемент не се наследява",
                },
            },
            "подпис_на_знанието": self.подпис_на_знанието,
            "произход": self.произход.речник(),
        }


def разложи(
    плик: Mapping[str, Any], *, доставено_от: Iterable[str] = (),
) -> "НамеренСлучай | None":
    """Етап 2: от плик на решение към разложено преносимо знание.

    Връща ``None``, когато пликът не е годно положително доказателство.
    """

    if not _поддържана_схема(плик.get("schema")):
        return None
    if _главни(плик.get("event_type")) != "ENGINEER_RESOLVED":
        return None
    товар = _речник(плик.get("payload"))
    действие = _главни(товар.get("action_class"))
    причина = _главни(товар.get("reason_code"))
    if действие in НЕДОКАЗАТЕЛНИ_ДЕЙСТВИЯ or причина in НЕДОКАЗАТЕЛНИ_ПРИЧИНИ:
        return None
    изходно = _речник(товар.get("original"))
    решено = _речник(товар.get("resolved"))
    вход, _ = входни_доказателства({
        "annotation_text": товар.get("annotation_text"),
        "count": изходно.get("count"),
        "diameter_mm": изходно.get("diameter_mm"),
        "declared_length_cm": изходно.get("declared_length_cm"),
    })
    if вход is None:
        return None
    код = _главни(решено.get("shape_code"))
    if not код:
        return None
    дължина = _положително(решено.get("production_length_cm"))
    участъци, _, пълни = derive_straight_segment(
        код, решено.get("segment_lengths_cm") or [], дължина
    )
    if not участъци or not пълни or дължина is None:
        return None
    ревизия = _цяло(решено.get("shape_revision"))
    if ревизия is None:
        return None
    завои = tuple(
        стойност
        for стойност in (
            _число_или_none(ъгъл) for ъгъл in (решено.get("turn_angles_deg") or ())
        )
        if стойност is not None
    )
    геометрия = _списък_текстове(_речник(товар.get("geometry")).get("handles"))
    без_геометрия = not геометрия
    рамена = len(участъци)
    форма = ПараметричнаФорма(
        код=код,
        име=_текст(решено.get("shape_name")) or код,
        ревизия=ревизия,
        рамена=рамена,
        завои_deg=завои,
    )
    # Правилото „прав прът без геометрия" е преносимо само ако САМИЯТ ДОНОР го
    # потвърждава: приетата от него производствена дължина трябва да е
    # обявената в надписа. Поправил ли е инженерът 300 на 305, той е добавил
    # знание, което НЕ е в надписа на целевата позиция — и правилото „участъкът
    # е обявената дължина" би дало различен отговор от неговия. Такъв донор не
    # носи преносимо правило.
    дължината_е_обявената = (
        abs(дължина - вход.обявена_дължина_cm) <= ДОПУСК_СБОР_CM
    )
    if рамена == 1 and без_геометрия and дължината_е_обявената:
        правило = ПРАВИЛО_ПРАВ_БЕЗ_ГЕОМЕТРИЯ
    elif рамена > 1:
        правило = ПРАВИЛО_РАМЕНА_ОТ_ЦЕЛТА
    else:
        правило = БЕЗ_ПРЕНОСИМО_ПРАВИЛО
    самоличност = _речник(плик.get("source_identity"))
    произход = Произход(
        event_id=_текст(плик.get("event_id")),
        occurred_at=_текст(плик.get("occurred_at")),
        проект=_текст(самоличност.get("project_name")),
        чертеж_sha256=_текст(самоличност.get("source_sha256")),
        източник_отпечатък=_текст(самоличност.get("drawing_family_id")),
        source_generation_id=_текст(самоличност.get("source_generation_id")),
        handle=_текст(товар.get("annotation_handle")),
        engine_version=_текст(самоличност.get("engine_version")),
        действие=действие,
        причина=причина,
        доставено_от=tuple(
            sorted({_текст(име) for име in доставено_от if _текст(име)})
        ),
    )
    if not произход.event_id or not произход.handle:
        return None
    return НамеренСлучай(
        вход=вход,
        правило=правило,
        форма=форма,
        донорски_размери_cm=tuple(участъци),
        донорска_дължина_cm=дължина,
        без_геометрия=без_геометрия,
        произход=произход,
    )


