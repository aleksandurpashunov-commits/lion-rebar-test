def _провери_полетата(
    ред: Mapping[str, Any],
    вход: ВходниДоказателства,
    случай: НамеренСлучай,
) -> tuple[tuple[Поле, ...], tuple[str, ...]]:
    полета: list[Поле] = []
    остава: list[str] = []

    полета.append(Поле(
        "count", вход.бройка, ОТ_ЦЕЛТА, ПОДКРЕПЕНО,
        "бройката е прочетена от надписа на ТАЗИ позиция",
    ))
    полета.append(Поле(
        "diameter_mm", вход.диаметър_mm, ОТ_ЦЕЛТА, ПОДКРЕПЕНО,
        "диаметърът е прочетен от надписа на ТАЗИ позиция",
    ))
    полета.append(Поле(
        "production_length_cm", вход.обявена_дължина_cm, ОТ_ЦЕЛТА, ПОДКРЕПЕНО,
        "обявената дължина е от надписа на ТАЗИ позиция",
    ))
    присъда_форма, обяснение_форма = _присъда_за_формата(ред, случай)
    полета.append(Поле(
        "shape_code", случай.форма.код, ОТ_ФОРМАТА,
        присъда_форма, обяснение_форма,
    ))
    участъци, източник, присъда, обяснение = _участъци_от_целта(ред, вход, случай)
    полета.append(Поле(
        "segment_lengths_cm", участъци, източник, присъда, обяснение,
    ))
    завои, източник_завои, присъда_завои, обяснение_завои = _завои(ред, случай)
    полета.append(Поле(
        "turn_angles_deg", завои, източник_завои, присъда_завои, обяснение_завои,
    ))

    if присъда != ПОДКРЕПЕНО:
        остава.append(
            "въведи %d участъка от котите на чертежа" % случай.форма.рамена
        )
    остава.append("принадлежността към греда/елемент НЕ е пренесена — провери я")
    остава.append("въведи своя бележка: бележката на донора не се копира")
    if случай.без_геометрия:
        остава.append(
            "решението е взето БЕЗ геометрия: провери дали тази позиция "
            "наистина няма начертан прът"
        )
    return tuple(полета), tuple(остава)


def _присъда_за_формата(
    ред: Mapping[str, Any], случай: НамеренСлучай,
) -> tuple[str, str]:
    """Противоречи ли ТАЗИ позиция на предложената параметрична форма."""

    кандидат = _главни(ред.get("master_shape_code"))
    рамена_на_целта = _цяло(ред.get("segment_count"))
    if кандидат and кандидат == случай.форма.код:
        return ПОДКРЕПЕНО, (
            "разпознаването на тази позиция стига до същата форма %s"
            % случай.форма.код
        )
    if (
        рамена_на_целта is not None
        and рамена_на_целта > 1
        and рамена_на_целта != случай.форма.рамена
    ):
        return ПРОТИВОРЕЧИ, (
            "начертаното на тази позиция дава %d участъка, а формата %s иска %d"
            % (рамена_на_целта, случай.форма.код, случай.форма.рамена)
        )
    if кандидат and кандидат != случай.форма.код:
        # Различна кандидат-форма НЕ е противоречие: точно това е случаят, в
        # който инженерът поправя автоматиката. Остава за решение на оператора,
        # а не за мълчаливо приемане.
        return ПОДКРЕПЕНО, (
            "разпознаването предлага %s, предишното решение — %s; формата идва "
            "от решението и подлежи на твоя проверка"
            % (кандидат, случай.форма.код)
        )
    return ПОДКРЕПЕНО, (
        "формата идва от предишното решение; тази позиция не ѝ противоречи"
    )


def _участъци_от_целта(
    ред: Mapping[str, Any],
    вход: ВходниДоказателства,
    случай: НамеренСлучай,
) -> tuple[list[float], str, str, str]:
    """Размерите идват от ЦЕЛТА или остават неизвестни. Донорските — никога."""

    if случай.правило == ПРАВИЛО_ПРАВ_БЕЗ_ГЕОМЕТРИЯ:
        участъци, име_на_правилото, пълни = derive_straight_segment(
            случай.форма.код, [], вход.обявена_дължина_cm
        )
        if участъци and пълни:
            return (
                участъци, ОТ_ПРАВИЛО, ПОДКРЕПЕНО,
                "един участък = обявената дължина на ТАЗИ позиция (%s); "
                "правило на програмата: %s"
                % (_число(вход.обявена_дължина_cm), име_на_правилото),
            )
        return (
            [], БЕЗ_ИЗТОЧНИК, НЕИЗВЕСТНО,
            "правилото за прав прът не дава участък за тази позиция",
        )
    свои = _числов_списък(
        ред.get("canonical_segment_lengths_cm")
        or ред.get("production_segments_cm")
    )
    донорски = "/".join(_число(стойност) for стойност in случай.донорски_размери_cm)
    if not свои:
        return (
            [], БЕЗ_ИЗТОЧНИК, НЕИЗВЕСТНО,
            "тази позиция не носи свои участъци; донорските %s НЕ се пренасят"
            % донорски,
        )
    if len(свои) != случай.форма.рамена:
        return (
            [], БЕЗ_ИЗТОЧНИК, НЕИЗВЕСТНО,
            "тази позиция носи %d свои участъка, а формата %s иска %d"
            % (len(свои), случай.форма.код, случай.форма.рамена),
        )
    if abs(sum(свои) - вход.обявена_дължина_cm) > ДОПУСК_СБОР_CM:
        return (
            [], БЕЗ_ИЗТОЧНИК, НЕИЗВЕСТНО,
            "сборът на своите участъци (%s) не е обявената дължина (%s)"
            % (_число(sum(свои)), _число(вход.обявена_дължина_cm)),
        )
    return (
        свои, ОТ_ЦЕЛТА, ПОДКРЕПЕНО,
        "участъците са СВОИ на тази позиция и сборът им е обявената дължина",
    )


def _завои(
    ред: Mapping[str, Any], случай: НамеренСлучай,
) -> tuple[list[float], str, str, str]:
    """Завоите са част от формата. Знакът им не се измисля."""

    if случай.форма.рамена <= 1:
        return [], ОТ_ПРАВИЛО, ПОДКРЕПЕНО, "форма с едно рамо няма завои"
    свои = _числов_списък(ред.get("canonical_turn_angles_deg"))
    if свои and len(свои) == len(случай.форма.завои_deg):
        return (
            свои, ОТ_ЦЕЛТА, ПОДКРЕПЕНО,
            "завоите са измерени по НАЧЕРТАНОТО на тази позиция",
        )
    if not случай.форма.завои_deg:
        return (
            [], ОТ_ФОРМАТА, ПОДКРЕПЕНО,
            "решението не носи завои; картината се рисува от MASTER формата",
        )
    return (
        [], БЕЗ_ИЗТОЧНИК, НЕИЗВЕСТНО,
        "завоите на донора не се пренасят, а тази позиция не ги дава",
    )


def _защо_е_намерен(
    вход: ВходниДоказателства,
    случай: НамеренСлучай,
    ред: Mapping[str, Any],
) -> tuple[str, ...]:
    причини = [
        "еднакъв надпис: %s" % вход.надпис,
        "еднаква бройка: %d" % вход.бройка,
        "еднакъв диаметър: %s mm" % _число(вход.диаметър_mm),
        "еднаква обявена дължина: %s cm" % _число(вход.обявена_дължина_cm),
    ]
    същият_файл = bool(
        случай.произход.чертеж_sha256
        and случай.произход.чертеж_sha256
        == _текст(_речник(ред.get("data_identity")).get("source_sha256"))
    )
    причини.append(
        "същият DXF файл"
        if същият_файл
        else "друг DXF файл: %s" % (случай.произход.проект or "—")
    )
    причини.append(
        "ВАЖНО: еднаквият надпис САМ не доказва еднаква форма или "
        "принадлежност — затова всяко поле е проверено отделно"
    )
    return tuple(причини)


