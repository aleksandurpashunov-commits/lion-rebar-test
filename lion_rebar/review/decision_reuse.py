def донорски_пътища() -> list[str]:
    """РАЗРЕШЕНИТЕ донорски проекти от средата.

    ``LION_REBAR_DECISION_REUSE_DONORS`` носи пътища, разделени с ``;``. Без
    него се чете само своето досие: решения не се наследяват между проекти без
    изрично разрешение (data identity gate на ``CLAUDE.md``).

    Едно място за четенето нарочно: указателят в анализа, указателят в
    прозореца и Финалният контрол трябва да гледат ЕДИН И СЪЩ набор, иначе
    оттегленото в донора няма да стигне до проверката на зависимите.
    """

    import os

    return [
        част.strip()
        for част in str(
            os.environ.get("LION_REBAR_DECISION_REUSE_DONORS", "")
        ).split(";")
        if част.strip()
    ]


def прочети_жизнения_цикъл(корен: "Path | str") -> dict[str, Any]:
    """Кои решения са доставени, отменени и ОТТЕГЛЕНИ — без да се пише нищо."""

    работна = Path(корен) / "working"
    пликове = _jsonl(работна / JOURNAL_NAME)
    доставени: dict[str, str] = {}
    for ред in _jsonl(работна / OUTBOX_NAME):
        ид = _текст(ред.get("event_id"))
        if ид and _главни(ред.get("state")) == "DELIVERED":
            доставени[ид] = _текст(ред.get("session_id"))
    отменени: set[str] = set()
    оттеглени: dict[str, dict[str, Any]] = {}
    for плик in пликове:
        if _главни(плик.get("event_type")) == WITHDRAW_EVENT_TYPE:
            товар = _речник(плик.get("payload"))
            for ид in товар.get("withdraws_event_ids") or []:
                оттеглени[_текст(ид)] = {
                    "оттеглено_от": _текст(плик.get("event_id")),
                    "кога": _текст(плик.get("occurred_at")),
                    "мотив": _текст(товар.get("reason")),
                    "автор": (
                        _текст(_речник(плик.get("actor")).get("recorded_as"))
                        or _текст(товар.get("actor"))
                    ),
                }
            continue
        for ид in плик.get("supersedes_event_ids") or []:
            отменени.add(_текст(ид))
    return {
        "пликове": пликове,
        "доставени": доставени,
        "отменени": отменени,
        "оттеглени": оттеглени,
    }


def _случаи_от_проект(
    корен: Path,
) -> tuple[int, list[НамеренСлучай], dict[str, int], int]:
    цикъл = прочети_жизнения_цикъл(корен)
    пликове = цикъл["пликове"]
    доставени = цикъл["доставени"]
    отменени = цикъл["отменени"]
    оттеглени = цикъл["оттеглени"]
    отказ: dict[str, int] = {}
    случаи: list[НамеренСлучай] = []
    for плик in пликове:
        ид = _текст(плик.get("event_id"))
        if _главни(плик.get("event_type")) == WITHDRAW_EVENT_TYPE:
            continue
        if not плик.get("active", True):
            отказ["НЕАКТИВНО"] = отказ.get("НЕАКТИВНО", 0) + 1
            continue
        if ид in оттеглени:
            отказ["ОТТЕГЛЕНО"] = отказ.get("ОТТЕГЛЕНО", 0) + 1
            continue
        if ид in отменени:
            отказ["ОТМЕНЕНО"] = отказ.get("ОТМЕНЕНО", 0) + 1
            continue
        if ид not in доставени:
            отказ["НЕДОСТАВЕНО"] = отказ.get("НЕДОСТАВЕНО", 0) + 1
            continue
        случай = разложи(плик, доставено_от=("ПРОЕКТНО_ДОСИЕ",))
        if случай is None:
            отказ["НЕ_Е_ДОКАЗАТЕЛСТВО"] = отказ.get("НЕ_Е_ДОКАЗАТЕЛСТВО", 0) + 1
            continue
        случаи.append(случай)
    return len(пликове), случаи, отказ, len(оттеглени)


# --------------------------------------------------------------------------
# Зависимите вече приети резултати
# --------------------------------------------------------------------------
def зависими_за_повторна_проверка(
    корен: "Path | str", *, допълнителни: "Iterable[Path | str] | None" = None,
) -> list[dict[str, Any]]:
    """Приети решения, чието ОСНОВАНИЕ е отпаднало — за повторна проверка.

    Историята НЕ се трие: оттеглянето е дописано събитие, а приетото решение си
    остава в журнала. Тук само се ИЗБРОЯВА какво е изгубило основанието си, за
    да може Финалният контрол да го спре и операторът да го види.

    ``допълнителни`` са разрешените донорски проекти. Нужни са, защото
    основанието може да е решение В ДОНОРА и оттеглянето му се записва ТАМ —
    без тях целевият проект не би разбрал, че основанието е отпаднало. Без
    подаден списък се ползва ``донорски_пътища()``.
    """

    цикъл = прочети_жизнения_цикъл(корен)
    паднали = set(цикъл["оттеглени"]) | set(цикъл["отменени"])
    оттеглени_навсякъде = dict(цикъл["оттеглени"])
    пътища = (
        донорски_пътища() if допълнителни is None
        else [str(път) for път in допълнителни]
    )
    for път in пътища:
        try:
            чужд = прочети_жизнения_цикъл(път)
        except (OSError, ValueError):
            continue
        паднали |= set(чужд["оттеглени"]) | set(чужд["отменени"])
        оттеглени_навсякъде.update(чужд["оттеглени"])
    цикъл = {**цикъл, "оттеглени_навсякъде": оттеглени_навсякъде}
    резултат: list[dict[str, Any]] = []
    for плик in цикъл["пликове"]:
        ид = _текст(плик.get("event_id"))
        if _главни(плик.get("event_type")) == WITHDRAW_EVENT_TYPE:
            continue
        if ид in цикъл["оттеглени"] or ид in цикъл["отменени"]:
            continue
        товар = _речник(плик.get("payload"))
        одит = _речник(товар.get("preizpolzvane"))
        основание = [_текст(стойност) for стойност in (одит.get("основание") or [])]
        отпаднали = sorted(ид_основание for ид_основание in основание
                           if ид_основание in паднали)
        if not основание or not отпаднали:
            continue
        резултат.append({
            "event_id": ид,
            "annotation_handle": _текст(товар.get("annotation_handle")),
            "annotation_text": _текст(товар.get("annotation_text")),
            "основание": основание,
            "отпаднало_основание": отпаднали,
            "причина": "ОСНОВАНИЕТО_Е_ОТТЕГЛЕНО",
            "оттеглянето": [
                цикъл["оттеглени_навсякъде"].get(ид_основание)
                for ид_основание in отпаднали
                if цикъл["оттеглени_навсякъде"].get(ид_основание)
            ],
        })
    return резултат


