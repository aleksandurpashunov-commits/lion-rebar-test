# -*- coding: utf-8 -*-
"""Производственият вектор от самата геометрия, закръглена към мрежата на проектанта.

## Защо

Намерените на етап 6 дефекти показаха, че досмятането Δ = обявена − отпечатано
дава винаги точен сбор и произволни участъци. Поправката беше отказ. Но при
цял клас позиции ВЕРНИЯТ вектор е налице в самия чертеж и не иска никакво
досмятане: начертаното е в мащаб, а проектантът закръгля размерите към мрежа.

Измерено на `d-2` (стойностите на проектанта са от неговата ведомост):

| надпис | семантични участъци | закръглени | обявена | ведомост |
|---|---|---|---|---|
| `2015` | 14,3 + 594,3 | **15 + 595** | 610 | 15 + 595 |
| `2A7B` | 349,485 + 9,6 | **350 + 10** | 360 | 350 + 10 |
| `2AB5` | 208,9 + 9,4 | **210 + 10** | 220 | 210 + 10 |
| `2C1B` | 9,6 + 449,1 | **10 + 450** | 460 | 10 + 450 |

## Доказателството е самопроверяващо се

Нищо не се досмята: закръгляват се ВСИЧКИ участъци, независимо един от друг, и
чак после се проверява дали сборът им е ТОЧНО обявената дължина. Вероятността
независимо закръгляне на няколко участъка да улучи точно надписаната обща
дължина по случайност е малка, а самото закръгляне не ползва обявената дължина.

Затова чертежът и надписът се потвърждават ВЗАИМНО — два независими източника.

## Условията за приемане

1. **Семантични участъци**, не сурови върхове: дъгите на огъвките се сгъват
   (`geometry_core_v2.semantic_path_from_polyline`). Без това стреме с 6 участъка
   се чете като 11 и закръглянето дава безсмислица с верен сбор — измерено на
   `d-1/4819`.
2. **Броят участъци съвпада** с установения от разпознаването. Несъвпадение
   значи, че се чете друга геометрия — измерено на `d-1/4B5B` (F007 с 3 участъка,
   а семантичният път дава 2).
3. **Чертежът е в мащаб**: сборът на семантичните участъци се различава от
   обявената дължина с не повече от ``МАКС_РАЗЛИКА_НА_ОГЪВКА_CM`` на огъвка. При по-голяма
   разлика чертежът и надписът вече се разминават и никакво закръгляне не е
   доверено — измерено на `s-9/147C2` (сбор 247,96 при обявени 240).
4. **Мрежата не се предполага**: пробват се няколко и се избира тази с
   най-малко общо отместване. При равенство — отказ.
5. **Никое отместване над ``МАКС_ОТМЕСТВАНЕ_CM``**, и никоя стойност точно по
   средата между две деления (двусмислено закръгляне).

## Какво този модул НЕ прави

* Не презаписва вече доказан производствен вектор. При разминаване връща
  присъда ``РАЗМИНАВАНЕ``, за да я види операторът.
* Не ползва обявената дължина при самото закръгляне — само за проверката.
* Не съдържа име на файл, handle или конкретен размер.
"""
from __future__ import annotations

import math
from typing import Any, Mapping, Sequence

#: Мрежите, които се пробват. Проектантите закръглят до 5 или 10 cm; 1 cm е
#: „почти без закръгляне" и служи за чертежи, рисувани точно; 25 покрива
#: по-грубите стилове. Мрежата НЕ се предполага — избира се по данните.
МРЕЖИ_CM: tuple[float, ...] = (1.0, 5.0, 10.0, 25.0)

#: Докъде сборът на начертаното може да се разминава с надписаната обща
#: дължина, за да се смята чертежът за „в мащаб" — НА ОГЪВКА, не общо.
#: Всяка огъвка внася разширяване през радиуса, затова границата расте с броя
#: им. Избрано по измерване: при спорните позиции на d-2 разликата е 0,9–1,7 cm
#: при една огъвка и 1,6–2,8 cm при две, а при случаите, където чертежът и
#: надписът наистина се разминават — 8–9 cm при една огъвка.
МАКС_РАЗЛИКА_НА_ОГЪВКА_CM = 2.0

#: Колко най-много може да мръдне един участък при закръглянето.
МАКС_ОТМЕСТВАНЕ_CM = 6.0

#: Докъде една отпечатана стойност се смята за същата като начертаната или
#: закръглената. Котите са цели числа, начертаното е измерено; под тази граница
#: закръгляването е прилепване в рамките на шума и не СМЕНЯ размер.
#: Измерено върху корпуса: 226 от 376 приемания местят под 0,5 cm.
ДОПУСК_ОБЯВЕН_CM = 0.5

ПРИЕТО = "GRID_ROUNDED"
РАЗМИНАВАНЕ = "DISAGREES_WITH_EXISTING"
ПРОТИВОРЕЧИ_НА_ОТПЕЧАТАН = "CONTRADICTS_PRINTED"
ОТКАЗ = "REFUSED"

#: Полето, в което се записва присъдата.
ПОЛЕ = "grid_rounded_segments"


def _закръгли(стойности: Sequence[float], стъпка: float) -> list[float] | None:
    """Закръгля всеки участък поотделно. ``None`` при двусмислие или далечно отместване."""

    изход: list[float] = []
    for стойност in стойности:
        частно = float(стойност) / стъпка
        дроб = частно - math.floor(частно)
        if abs(дроб - 0.5) < 1e-6:
            return None                      # точно по средата — двусмислено
        закръглена = round(частно) * стъпка
        закръглена = float(закръглена)
        if закръглена <= 0.0:
            return None
        if abs(закръглена - float(стойност)) > МАКС_ОТМЕСТВАНЕ_CM:
            return None
        изход.append(закръглена)
    return изход


def _отпечатана(стойност: float, отпечатани: Sequence[float]) -> float | None:
    """Отпечатаната стойност, която съвпада с ``стойност``, или ``None``."""

    най_близка = None
    най_малко = ДОПУСК_ОБЯВЕН_CM
    for отпечатана in отпечатани:
        try:
            разлика = abs(float(стойност) - float(отпечатана))
        except (TypeError, ValueError):
            continue
        if разлика <= най_малко:
            най_малко = разлика
            най_близка = float(отпечатана)
    return най_близка


def _изхвърля_отпечатан(
    участъци: Sequence[float],
    вектор: Sequence[float],
    отпечатани: Sequence[float],
) -> list[dict[str, Any]] | None:
    """Кои участъци закръгляването би преместило ОТ отпечатан размер.

    ЗАЩО. Закръгляването към мрежа е поправка на схематично начертан размер и е
    оправдано, когато чертежът сам отпечатва закръглената стойност (измерено:
    `тест-006/8F46` — начертано 26,0, отпечатана кота 25, доказана рамо по рамо).
    Обратното не е оправдано: когато чертежът отпечатва НАЧЕРТАНАТА стойност, а
    закръглената я няма никъде, мрежата изхвърля обявен размер, за да затвори
    сбора (измерено: `Тест-002` — начертано и отпечатано 21, предложено 20; и
    трите позиции противоречат на ведомостта на проектанта 11 от 11 пъти).

    Цялото число САМО ПО СЕБЕ СИ не е обявен размер — затова тук се гледа
    отпечатаното, не дали числото е цяло. Преместване до ``ДОПУСК_ОБЯВЕН_CM``
    не сменя размер и не се брои.
    """

    if not отпечатани:
        return None
    изхвърлени: list[dict[str, Any]] = []
    for индекс, (начертан, закръглен) in enumerate(zip(участъци, вектор)):
        if abs(float(закръглен) - float(начертан)) <= ДОПУСК_ОБЯВЕН_CM:
            continue
        отпечатан_начертан = _отпечатана(начертан, отпечатани)
        if отпечатан_начертан is None:
            continue
        if _отпечатана(закръглен, отпечатани) is not None:
            continue                      # и закръглената е отпечатана
        изхвърлени.append({
            "segment_index": индекс,
            "drawn_cm": round(float(начертан), 4),
            "rounded_cm": float(закръглен),
            "printed_cm": отпечатан_начертан,
        })
    return изхвърлени or None


def solve(
    semantic_segments: Sequence[float],
    declared_length_cm: float,
    *,
    grids_cm: Sequence[float] = МРЕЖИ_CM,
    printed_values_cm: Sequence[float] = (),
) -> dict[str, Any]:
    """Пробва мрежите и връща присъда.

    Функцията е чиста: не чете DXF и не пипа ред от отчет, за да е проверима
    без чертеж.

    ``printed_values_cm`` са стойностите, които ЧЕРТЕЖЪТ отпечатва за този прът
    (доказаните рамо по рамо и котите около него). Ползват се само за ВЕТО —
    никога като източник на число, защото близостта на кота не доказва
    принадлежност. Виж ``_изхвърля_отпечатан``.
    """

    участъци = [float(с) for с in semantic_segments]
    обявена = float(declared_length_cm)
    основа: dict[str, Any] = {
        "semantic_segments_cm": [round(с, 4) for с in участъци],
        "declared_length_cm": обявена,
    }
    if len(участъци) < 2 or обявена <= 0 or any(с <= 0 for с in участъци):
        return {**основа, "status": ОТКАЗ, "reason": "няма годни участъци"}

    разлика = abs(sum(участъци) - обявена)
    огъвки = max(1, len(участъци) - 1)
    граница = МАКС_РАЗЛИКА_НА_ОГЪВКА_CM * огъвки
    основа["drawn_total_cm"] = round(sum(участъци), 4)
    основа["drawn_vs_declared_cm"] = round(разлика, 4)
    основа["bends"] = огъвки
    основа["scale_tolerance_cm"] = граница
    if разлика > граница:
        return {**основа, "status": ОТКАЗ,
                "reason": ("начертаното и надписът се разминават с %.2f cm "
                           "(над %.1f при %d огъвки) — чертежът не е в мащаб "
                           "за този прът" % (разлика, граница, огъвки))}

    отпечатани = [float(с) for с in printed_values_cm
                  if isinstance(с, (int, float))]
    # МЕНЮТО от чертежа. Закръгляването към една мрежа е определено само от
    # начертаните участъци — обявената дължина не участва в него. Затова
    # чертежът дава най-много по един кандидат на мрежа, а обявената дължина
    # ИЗБИРА онзи, чийто сбор затваря. Измерено: при 93 от 376 приемания друга
    # обявена дължина избира друг кандидат, и при 93 от 93 сменéният вектор е
    # също в това меню. Записва се, за да е видим изборът.
    меню: list[dict[str, Any]] = []
    решения: list[tuple[float, float, tuple[float, ...]]] = []
    отхвърлени: list[dict[str, Any]] = []
    for стъпка in grids_cm:
        закръглени = _закръгли(участъци, стъпка)
        if закръглени is None:
            continue
        затваря = abs(sum(закръглени) - обявена) <= 1e-6
        изхвърля = _изхвърля_отпечатан(участъци, закръглени, отпечатани)
        меню.append({"grid_cm": float(стъпка), "segments_cm": list(закръглени),
                     "total_cm": round(sum(закръглени), 4),
                     "closes_declared": затваря,
                     "discards_printed": изхвърля or []})
        if not затваря:
            continue
        if изхвърля:
            отхвърлени.append({"grid_cm": float(стъпка),
                               "segments_cm": list(закръглени),
                               "discards_printed": изхвърля})
            continue
        отместване = sum(abs(з - с) for з, с in zip(закръглени, участъци))
        решения.append((отместване, float(стъпка), tuple(закръглени)))
    основа["alternatives_from_drawing"] = меню

    if not решения and отхвърлени:
        # Сборът затваря, но само за сметка на отпечатан размер. Това НЕ е
        # отказ „няма решение" и не се скрива: пазят се двата варианта и
        # причината, а производственото одобрение се блокира по-нататък.
        пръв = отхвърлени[0]
        изхвърлени = ", ".join(
            "участък %d: начертано %.2f и отпечатано %.2f, а мрежата иска %.2f"
            % (и["segment_index"], и["drawn_cm"], и["printed_cm"], и["rounded_cm"])
            for и in пръв["discards_printed"])
        return {**основа, "status": ПРОТИВОРЕЧИ_НА_ОТПЕЧАТАН,
                "segments_cm": list(пръв["segments_cm"]),
                "grid_cm": пръв["grid_cm"],
                "printed_values_cm": отпечатани,
                "rejected_solutions": отхвърлени,
                "reason": ("закръгляването затваря сбора само като изхвърли "
                           "отпечатан размер (%s); обявеният размер има "
                           "предимство пред мрежата — за решение на оператора"
                           % изхвърлени)}

    if not решения:
        return {**основа, "status": ОТКАЗ,
                "reason": "нито една мрежа не затваря сбора точно"}

    решения.sort(key=lambda т: (т[0], т[1]))
    най_малко, стъпка, вектор = решения[0]
    различни = {т[2] for т in решения}
    if len(различни) > 1:
        втори = [т for т in решения if т[2] != вектор][0]
        if abs(втори[0] - най_малко) < 1e-6:
            return {**основа, "status": ОТКАЗ,
                    "reason": ("две мрежи дават различни вектори с еднакво "
                               "отместване: %s и %s" % (list(вектор),
                                                        list(втори[2])))}
    # ЗАЩО формулировката е такава. Мрежа, която не затваря сбора, изобщо не
    # влиза в избора (``continue`` по-горе). Значи точният сбор е КРИТЕРИЙ ЗА
    # ИЗБОР и НЕ е независимо потвърждение на вектора — твърдението, че е,
    # беше невярно и е махнато.
    #
    # Основанието за производственото приемане е ИЗМЕРВАНЕТО: чертежът трябва
    # вече да е в мащаб (портата по-горе, ``scale_tolerance_cm``), а
    # закръгляването е малка поправка върху него. Измерено върху корпуса:
    # всичките 17 приети позиции имат начертан сбор до 0,86 % от обявения
    # (средно 0,47 %), при отместване 0,5–2,8 cm.
    отклонение = (основа["drawn_vs_declared_cm"] / обявена * 100.0) if обявена else None
    # Кой участък на приетия вектор се потвърждава от отпечатан размер. Това е
    # ПРОИЗХОДЪТ, не оценка: `None` значи „чертежът не отпечатва тази стойност",
    # а не „стойността е грешна".
    подкрепа = [_отпечатана(с, отпечатани) for с in вектор] if отпечатани else []
    return {**основа, "status": ПРИЕТО, "segments_cm": list(вектор),
            "grid_cm": стъпка, "total_shift_cm": round(най_малко, 4),
            "alternatives": len(различни),
            "printed_values_cm": отпечатани,
            "printed_support_cm": подкрепа,
            "drawn_vs_declared_pct": (None if отклонение is None
                                      else round(отклонение, 4)),
            "basis": "IN_SCALE_MEASUREMENT",
            "sum_is_selection_not_confirmation": True,
            "reason": ("начертаното е в мащаб (разминаване %.2f cm = %.2f %% от "
                       "обявената дължина, при граница %.1f cm); всеки участък е "
                       "закръглен поотделно към мрежа %g cm с общо отместване "
                       "%.2f cm. Точният сбор е критерият, по който мрежата е "
                       "ИЗБРАНА, и затова НЕ е независимо потвърждение."
                       % (основа["drawn_vs_declared_cm"],
                          отклонение if отклонение is not None else 0.0,
                          основа["scale_tolerance_cm"], стъпка, най_малко))}


def printed_values_for_row(row: Mapping[str, Any]) -> list[float]:
    """Стойностите, които ЧЕРТЕЖЪТ отпечатва за този прът.

    Два източника, различни по сила и нарочно събрани заедно само за вето:

    * ``chain_printed_dimensions`` при ``CONFIRMED`` — рамо по рамо, с доказано
      взаимно еднозначно присвояване надпис ↔ рамо. Най-силният източник;
    * ``nearby_dimensions_cm`` — котите около пръта, БЕЗ доказано присвояване.
      Годни да кажат „чертежът отпечатва тази стойност", негодни да кажат „тази
      стойност е на ТОЗИ участък". Затова не се ползват като източник на число:
      близост, приета за принадлежност, е повтарящият се дефект в проекта.
    """

    стойности: list[float] = []
    верига = row.get("chain_printed_dimensions")
    if isinstance(верига, Mapping) and str(верига.get("status") or "") == "CONFIRMED":
        for стойност in (верига.get("segments_cm") or ()):
            try:
                стойности.append(float(стойност))
            except (TypeError, ValueError):
                continue
    for стойност in (row.get("nearby_dimensions_cm") or ()):
        try:
            стойности.append(float(стойност))
        except (TypeError, ValueError):
            continue
    return стойности


def verdict_for_row(
    row: Mapping[str, Any],
    semantic_segments: Sequence[float],
) -> dict[str, Any] | None:
    """Присъдата за един ред от отчета, или ``None`` ако случаят не е за тук."""

    обявена = row.get("declared_length_cm")
    try:
        обявена = float(обявена)
    except (TypeError, ValueError):
        return None
    if обявена <= 0:
        return None

    обявен_брой = row.get("segment_count")
    try:
        обявен_брой = int(обявен_брой)
    except (TypeError, ValueError):
        return None
    if обявен_брой != len(semantic_segments):
        # Чете се друга геометрия — правилото не важи.
        return None

    присъда = solve(semantic_segments, обявена,
                    printed_values_cm=printed_values_for_row(row))
    налични = [float(с) for с in (row.get("production_segments_cm") or ())]
    if присъда["status"] != ПРИЕТО or not налични:
        return присъда
    ако_съвпада = (len(налични) == len(присъда["segments_cm"])
                   and all(abs(а - б) <= 0.51 for а, б
                           in zip(sorted(налични),
                                  sorted(присъда["segments_cm"]))))
    if ако_съвпада:
        return {**присъда, "status": ПРИЕТО, "confirms_existing": True}
    return {**присъда, "status": РАЗМИНАВАНЕ,
            "existing_segments_cm": налични,
            "reason": ("закръглената геометрия дава друг вектор от вече "
                       "доказания; изборът е на оператора")}
