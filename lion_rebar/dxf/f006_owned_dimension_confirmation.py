# -*- coding: utf-8 -*-
"""Второто, независимо доказателство за стреме с куки (F006).

## Защо съществува този модул

``HOOKED_CLOSURE`` значи: начертаната полилиния е геометрично ОТВОРЕНА, но двете
крайни куки са толкова близо, че формата е сравнена със ЗАТВОРЕНАТА MASTER
топология на F006 — при РАЗШИРЕН допуск на отношенията между дължините
(0,20–0,25 вместо 0,05; ``shape_recognition.py``). Заради този разширен допуск
``matcher_evidence`` винаги иска ръчно потвърждение.

Разширеният допуск е ЕДИНСТВЕНАТА причина за ръчното потвърждение. Когато обаче
проектантът сам е надписал котите ВЪРХУ същия контур и те независимо дават същия
производствен вектор, решението вече не стъпи на разширения допуск, а на две
независими доказателства, които съвпадат:

1. измерената геометрия на кандидата (вече доказана преди този модул);
2. котите на проектанта, чиито опорни точки лежат върху върховете на контура.

## Какво този модул НЕ прави

* **не сменя нито едно число** — сегментите, диаметърът, бройката и формата
  остават каквито са; тук се добавя само доказателство;
* **не досмята липсващ размер** от разликата между обявената дължина и сбора на
  участъците — при по-малко от три собствени коти отговорът е отказ;
* **не обединява коти от два контура** — това би създало несъществуващ размерен
  комплект от съседни кандидати;
* **не махa други спирачки** — ``WEAK_CANDIDATE_SEPARATION``,
  ``OWNERSHIP_CONFLICT`` и останалите си остават;
* **не работи по име на файл, handle или конкретен размер.**

При несъгласие между двата източника модулът НЕ избира победител: записва
противоречието, за да го види операторът. Това е добавена стойност, а не загуба
— досега разминаването не се е виждало никъде.
"""
from __future__ import annotations

from typing import Any, Mapping, Sequence

#: Допуск при сравняване на двата източника, в cm. Котите на проектанта са цели
#: числа или с една десетична; измерената геометрия носи грешка от закръгляне на
#: върховете. По-голям допуск би приел различен размерен комплект за същия.
СЪВПАДЕНИЕ_CM = 0.55

#: Най-малко колко РАЗЛИЧНИ собствени коти трябват. Две са квадратно стреме:
#: ``read_owned_stirrup`` приема втората страна за равна на първата и се пази с
#: обичайната кука на проектанта. Това е допускане за ФОРМАТА, не досмятане от
#: разликата между обявената дължина и сбора — а и тук резултатът пак трябва да
#: съвпадне с вече доказания вектор, иначе присъдата е разминаване.
НУЖНИ_КОТИ = 2

ПОТВЪРДЕНО = "CONFIRMED"
РАЗМИНАВАНЕ = "DISAGREES"
БЕЗ_СОБСТВЕНИ_КОТИ = "NO_OWNED_DIMENSIONS"
НЕЗАТВОРЕНО_УРАВНЕНИЕ = "EQUATION_OPEN"

#: Полето, в което се записва присъдата. Чете се от ``matcher_evidence``.
ПОЛЕ = "f006_owned_dimension_confirmation"


def _положително(стойност: Any) -> float | None:
    try:
        число = float(стойност)
    except (TypeError, ValueError):
        return None
    return число if число > 0 else None


def _вектор(широчина: float, височина: float, кука: float) -> list[float]:
    """Производственият вектор на стреме: кука, страна, страна, ... , кука.

    Редът е същият, който ползва ``batch_geometry_report`` при собствените
    коти — не се измисля нова наредба.
    """

    return [кука, височина, широчина, височина, широчина, кука]


def _стреме_ли_е(вектор: Sequence[float]) -> bool:
    """Има ли векторът устройството на стреме: кука, страна, страна, ... , кука.

    Пази срещу съвпадение по множество при безсмислена наредба (например
    ``[10, 20, 20, 95, 95, 10]`` има същите стойности, но не е стреме).
    """

    if len(вектор) != 6:
        return False
    в = [float(с) for с in вектор]
    return (abs(в[0] - в[5]) <= СЪВПАДЕНИЕ_CM
            and abs(в[1] - в[3]) <= СЪВПАДЕНИЕ_CM
            and abs(в[2] - в[4]) <= СЪВПАДЕНИЕ_CM)


def _еднакви(а: Sequence[float], б: Sequence[float]) -> bool:
    """Двата вектора са едно и също стреме.

    Сравняват се СТОЙНОСТИТЕ, не наредбата. Затворено стреме 95 x 20 и 20 x 95 е
    един и същ обект: разликата е само откъде обхождането започва. Измерено на
    `тест-004` (3 позиции, напр. `5C10::BJ-FI-L` = `28N8x255`): котите дават
    ``[10, 20, 95, 20, 95, 10]``, а измерената геометрия ``[10, 95, 20, 95, 20,
    10]`` — същият правоъгълник, обходен от другата страна.

    Наредбата НЕ се приравнява мълчаливо: разликата се записва в присъдата
    (``order_differs``), защото за машинния изход посоката на обхождане има
    значение. Тук тя не се поправя — това би сменило число.
    """

    if len(а) != len(б):
        return False
    if not (_стреме_ли_е(а) and _стреме_ли_е(б)):
        return False
    return all(abs(х - у) <= СЪВПАДЕНИЕ_CM
               for х, у in zip(sorted(float(с) for с in а),
                               sorted(float(с) for с in б)))


def confirm_row(
    row: Mapping[str, Any],
    *,
    owned_values_by_contour: Mapping[str, Sequence[float]],
    owned_records_by_contour: Mapping[str, Sequence[Mapping[str, Any]]],
    preferred_hook: float | None,
    read_owned_stirrup,
    segments_match_total,
) -> dict[str, Any] | None:
    """Присъдата за един ред. ``None`` значи „случаят не е за този модул".

    Помощниците се подават отвън (``read_owned_stirrup``,
    ``segments_match_total``), за да е функцията чиста и проверима без DXF.
    """

    if str(row.get("master_shape_code") or "").strip().upper() != "F006":
        return None

    налични = list(row.get("production_segments_cm") or ())
    if len(налични) != 6:
        # Без вече доказан вектор няма какво да се потвърждава: тогава работи
        # обичайният път, който ИЗВЕЖДА размерите.
        return None

    обявена = _положително(row.get("declared_length_cm"))
    if обявена is None:
        return None

    # Само един контур. Коти от два кандидата никога не се обединяват.
    свои = [
        (str(handle), list(owned_values_by_contour[str(handle)]))
        for handle in (row.get("candidate_handles") or ())
        if str(handle) in owned_values_by_contour
    ]
    if len(свои) != 1:
        return {
            "status": БЕЗ_СОБСТВЕНИ_КОТИ,
            "reason": ("няма точно един кандидат със собствени коти (намерени %d)"
                       % len(свои)),
        }
    собственик, стойности = свои[0]
    if len({round(float(с), 2) for с in стойности}) < НУЖНИ_КОТИ:
        return {
            "status": БЕЗ_СОБСТВЕНИ_КОТИ,
            "owner_geometry_handle": собственик,
            "reason": ("собствените коти са %d различни, а трябват поне %d; "
                       "липсващият размер НЕ се досмята"
                       % (len({round(float(с), 2) for с in стойности}), НУЖНИ_КОТИ)),
        }

    прочетено = read_owned_stirrup(стойности, preferred_hook)
    if not прочетено:
        return {
            "status": БЕЗ_СОБСТВЕНИ_КОТИ,
            "owner_geometry_handle": собственик,
            "reason": "собствените коти не се четат като стреме",
        }
    широчина, височина, кука = прочетено
    от_коти = _вектор(широчина, височина, кука)

    записи = [
        {"handle": str(з.get("handle") or ""),
         "measurement": з.get("measurement")}
        for з in owned_records_by_contour.get(собственик, ())
    ]
    общо = {
        "owner_geometry_handle": собственик,
        "dimension_handles": [з["handle"] for з in записи],
        "dimension_measurements_cm": записи,
        "segments_from_owned_dimensions_cm": от_коти,
        "segments_in_row_cm": [float(с) for с in налични],
        "declared_length_cm": обявена,
        "tolerance_cm": СЪВПАДЕНИЕ_CM,
    }

    if not segments_match_total("F006", sum(от_коти), обявена):
        # Уравнението не се затваря дори с добавката за огъване. Това е отказ,
        # не повод да се търси „най-близкото".
        return {**общо, "status": НЕЗАТВОРЕНО_УРАВНЕНИЕ,
                "reason": ("сборът на собствените коти %.4g cm не се затваря с "
                           "обявената дължина %.4g cm" % (sum(от_коти), обявена))}

    if not _еднакви(от_коти, налични):
        return {**общо, "status": РАЗМИНАВАНЕ,
                "reason": ("котите на проектанта дават друг размерен комплект от "
                           "измерената геометрия; изборът е на оператора")}

    различна_наредба = any(
        abs(float(х) - float(у)) > СЪВПАДЕНИЕ_CM
        for х, у in zip(от_коти, налични))
    бележка = ("котите на проектанта върху контура дават същото стреме като "
               "измерената геометрия (допуск %.2f cm)" % СЪВПАДЕНИЕ_CM)
    if различна_наредба:
        бележка += ("; РАЗЛИЧНА НАРЕДБА на участъците — същите размери, обходени "
                    "от другата страна; посоката НЕ е поправена тук")
    return {**общо, "status": ПОТВЪРДЕНО, "order_differs": различна_наредба,
            "reason": бележка}


def hooked_closure_is_confirmed(row: Mapping[str, Any]) -> bool:
    """Има ли втори, независим източник, който потвърждава вектора.

    Само това пита ``matcher_evidence``. Всяко друго състояние (разминаване,
    липса на коти, незатворено уравнение) значи „не".
    """

    присъда = row.get(ПОЛЕ)
    if not isinstance(присъда, Mapping):
        return False
    return str(присъда.get("status") or "") == ПОТВЪРДЕНО
