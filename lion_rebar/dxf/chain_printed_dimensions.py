def _разстояние_до_рамото(точка: tuple[float, float], рамо: Рамо) -> float:
    ax, ay = рамо.начало
    bx, by = рамо.край
    dx, dy = bx - ax, by - ay
    L2 = dx * dx + dy * dy
    if L2 <= 0.0:
        return math.dist(точка, рамо.начало)
    t = ((точка[0] - ax) * dx + (точка[1] - ay) * dy) / L2
    t = max(0.0, min(1.0, t))
    return math.dist(точка, (ax + t * dx, ay + t * dy))


def надписи_на_рамената(
    рамена: Sequence[Рамо],
    указател: ВериженУказател,
    *,
    изключени: Sequence[str] = (),
) -> list[tuple[Надпис, list[float]]]:
    """Числовите надписи, които стоят в обхвата на поне едно рамо."""

    забранени = {str(з) for з in изключени}
    изход: list[tuple[Надпис, list[float]]] = []
    for надпис in указател.надписи:
        if надпис.handle in забранени:
            continue
        разстояния = [_разстояние_до_рамото(надпис.точка, рамо) for рамо in рамена]
        обхват = ОБХВАТ_ВИСОЧИНИ * надпис.височина
        if min(разстояния) <= обхват:
            изход.append((надпис, разстояния))
    return изход


#: Докъде текстът трябва да е успореден на рамото, за да се брои за негова
#: кота при вето. По модул 180°. Котите в h01-1001 са изписани по рамото с
#: отклонение под 2°; 15° оставя място за небрежно изписан текст, но не
#: допуска напречен надпис (номер на позиция, брой) като кота.
ВЕТО_УСПОРЕДНОСТ_DEG = 15.0


def отпечатани_до_рамената(
    опорни_handles: Sequence[str],
    указател: ВериженУказател,
    *,
    изключени: Sequence[str] = (),
) -> list[tuple[float, tuple[float, ...]]] | None:
    """За всяко рамо: (начертана дължина, числата, изписани до него и по него).

    НЕ е доказателство за размер — нищо не се присвоява. Служи само за ВЕТО:
    когато до рамото проектантът е написал числа, закръгленото от линиите
    число трябва да е едно от тях. Число се брои към рамо, ако то е най-близкото
    рамо, е в обхвата ``ОБХВАТ_ВИСОЧИНИ`` и е изписано успоредно на него.
    ``None`` — веригата не се сглобява и правилото не се произнася.
    """

    събрано = събери_веригата(опорни_handles, указател)
    if събрано is None:
        return None
    подредени = подреди_веригата(събрано[0])
    if подредени is None:
        return None
    рамена = рамена_на_веригата(подредени)
    if not рамена:
        return None
    забранени = {str(з) for з in изключени}
    по_рамо: list[list[float]] = [[] for _ in рамена]
    for надпис in указател.надписи:
        if надпис.handle in забранени:
            continue
        разстояния = [_разстояние_до_рамото(надпис.точка, рамо) for рамо in рамена]
        най = min(range(len(рамена)), key=lambda и: разстояния[и])
        if разстояния[най] > ОБХВАТ_ВИСОЧИНИ * надпис.височина:
            continue
        ъгъл = рамена[най].посока_deg % 180.0
        текст = надпис.ротация % 180.0
        разлика = min(abs(текст - ъгъл), 180.0 - abs(текст - ъгъл))
        if разлика > ВЕТО_УСПОРЕДНОСТ_DEG:
            continue
        if надпис.стойност not in по_рамо[най]:
            по_рамо[най].append(надпис.стойност)
    return [(рамо.дължина, tuple(стойности)) for рамо, стойности in zip(рамена, по_рамо)]


def _най_добро_присвояване(
    рамена: Sequence[Рамо],
    кандидати: Sequence[tuple[Надпис, list[float]]],
) -> tuple[tuple[Надпис, ...], float, float] | None:
    """Взаимно еднозначно съответствие рамо ↔ надпис с най-малък сбор разстояния.

    Връща (подредени надписи, цена, запас спрямо най-добрия РАЗЛИЧЕН вектор).

    По-малко надписи от рамена е отказ: рамо без собствен размер не се досмята.
    ПОВЕЧЕ надписи се допуска до ``МАКС_ИЗЛИШНИ``, защото проектантът често
    поставя чужда кота в обхвата — измерено на `s-9/14AE4`, където третият
    собствен размер „15" стои на 2,6 височини, а чужда „25" на 2,6 и 3,6.
    Излишъкът НЕ отслабва доказателството: изборът пак трябва да е еднозначен
    със запас И сборът пак трябва да е точно обявената дължина.
    """

    брой = len(рамена)
    if len(кандидати) < брой:
        return None
    if len(кандидати) > брой + МАКС_ИЗЛИШНИ:
        return None
    наредби = list(permutations(range(len(кандидати)), брой))
    if len(наредби) > МАКС_НАРЕДБИ:
        return None
    най_добро: tuple[tuple[Надпис, ...], float] | None = None
    по_вектор: dict[tuple[float, ...], float] = {}
    for наредба in наредби:
        цена = 0.0
        добра = True
        for рамо_индекс, кандидат_индекс in enumerate(наредба):
            надпис, разстояния = кандидати[кандидат_индекс]
            разстояние = разстояния[рамо_индекс]
            if разстояние > ОБХВАТ_ВИСОЧИНИ * надпис.височина:
                добра = False
                break
            цена += разстояние
        if not добра:
            continue
        избор = tuple(кандидати[и][0] for и in наредба)
        вектор = tuple(н.стойност for н in избор)
        if вектор not in по_вектор or цена < по_вектор[вектор]:
            по_вектор[вектор] = цена
        if най_добро is None or цена < най_добро[1]:
            най_добро = (избор, цена)
    if най_добро is None:
        return None
    най_добър_вектор = tuple(н.стойност for н in най_добро[0])
    други = [ц for в, ц in по_вектор.items() if в != най_добър_вектор]
    цена = най_добро[1]
    if not други:
        запас = math.inf
    elif цена <= 0.0:
        запас = math.inf
    else:
        запас = min(други) / цена
    return най_добро[0], цена, запас


def _редът_е_съгласуван(
    рамена: Sequence[Рамо],
    стойности: Sequence[float],
) -> bool:
    """По-дългото начертано рамо не носи по-малко число от по-късо рамо."""

    for и in range(len(рамена)):
        for й in range(len(рамена)):
            if и == й:
                continue
            дълго, късо = рамена[и].дължина, рамена[й].дължина
            ако_равни = abs(дълго - късо) <= ДЯЛ_РАВНИ_РАМЕНА * max(дълго, късо)
            if ако_равни or дълго <= късо:
                continue
            if стойности[и] < стойности[й]:
                return False
    return True


