def присъда(
    опорни_handles: Sequence[str],
    указател: ВериженУказател,
    обявена_cm: float,
    *,
    очаквани_рамена: int | None = None,
    изключени_надписи: Sequence[str] = (),
    научени_стилове: Mapping[str, Mapping[str, Any]] | None = None,
    дневник: list | None = None,
) -> ВерижноДоказателство | None:
    """Отпечатаният производствен вектор на веригата или ``None`` при отказ.

    ``научени_стилове`` е {геометричен слой (главни букви): {"dimension_layer":
    …, "parallel_deg": …}} от приетите правила на паметта. Ползва се САМО ако
    неограниченият прочит вече е отказал, и само за да ОГРАНИЧИ кои текстове се
    гледат — вж. ``lion_rebar/learning/dimension_style.py``. Всички останали
    проверки, и най-вече точният сбор срещу обявената дължина, остават същите.
    """

    основна = _присъда_с_надписи(
        опорни_handles, указател, обявена_cm,
        очаквани_рамена=очаквани_рамена, изключени_надписи=изключени_надписи,
        дневник=дневник,
    )
    if основна is not None or not научени_стилове:
        return основна
    събрано = събери_веригата(опорни_handles, указател)
    if събрано is None:
        return None
    # Навикът без слой („*") важи за всеки слой и се слива с правилото за слоя.
    стил = {**dict(научени_стилове.get("*") or {}),
            **dict(научени_стилове.get(събрано[1].strip().upper()) or {})}
    if not стил:
        return None
    свит = указател
    описание: list[str] = []
    размерен = str(стил.get("dimension_layer") or "")
    if размерен:
        стеснен = свит.само_с_надписи_от(размерен)
        if len(стеснен.надписи) < len(свит.надписи):
            свит = стеснен
            описание.append("слой %s" % размерен)
    успоредно = стил.get("parallel_deg")
    if успоредно is not None:
        подредени = подреди_веригата(събрано[0])
        рамена = рамена_на_веригата(подредени) if подредени else None
        if рамена:
            стеснен = свит.само_с_успоредни_надписи(рамена, float(успоредно))
            if len(стеснен.надписи) < len(свит.надписи):
                свит = стеснен
                описание.append("успоредни до %g°" % float(успоредно))
    if not описание:
        return None
    втора = _присъда_с_надписи(
        опорни_handles, свит, обявена_cm,
        очаквани_рамена=очаквани_рамена, изключени_надписи=изключени_надписи,
    )
    if втора is None:
        return None
    return ВерижноДоказателство(
        **{**втора.__dict__, "научен_стил": " + ".join(описание)})


def _присъда_с_надписи(
    опорни_handles: Sequence[str],
    указател: ВериженУказател,
    обявена_cm: float,
    *,
    очаквани_рамена: int | None = None,
    изключени_надписи: Sequence[str] = (),
    дневник: list | None = None,
) -> ВерижноДоказателство | None:
    """Самото правило, върху надписите, които указателят дава."""

    try:
        обявена = float(обявена_cm)
    except (TypeError, ValueError):
        _запиши(дневник, "OBYAVENA_DALZHINA", repr(обявена_cm))
        return None
    if not math.isfinite(обявена) or обявена <= 0.0:
        _запиши(дневник, "OBYAVENA_DALZHINA", "%r" % обявена_cm)
        return None

    събрано = събери_веригата(опорни_handles, указател, дневник)
    if събрано is None:
        return None
    отсечки, слой = събрано
    подредени = подреди_веригата(отсечки, дневник)
    if подредени is None:
        return None
    сглобено = рамена_и_огъвки(подредени)
    if сглобено is None:
        _запиши(дневник, "SGLOBYAVANETO_PADNA")
        return None
    рамена, огъвки = сглобено
    if len(рамена) < 2:
        _запиши(дневник, "MALKO_RAMENA", "%d рамо" % len(рамена))
        return None
    if очаквани_рамена is not None and len(рамена) != очаквани_рамена:
        _запиши(дневник, "DRUG_BROY_RAMENA",
                "%d вместо %d" % (len(рамена), очаквани_рамена))
        return None

    кандидати = надписи_на_рамената(рамена, указател, изключени=изключени_надписи)
    избор = _най_добро_присвояване(рамена, кандидати)
    if избор is None:
        _запиши(дневник, "NYAMA_PRISVOYAVANE",
                "%d рамена, %d надписа" % (len(рамена), sum(len(к) for к in кандидати)))
        return None
    надписи, _цена, запас = избор
    if запас < ЗАПАС_НА_ПРИСВОЯВАНЕТО:
        _запиши(дневник, "MALAK_ZAPAS", "запас %.3f при искани %.2f"
                % (запас, ЗАПАС_НА_ПРИСВОЯВАНЕТО))
        return None

    стойности = tuple(н.стойност for н in надписи)
    if abs(sum(стойности) - обявена) > ДОПУСК_СБОР_CM:
        _запиши(дневник, "SBORAT_NE_ZATVARYA",
                "сбор %.2f при обявени %.2f" % (sum(стойности), обявена),
                printed_cm=list(стойности),
                dimension_text_handles=[н.handle for н in надписи],
                assignment_margin=round(запас, 4))
        return None
    if not _редът_е_съгласуван(рамена, стойности):
        _запиши(дневник, "REDAT_NE_E_SAGLASUVAN", str(list(стойности)))
        return None

    в_височини = 0.0
    for рамо_индекс, надпис in enumerate(надписи):
        разстояние = _разстояние_до_рамото(надпис.точка, рамена[рамо_индекс])
        в_височини = max(в_височини, разстояние / надпис.височина)

    геометрия = tuple(dict.fromkeys(h for рамо in рамена for h in рамо.handles))
    опорни = {str(з) for з in опорни_handles}
    добавени = tuple(h for h in геометрия if h not in опорни)
    return ВерижноДоказателство(
        участъци_cm=стойности,
        начертани_cm=tuple(рамо.дължина for рамо in рамена),
        завои_deg=tuple(завои_между_рамената(рамена)),
        огъвки=tuple(огъвки),
        геометрия_handles=геометрия,
        надписи_handles=tuple(н.handle for н in надписи),
        добавени_handles=добавени,
        обявена_cm=обявена,
        слой=слой,
        запас=запас,
        най_далечен_надпис_височини=в_височини,
    )


def уникално_притежание(присъди: Mapping[str, ВерижноДоказателство]) -> set[str]:
    """Кои позиции трябва да отпаднат, защото си делят надпис или геометрия.

    Един отпечатан размер принадлежи на ЕДИН прът. Ако два надписа стигнат до
    един и същ текст или до една и съща отсечка, и двете доказателства падат —
    близостта не решава кой е собственикът.
    """

    брой_текст: dict[str, int] = {}
    брой_геом: dict[str, int] = {}
    for доказателство in присъди.values():
        for handle in доказателство.надписи_handles:
            брой_текст[handle] = брой_текст.get(handle, 0) + 1
        for handle in доказателство.геометрия_handles:
            брой_геом[handle] = брой_геом.get(handle, 0) + 1
    падат: set[str] = set()
    for ключ, доказателство in присъди.items():
        if any(брой_текст.get(h, 0) > 1 for h in доказателство.надписи_handles):
            падат.add(ключ)
        elif any(брой_геом.get(h, 0) > 1 for h in доказателство.геометрия_handles):
            падат.add(ключ)
    return падат
