def _запиши(дневник, код: str, подробност: str = "", **данни: Any) -> None:
    """Записва причината за отказ, ако някой е поискал да я знае.

    ``данни`` носят числата на отказа, когато те сами са доказателство —
    напр. при ``SBORAT_NE_ZATVARYA`` отпечатаните размери, които са
    присвоени еднозначно на рамената, но не дават обявената дължина.
    """

    if дневник is None:
        return
    дневник.append({"code": код, "reason": ПРИЧИНИ.get(код, код),
                    "detail": подробност, **данни})

_ЧИСЛО = re.compile(r"^\s*\d{1,5}(?:[.,]\d{1,2})?\s*$")


@dataclass(frozen=True)
class Отсечка:
    """Примитив от чертежа: права или дъга, с краища и завой."""

    handle: str
    начало: tuple[float, float]
    край: tuple[float, float]
    bulge: float

    @property
    def дъга(self) -> bool:
        return abs(self.bulge) > 1e-9

    @property
    def хорда(self) -> float:
        return math.dist(self.начало, self.край)

    @property
    def завой_deg(self) -> float:
        """Ъгълът на завоя на дъгата със знак; 0 за права."""

        return 0.0 if not self.дъга else math.degrees(4.0 * math.atan(self.bulge))


@dataclass(frozen=True)
class Рамо:
    """Производствен участък: права (или слети колинеарни прави)."""

    начало: tuple[float, float]
    край: tuple[float, float]
    handles: tuple[str, ...]

    @property
    def дължина(self) -> float:
        return math.dist(self.начало, self.край)

    @property
    def посока_deg(self) -> float:
        return math.degrees(math.atan2(self.край[1] - self.начало[1],
                                       self.край[0] - self.начало[0]))


