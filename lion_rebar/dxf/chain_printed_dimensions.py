def _възел(точка: tuple[float, float]) -> tuple[int, int]:
    стъпка = ДОПУСК_ВРЪЗКА_CM
    return (int(round(точка[0] / стъпка)), int(round(точка[1] / стъпка)))


def събери_веригата(
    опорни: Sequence[str],
    указател: ВериженУказател,
    дневник: list | None = None,
) -> tuple[list[Отсечка], str] | None:
    """Транзитивното затваряне по съвпадащи краища в рамките на един слой."""

    опорни = [h for h in (str(з) for з in опорни) if h in указател.по_handle]
    if not опорни:
        _запиши(дневник, "NYAMA_OPORNI")
        return None
    слоеве = {указател.слой_на_handle.get(h, "") for h in опорни}
    if len(слоеве) != 1:
        # Прът, разпънат по два слоя, не се доказва оттук.
        _запиши(дневник, "DVA_SLOYA", ", ".join(sorted(слоеве)))
        return None
    слой = слоеве.pop()
    # Индексът по възел се строи ВЕДНЪЖ на слой и се пази: иначе всеки ред го
    # прави наново и цената става брой_редове × брой_отсечки.
    по_възел = указател.възли_на_слоя(слой)

    взети: dict[int, Отсечка] = {}
    за_обхождане: list[Отсечка] = []
    for handle in опорни:
        for отсечка in указател.по_handle[handle]:
            if id(отсечка) not in взети:
                взети[id(отсечка)] = отсечка
                за_обхождане.append(отсечка)
    while за_обхождане:
        текуща = за_обхождане.pop()
        for точка in (текуща.начало, текуща.край):
            ключ = _възел(точка)
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    for съседна in по_възел.get((ключ[0] + dx, ключ[1] + dy), ()):
                        if id(съседна) in взети:
                            continue
                        близо = min(math.dist(точка, съседна.начало),
                                    math.dist(точка, съседна.край))
                        if близо > ДОПУСК_ВРЪЗКА_CM:
                            continue
                        взети[id(съседна)] = съседна
                        за_обхождане.append(съседна)
                        if len(взети) > МАКС_ОТСЕЧКИ:
                            _запиши(дневник, "TVARDE_MNOGO_OTSECHKI",
                                    "над %d" % МАКС_ОТСЕЧКИ)
                            return None
    return list(взети.values()), слой


def подреди_веригата(отсечки: Sequence[Отсечка],
                    дневник: list | None = None) -> list[Отсечка] | None:
    """Прост отворен път или отказ. Връща отсечките в ред, ориентирани напред."""

    if not отсечки:
        return None
    възли: dict[tuple[int, int], list[tuple[int, int]]] = {}
    for индекс, отсечка in enumerate(отсечки):
        възли.setdefault(_възел(отсечка.начало), []).append((индекс, 0))
        възли.setdefault(_возел_край(отсечка), []).append((индекс, 1))
    краища = [в for в, списък in възли.items() if len(списък) == 1]
    претоварени = [в for в, списък in възли.items() if len(списък) > 2]
    if претоварени:
        _запиши(дневник, "RAZKLONENIE", "%d възела" % len(претоварени))
        return None
    if len(краища) != 2:
        _запиши(дневник, "PREKASVANE_ILI_PRIMKA", "%d свободни края" % len(краища))
        return None
    подредени: list[Отсечка] = []
    използвани: set[int] = set()
    текущ_възел = краища[0]
    while True:
        следващи = [(и, к) for и, к in възли.get(текущ_възел, ()) if и not in използвани]
        if not следващи:
            break
        индекс, край = следващи[0]
        отсечка = отсечки[индекс]
        използвани.add(индекс)
        if край == 0:
            подредени.append(отсечка)
            текущ_възел = _возел_край(отсечка)
        else:
            подредени.append(Отсечка(отсечка.handle, отсечка.край,
                                     отсечка.начало, -отсечка.bulge))
            текущ_възел = _възел(отсечка.начало)
    if len(подредени) != len(отсечки):
        _запиши(дневник, "NESVARZANI_PARCHETA",
                "подредени %d от %d" % (len(подредени), len(отсечки)))
        return None
    return подредени


def _возел_край(отсечка: Отсечка) -> tuple[int, int]:
    return _възел(отсечка.край)


def рамена_на_веригата(подредени: Sequence[Отсечка]) -> list[Рамо] | None:
    """Правите участъци; дъгите са огъвки. Колинеарните съседни прави се сливат."""

    резултат = рамена_и_огъвки(подредени)
    return None if резултат is None else резултат[0]


def рамена_и_огъвки(
    подредени: Sequence[Отсечка],
) -> tuple[list[Рамо], list[Огъвка]] | None:
    """Рамената И начинът, по който е начертана всяка огъвка между тях.

    ЗАЩО отделно: дали чертожникът е НАЧЕРТАЛ огъвката (допирателна дъга с
    радиус) или е оставил две прави да се срещнат в точка е единственото, което
    чертежът казва за самата огъвка. Дължината на рамото не казва нищо за
    ъгъла — разтеглено рамо може да запази посоката си, а рамо в мащаб не
    удостоверява ъгъла до себе си.
    """

    подредени = _свий_заобленията(подредени)
    рамена: list[Рамо] = []
    огъвки: list[Огъвка] = []
    текущи: list[Отсечка] = []
    висяща: Огъвка | None = None

    def затвори() -> None:
        nonlocal висяща
        if not текущи:
            return
        if рамена and висяща is not None:
            огъвки.append(висяща)
        рамена.append(Рамо(текущи[0].начало, текущи[-1].край,
                           tuple(dict.fromkeys(о.handle for о in текущи))))
        висяща = None
        текущи.clear()

    for отсечка in подредени:
        if отсечка.дъга:
            радиус = (отсечка.хорда
                      / (2.0 * math.sin(math.radians(abs(отсечка.завой_deg)) / 2.0))
                      if abs(отсечка.завой_deg) > 1e-9 else None)
            затвори()
            висяща = Огъвка(ДЪГА, отсечка.завой_deg, радиус)
            continue
        if текущи:
            предишна = текущи[-1]
            ъгъл_a = math.degrees(math.atan2(предишна.край[1] - предишна.начало[1],
                                             предишна.край[0] - предишна.начало[0]))
            ъгъл_b = math.degrees(math.atan2(отсечка.край[1] - отсечка.начало[1],
                                             отсечка.край[0] - отсечка.начало[0]))
            разлика = (ъгъл_b - ъгъл_a + 180.0) % 360.0 - 180.0
            if abs(разлика) > ДОПУСК_КОЛИНЕАРНОСТ_DEG:
                затвори()
                висяща = Огъвка(ОСТЪР, разлика, None)
        текущи.append(отсечка)
    затвори()
    if not рамена or len(рамена) > МАКС_РАМЕНА:
        return None
    if len(огъвки) != len(рамена) - 1:
        # Броят огъвки трябва да е с един по-малък от рамената; иначе редът е
        # неразбираем и правилото не бива да се произнася.
        return None
    return рамена, огъвки


def _свий_заобленията(подредени: Sequence[Отсечка]) -> list[Отсечка]:
    """Заобление от къси прави хорди → ЕДНА начертана дъга.

    Някои бюра чертаят огъвката не като дъга (bulge), а като поредица от
    къси прави отсечки. Без това всяка хорда тук е отделно „рамо“, рамената
    стават над ``МАКС_РАМЕНА`` и сглобяването пада — измерено на h01-1001
    (07.10.2026): 49 позиции с „рамената и огъвките не се сглобяват“, макар
    до всеки прът проектантът да е написал размерите на рамената.

    Кое е заобление решава ``shape_recognition.fillet_runs`` — същото правило,
    по което разпознаването вижда формата. Поредицата става дъга между двете
    допирателни точки със завоя между съседните рамена; рамената запазват
    начертаната си дължина. Без заобление списъкът се връща непроменен.
    """

    from lion_rebar.dxf.shape_recognition import fillet_runs

    изход: list[Отсечка] = []
    индекс = 0
    while индекс < len(подредени):
        if подредени[индекс].дъга:
            изход.append(подредени[индекс])
            индекс += 1
            continue
        край = индекс
        while край < len(подредени) and not подредени[край].дъга:
            край += 1
        блок = list(подредени[индекс:край])
        точки = [блок[0].начало] + [отсечка.край for отсечка in блок]
        следващ = 0
        for първа, последна, _пресечна in fillet_runs(точки):
            изход.extend(блок[следващ:първа])
            преди, след = блок[първа - 1], блок[последна + 1]
            посока_a = math.atan2(преди.край[1] - преди.начало[1],
                                  преди.край[0] - преди.начало[0])
            посока_b = math.atan2(след.край[1] - след.начало[1],
                                  след.край[0] - след.начало[0])
            завой = (посока_b - посока_a + math.pi) % (2.0 * math.pi) - math.pi
            изход.append(Отсечка(блок[първа].handle, блок[първа].начало,
                                 блок[последна].край, math.tan(завой / 4.0)))
            следващ = последна + 1
        изход.extend(блок[следващ:])
        индекс = край
    return изход


def завои_между_рамената(рамена: Sequence[Рамо]) -> list[float]:
    """Измереният завой между съседни рамена, със знак от начертаното."""

    изход: list[float] = []
    for предишно, следващо in zip(рамена, рамена[1:]):
        разлика = (следващо.посока_deg - предишно.посока_deg + 180.0) % 360.0 - 180.0
        изход.append(разлика)
    return изход


