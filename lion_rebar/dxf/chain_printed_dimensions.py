# -*- coding: utf-8 -*-
"""Производственият вектор от НАЧЕРТАНОТО: верига от свързани отсечки, всяка
със СВОЙ отпечатан размер.

## Защо съществува този модул

Досега програмата мери участъците само върху обектите, които matcher-ът е избрал
за надписа. Когато проектантът е начертал ПРЪТА КАТО НЯКОЛКО ОБЕКТА, останалите
участъци и техните собствени коти изобщо не се четат. Това е един и същ дефект в
два различни случая, и двата измерени:

* **F007 „S"-куките** (86 позиции в d-1, s-10, s-11, тест-004). Прътът е две
  полилинии, свързани в обща точка на разстояние 0,0000: `4B54` (право рамо
  10,383 + дъга) и `4B53` (право рамо 24,300 + дъга + право рамо 9,924).
  Програмата вижда само `4B53`, отчита ДВА производствени участъка и затова
  MASTER формата с ТРИ участъка не ѝ приляга. Цялата верига има три рамена и две
  огъвки по 135° — точно F007.
* **Двете куки на гредата** (`s-9/14736`, `s-9/14AE4`, `тест-006/D0CB`,
  `тест-006/D2D9`). Прътът е три отсечки `LINE` със споделени краища на
  разстояние 0,0000. Програмата взима две от трите и досмята остатъка 30 cm на
  едната кука. Проектантът е надписал и трите: 405 + 15 + 15 = 435.

## Какво прави правилото

Нищо не се измисля и нищо не се досмята. Всяко число идва от текст, написан от
проектанта; принадлежността на текста към рамото се доказва; сборът трябва да
излезе ТОЧНО обявената дължина.

1. **Веригата** — транзитивното затваряне по съвпадащи краища (`ДОПУСК_ВРЪЗКА_CM`),
   само в рамките на СЪЩИЯ слой. Веригата трябва да е прост отворен път: всеки
   вътрешен възел с точно две присъединени краища. Разклонение, примка или
   твърде дълга верига са отказ.
2. **Рамената** — правите участъци; дъгите са огъвки, а не рамена. Съседни
   колинеарни прави се сливат. Броят рамена трябва да съвпадне с MASTER формата.
3. **Собственият надпис** — чисто число на разстояние до
   `ОБХВАТ_ВИСОЧИНИ` × височината на текста от своето рамо. Измерено: истинските
   притежатели стоят на 0,30–1,40 височини; най-близкият чужд надпис в `s-9` е на
   2,7 височини. Надписът на самата позиция („2N8x435") не е чисто число и отпада.
4. **Присвояването** — пълно взаимно еднозначно съответствие рамо ↔ надпис с
   най-малък сбор от разстояния. Не „най-близкият за рамото": в `d-1` котата
   „20" на дългото рамо е по-близо до третото рамо (6,61), отколкото собствената
   му кота „10" (13,74), и само присвояването ги разделя вярно. Полученият
   ВЕКТОР трябва да е по-добър от най-добрия РАЗЛИЧЕН вектор със `ЗАПАС`.
5. **Сборът** — сумата на отпечатаните стойности трябва да е обявената дължина в
   границите на `ДОПУСК_СБОР_CM`. Това е независимата проверка: числата идват от
   котите, дължината идва от надписа на позицията.
6. **Съгласуваност на реда** — по-дългото начертано рамо не може да носи
   по-малко отпечатано число от по-късо рамо (извън лентата на равенството).
   Това хваща разменено присвояване, каквото сборът сам не би хванал.

## Какво правилото НЕ прави

* **не досмята остатък** — рамо без собствен надпис е отказ за цялата верига;
* **не вдига глобален допуск** — не пипа нито един съществуващ праг;
* **не мери начертаната дължина срещу отпечатаната** — символът нарочно не е в
  мащаб (MASTER F007: „кривината е схематична"; начертаното дълго рамо е 24,3 при
  отпечатани 20). Затова начертаното дава РЕДА и БРОЯ, а числата идват от котите;
* **не работи по име на файл, слой, handle или конкретен размер.**
"""
