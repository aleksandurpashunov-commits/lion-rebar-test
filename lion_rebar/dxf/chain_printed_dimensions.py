def _точка(стойност: Any) -> tuple[float, float] | None:
    if not isinstance(стойност, (list, tuple)) or len(стойност) < 2:
        return None
    try:
        x, y = float(стойност[0]), float(стойност[1])
    except (TypeError, ValueError):
        return None
    return (x, y) if math.isfinite(x) and math.isfinite(y) else None


def отсечки_на_обекта(запис: Any) -> list[Отсечка]:
    """Примитивите на един DXF обект. Празен списък = обектът не е верижен."""

    вид = str(getattr(запис, "entity_type", "") or "").upper()
    геометрия = getattr(запис, "geometry", None) or {}
    handle = str(getattr(запис, "handle", "") or "")
    if вид == "LINE":
        начало, край = _точка(геометрия.get("start")), _точка(геометрия.get("end"))
        if начало is None or край is None or math.dist(начало, край) <= 0.0:
            return []
        return [Отсечка(handle, начало, край, 0.0)]
    if вид not in {"LWPOLYLINE", "POLYLINE"}:
        return []
    сурови = геометрия.get("points")
    if not isinstance(сурови, (list, tuple)) or len(сурови) < 2:
        return []
    явни = геометрия.get("bulges")
    има_явни = isinstance(явни, (list, tuple))
    върхове: list[tuple[tuple[float, float], float]] = []
    for индекс, суров in enumerate(сурови):
        точка = _точка(суров)
        if точка is None:
            return []
        if има_явни and индекс < len(явни):
            try:
                bulge = float(явни[индекс])
            except (TypeError, ValueError):
                bulge = 0.0
        elif isinstance(суров, (list, tuple)) and len(суров) >= 3:
            try:
                bulge = float(суров[2])
            except (TypeError, ValueError):
                bulge = 0.0
        else:
            bulge = 0.0
        върхове.append((точка, bulge if math.isfinite(bulge) else 0.0))
    if bool(геометрия.get("closed")):
        # Затворен контур не е отворена верига — с него работят други правила.
        return []
    изход = []
    for индекс in range(len(върхове) - 1):
        (точка, bulge), (следваща, _) = върхове[индекс], върхове[индекс + 1]
        if math.dist(точка, следваща) <= 0.0:
            continue
        изход.append(Отсечка(handle, точка, следваща, bulge))
    return изход


def _число_от_текст(текст: str | None) -> float | None:
    if not текст:
        return None
    ако = _ЧИСЛО.match(текст)
    if ако is None:
        return None
    try:
        стойност = float(текст.strip().replace(",", "."))
    except ValueError:
        return None
    return стойност if math.isfinite(стойност) and стойност > 0 else None


@dataclass(frozen=True)
class Надпис:
    handle: str
    стойност: float
    точка: tuple[float, float]
    височина: float
    слой: str
    #: Ъгълът, под който е изписан текстът. Проектантът често пише размера
    #: УСПОРЕДНО на рамото, което е независим признак за принадлежност.
    ротация: float = 0.0


class ВериженУказател:
    """Подготвен веднъж за целия чертеж: отсечки по слой и числови надписи."""

    def __init__(self, entities: Iterable[Any]) -> None:
        self.по_handle: dict[str, list[Отсечка]] = {}
        self.по_слой: dict[str, list[Отсечка]] = {}
        self.слой_на_handle: dict[str, str] = {}
        self.надписи: list[Надпис] = []
        self._възли: dict[str, dict[tuple[int, int], list[Отсечка]]] = {}
        for запис in entities:
            handle = str(getattr(запис, "handle", "") or "")
            слой = str(getattr(запис, "layer", "") or "")
            вид = str(getattr(запис, "entity_type", "") or "").upper()
            if вид in {"TEXT", "MTEXT"}:
                стойност = _число_от_текст(getattr(запис, "text", None))
                if стойност is None:
                    continue
                геометрия = getattr(запис, "geometry", None) or {}
                точка = _точка(геометрия.get("insert"))
                if точка is None:
                    continue
                try:
                    височина = float(геометрия.get("height")
                                     or геометрия.get("estimated_text_height") or 0.0)
                except (TypeError, ValueError):
                    височина = 0.0
                if not math.isfinite(височина) or височина <= 0.0:
                    continue
                try:
                    ротация = float(геометрия.get("rotation") or 0.0)
                except (TypeError, ValueError):
                    ротация = 0.0
                if not math.isfinite(ротация):
                    ротация = 0.0
                self.надписи.append(
                    Надпис(handle, стойност, точка, височина, слой, ротация))
                continue
            части = отсечки_на_обекта(запис)
            if not части:
                continue
            self.по_handle[handle] = части
            self.слой_на_handle[handle] = слой
            self.по_слой.setdefault(слой, []).extend(части)

    def възли_на_слоя(self, слой: str) -> dict[tuple[int, int], list[Отсечка]]:
        """Отсечките на слоя, подредени по възел. Строи се веднъж и се пази."""

        готово = self._възли.get(слой)
        if готово is not None:
            return готово
        индекс: dict[tuple[int, int], list[Отсечка]] = {}
        for отсечка in self.по_слой.get(слой) or ():
            for точка in (отсечка.начало, отсечка.край):
                индекс.setdefault(_възел(точка), []).append(отсечка)
        self._възли[слой] = индекс
        return индекс

    def само_с_успоредни_надписи(
        self, рамена: "Sequence[Рамо]", допуск_deg: float,
    ) -> "ВериженУказател":
        """Само надписите, изписани УСПОРЕДНО на най-близкото си рамо.

        Ъглите се сравняват по модул 180°: текстът е успореден на рамото и
        когато е завъртян на 180° спрямо него.
        """

        избрани = []
        for надпис in self.надписи:
            най = min(рамена, key=lambda р: _разстояние_до_рамото(надпис.точка, р))
            ъгъл = най.посока_deg % 180.0
            текст = надпис.ротация % 180.0
            разлика = min(abs(текст - ъгъл), 180.0 - abs(текст - ъгъл))
            if разлика <= допуск_deg:
                избрани.append(надпис)
        свит = ВериженУказател.__new__(ВериженУказател)
        свит.по_handle = self.по_handle
        свит.по_слой = self.по_слой
        свит.слой_на_handle = self.слой_на_handle
        свит._възли = self._възли
        свит.надписи = избрани
        return свит

    def само_с_надписи_от(self, слой: str) -> "ВериженУказател":
        """Същата геометрия, но само числовите надписи от този слой.

        Геометрията и индексът по възли се СПОДЕЛЯТ — стеснява се единствено
        списъкът с надписи.
        """

        свит = ВериженУказател.__new__(ВериженУказател)
        свит.по_handle = self.по_handle
        свит.по_слой = self.по_слой
        свит.слой_на_handle = self.слой_на_handle
        свит._възли = self._възли
        свит.надписи = [н for н in self.надписи if н.слой == слой]
        return свит


