# -*- coding: utf-8 -*-
"""Кога кандидат става ПРИЕТО ПРАВИЛО — изчислено, не твърдо нула.

## Защо съществува този модул

До 30.09.2026 `learning_pack` пишеше `activated_rule_count = 0` като **литерал**
на три места, а тест го пазеше (`test_pack_reports_candidates_but_activates_no_rule`).
Тоест механизмът беше изключен по конструкция: колкото и доказателства да се
натрупат, числото оставаше нула и никой не можеше да види какво точно липсва.

Собственик, 30.09.2026: „Разрешавам активирането на този механизъм в
експерименталната версия. Не го оставяй постоянно изключен чрез
`activated_rule_count = 0`. Запази изключения режим като валидна контролна
конфигурация."

И за самото право на автоматично прилагане (ниво В): „Автоматично прилагане е
допустимо само в изрично описан обхват, с проверими условия, отрицателни примери
и успешно преминаване на независимите проверки на текущия случай. Повторенията
сами по себе си не дават това право."

## Критериите, всеки проверим от данните на кандидата

| критерий | код на спирачката | какво се иска |
|---|---|---|
| без противоречиви етикети | `CONFLICT` | еднакви условия не водят до различни решения |
| поне два НЕЗАВИСИМИ свидетеля | `ONE_WITNESS` | брои се независимо наблюдение, не повторение на същото |
| определен обхват | `NO_SCOPE` | проектна конвенция, семейна конвенция или общо правило |
| преминал одит и регресия | `NO_AUDIT` | записана присъда, не обещание |
| обхватът на прилагане да е доказан | `SCOPE_NOT_PROVEN` | общо правило иска ≥ 2 различни семейства |

**Повторенията не са критерий.** `repeat_count` нарочно не участва: двайсет
повторения на един и същ чертеж остават един свидетел.

## Изключеният режим остава валиден

`LION_REBAR_RULE_ACTIVATION=off` връща нула активирани и записва режима в
изхода. Това е контролната конфигурация за опита — не мъртъв код, а обявено
състояние, което се сравнява с включеното.

## Какво този модул НЕ прави

* не прилага правило — само казва има ли право;
* не чете и не пише хранилище;
* не съдържа име на проект, слой или конкретен размер.
"""
from __future__ import annotations

import os
from typing import Any, Mapping

#: Колко независими свидетеля са минимум. Числото не е ново: то е същото, което
#: обучителите ползват (`MIN_FAMILIES_TO_ACCEPT`, `НУЖНИ_СЕМЕЙСТВА`). Сменено е
#: КАКВО се брои — независими групи, не имена на файлове.
МИН_НЕЗАВИСИМИ_СВИДЕТЕЛИ = 2

#: Обхватите, подредени от най-тесен към най-широк. Най-тесният доказан обхват
#: печели — извън него правилото дава предложение или отказ.
ПОЗИЦИЯ = "POSITION_DECISION"
ПРОЕКТНА = "PROJECT_CONVENTION"
СЕМЕЙНА = "FAMILY_CONVENTION"
ОБЩА = "GENERAL_RULE"

ИЗКЛЮЧЕНО = {"0", "off", "no", "false", "изкл", "изключено"}


def активирането_е_включено() -> bool:
    """Дали активирането важи. По подразбиране: да."""

    стойност = str(os.environ.get("LION_REBAR_RULE_ACTIVATION") or "").strip().lower()
    if not стойност:
        return True
    return стойност not in ИЗКЛЮЧЕНО


def обхват_на_кандидата(кандидат: Mapping[str, Any]) -> str | None:
    """Най-тесният обхват, който доказателството на кандидата поддържа."""

    семейства = int(кандидат.get("independent_drawing_family_count") or 0)
    проекти = int(кандидат.get("project_count") or 0)
    наблюдения = int(кандидат.get("independent_observation_count") or 0)
    if bool(кандидат.get("per_position")):
        return ПОЗИЦИЯ
    if семейства >= 2 and наблюдения >= МИН_НЕЗАВИСИМИ_СВИДЕТЕЛИ:
        return ОБЩА
    if наблюдения >= МИН_НЕЗАВИСИМИ_СВИДЕТЕЛИ and проекти >= 2:
        return СЕМЕЙНА
    if наблюдения >= 1 and проекти >= 1:
        return ПРОЕКТНА
    return None


def присъда(кандидат: Mapping[str, Any]) -> dict[str, Any]:
    """Има ли този кандидат право на автоматично прилагане, и ако не — защо."""

    режим_включен = активирането_е_включено()
    спирачки: list[str] = []

    if bool(кандидат.get("has_conflicting_labels")):
        спирачки.append("CONFLICT")
    наблюдения = int(кандидат.get("independent_observation_count") or 0)
    if наблюдения < МИН_НЕЗАВИСИМИ_СВИДЕТЕЛИ:
        спирачки.append("ONE_WITNESS")
    обхват = обхват_на_кандидата(кандидат)
    if обхват is None:
        спирачки.append("NO_SCOPE")
    elif обхват == ОБЩА and int(кандидат.get("independent_drawing_family_count") or 0) < 2:
        спирачки.append("SCOPE_NOT_PROVEN")
    # Одитът и регресията са ЗАПИСАНА присъда, не обещание. Полето се пълни от
    # онова, което е изпълнило проверките — затова липсата му е спирачка, а не
    # мълчание.
    одит = кандидат.get("audit_and_regression")
    минал_одит = bool(isinstance(одит, Mapping) and одит.get("passed"))
    if not минал_одит:
        спирачки.append("NO_AUDIT")

    активиран = режим_включен and not спирачки
    изход: dict[str, Any] = {
        "schema": "lion-rebar-rule-activation/v1",
        "activated": активиран,
        "mode": "ON" if режим_включен else "OFF_CONTROL_CONFIGURATION",
        "scope": обхват,
        "independent_witnesses": наблюдения,
        "independent_families": int(кандидат.get("independent_drawing_family_count") or 0),
        "blocked_by": спирачки,
    }
    if not режим_включен:
        изход["blocked_by"] = [*спирачки, "ACTIVATION_DISABLED"]
        изход["activated"] = False
    изход["explanation"] = _обяснение(изход)
    return изход


def _обяснение(присъда_: Mapping[str, Any]) -> str:
    if присъда_.get("activated"):
        return ("правилото има право на автоматично прилагане в обхват %s, при %d "
                "независими свидетеля" % (присъда_.get("scope"),
                                          присъда_.get("independent_witnesses")))
    причини = {
        "CONFLICT": "еднакви условия водят до различни решения",
        "ONE_WITNESS": "един свидетел — повторенията не са второ доказателство",
        "NO_SCOPE": "обхватът не е определен от доказателството",
        "SCOPE_NOT_PROVEN": "общо правило иска поне две различни семейства",
        "NO_AUDIT": "липсва записана присъда от одит и регресия",
        "ACTIVATION_DISABLED": "активирането е изключено (контролна конфигурация)",
    }
    изброени = "; ".join(причини.get(к, к) for к in присъда_.get("blocked_by") or ())
    return "без право на автоматично прилагане: %s" % (изброени or "неизвестна причина")


def обобщи(кандидати) -> dict[str, Any]:
    """Присъда за всеки кандидат + броевете за обобщението на пакета."""

    присъди = [присъда(к) for к in кандидати]
    по_спирачка: dict[str, int] = {}
    for п in присъди:
        for к in п.get("blocked_by") or ():
            по_спирачка[к] = по_спирачка.get(к, 0) + 1
    return {
        "verdicts": присъди,
        "activated_rule_count": sum(1 for п in присъди if п.get("activated")),
        "candidate_count": len(присъди),
        "mode": "ON" if активирането_е_включено() else "OFF_CONTROL_CONFIGURATION",
        "blocked_by_counts": по_спирачка,
    }


