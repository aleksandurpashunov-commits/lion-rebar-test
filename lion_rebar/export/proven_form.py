# -*- coding: utf-8 -*-
"""Коя форма отива в производството и **откъде идва всеки ъгъл**.

## Продуктовият договор

* **Стандартният режим е „По проекта“.** Извлича се доказаната проектна форма и
  се възпроизвежда.
* **MASTER помага за съвместими шаблони, но НЕ заменя различна геометрия** заради
  сходно име, силует или обща дължина.
* **„Уговорена производствена форма“ е отделен режим, изключен по подразбиране.**

## Какво беше грешно и е махнато

По-ранната редакция правеше така: *„ако някое рамо е извън 8 % от отпечатания си
размер → вземи ъглите от MASTER“*. Това е **необоснована зависимост** и е
премахната. Тя е грешна и в двете си части:

* **разтеглено рамо може да запази посоката си** — на `d-1` средното рамо е
  начертано 24,30 при отпечатани 20, но огъвките от двете му страни са
  начертани като дъги с радиус 1,500 и завой точно 135,00°. Извън мащаб не
  значи „ъгълът е грешен“;
* **и обратното: MASTER няма как да се докаже от една дължина.** Несъответна
  дължина не е основание да се вземат ЧУЖДИ ъгли. Когато чертежът не установява
  ъгъла, той просто не е установен — не се взима отникъде.

## Какво ОСТАВА вход, и защо това не е същото

Мащабът се ползва САМО като **положително** доказателство за местната вярност на
чертежа, и никога като спусък към MASTER:

    и двете съседни рамена са начертани в мащаб
        → чертежът е верен на това място
        → начертаният завой е ИЗМЕРВАНЕ, а не какъвто се е получил

Това дава ``ИЗВЛЕЧЕНА`` — *надеждно извлечена посока*, изрично по-слабо от
``ОРАЗМЕРЕН``. Не е „правилните дължини удостоверяват ъгъла“: сами по себе си не
го удостоверяват и затова състоянието не е обявено за оразмерено. Твърдението е
по-тясно — че на място, където чертежът е проверимо в мащаб, начертаната посока
е данна от чертежа.

Измерено върху корпуса: **84 от 132** позиции, които иначе оставаха неразрешени,
са начертани в мащаб до 0,22 cm и носят точно ±90,00° остри ъгли (`s-9/14723`,
участъци [25; 405; 25] при начертани [25,0; 404,78; 25,0]). Останалите 48 имат
поне едно рамо извън мащаб — типично куката, начертана 23,18 при отпечатани 15 —
и си остават неразрешени, освен ако правило в обхват ги покрива.

## Какво се проверява сега

За **всяка огъвка поотделно** се решава откъде идва ъгълът ѝ:

| състояние | кога | какво дава |
|---|---|---|
| ``ОРАЗМЕРЕН`` | проектантът е надписал ъгъла (ъглова кота, собствена на върха) | измерения ъгъл |
| ``ИЗВЛЕЧЕНА`` | чертожникът е **НАЧЕРТАЛ** огъвката: допирателна дъга с радиус, ИЛИ остър ъгъл между две рамена, начертани в мащаб | начертания завой |
| ``ПО_ПРАВИЛО`` | остър ъгъл, но има **одобрено инженерно правило В ОБХВАТА СИ** | ъгъла на правилото, с името му |
| ``НЕРАЗРЕШЕН`` | нищо от горните | **нищо** — оригиналната форма отива за преглед |

Формата е доказана само когато ВСИЧКИ ѝ огъвки са доказани. При неразрешена
огъвка **не се произвежда предполагаем ъгъл**: записва се точно какво липсва.

Измерено върху двата истински случая:

* `d-1/4B5B` „Есове“ — две `DRAFTED_ARC`, радиус 1,500 при Ø6 (2,5·d), завои
  −135,00° и +135,00° → **ИЗВЛЕЧЕНА**. Начертаното е S/Z, не C;
* `s-9/14736` двете куки — две `SHARP_CORNER` при 27,24° и 152,76°; куката е
  начертана 23,18 при отпечатани 15 (+54,5 %), а вертикалната ѝ проекция е точно
  15·sin45°. Рамото до огъвката НЕ е в мащаб, значи ъгълът НЕ е измерване. Има
  обаче одобрено правило `BEAM_ENGINEERING_90_F003` в обхвата си →
  **ПО_ПРАВИЛО**, 90°/90°;
* `s-9/14723` — участъци [25; 405; 25], начертани [25,0; 404,78; 25,0], завои
  −90,00° и −90,00°. И трите рамена са в мащаб → **ИЗВЛЕЧЕНА**, без MASTER.

## Какво този модул НЕ прави

* не мени участъците — те са доказани другаде;
* не взима ъгли от MASTER по подразбиране;
* не одобрява и не блокира позиция — дава присъда и я записва;
* не твърди приложим стандарт за радиуса. ``МАКС_РАДИУС_НА_ДИАМЕТЪР`` е само
  граница срещу безсмислици (дъга с радиус 20·d при завой 135° не е огъвка), а
  не изискване за минимален дорник.
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import Any, Mapping, Sequence

#: Стандартният режим: производството следва доказаното от проекта.
РЕЖИМ_ПРОЕКТ = "PROEKT"

#: Отделната настройка: уговорена производствена форма. Иска определен обхват и
#: основание; не се включва по подразбиране и не важи глобално.
РЕЖИМ_УГОВОРЕНА = "UGOVORENA_FORMA"

РЕЖИМИ = (РЕЖИМ_ПРОЕКТ, РЕЖИМ_УГОВОРЕНА)

ОРАЗМЕРЕН = "DIMENSIONED_ANGLE"
ИЗВЛЕЧЕНА = "DERIVED_DIRECTION"
ПО_ПРАВИЛО = "APPROVED_RULE"
НЕРАЗРЕШЕН = "UNRESOLVED"

#: Подредба по сила: по-ранното е по-силно доказателство.
СИЛА = (ОРАЗМЕРЕН, ИЗВЛЕЧЕНА, ПО_ПРАВИЛО, НЕРАЗРЕШЕН)

#: Горна граница за радиуса на огъвката, в диаметри. Само срещу безсмислици:
#: „огъвка“ с радиус 20 диаметъра при завой 135° е крива, не огъвка. НЕ е
#: изискване за минимален дорник и не твърди приложим стандарт.
МАКС_РАДИУС_НА_ДИАМЕТЪР = 20.0

#: Разминаване между измерения и шаблонния завой, над което се пише бележка.
ЗНАЧИМО_РАЗМИНАВАНЕ_DEG = 5.0

ПОЛЕ = "proven_form"


@dataclass(frozen=True)
class ОгъвкаПрисъда:
    """Откъде идва ъгълът на ЕДНА огъвка."""

    индекс: int
    състояние: str
    ъгъл_deg: float | None
    начертан_deg: float
    начертана_като: str
    радиус_cm: float | None
    радиус_на_диаметър: float | None
    правило: str
    липсва: str

    def as_dict(self) -> dict[str, Any]:
        return {
            "index": self.индекс,
            "state": self.състояние,
            "angle_deg": (None if self.ъгъл_deg is None
                          else round(self.ъгъл_deg, 4)),
            "drawn_turn_deg": round(self.начертан_deg, 4),
            "drawn_as": self.начертана_като,
            "radius_cm": (None if self.радиус_cm is None
                          else round(self.радиус_cm, 4)),
            "radius_per_diameter": (None if self.радиус_на_диаметър is None
                                    else round(self.радиус_на_диаметър, 3)),
            "rule": self.правило,
            "missing": self.липсва,
        }


@dataclass(frozen=True)
class ДоказанаФорма:
    """Производствената форма и произходът на всяко число."""

    участъци_cm: tuple[float, ...]
    ъгли_deg: tuple[float, ...]
    състояние: str
    режим: str
    огъвки: tuple[ОгъвкаПрисъда, ...]
    начертани_cm: tuple[float, ...]
    в_мащаб: tuple[bool, ...]
    шаблонни_ъгли_deg: tuple[float, ...]
    разминаване_deg: float | None
    бележки: tuple[str, ...] = field(default_factory=tuple)

    @property
    def доказана(self) -> bool:
        return self.състояние != НЕРАЗРЕШЕН and len(self.ъгли_deg) == len(
            self.участъци_cm) - 1

    def as_dict(self) -> dict[str, Any]:
        return {
            "segments_cm": list(self.участъци_cm),
            "turn_angles_deg": [round(с, 4) for с in self.ъгли_deg],
            "state": self.състояние,
            "proven": self.доказана,
            "mode": self.режим,
            "bends": [о.as_dict() for о in self.огъвки],
            "drawn_lengths_cm": [round(с, 4) for с in self.начертани_cm],
            "legs_to_scale": list(self.в_мащаб),
            "template_turn_angles_deg": [round(с, 4) for с in self.шаблонни_ъгли_deg],
            "template_disagreement_deg": (
                None if self.разминаване_deg is None
                else round(self.разминаване_deg, 4)),
            "notes": list(self.бележки),
        }


def режим_от_настройките(policy: Any | None = None) -> str:
    """Режимът: от политиката, с променлива на средата за измерване."""

    import os

    от_средата = str(os.environ.get("LION_REBAR_FORMA_REZHIM") or "").strip().upper()
    if от_средата in РЕЖИМИ:
        return от_средата
    от_политиката = str(
        getattr(policy, "production_form_mode", "") or ""
    ).strip().upper()
    return от_политиката if от_политиката in РЕЖИМИ else РЕЖИМ_ПРОЕКТ


#: Кога едно рамо се брои за начертано В МАЩАБ. Ползва се САМО като
#: положително доказателство за местната вярност на чертежа.
ДОПУСК_МАЩАБ = 0.08
КЪСО_РАМО_CM = 12.0
ДОПУСК_КЪСО_CM = 1.0


#: Производствените ъгли, които ЗАКЛЮЧЕНАТА библиотека познава. Прочетени от
#: `lion-rebar-master 0.3.15` (`shape_image.shape_turn_angles_deg` върху
#: формите със състояние LOCKED/APPROVED), не измислени. Сменят се заедно с
#: engine-а: ``за_реда`` подава живия набор, когато има достъп до формите.
ПРОИЗВОДСТВЕНИ_ЪГЛИ = (29.0, 45.0, 90.0, 135.0)

#: Колко може да се отклони начертан завой от производствен ъгъл, за да се
#: приеме за посока. Измерено: реалните 84 позиции падат на 0,0006° от кръгъл
#: ъгъл, а най-близкият контрапример е на 1,76°.
ПРОЗОРЕЦ_DEG = 1.0



def завоят_е_производствен(завой: float, набор=None) -> bool:
    """Пада ли начертаният завой до ``ПРОЗОРЕЦ_DEG`` от производствен ъгъл."""

    ъгли = tuple(набор) if набор else ПРОИЗВОДСТВЕНИ_ЪГЛИ
    if not ъгли:
        return False
    try:
        м = abs(float(завой))
    except (TypeError, ValueError):
        return False
    return any(abs(м - abs(float(а))) <= ПРОЗОРЕЦ_DEG for а in ъгли)


def рамото_е_в_мащаб(начертано: float | None, отпечатано: float | None) -> bool:
    """Съвпада ли начертаната дължина с отпечатаната."""

    try:
        н, о = float(начертано), float(отпечатано)
    except (TypeError, ValueError):
        return False
    if not (math.isfinite(н) and math.isfinite(о)) or о <= 0:
        return False
    if о < КЪСО_РАМО_CM:
        return abs(н - о) <= ДОПУСК_КЪСО_CM
    return abs(н - о) / о <= ДОПУСК_МАЩАБ


def рамото_удостоверява_посока(начертано: float | None,
                               отпечатано: float | None) -> bool:
    """Достатъчно точно ли е начертано рамото, за да носи ПОСОКА.

    ``рамото_е_в_мащаб`` отговаря на друг въпрос — „в мащаб ли е чертежът тук" —
    и затова под ``КЪСО_РАМО_CM`` минава на абсолютен под ±``ДОПУСК_КЪСО_CM``.
    В относителни числа този под се разхлабва: при 10 cm е 10 %, при 5 cm —
    20 %, докато дългото рамо се мери с 8 %.

    Посоката не бива да се удостоверява по-леко там, където геометрията е
    по-малка. Измерено: контрапримерът КП-5 е построен точно върху тази хлабина
    — рамо 5 cm, начертано 4,0014 cm (19,97 %), минава абсолютния под и прави
    прав ъгъл на 124,15°. Същевременно петте реални `F009` в `тест-006` имат
    рамо 10 cm, начертано с отклонение 0,0000 cm.

    Затова тук се иска ЕДИН и същ ОТНОСИТЕЛЕН допуск при всяка дължина. Нов
    допуск не се въвежда: взима се вече решеният ``ДОПУСК_МАЩАБ``.
    """

    try:
        н, о = float(начертано), float(отпечатано)
    except (TypeError, ValueError):
        return False
    if not (math.isfinite(н) and math.isfinite(о)) or о <= 0:
        return False
    return abs(н - о) / о <= ДОПУСК_МАЩАБ


def _радиусът_е_правдоподобен(радиус_cm: float | None,
                              диаметър_mm: float | None) -> tuple[bool, float | None]:
    if радиус_cm is None or радиус_cm <= 0:
        return False, None
    if not диаметър_mm or диаметър_mm <= 0:
        return True, None          # без диаметър не се съди; дъгата пак е начертана
    отношение = радиус_cm / (float(диаметър_mm) / 10.0)
    return отношение <= МАКС_РАДИУС_НА_ДИАМЕТЪР, отношение


def класифицирай_огъвка(
    индекс: int,
    огъвка: Mapping[str, Any],
    *,
    диаметър_mm: float | None = None,
    оразмерен_ъгъл_deg: float | None = None,
    правило: str = "",
    ъгъл_по_правило_deg: float | None = None,
    съседните_рамена_са_в_мащаб: bool = False,
    съседните_рамена_удостоверяват_посока: bool = False,
    производствени_ъгли=None,
) -> ОгъвкаПрисъда:
    """Откъде идва ъгълът на една огъвка — по реда на силата на доказателството."""

    from lion_rebar.dxf.chain_printed_dimensions import ДЪГА

    начертан = float(огъвка.get("turn_deg") or 0.0)
    вид = str(огъвка.get("kind") or "")
    радиус = огъвка.get("radius_cm")
    радиус = None if радиус is None else float(радиус)
    правдоподобен, отношение = _радиусът_е_правдоподобен(радиус, диаметър_mm)

    if оразмерен_ъгъл_deg is not None:
        return ОгъвкаПрисъда(
            индекс, ОРАЗМЕРЕН, float(оразмерен_ъгъл_deg), начертан, вид,
            радиус, отношение, "", "")
    if вид == ДЪГА and правдоподобен:
        return ОгъвкаПрисъда(
            индекс, ИЗВЛЕЧЕНА, начертан, начертан, вид, радиус, отношение, "", "")
    if правило and ъгъл_по_правило_deg is not None:
        # ОДОБРЕНОТО ПРАВИЛО стои ПРЕД начертания остър ъгъл. Символът не бива
        # да изхвърля правило в обхват: измерено на `s-9/14736`, 0,1 mm
        # начертана кука местеше производствения ъгъл с 62,76°.
        #
        # Начертаната ДЪГА остава НАД правилото (клонът по-горе) — тя е
        # доказаната проектна форма, а правилото е обобщение.
        #
        # ЗНАКЪТ (посоката на огъване) остава от правилото — НЕ е решено да идва
        # от чертежа. Записано на 29.09.2026 след независим преглед, за да не се
        # преоткрива:
        #
        # * Измерено: **17 реда** (`s-9` 8, `тест-006` 9, всички F003 по
        #   `U_PROPORTION_F003`) минаха от `[−90, −90]` на `[+90, +90]` между
        #   прогоните от 14:2x и 17:2x. Твърдението „0 сменени ъгъла от 236 реда"
        #   в отчета на предишната сесия е НЕВЯРНО: сравнението четеше ъгъла на
        #   правилото от `canonical_turn_angles_deg`, който дотогава вече е
        #   презаписан — не можеше да даде друго освен нула.
        # * Измерено: при **51 от 142** реда в `s-9` и `тест-006` знакът на
        #   правилото се различава от начертания.
        # * Докъде стига знакът: Excel го изхвърля (`abs()` на три места в
        #   `excel_export.py`), проверката `_turns_contradict_shape` също сравнява
        #   по абсолютна стойност. Тоест НИТО ЕДНО число в експорта не зависи от
        #   него. Стига само до посоката на РИСУНКАТА на формата.
        # * Затова не се пипа: за симетрично „П" огледалният образ е конгруентен,
        #   а за несиметрична форма (F007 `(−90, −135)`, F009, F012, F021) въпросът
        #   „символът да показва ли начертаната хиралност" е продуктов и иска
        #   решение на собственика. Рисунката не може да се провери тук — рендерът
        #   не върви в тази среда.
        return ОгъвкаПрисъда(
            индекс, ПО_ПРАВИЛО, float(ъгъл_по_правило_deg), начертан, вид,
            радиус, отношение, правило, "")
    if (вид != ДЪГА and съседните_рамена_са_в_мащаб
            and съседните_рамена_удостоверяват_посока
            and завоят_е_производствен(начертан, производствени_ъгли)):
        # Остър ъгъл, но чертежът е ВЕРЕН на това място: и двете съседни рамена
        # съвпадат с отпечатаните си размери. Тогава начертаният завой е
        # измерване, а не какъвто се е получил.
        return ОгъвкаПрисъда(
            индекс, ИЗВЛЕЧЕНА, начертан, начертан, вид, радиус, отношение, "", "")
    липсва = (
        "огъвката е начертана като остър ъгъл между две прави и поне едно от "
        "съседните рамена НЕ е в мащаб — начертаният завой %.2f° е какъвто се е "
        "получил, не измерен; няма нито ъглова кота, нито одобрено правило в "
        "обхват" % начертан
        if вид != ДЪГА else
        "дъгата има радиус %s, който не е правдоподобен за огъвка при този "
        "диаметър" % ("няма" if радиус is None else "%.3f cm" % радиус)
    )
    return ОгъвкаПрисъда(
        индекс, НЕРАЗРЕШЕН, None, начертан, вид, радиус, отношение, "", липсва)


def реши(
    *,
    участъци_cm: Sequence[float],
    начертани_cm: Sequence[float],
    огъвки: Sequence[Mapping[str, Any]],
    шаблонни_ъгли_deg: Sequence[float] = (),
    диаметър_mm: float | None = None,
    оразмерени_ъгли_deg: Sequence[float | None] = (),
    правило: str = "",
    ъгли_по_правило_deg: Sequence[float] = (),
    режим: str = РЕЖИМ_ПРОЕКТ,
    производствени_ъгли=None,
) -> ДоказанаФорма:
    """Производствената форма и произходът на всеки ъгъл."""

    участъци = tuple(float(с) for с in участъци_cm)
    начертани = tuple(float(с) for с in начертани_cm)
    шаблонни = tuple(float(с) for с in шаблонни_ъгли_deg)
    по_правило = tuple(float(с) for с in ъгли_по_правило_deg)
    оразмерени = tuple(оразмерени_ъгли_deg) if оразмерени_ъгли_deg else ()

    в_мащаб = tuple(
        рамото_е_в_мащаб(н, о) for н, о in zip(начертани, участъци)
    ) if len(начертани) == len(участъци) else ()
    # Посоката се удостоверява с ЕДИН относителен допуск при всяка дължина —
    # виж ``рамото_удостоверява_посока``. ``в_мащаб`` остава такъв, какъвто е:
    # той е отчетна стойност (`legs_to_scale`) и отговаря на друг въпрос.
    удостоверяващи = tuple(
        рамото_удостоверява_посока(н, о) for н, о in zip(начертани, участъци)
    ) if len(начертани) == len(участъци) else ()

    присъди: list[ОгъвкаПрисъда] = []
    for индекс, огъвка in enumerate(огъвки):
        съседни = bool(
            в_мащаб and индекс + 1 < len(в_мащаб)
            and в_мащаб[индекс] and в_мащаб[индекс + 1]
        )
        удостоверени = bool(
            удостоверяващи and индекс + 1 < len(удостоверяващи)
            and удостоверяващи[индекс] and удостоверяващи[индекс + 1]
        )
        присъди.append(класифицирай_огъвка(
            индекс,
            огъвка,
            съседните_рамена_са_в_мащаб=съседни,
            съседните_рамена_удостоверяват_посока=удостоверени,
            производствени_ъгли=производствени_ъгли,
            диаметър_mm=диаметър_mm,
            оразмерен_ъгъл_deg=(оразмерени[индекс]
                                if индекс < len(оразмерени) else None),
            правило=правило,
            ъгъл_по_правило_deg=(по_правило[индекс]
                                 if индекс < len(по_правило) else None),
        ))

    състояние = (max((п.състояние for п in присъди), key=СИЛА.index)
                 if присъди else НЕРАЗРЕШЕН)
    ъгли = tuple(п.ъгъл_deg for п in присъди if п.ъгъл_deg is not None)
    if len(ъгли) != len(присъди):
        ъгли = ()
        състояние = НЕРАЗРЕШЕН

    начертани_завои = tuple(float(о.get("turn_deg") or 0.0) for о in огъвки)
    разминаване = (
        max(abs(abs(a) - abs(b)) for a, b in zip(начертани_завои, шаблонни))
        if шаблонни and len(шаблонни) == len(начертани_завои) else None
    )

    бележки: list[str] = []
    if режим == РЕЖИМ_УГОВОРЕНА and шаблонни and len(шаблонни) == len(присъди):
        ъгли, състояние = шаблонни, ПО_ПРАВИЛО
        бележки.append(
            "UGOVORENA_FORMA: по изрична настройка производството следва "
            "уговорената форма, а не доказаното от чертежа"
        )
    elif състояние == НЕРАЗРЕШЕН:
        липсващи = "; ".join(
            "огъвка %d: %s" % (п.индекс + 1, п.липсва)
            for п in присъди if п.състояние == НЕРАЗРЕШЕН
        )
        бележки.append(
            "FORMA_ZA_PREGLED: ъглите НЕ са доказани и не се произвеждат. "
            "Оригиналната форма отива за преглед. Липсва — " + (липсващи or "няма огъвки")
        )
    else:
        по_състояние = {}
        for п in присъди:
            по_състояние.setdefault(п.състояние, []).append(п.индекс + 1)
        бележки.append(
            "FORMA_OT_PROEKTA: " + "; ".join(
                "%s за огъвк%s %s" % (с, "а" if len(и) == 1 else "и",
                                      ", ".join(str(x) for x in и))
                for с, и in по_състояние.items())
            + " → " + ", ".join("%.2f°" % ъ for ъ in ъгли)
        )
        if правило and any(п.състояние == ПО_ПРАВИЛО for п in присъди):
            бележки.append("PRAVILO_V_OBHVAT: %s" % правило)

    if (разминаване is not None and разминаване > ЗНАЧИМО_РАЗМИНАВАНЕ_DEG
            and състояние != НЕРАЗРЕШЕН):
        бележки.append(
            "SHABLONAT_NE_SAVPADA: начертаното дава %s, а шаблонът на формата — "
            "%s (разлика %.1f°). Шаблонът НЕ заменя доказаната геометрия."
            % (", ".join("%.1f°" % з for з in начертани_завои),
               ", ".join("%.1f°" % з for з in шаблонни), разминаване)
        )

    return ДоказанаФорма(
        участъци_cm=участъци,
        ъгли_deg=tuple(ъгли),
        състояние=състояние,
        режим=режим,
        огъвки=tuple(присъди),
        начертани_cm=начертани,
        в_мащаб=в_мащаб,
        шаблонни_ъгли_deg=шаблонни,
        разминаване_deg=разминаване,
        бележки=tuple(бележки),
    )


def начертай(
    участъци_cm: Sequence[float],
    ъгли_deg: Sequence[float],
    **kwargs: Any,
) -> str:
    """SVG на ДОКАЗАНАТА форма — от участъците и завоите, без MASTER шаблон.

    Ползва одобрения рисувач на редактора (``export/engine_draft_render.py``).
    Знакът на завоя дава посоката: положителен = наляво.
    """

    from lion_rebar.export.engine_draft_render import DraftSegment, render_draft_svg

    дължини = [float(с) for с in участъци_cm]
    завои = [float(с) for с in ъгли_deg]
    if len(дължини) < 2 or len(завои) != len(дължини) - 1:
        raise ValueError(
            "рисувачът иска %d завоя за %d участъка, получени са %d"
            % (max(0, len(дължини) - 1), len(дължини), len(завои))
        )
    участъци = tuple(
        DraftSegment(
            length_cm=дължина,
            bend_after_deg=(abs(завои[индекс]) if индекс < len(завои) else None),
            bend_direction=(
                ("LEFT" if завои[индекс] >= 0 else "RIGHT")
                if индекс < len(завои) else None
            ),
        )
        for индекс, дължина in enumerate(дължини)
    )
    return render_draft_svg(участъци, initial_direction="RIGHT", **kwargs)


def ъгли_на_заключената_форма(код: str, форми: Any) -> list[float]:
    """Завоите на ЗАКЛЮЧЕНАТА форма с този код, или празно.

    Ползва се САМО когато одобрено правило вече е решило, че формата е тази.
    Източникът е дефиницията в ENGINE, не таблица в кода — същият, от който
    рисува и редакторът.
    """

    if not код or not форми:
        return []
    for ф in форми:
        if str(getattr(ф, "code", "")).strip().upper() != код.strip().upper():
            continue
        if str(getattr(ф, "state", "")).strip().upper() not in ("LOCKED", "APPROVED"):
            return []
        from lion_rebar.export.shape_image import shape_turn_angles_deg
        return [float(x) for x in shape_turn_angles_deg(ф)]
    return []


def за_реда(row: Mapping[str, Any], *, режим: str = РЕЖИМ_ПРОЕКТ,
            форми: Any = None) -> ДоказанаФорма | None:
    """Присъдата за един ред от пакетния отчет, или ``None`` без доказателство."""

    from lion_rebar.dxf import chain_printed_dimensions as верига

    присъда = row.get(верига.ПОЛЕ)
    if not isinstance(присъда, Mapping):
        return None
    if str(присъда.get("status") or "") != верига.ПОТВЪРДЕНО:
        return None
    участъци = [float(с) for с in (присъда.get("segments_cm") or ())]
    начертани = [float(с) for с in (присъда.get("drawn_lengths_cm") or ())]
    огъвки = list(присъда.get("bends") or ())
    if len(участъци) < 2 or len(начертани) != len(участъци):
        return None
    if len(огъвки) != len(участъци) - 1:
        return None

    шаблонни = [
        float(с) for с in (row.get("canonical_turn_angles_deg") or ())
        if isinstance(с, (int, float))
    ]
    # Одобреното инженерно правило важи САМО в своя обхват: то е записано на реда
    # от прохода, който го е приложил, заедно с ъглите, които налага.
    правило = str(row.get("contextual_rule_code") or "").strip()
    по_правило = шаблонни if (правило and len(шаблонни) == len(огъвки)) else []
    if правило and not по_правило and not row.get("master_conflict") \
            and not (row.get("master_ambiguous_shape_codes") or ()):
        # Редът носи ОДОБРЕНО правило и еднозначна форма, но собствените му
        # канонични ъгли липсват. Тогава ъглите на правилото идват от
        # дефиницията на заключената форма — правилото вече е решило коя е тя.
        #
        # Измерено: 24 от 48-те позиции с неудостоверен ъгъл са точно такива
        # (`U_PROPORTION_F003` × 21, `U_PROPORTION_F005` × 3). Без това те
        # излизаха с празен ъгъл, макар параметърът да е определен.
        от_формата = ъгли_на_заключената_форма(
            str(row.get("master_shape_code") or ""), форми)
        if len(от_формата) == len(огъвки):
            по_правило = от_формата
    диаметър = row.get("diameter_mm")
    try:
        диаметър = float(диаметър) if диаметър is not None else None
    except (TypeError, ValueError):
        диаметър = None

    # Живият набор производствени ъгли — от ЗАКЛЮЧЕНИТЕ форми на engine-а,
    # не от константата. Така прозорецът следва библиотеката, а не обратното.
    #
    # СТЕСНЕНО на 29.09.2026: наборът е на СВОЯТА форма, а не обединението на
    # всички. ЗАЩО. Записаната незатворена граница
    # (`test_izmerenata_granica_45_moje_da_sedne_varhu_29`) казва, че при 8 %
    # относителен допуск истински 45° може да се начертае 29,0013° и да седне
    # върху производствения 29° — прозорецът нямал как да го различи. Но 29°
    # изобщо не е ъгъл на формите, които този клон обслужва: идва от
    # F012/F013/F014/F016/F019, а клонът работи по F003/F004/F005/F009, чиито
    # собствени завои са 90°. Границата съществуваше заради ЧУЖД ъгъл в
    # прозореца.
    #
    # Цената е измерена ПРЕДИ промяната (`P_NABOR_NA_FORMATA.json`): върху
    # корпуса от 11 чертежа присъдите на **236 реда** са ЕДНАКВИ с обединението
    # и със собствения набор — **0 сменени**. Стеснението не мести нито една
    # вярна позиция; само затваря чуждия ъгъл.
    #
    # Когато редът няма еднозначна заключена форма, наборът остава предишният
    # (константата в `завоят_е_производствен`): за такъв ред няма своя форма, с
    # която да се мери, и това е отделен, незатворен случай.
    живи = None
    if форми:
        from lion_rebar.export.shape_image import shape_turn_angles_deg
        свой_код = str(row.get("master_shape_code") or "").strip().upper()
        двусмислена = bool(row.get("master_conflict")) or bool(
            row.get("master_ambiguous_shape_codes") or ())
        само_своята = bool(свой_код) and not двусмислена
        набор = set()
        for ф in форми:
            if str(getattr(ф, "state", "")).strip().upper() not in ("LOCKED", "APPROVED"):
                continue
            if само_своята and str(getattr(ф, "code", "")).strip().upper() != свой_код:
                continue
            for з in shape_turn_angles_deg(ф):
                набор.add(round(abs(float(з)), 2))
        живи = tuple(sorted(набор)) or None

    return реши(
        участъци_cm=участъци,
        начертани_cm=начертани,
        огъвки=огъвки,
        шаблонни_ъгли_deg=шаблонни,
        диаметър_mm=диаметър,
        правило=правило,
        ъгли_по_правило_deg=по_правило,
        режим=режим,
        производствени_ъгли=живи,
    )
