from __future__ import annotations

import json
import math
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from statistics import median
from typing import TYPE_CHECKING, Mapping, Sequence

from lion_rebar.config.constants import APP_VERSION
from lion_rebar.dxf.models import DxfEntityRecord
from lion_rebar.project.models import ProjectModel
from lion_rebar.utils.files import sha256_file

if TYPE_CHECKING:
    from lion_rebar.export.excel_export import ExportPosition


POSITION_LAYER = "LION_POSITIONS"
POSITION_BLOCK_PREFIX = "LION_POS_"
POSITION_LAYER_COLOR = 1  # ACI red: immediately visible in AutoCAD.


class DxfPositionExportError(RuntimeError):
    pass


@dataclass(frozen=True)
class DxfPositionExportResult:
    dxf_path: Path
    traceability_path: Path
    marker_count: int
    unique_position_count: int
    layer_name: str
    marker_radius: float
    base_text_height: float


@dataclass(frozen=True)
class MarkerStyle:
    radius: float
    base_text_height: float
    gap: float


def generate_dxf_position_export(
    project: ProjectModel,
    entities: Sequence[DxfEntityRecord],
    positions: Sequence["ExportPosition"],
    position_numbers_by_annotation: Mapping[str, int],
    output_path: Path,
) -> DxfPositionExportResult:
    """Create a copy of the source DXF with numbered circular BLOCK markers.

    Excel and DXF must use the same registry.  The mapping passed here is the
    exact registry generated by ``generate_excel_export``; the DXF exporter
    never renumbers positions independently.
    """

    try:
        import ezdxf  # type: ignore
        from ezdxf.enums import TextEntityAlignment  # type: ignore
    except ImportError as exc:
        raise DxfPositionExportError(
            "Липсва библиотеката ezdxf. Стартирай INSTALL_LION_REBAR.bat."
        ) from exc

    source_path = _source_dxf_path(project)
    if not positions:
        raise DxfPositionExportError("Няма одобрени позиции за DXF export.")

    entity_map = {record.handle: record for record in entities}
    missing_numbers = sorted(
        position.annotation_handle
        for position in positions
        if position.annotation_handle not in position_numbers_by_annotation
    )
    if missing_numbers:
        preview = ", ".join(missing_numbers[:5])
        raise DxfPositionExportError(
            "DXF export е блокиран: липсва Excel номер за одобрена позиция "
            f"({preview}{'…' if len(missing_numbers) > 5 else ''})."
        )

    missing_entities = sorted(
        position.annotation_handle
        for position in positions
        if position.annotation_handle not in entity_map
    )
    if missing_entities:
        preview = ", ".join(missing_entities[:5])
        raise DxfPositionExportError(
            "DXF export е блокиран: липсват координати за одобрена позиция "
            f"({preview}{'…' if len(missing_entities) > 5 else ''})."
        )

    try:
        document = ezdxf.readfile(str(source_path))
    except Exception as exc:
        raise DxfPositionExportError(f"Изходният DXF не може да бъде прочетен: {exc}") from exc

    if POSITION_LAYER not in document.layers:
        document.layers.add(
            POSITION_LAYER,
            color=POSITION_LAYER_COLOR,
            linetype="Continuous",
        )
    else:
        layer = document.layers.get(POSITION_LAYER)
        layer.color = POSITION_LAYER_COLOR
        layer.on()

    unique_numbers = sorted(
        {int(position_numbers_by_annotation[position.annotation_handle]) for position in positions}
    )
    invalid_numbers = [number for number in unique_numbers if number <= 0]
    if invalid_numbers:
        raise DxfPositionExportError("Невалиден Excel номер за DXF marker.")

    reserved_conflicts = [
        _block_name(number) for number in unique_numbers if document.blocks.get(_block_name(number)) is not None
    ]
    if reserved_conflicts:
        raise DxfPositionExportError(
            "Изходният DXF вече съдържа LION позиционни блокове. "
            "Използвай оригиналния DXF, а не предишен маркиран export."
        )

    annotation_records = [entity_map[position.annotation_handle] for position in positions]
    style = _marker_style(annotation_records)
    for number in unique_numbers:
        block = document.blocks.new(name=_block_name(number))
        block.add_circle(
            (0, 0, 0),
            radius=style.radius,
            dxfattribs={"layer": "0", "color": 0},  # BYBLOCK
        )
        text = block.add_text(
            str(number),
            height=_number_text_height(style.radius, number),
            dxfattribs={"layer": "0", "color": 0, "style": "Standard"},
        )
        text.set_placement((0, 0, 0), align=TextEntityAlignment.MIDDLE_CENTER)

    modelspace = document.modelspace()
    occupied: list[tuple[float, float]] = []
    marker_rows: list[dict] = []
    ordered_positions = sorted(
        positions,
        key=lambda position: (
            int(position_numbers_by_annotation[position.annotation_handle]),
            int(position.frame_index),
            position.annotation_handle,
        ),
    )
    for position in ordered_positions:
        number = int(position_numbers_by_annotation[position.annotation_handle])
        record = entity_map[position.annotation_handle]
        center = _choose_marker_center(record, style, occupied)
        block_name = _block_name(number)
        block_ref = modelspace.add_blockref(
            block_name,
            (center[0], center[1], 0.0),
            dxfattribs={
                "layer": POSITION_LAYER,
                "rotation": 0.0,
                "color": 256,  # BYLAYER
            },
        )
        occupied.append(center)
        marker_rows.append(
            {
                "position_number": number,
                "block_name": block_name,
                "insert_handle": str(getattr(block_ref.dxf, "handle", "")),
                "annotation_handle": position.annotation_handle,
                "annotation_text": position.annotation_text,
                "frame_index": int(position.frame_index),
                "x": round(center[0], 6),
                "y": round(center[1], 6),
            }
        )

    output_path = Path(output_path)
    if output_path.suffix.lower() != ".dxf":
        output_path = output_path.with_suffix(".dxf")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    try:
        document.saveas(str(output_path))
    except Exception as exc:
        raise DxfPositionExportError(f"Маркираният DXF не може да бъде записан: {exc}") from exc

    traceability_path = output_path.with_name(output_path.stem + "_TRACEABILITY.json")
    traceability = {
        "schema": "lion-rebar-dxf-position-traceability/v1",
        "project": project.name,
        "generated_at": datetime.now().astimezone().isoformat(timespec="seconds"),
        "app_version": APP_VERSION,
        "source_dxf": str(source_path),
        "source_sha256": sha256_file(source_path),
        "output_dxf": str(output_path),
        "output_sha256": sha256_file(output_path),
        "layer": POSITION_LAYER,
        "block_prefix": POSITION_BLOCK_PREFIX,
        "marker_radius": style.radius,
        "base_text_height": style.base_text_height,
        "marker_count": len(marker_rows),
        "unique_position_count": len(unique_numbers),
        "markers": marker_rows,
    }
    traceability_path.write_text(
        json.dumps(traceability, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    return DxfPositionExportResult(
        dxf_path=output_path,
        traceability_path=traceability_path,
        marker_count=len(marker_rows),
        unique_position_count=len(unique_numbers),
        layer_name=POSITION_LAYER,
        marker_radius=style.radius,
        base_text_height=style.base_text_height,
    )


def _source_dxf_path(project: ProjectModel) -> Path:
    relative = str(project.source_dxf or "").strip()
    if not relative:
        raise DxfPositionExportError("Проектът няма импортиран изходен DXF.")
    source = Path(project.root) / relative
    if not source.is_file():
        raise DxfPositionExportError(f"Липсва изходният DXF на проекта: {source}")
    return source


def _marker_style(records: Sequence[DxfEntityRecord]) -> MarkerStyle:
    heights = [height for record in records if (height := _record_text_height(record)) is not None]
    base = float(median(heights)) if heights else 1.0
    if not math.isfinite(base) or base <= 0:
        base = 1.0
    # Diameter = 3.6 x the normal annotation height.  This is deliberately
    # readable at normal CAD zoom but remains compact beside the source label.
    radius = base * 1.8
    return MarkerStyle(radius=radius, base_text_height=base, gap=radius * 0.35)


def _record_text_height(record: DxfEntityRecord) -> float | None:
    geometry = record.geometry
    for key in ("height", "char_height"):
        try:
            value = float(geometry.get(key))
        except (TypeError, ValueError):
            continue
        if math.isfinite(value) and value > 0:
            return value
    return None


def _number_text_height(radius: float, number: int) -> float:
    digits = max(1, len(str(abs(int(number)))))
    # Keep one visual circle size for every position.  Only the text height is
    # reduced for 3+ digits so every number remains fully inside the circle.
    return min(radius * 0.92, radius * 2.1 / digits)


def _block_name(number: int) -> str:
    return f"{POSITION_BLOCK_PREFIX}{int(number):03d}"


def _choose_marker_center(
    record: DxfEntityRecord,
    style: MarkerStyle,
    occupied: Sequence[tuple[float, float]],
) -> tuple[float, float]:
    bbox = _visual_bbox(record)
    r = style.radius
    gap = style.gap
    if bbox is not None:
        min_x, min_y, max_x, max_y = bbox
        mid_x = (min_x + max_x) / 2.0
        mid_y = (min_y + max_y) / 2.0
        candidates = [
            (min_x - r - gap, mid_y),
            (min_x - r - gap, max_y + r + gap * 0.4),
            (min_x - r - gap, min_y - r - gap * 0.4),
            (mid_x, max_y + r + gap),
            (mid_x, min_y - r - gap),
            (max_x + r + gap, mid_y),
        ]
    else:
        anchor = _record_anchor(record)
        if anchor is None:
            raise DxfPositionExportError(
                f"Липсва координата за DXF надпис {record.handle}."
            )
        x, y = anchor
        candidates = [
            (x - 2.35 * r, y),
            (x - 2.35 * r, y + 2.35 * r),
            (x - 2.35 * r, y - 2.35 * r),
            (x, y + 2.35 * r),
            (x, y - 2.35 * r),
            (x + 2.35 * r, y),
        ]

    minimum_distance = r * 2.25
    for candidate in candidates:
        if all(math.dist(candidate, other) >= minimum_distance for other in occupied):
            return candidate

    # Dense details can exhaust the six normal placements.  Continue left in
    # deterministic steps instead of overlapping two numbered blocks.
    start_x, start_y = candidates[0]
    for step in range(1, 51):
        candidate = (start_x - step * minimum_distance, start_y)
        if all(math.dist(candidate, other) >= minimum_distance for other in occupied):
            return candidate
    return (start_x - 51 * minimum_distance, start_y)


def _record_anchor(record: DxfEntityRecord) -> tuple[float, float] | None:
    value = record.geometry.get("visual_anchor") or record.geometry.get("insert")
    try:
        return float(value[0]), float(value[1])
    except (TypeError, ValueError, IndexError):
        return None


def _visual_bbox(record: DxfEntityRecord) -> tuple[float, float, float, float] | None:
    raw = record.geometry.get("visual_bbox")
    if not isinstance(raw, (list, tuple)):
        return None
    points: list[tuple[float, float]] = []
    for value in raw:
        try:
            points.append((float(value[0]), float(value[1])))
        except (TypeError, ValueError, IndexError):
            continue
    if not points:
        return None
    xs = [point[0] for point in points]
    ys = [point[1] for point in points]
    return min(xs), min(ys), max(xs), max(ys)
