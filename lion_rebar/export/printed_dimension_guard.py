# -*- coding: utf-8 -*-
"""Отпечатаният размер не се изхвърля, за да излезе обявената дължина.

## Защо съществува този модул

На 29.09.2026 закръгляването към мрежа получи вето: кандидат, който мести
участък ОТ стойност, която чертежът отпечатва, КЪМ стойност, която не отпечатва,
се отказва (``grid_rounded_segments``). Ветото обаче важеше само за
ПРЕДЛОЖЕНИЕТО на този един доказател.

Измерено веднага след това върху корпуса от 11 прогона (``B2_INSTALIRANITE.json``):
**17 позиции** носят ВЕЧЕ ИНСТАЛИРАН производствен вектор, който прави точно
същото. От тях **9 са в експортния контекст**, а 8 са спрени по друга причина —
``UNKNOWN_FRAME`` — тоест едно операторско решение за площта би ги освободило,
без размерният конфликт да е погледнат.

Разпределението по стратегия показва, че дефектът е концентриран:

| стратегия на инсталирания вектор | случаи |
|---|---|
| ``A_E_TOTAL_MINUS_PRINTED`` (досмятане Δ = обявена − отпечатано) | 11 |
| ``A_E_DELTA_SPLIT_TWO_EQUAL_BENDS`` | 1 |
| без записан източник | 5 |
| всички останали доказатели (333 + 11 + 6 + 3 проверени) | **0** |

Най-острият случай, ``s-9/15D46`` при обявени 640 cm: начертано
``600,1 + 25,0 + 25,0`` = 650,1, чертежът отпечатва **25**, а инсталираният
вектор е ``[20 · 600 · 20]``. Надписът и чертежът се разминават с 10 cm и
разминаването е погълнато от двете куки — по 5 cm на всяка, без позицията да е
маркирана.

## Какво прави правилото

Проверява КРАЙНИЯ вектор, независимо кой доказател го е сложил, и отказва, когато
той изхвърля отпечатан размер. Не избира вместо оператора и **не подменя**
стойност с близка кота: при конфликт пази двата варианта и иска преглед.

Собственик, 30.09.2026: „Не заменяй автоматично стойности с близки коти без
доказана принадлежност. При конфликт или недостатъчно доказателство запази двата
варианта и изискай конкретен преглед. Не избирай размер само за да излезе
обявената обща дължина."

## Как е сдвояването

Доказателите подреждат участъците по свой канон, затова сравнение по ИНДЕКС дава
лъжливи попадения (измерено: ``s-9/1471C`` излизаше нарушение само защото
инсталираният е ``[25, 405]`` при начертани ``[405, 25]``). Алчното сдвояване по
множество също лъже (при начертани ``[25,27; 25,0]`` и инсталиран ``[25,0; 30,0]``
първата изяжда единствената 25,0). Затова тук се избира присвояването с
НАЙ-МАЛКА обща разлика — изчерпателно до ``МАКС_УЧАСТЪЦИ_ЗА_ТОЧНО_СДВОЯВАНЕ``
участъка. Над този брой присвояването се отбелязва като неточно и правилото се
въздържа, вместо да гадае.

Мярката мина през три поправки, преди да е вярна: 21 → 33 → **17**.

## Силата на отпечатаното НЕ е една и съща

Разделят се два източника и присъдата казва кой е:

* ``ДОКАЗАНА_КОТА_НА_РАМОТО`` — ``chain_printed_dimensions`` при ``CONFIRMED``,
  тоест кота, присвоена на рамо с доказано взаимно еднозначно съответствие;
* ``БЛИЗКА_КОТА_БЕЗ_ПРИСВОЯВАНЕ`` — ``nearby_dimensions_cm``: чертежът отпечатва
  тази стойност някъде около пръта, но че е на ТОВА рамо не е доказано.

И двете водят до преглед, защото и двете са „конфликт или недостатъчно
доказателство". Разликата се показва на оператора, за да знае колко тежи.

## Какво това правило НЕ прави

* не подменя стойност и не предлага число;
* не чете DXF — работи върху вече прочетения ред, за да е проверимо без чертеж;
* не съдържа име на файл, handle или конкретен размер.
"""
from __future__ import annotations

import itertools
from typing import Any, Mapping, Sequence

#: Докъде две стойности се смятат за една и съща. Котите са цели числа, а
#: начертаното е измерено; под тази граница преместването е прилепване в рамките
#: на шума, не смяна на размер. Същата стойност като
#: ``grid_rounded_segments.ДОПУСК_ОБЯВЕН_CM`` — умишлено, за да не се разминават
#: двете правила.
ДОПУСК_CM = 0.5

#: Докъде присвояването се смята изчерпателно. 6! = 720 размествания; над това
#: правилото се въздържа и го казва, вместо да гадае по индекс.
МАКС_УЧАСТЪЦИ_ЗА_ТОЧНО_СДВОЯВАНЕ = 6

ДОКАЗАНА = "ДОКАЗАНА_КОТА_НА_РАМОТО"
БЛИЗКА = "БЛИЗКА_КОТА_БЕЗ_ПРИСВОЯВАНЕ"

ПРОТИВОРЕЧИ = "PRODUCTION_CONTRADICTS_PRINTED"
#: Полето, в което се записва присъдата върху реда.
ПОЛЕ = "printed_dimension_guard"


def отпечатани_за_реда(row: Mapping[str, Any]) -> tuple[list[float], list[float]]:
    """(доказани рамо по рамо, отпечатани около пръта) — в този ред на сила."""

    доказани: list[float] = []
    верига = row.get("chain_printed_dimensions")
    if isinstance(верига, Mapping) and str(верига.get("status") or "") == "CONFIRMED":
        for стойност in (верига.get("segments_cm") or ()):
            число = _число(стойност)
            if число is not None:
                доказани.append(число)
    около: list[float] = []
    for стойност in (row.get("nearby_dimensions_cm") or ()):
        число = _число(стойност)
        if число is not None:
            около.append(число)
    return доказани, около


def _число(стойност: Any) -> float | None:
    if isinstance(стойност, bool):
        return None
    try:
        число = float(стойност)
    except (TypeError, ValueError):
        return None
    return число if число == число and abs(число) != float("inf") else None


def _съвпада(стойност: float, пул: Sequence[float]) -> float | None:
    """Отпечатаната стойност, която съвпада със ``стойност``, или ``None``."""

    най_близка = None
    най_малко = ДОПУСК_CM
    for отпечатана in пул:
        разлика = abs(float(стойност) - float(отпечатана))
        if разлика <= най_малко:
            най_малко = разлика
            най_близка = float(отпечатана)
    return най_близка


def _най_добро_присвояване(
    начертани: Sequence[float],
    вектор: Sequence[float],
) -> tuple[tuple[int, ...], bool]:
    """Редът на вектора с най-малка обща разлика; втората стойност е ТОЧНО ли е."""

    ако = tuple(range(len(вектор)))
    if len(вектор) > МАКС_УЧАСТЪЦИ_ЗА_ТОЧНО_СДВОЯВАНЕ:
        return ако, False
    най_добро: tuple[float, tuple[int, ...]] | None = None
    for разместване in itertools.permutations(ако):
        цена = sum(abs(float(вектор[разместване[и]]) - float(начертани[и]))
                   for и in range(len(начертани)))
        if най_добро is None or цена < най_добро[0]:
            най_добро = (цена, разместване)
    return (най_добро[1] if най_добро else ако), True


def изхвърлени_отпечатани(
    начертани: Sequence[float],
    вектор: Sequence[float],
    доказани: Sequence[float],
    около: Sequence[float],
) -> tuple[list[dict[str, Any]], bool]:
    """Кои отпечатани размери крайният вектор изхвърля, и точно ли е сдвоен."""

    начертани = [_число(с) for с in начертани]
    вектор_числа = [_число(с) for с in вектор]
    if None in начертани or None in вектор_числа:
        return [], True
    if not начертани or len(начертани) != len(вектор_числа):
        return [], True
    ред, точно = _най_добро_присвояване(начертани, вектор_числа)
    изхвърлени: list[dict[str, Any]] = []
    for и, начертан in enumerate(начертани):
        инсталиран = vector_stoynost = вектор_числа[ред[и]]
        if abs(инсталиран - начертан) <= ДОПУСК_CM:
            continue
        # Отпечатана ли е НАЧЕРТАНАТА стойност, и с каква сила.
        отпечатан = _съвпада(начертан, доказани)
        сила = ДОКАЗАНА
        if отпечатан is None:
            отпечатан = _съвпада(начертан, около)
            сила = БЛИЗКА
        if отпечатан is None:
            continue
        # Ако и НОВАТА стойност е отпечатана, това не е изхвърляне, а избор
        # между два обявени размера — отделен случай, който не се решава тук.
        if (_съвпада(инсталиран, доказани) is not None
                or _съвпада(инсталиран, около) is not None):
            continue
        изхвърлени.append({
            "segment_index": и,
            "drawn_cm": round(начертан, 4),
            "printed_cm": отпечатан,
            "printed_source": сила,
            "installed_cm": round(vector_stoynost, 4),
            "difference_cm": round(abs(vector_stoynost - начертан), 4),
        })
    return изхвърлени, точно


def присъда_за_реда(
    row: Mapping[str, Any],
    вектор: Sequence[float] | None = None,
    *,
    начертани: Sequence[float] | None = None,
) -> dict[str, Any] | None:
    """Присъдата за КРАЙНИЯ вектор на един ред, или ``None`` ако случаят не е за тук.

    ``вектор`` е онова, което ще излезе в производството. Когато викащият го
    държи отделно (например сглобения за експорта вектор), го подава изрично;
    иначе се взима ``production_segments_cm`` от реда.

    ``начертани`` са нормализираните участъци. По подразбиране се взимат от
    присъдата на закръгляването, която вече ги е сметнала — така двете правила
    гледат едно и също нормализирано измерване, а не различни прочити.
    """

    краен = list(вектор) if вектор is not None else list(
        row.get("production_segments_cm") or ())
    if not краен:
        return None
    if начертани is None:
        мрежа = row.get("grid_rounded_segments")
        if isinstance(мрежа, Mapping):
            начертани = мрежа.get("semantic_segments_cm") or ()
        else:
            начертани = ()
    начертани = list(начертани)
    if len(начертани) != len(краен):
        # Различен брой участъци значи, че се сравняват две различни геометрии;
        # правилото се въздържа, вместо да съпоставя каквото и да е.
        return None

    доказани, около = отпечатани_за_реда(row)
    if not доказани and not около:
        return None
    изхвърлени, точно = изхвърлени_отпечатани(начертани, краен, доказани, около)
    основа: dict[str, Any] = {
        "drawn_segments_cm": [round(float(с), 4) for с in начертани],
        "production_segments_cm": [float(с) for с in краен],
        "printed_proven_cm": доказани,
        "printed_nearby_cm": около,
        "assignment_exact": точно,
    }
    if not изхвърлени:
        return {**основа, "status": "OK"}
    if not точно:
        # Без точно сдвояване не се твърди нарушение: правилото казва, че не
        # може да прецени, и го оставя видимо.
        return {**основа, "status": "OK",
                "note": ("над %d участъка — присвояването не е изчерпателно, "
                         "правилото се въздържа"
                         % МАКС_УЧАСТЪЦИ_ЗА_ТОЧНО_СДВОЯВАНЕ)}
    описание = "; ".join(
        "участък %d: начертано %.2f съвпада с отпечатано %.2f (%s), а в "
        "производството влиза %.2f"
        % (и["segment_index"], и["drawn_cm"], и["printed_cm"],
           "доказана кота" if и["printed_source"] == ДОКАЗАНА else "близка кота",
           и["installed_cm"])
        for и in изхвърлени
    )
    return {
        **основа,
        "status": ПРОТИВОРЕЧИ,
        "discarded_printed": изхвърлени,
        "strongest_printed_source": (
            ДОКАЗАНА if any(и["printed_source"] == ДОКАЗАНА for и in изхвърлени)
            else БЛИЗКА),
        "reason": (
            "производственият вектор изхвърля отпечатан размер (%s); обявената "
            "обща дължина не е основание да се смени размер, който чертежът "
            "отпечатва — за конкретен преглед, с двата варианта" % описание),
    }


