def _ред_с_верига(геометрия, кандидат):
    from lion_rebar.dxf import chain_printed_dimensions as вер

    return {
        "candidate_handles": list(кандидат),
        вер.ПОЛЕ: {"status": вер.ПОТВЪРДЕНО, "geometry_handles": list(геометрия)},
    }


def test_proslediмostta_obhvashta_cyalata_veriga():
    """Кандидатът е половин прът; проследимостта взима цялата верига."""

    from lion_rebar.export.batch_auto_output import _chain_geometry_handles

    ред = _ред_с_верига(("4B53", "4B54"), ("4B53",))
    assert _chain_geometry_handles(ред, ("4B53",)) == ("4B53", "4B54")


def test_verigata_ne_podmenya_geometriyata():
    """Верига, която НЕ съдържа кандидата, не се ползва."""

    from lion_rebar.export.batch_auto_output import _chain_geometry_handles

    ред = _ред_с_верига(("9999", "8888"), ("4B53",))
    assert _chain_geometry_handles(ред, ("4B53",)) == ()


