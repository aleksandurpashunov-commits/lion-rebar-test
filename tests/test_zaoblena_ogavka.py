"""Заоблената огъвка, начертана като многоъгълник, е ЕДНА огъвка.

Образецът е изрязан от ``S-_H01-1001_Rev.0_2020-09-23_Bottom_Reinforcement`` —
чертеж от бюро, с което не е работено. Координатите са ИСТИНСКИТЕ на прът
``8N10x124/20`` (handle ``35C5``), преместени в началото на координатите.

Прътът е обикновено „С“ от три участъка — 49 · 23 · 49 — но е начертан с
двайсет върха, защото всяка огъвка е заобление от осем отсечки по ~0,46 cm.
Завоите в двете поредици сумират точно −90,01°. Нито една MASTER форма няма 19
участъка, затова преди сливането формата му беше ``None``.

ИЗМЕРЕНО 06.10.2026 преди включването:

* 13-те познати чертежа — правилото пипа 79 полилинии от 6703, а целият път
  върху 11-те чертежа дава **0 разлики по позиция** и непроменен сбор
  2562 / 2308 / 254;
* същият чертеж — „няма активна MASTER форма“ пада от **67 на 32**, а формите,
  които се появяват, са F003, F004, F012, F013 и F016.
"""
from __future__ import annotations

import math

import pytest

from lion_rebar.dxf.recognition_policy import DEFAULT_RECOGNITION_POLICY
from lion_rebar.dxf.shape_recognition import (
    FILLET_MIN_RUN_SEGMENTS,
    collapse_fillets,
    fingerprint_from_points,
)

#: Истинските координати на ``8N10x124/20``: два заоблени ъгъла по 90°.
ПРЪТ_С = [
    (0.0, 0.0), (0.0, -46.609), (-0.061, -47.052),
    (-0.211, -47.507), (-0.446, -47.925), (-0.732, -48.268),
    (-1.075, -48.554), (-1.493, -48.789), (-1.948, -48.939),
    (-2.391, -49.0), (-20.609, -49.0), (-21.051, -48.939),
    (-21.507, -48.789), (-21.925, -48.554), (-22.267, -48.268),
    (-22.554, -47.925), (-22.788, -47.507), (-22.938, -47.052),
    (-23.0, -46.609), (-23.0, 0.0),
]


def _участъци(points) -> list[float]:
    return [
        round(math.dist(points[i], points[i + 1]), 1)
        for i in range(len(points) - 1)
    ]


# --------------------------------------------------------------------------- #
# истинският случай


def test_zaobleniyata_stavat_edna_ogavka() -> None:
    """Двайсет върха стават четири, и участъците са размерите на проектанта."""

    свит = collapse_fillets(ПРЪТ_С)

    assert len(свит) == 4
    assert _участъци(свит) == [49.0, 23.0, 49.0]


def test_fingerprintat_vizhda_tri_uchastaka() -> None:
    """ЧЕРВЕН срещу стария код: там подписът е с 19 участъка.

    Това е числото, по което се търси MASTER форма — затова преди сливането
    нито една форма не съвпадаше.
    """

    отпечатък = fingerprint_from_points(ПРЪТ_С, policy=DEFAULT_RECOGNITION_POLICY)

    assert отпечатък is not None
    assert отпечатък.segment_count == 3
    assert [round(ъгъл) for ъгъл in отпечатък.turn_angles_deg] == [-90, -90]


