def test_kasoto_ramo_ne_e_zaoblenie() -> None:
    """Късо рамо до заобление оцелява.

    Това беше първата ми сгрешена редакция: критерият „къса спрямо най-дългата
    отсечка“ броеше рамо от 15,9 при най-дълъг участък 125,9 за част от
    заоблението. Разграничава ги подобието: отсечките на едно заобление са
    еднакви помежду си, а рамото е десетки пъти по-дълго от тях.
    """

    # рамо 16 нагоре, заоблен ъгъл, после дълъг участък 120
    точки = [(0.0, 16.0), (0.0, 0.6)]
    радиус = 0.6
    for стъпка in range(1, 9):
        ъгъл = math.radians(90.0 * стъпка / 8.0)
        точки.append((радиус * (1 - math.cos(ъгъл)) * -1, радиус * (1 - math.sin(ъгъл))))
    точки.append((-120.0, 0.0))

    свит = collapse_fillets(точки)

    участъци = _участъци(свит)
    assert len(участъци) == 2
    assert участъци[0] == pytest.approx(16.0, abs=0.2)
    assert участъци[1] == pytest.approx(120.0, abs=0.2)


def test_ostriyat_agal_ne_se_sliva() -> None:
    """Истинска огъвка е ЕДНА стъпка от 90° — не се пипа."""

    точки = [(0.0, 0.0), (0.0, 100.0), (50.0, 100.0), (50.0, 0.0)]

    assert collapse_fillets(точки) == tuple(точки)


def test_poredica_pod_praga_ne_e_zaoblenie() -> None:
    """Под ``FILLET_MIN_RUN_SEGMENTS`` къси отсечки не са заобление."""

    assert FILLET_MIN_RUN_SEGMENTS == 3
    точки = [(0.0, 0.0), (0.0, 50.0), (0.3, 50.3), (0.6, 50.6), (50.0, 50.9)]

    assert collapse_fillets(точки) == tuple(точки)


def test_raznoposochnite_zavoi_ne_sa_edno_zaoblenie() -> None:
    """Зигзаг не е дъга: завоите на едно заобление са еднопосочни."""

    точки = [(0.0, 0.0), (0.0, 50.0)]
    x, y = 0.0, 50.0
    for стъпка in range(6):
        знак = 1 if стъпка % 2 == 0 else -1
        x += 0.4 * знак
        y += 0.4
        точки.append((x, y))
    точки.append((0.0, 100.0))

    свит = collapse_fillets(точки)

    assert len(свит) == len(точки)


def test_prav_prat_ostava_prav() -> None:
    """Без заобление нищо не се мени — пази работещото."""

    точки = [(0.0, 0.0), (0.0, 120.0), (60.0, 120.0)]

    assert collapse_fillets(точки) == tuple(точки)
