class TestПодредбатаНеПада:
    """Смесени стилове в един чертеж не бива да чупят сортирането.

    Ключът за подредба на едно семейство трябва да е с един и същ размер:
    иначе сравняването на четворка с двойка пада с ``TypeError``.
    """

    def test_смесени_ядра_се_сортират(self) -> None:
        from lion_rebar.export.excel_export import _vertical_section_natural_key

        ключове = [
            _vertical_section_natural_key("CORE", "Стб.Ядро B.1 - (Сх.арм.2 )"),
            _vertical_section_natural_key("CORE", "Стб.Я.1 - (Сх.арм.2 )"),
            _vertical_section_natural_key("CORE", "Стб.ядро 5 - (Сх.арм.2 )"),
        ]
        assert len({len(k) for k in ключове}) == 1
        sorted(ключове)  # не хвърля

    def test_неизвестен_вид_се_сортира(self) -> None:
        from lion_rebar.export.excel_export import _vertical_section_natural_key

        ключове = [
            _vertical_section_natural_key("SECTION", "Нещо ново (Сх.арм.1 )"),
            _vertical_section_natural_key("SECTION", "Друго (Сх.арм.2 )"),
        ]
        sorted(ключове)


class TestОбосновкаСамоПриОтмяна:
    """Собственик: „в това съобщение, което трябва да опиша, не намирам логика."

    Мотивът пази решение, което БИЕ автоматиката. Когато рамката само
    огражда елемент преди анализа, няма какво да се оправдава — тридесет
    елемента значеха тридесет обосновки за нищо.

    Проверката е по изходния код: сглобяването на ``MainWindow`` иска engine
    registry, дневник и сесия, а питаното е едно — че текстовото поле стои
    под условие.
    """

    def test_полето_за_мотив_е_под_условие(self) -> None:
        import inspect

        from lion_rebar.ui.main_window import MainWindow

        редове = inspect.getsource(MainWindow._operator_box_drawn).split("\n")
        искане = next(
            ред for ред in редове if 'редове.extend(["", "Обосновка:"])' in ред
        )
        поле = next(ред for ред in редове if "QInputDialog.getText(" in ред)
        условие = next(ред for ред in редове if "if премествани:" in ред)
        # Тялото на метода е на 8 интервала. И искането, и полето трябва да
        # са по-навътре, тоест вътре в условие — и то след него.
        assert len(искане) - len(искане.lstrip()) > 8, "обосновката не е под условие"
        assert len(поле) - len(поле.lstrip()) > 8
        assert редове.index(условие) < редове.index(искане)

    def test_има_автоматичен_мотив_за_обикновената_рамка(self) -> None:
        import inspect

        from lion_rebar.export.operator_areas import MIN_NOTE_LENGTH
        from lion_rebar.ui.main_window import MainWindow

        код = inspect.getsource(MainWindow._operator_box_drawn)
        assert "Оградено преди анализа" in код
        мотив = "Оградено преди анализа — нищо не се отменя."
        assert len(мотив.strip()) >= MIN_NOTE_LENGTH
