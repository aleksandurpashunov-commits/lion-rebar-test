# --- приемането -------------------------------------------------------------


@pytest.mark.parametrize("участъци,обявена,очакван", [
    ([14.3, 594.3], 610.0, [15.0, 595.0]),
    ([349.485, 9.6], 360.0, [350.0, 10.0]),
    ([208.9, 9.4], 220.0, [210.0, 10.0]),
    ([9.6, 449.1], 460.0, [10.0, 450.0]),
    ([9.6, 409.2, 9.6], 430.0, [10.0, 410.0, 10.0]),
    ([14.3, 293.6, 14.3], 325.0, [15.0, 295.0, 15.0]),
])
def test_zakraglianeto_dava_vektora_na_proektanta(участъци, обявена, очакван) -> None:
    присъда = solve(участъци, обявена)
    assert присъда["status"] == ПРИЕТО, присъда.get("reason")
    assert присъда["segments_cm"] == очакван
    assert abs(sum(присъда["segments_cm"]) - обявена) < 1e-6


def test_zakraglianeto_NE_polzva_obyavenata_dulzhina() -> None:
    """Всеки участък се закръгля сам; обявената дължина е само проверка.

    Това е причината доказателството да е самопроверяващо се: ако закръглянето
    ползваше обявената дължина, съвпадението на сбора нямаше да значи нищо.
    """

    участъци = [14.3, 594.3]
    едната = solve(участъци, 610.0)
    другата = solve(участъци, 600.0)
    assert едната["status"] == ПРИЕТО
    # при друга обявена дължина същото закръгляне вече не затваря -> отказ
    assert другата["status"] == ОТКАЗ


