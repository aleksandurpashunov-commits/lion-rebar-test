# --- допълнителният доказател не поврежда реда ------------------------------


def test_neuspeshno_instalirane_vrushta_reda() -> None:
    """Дефект, намерен при измерване: неуспехът блокираше ред, минавал преди.

    `Тест-003/6A04B7` (`2x4N14x175`, F020) имаше вече доказан вектор
    [50, 18, 35, 18, 50]. Закръгляването дава [50, 20, 35, 20, 50];
    производственият инсталатор го отказва и при отказ БЛОКИРА реда — правилно
    за основен доказател, но не и за допълнителен. Загубени бяха 4 позиции.
    """

    from lion_rebar.dxf.batch_geometry_report import (
        _apply_grid_rounded_production_segments,
    )
    from lion_rebar.dxf.models import DxfEntityRecord

    ред = {
        "annotation_handle": "A1",
        "declared_length_cm": 175.0,
        "segment_count": 2,
        "master_shape_code": "F020",
        "candidate_handles": ["G1", "G2"],
        "production_segments_cm": [50.0, 125.0],
    }
    записи = [
        DxfEntityRecord(handle="G1", entity_type="LINE", layer="ARM",
                        geometry={"start": [0.0, 0.0], "end": [0.0, 49.6]}),
        DxfEntityRecord(handle="G2", entity_type="LINE", layer="ARM",
                        geometry={"start": [0.0, 49.6], "end": [125.4, 49.6]}),
    ]
    преди = dict(ред)
    _apply_grid_rounded_production_segments([ред], записи)

    # Каквото и да реши проходът, редът не бива да е БЛОКИРАН от него.
    assert not ред.get("production_export_blocked"), (
        ред.get("production_export_block_reason"))
    assert ред["production_segments_cm"] == преди["production_segments_cm"]


