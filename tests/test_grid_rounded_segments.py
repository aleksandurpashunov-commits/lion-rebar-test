def test_prisadata_kazva_che_sborat_e_kriteriy_za_izbor():
    """Присъдата не бива да твърди, че точният сбор потвърждава вектора.

    Мрежа, която не затваря сбора, изобщо не влиза в избора. Значи сборът е
    критерият, по който мрежата е ИЗБРАНА. Основанието за приемане е друго:
    начертаното вече е в мащаб.
    """

    присъда = solve([9.5, 294.0, 9.5], 315.0)
    assert присъда["status"] == ПРИЕТО
    assert присъда["sum_is_selection_not_confirmation"] is True
    assert присъда["basis"] == "IN_SCALE_MEASUREMENT"
    assert "НЕ е независимо потвърждение" in присъда["reason"]
    assert "потвърждава" not in присъда["reason"]


