"""Прът с един винкел: куката е символ, но завоят е начертан точно 90°.

Собственик, 31.10.2026, върху ``SS-1`` („ALFA armirovka.dxf“): позиции с един
винкел са елементарни, а не се разпознават сами. Измерено: ``33N10x870`` —
отпечатани [835; 35], начертани [835,0; 26,0], завой −90,0000°. Куката е
начертана като символ с постоянна дължина (26 в плочите, 25 в гредите), а
дългото рамо е в мащаб. Правилото „двете съседни рамена в мащаб“ не минава
заради куката и позицията спираше с ``PRODUCTION_ANGLE_UNPROVEN``.

Одобрено от собственика правило (31.10.2026, в чата): **символна кука,
начертан точно 90°, дълго рамо в мащаб, куката отпечатана**. Отпечатаната кука
е условие на самия вход — ``proven_form.за_реда`` работи само при потвърдена
верига от отпечатани размери.

Измерено върху корпуса от 11 чертежа и SS-1 преди промяната: 34 неразрешени
ъгъла, всичките F004 с един завой; 33 са точно ±90,0000° с дълго рамо в
мащаб, а ``2N14x240`` (отпечатани [225; 15], начертани [198,2; 25,0]) няма
нито едно рамо в мащаб и остава неразрешена.

Отказите остават откази: завой не на 90°, късото рамо в мащаб без дългото,
форма с повече от един завой (П с две символни куки е отделно решение) и
одобреното правило в обхват стои над това.
"""
from __future__ import annotations

from lion_rebar.dxf import chain_printed_dimensions as верига
from lion_rebar.dxf.batch_geometry_report import необходимият_ъгъл_е_недоказан
from lion_rebar.dxf.chain_printed_dimensions import ОСТЪР
from lion_rebar.export import proven_form as форма


def остър(завой):
    return {"kind": ОСТЪР, "turn_deg": завой, "radius_cm": None}


def _реши(участъци, начертани, завои):
    return форма.реши(
        участъци_cm=участъци,
        начертани_cm=начертани,
        огъвки=[остър(з) for з in завои],
        диаметър_mm=10.0,
    )


def _ред(участъци, начертани, завой, **допълнително):
    """Ред от пакетния отчет, както го дава SS-1, преди присъдата за формата."""

    return {
        верига.ПОЛЕ: {
            "status": верига.ПОТВЪРДЕНО,
            "segments_cm": list(участъци),
            "drawn_lengths_cm": list(начертани),
            "bends": [остър(завой)],
        },
        "master_shape_code": "F004",
        "canonical_turn_angles_deg": [90.0],
        "production_segments_cm": list(участъци),
        "diameter_mm": 10.0,
        **допълнително,
    }


def _присъда_на_реда(ред):
    присъда = форма.за_реда(ред)
    assert присъда is not None
    ред[форма.ПОЛЕ] = присъда.as_dict()
    return присъда


# --------------------------------------------------------------------------
# Случаите от SS-1 и корпуса
# --------------------------------------------------------------------------

def test_33N10x870_simvolnata_kuka_dava_90():
    """SS-1, потвърдена от собственика: [835; 35], начертани [835,0; 26,0]."""

    р = _реши((835.0, 35.0), (835.0, 26.0), (-90.0,))

    assert р.състояние == форма.СИМВОЛНА_КУКА
    assert р.ъгли_deg == (-90.0,)
    assert р.доказана is True
    assert р.в_мащаб == (True, False)


def test_kukata_moje_da_e_parvoto_ramo():
    """s-9 ``5N14x350``: веригата започва от куката — [20; 330]."""

    р = _реши((20.0, 330.0), (25.0, 324.9), (90.0,))

    assert р.състояние == форма.СИМВОЛНА_КУКА
    assert р.ъгли_deg == (90.0,)


def test_redat_veche_ne_spira_s_nedokazan_agal():
    """Целият път на реда: присъдата е доказана и спирачката не се задейства."""

    ред = _ред((640.0, 35.0), (635.0, 26.0), -90.0)     # SS-1 32N10x675
    присъда = _присъда_на_реда(ред)

    assert присъда.доказана
    assert необходимият_ъгъл_е_недоказан(ред) == ""


# --------------------------------------------------------------------------
# Положителна контрола и откази
# --------------------------------------------------------------------------

def test_2N14x240_bez_ramo_v_mashtab_ostava_spryana():
    """Положителна контрола: спирачката още работи за истинския отказ."""

    ред = _ред((225.0, 15.0), (198.2, 25.0), -90.0)
    присъда = _присъда_на_реда(ред)

    assert присъда.състояние == форма.НЕРАЗРЕШЕН
    assert необходимият_ъгъл_е_недоказан(ред) != ""


def test_zavoy_ne_na_90_ne_e_simvolna_kuka():
    for завой in (88.5, 135.0, 45.0):
        р = _реши((835.0, 35.0), (835.0, 26.0), (завой,))
        assert р.състояние == форма.НЕРАЗРЕШЕН, завой


def test_kasoto_ramo_v_mashtab_ne_zamenya_dalgoto():
    """Собственикът каза „дълго рамо в мащаб“ — не кое да е от двете."""

    р = _реши((835.0, 35.0), (700.0, 35.0), (90.0,))

    assert р.състояние == форма.НЕРАЗРЕШЕН


def test_ednakvi_ramena_nyamat_kuka():
    р = _реши((50.0, 50.0), (50.0, 30.0), (90.0,))

    assert р.състояние == форма.НЕРАЗРЕШЕН


def test_P_s_dve_simvolni_kuki_ne_e_v_obhvata():
    """Два завоя: правилото е само за прът с един винкел."""

    р = _реши((15.0, 405.0, 15.0), (25.0, 405.0, 25.0), (90.0, 90.0))

    assert р.състояние == форма.НЕРАЗРЕШЕН


def test_odobrenoto_pravilo_v_obhvat_stoi_nad_simvolnata_kuka():
    р = форма.реши(
        участъци_cm=(835.0, 35.0),
        начертани_cm=(835.0, 26.0),
        огъвки=[остър(-90.0)],
        правило="BEAM_ENGINEERING_90_F003",
        ъгли_по_правило_deg=(90.0,),
    )

    assert р.състояние == форма.ПО_ПРАВИЛО


def test_dvete_ramena_v_mashtab_ostavat_izvlechena():
    """Когато и куката е в мащаб, присъдата е по-силната — както досега."""

    р = _реши((835.0, 35.0), (835.0, 35.0), (90.0,))

    assert р.състояние == форма.ИЗВЛЕЧЕНА
