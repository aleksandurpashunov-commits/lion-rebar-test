# -*- coding: utf-8 -*-
"""Сверката на одобреното с бележките на собственика трябва да може да падне.

Положителната контрола е истинският случай от 07.10.2026: поправка, минала
всички тестове, пускаше „2*3N12x150“ с 128,8/18,8, а собственикът е написал
130/20. Сверка, която не хваща точно това, не мери нищо.
"""
from __future__ import annotations

from tools.recognition_viewer.sverka import (
    ДЕСЕТИЧНИ,
    ПРОТИВОРЕЧИЕ,
    СПРЯНА,
    СЪВПАДА,
    размери_от_бележка,
    сравни,
)


def _видове(находки):
    return {(н.handle, н.вид) for н in находки}


def test_хваща_отхвърлената_поправка():
    бележки = {"1B17": {"text": "2*3N12x150", "master_code": "F004", "note": "130/20"}}
    одобрени = {"1B17": {"text": "2*3N12x150", "shape_code": "F004", "segments": (128.8, 18.8)}}
    видове = _видове(сравни(бележки, одобрени, []))
    assert ("1B17", ПРОТИВОРЕЧИЕ) in видове
    assert ("1B17", ДЕСЕТИЧНИ) in видове


def test_същите_размери_в_друг_ред_съвпадат():
    бележки = {"32DF": {"text": "3N10x425", "master_code": "F004", "note": "405/20"}}
    одобрени = {"32DF": {"text": "3N10x425", "shape_code": "F004", "segments": (20.0, 405.0)}}
    assert _видове(сравни(бележки, одобрени, [])) == {("32DF", СЪВПАДА)}


def test_друга_форма_е_противоречие():
    бележки = {"3E7E": {"text": "3N12x435", "master_code": "F003", "note": ""}}
    одобрени = {"3E7E": {"text": "3N12x435", "shape_code": "F005", "segments": (30.0, 375.0, 30.0)}}
    assert _видове(сравни(бележки, одобрени, [])) == {("3E7E", ПРОТИВОРЕЧИЕ)}


def test_спряната_с_бележка_се_съобщава():
    бележки = {"3E12": {"text": "33N8x228", "master_code": "F006", "note": ""}}
    assert _видове(сравни(бележки, {}, ["3E12"])) == {("3E12", СПРЯНА)}


def test_свободният_текст_не_е_размер():
    assert размери_от_бележка("Двойно затворено стреме") is None
    assert размери_от_бележка("8 винкел/22/42") is None
    assert размери_от_бележка("20/60/20") == [20.0, 60.0, 20.0]
    assert размери_от_бележка(" 375 / 40 ") == [375.0, 40.0]


def test_правият_прът_не_е_десетично_рамо():
    одобрени = {"A": {"text": "3N12x880", "shape_code": "F001", "segments": (880.0,)}}
    assert сравни({}, одобрени, []) == []


def test_огънат_прът_без_доказател_не_е_потвърден():
    from tools.recognition_viewer.sverka import БЕЗ_ПРОИЗХОД

    одобрени = {"3F54": {"text": "8N14x115", "shape_code": "F004",
                         "segments": (20.0, 95.0), "source": "", "text_handles": []}}
    assert _видове(сравни({}, одобрени, [])) == {("3F54", БЕЗ_ПРОИЗХОД)}


def test_произходът_се_съобщава_с_котите():
    from tools.recognition_viewer.sverka import ПРОИЗХОД

    одобрени = {"3F54": {"text": "8N14x115", "shape_code": "F004",
                         "segments": (20.0, 95.0), "source": "CHAIN_PRINTED_DIMENSIONS",
                         "text_handles": ["4A1", "4A2"]}}
    находки = сравни({}, одобрени, [])
    assert [н.вид for н in находки] == [ПРОИЗХОД]
    assert "4A1" in находки[0].текст and "CHAIN_PRINTED_DIMENSIONS" in находки[0].текст
