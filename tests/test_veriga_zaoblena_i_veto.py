# -*- coding: utf-8 -*-
"""Котите до заобления прът и ветото срещу закръглянето (h01-1001, 07.10.2026).

Два дефекта от един и същ чертеж, в който огъвката е поредица от къси хорди:

* модулът за отпечатаните коти броеше всяка хорда за рамо и се отказваше
  („рамената и огъвките не се сглобяват“) — при 49 позиции, макар до пръта
  проектантът да е написал размерите;
* закръглянето към мрежата избираше между линиите и надписите тихо, в полза
  на линиите: „16N12x167“ получаваше 14/124/29, а до рамената пише 15/125/30.
"""
from __future__ import annotations

import math

from lion_rebar.dxf import chain_printed_dimensions as верига
from lion_rebar.dxf.batch_geometry_report import (
    _grid_vector_contradicts_printed_text,
    _semantic_segment_lengths_cm,
)
from lion_rebar.dxf.models import DxfEntityRecord


def _прът(рамо_a: float = 18.8, рамо_b: float = 128.8, радиус: float = 2.9,
          хорди: int = 8) -> DxfEntityRecord:
    """F004 с ъгъл в (0, 0): късо рамо нагоре, дълго надясно, огъвка от хорди."""

    точки = [[0.0, рамо_a]]
    for i in range(хорди + 1):
        ъгъл = math.pi + (math.pi / 2) * i / хорди
        точки.append([радиус + радиус * math.cos(ъгъл), радиус + радиус * math.sin(ъгъл)])
    точки.append([рамо_b, 0.0])
    return DxfEntityRecord("P1", "LWPOLYLINE", "s-arm", {"points": точки, "closed": False})


def _текст(handle: str, текст: str, точка, ротация: float) -> DxfEntityRecord:
    return DxfEntityRecord(
        handle, "TEXT", "s-arm",
        {"insert": [точка[0], точка[1], 0.0], "height": 3.0, "rotation": ротация},
        text=текст,
    )


def _коти(късо: str, дълго: str) -> list[DxfEntityRecord]:
    # Котата на късото (вертикално) рамо е изписана вертикално до него,
    # котата на дългото — хоризонтално под него. Както в h01-1001.
    return [_текст("T1", късо, (-2.0, 10.0), 90.0), _текст("T2", дълго, (65.0, -2.0), 0.0)]


def test_заобленият_прът_дава_отпечатания_вектор():
    указател = верига.ВериженУказател([_прът(), *_коти("20", "130")])
    присъда = верига.присъда(["P1"], указател, 150.0)
    assert присъда is not None
    assert sorted(присъда.участъци_cm) == [20.0, 130.0]
    # Огъвката е НАЧЕРТАНА (дъга), не остър ъгъл между две прави.
    assert [о.вид for о in присъда.огъвки] == [верига.ДЪГА]
    assert abs(abs(присъда.огъвки[0].завой_deg) - 90.0) < 0.5


def test_сборът_не_затваря_и_казва_числата():
    указател = верига.ВериженУказател([_прът(), *_коти("15", "125")])
    дневник: list = []
    assert верига.присъда(["P1"], указател, 150.0, дневник=дневник) is None
    assert дневник[0]["code"] == "SBORAT_NE_ZATVARYA"
    assert sorted(дневник[0]["printed_cm"]) == [15.0, 125.0]


def test_без_заобление_веригата_е_същата():
    # Положителна контрола: остър ъгъл минава както преди.
    остър = DxfEntityRecord("P1", "LWPOLYLINE", "s-arm",
                            {"points": [[0.0, 20.0], [0.0, 0.0], [130.0, 0.0]], "closed": False})
    указател = верига.ВериженУказател([остър, *_коти("20", "130")])
    присъда = верига.присъда(["P1"], указател, 150.0)
    assert присъда is not None
    assert [о.вид for о in присъда.огъвки] == [верига.ОСТЪР]


def _вето(коти: list[DxfEntityRecord], вектор):
    обекти = {"P1": _прът()}
    ред = {"candidate_handles": ["P1"], "annotation_handle": "A1"}
    участъци = _semantic_segment_lengths_cm(ред, обекти)
    указател = верига.ВериженУказател([обекти["P1"], *коти])
    return _grid_vector_contradicts_printed_text(ред, участъци, вектор, указател)


def test_вето_когато_до_рамото_пише_друго():
    # Начертано 18,8/128,8; мрежата дава 20/130, а до късото рамо пише 15.
    противоречие = _вето(_коти("15", "130"), (20.0, 130.0))
    assert противоречие is not None
    assert противоречие["написани"] == [15.0]


def test_без_вето_когато_написаното_съвпада():
    assert _вето(_коти("20", "130"), (20.0, 130.0)) is None


def test_чуждо_число_до_рамото_не_е_вето():
    # „82“ до 128-сантиметровото рамо не може да е негов размер.
    assert _вето([_текст("T1", "20", (-2.0, 10.0), 90.0),
                  _текст("T2", "82", (65.0, -2.0), 0.0)], (20.0, 130.0)) is None


def test_рамо_без_коти_не_се_проверява():
    assert _вето([], (20.0, 130.0)) is None
