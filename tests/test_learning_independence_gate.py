def test_bez_podpis_nablyudeniyata_sa_edno_svidetelstvo(tmp_path) -> None:
    """Наблюдение без подпис по съдържание не е отделно свидетелство.

    Дефектът, който тази проверка пази, вече се е случвал веднъж:
    ``record_observation`` приемаше ``source_sha256``, но никой не го подаваше
    (``test_learning_auto_cycle`` ред 193). Затова групата се изчислява ВЪТРЕ в
    ``record_observation``, а не се подава отвън: три записа без подпис дават
    един източник, не три.
    """

    from lion_rebar.learning.auto_cycle import (
        ГРУПА_НЕДОКАЗАНА, independence_summary, load_observations,
        record_observation,
    )

    път = tmp_path / "nablyudeniya.jsonl"
    профил = {"proposals": [], "refusals": [], "summary": {}}
    for име in ("А", "Б", "В"):
        record_observation(път, drawing=име, family=име, profile=профил,
                           layer_roles={}, source_sha256=име * 32)
    записи = load_observations(път)
    assert len(записи) == 3
    assert {з["independence_group"] for з in записи} == {ГРУПА_НЕДОКАЗАНА}
    обобщение = independence_summary(записи)
    assert обобщение["observations"] == 3
    assert обобщение["independent_sources"] == 0, (
        "нула ДОКАЗАНИ източника — липсващият подпис не е доказателство")


def test_stara_pamet_bez_podpis_plyus_edno_novo_NE_priema(памет, monkeypatch) -> None:
    """Групата на НЕДОКАЗАНИТЕ не е свидетелство — иначе дупката се връща.

    Случаят е при обновяване на програмата: в ``nablyudeniya.jsonl`` вече има
    записи от по-стар код, без подпис по съдържание. Всички те попадат в ЕДНА
    група ``НЕДОКАЗАНА``. Ако тази група се брои за източник, едно единствено ново
    наблюдение би дало „две свидетелства" и приемането щеше да стане пак по
    броя на файловете — точно поправеният дефект, върнат през задната врата.

    Тук два стари записа (без подпис) + един нов (с подпис) дават **1** доказан
    независим източник, не 2 и не 3.
    """

    from lion_rebar.learning.auto_cycle import (
        ГРУПА_НЕДОКАЗАНА, independence_summary, load_observations,
        observations_path, record_observation,
    )
    from lion_rebar.learning.knowledge_store import KnowledgeStore

    store = KnowledgeStore.load(памет)
    път = observations_path(store)
    # Два „стари" записа: истински профил, но БЕЗ подпис по съдържание.
    for име, обекти in (("стар-1", _чертеж("С1")), ("стар-2", _чертеж("С2"))):
        from lion_rebar.learning.spec_layer_profile import full_profile

        record_observation(път, drawing=име, family=име,
                           profile=full_profile(обекти), layer_roles={},
                           source_sha256=име.encode("utf-8").hex().ljust(64, "0"))
    # И един нов, през производствения път (значи с подпис).
    състояние = _цикъл(entities=_чертеж("Н1"), drawing="нов", сха="9" * 64)

    записи = load_observations(път)
    assert len(записи) == 3
    групи = {з["independence_group"] for з in записи}
    assert ГРУПА_НЕДОКАЗАНА in групи
    assert independence_summary(записи)["independent_sources"] == 1
    assert състояние.independent_sources == 1
    assert all(п.state == CANDIDATE for п in _правила_по_име(памет))


