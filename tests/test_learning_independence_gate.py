def test_grupovo_potvurzhdenie_na_57_pozicii_e_EDNO_svidetelstvo(памет) -> None:
    """57 потвърдени позиции в един източник са ЕДНО свидетелство, не 57.

    Правилото на мереното (``B0_PRAVILA_NA_MERENETO.md``, точка 1): едно групово
    потвърждение е ЕДНО действие, независимо колко позиции променя; броят
    засегнати позиции се отчита ОТДЕЛНО от броя свидетелства.

    Тук един чертеж носи **57** легендни записа и после се появява втори файл на
    същия чертеж (57 + 30 нови надписа, вложеност 1,0000). Очакваното: подкрепата
    в правилото е 57, редовете доказателства са 2, а НЕЗАВИСИМИТЕ ИЗТОЧНИЦИ
    остават **1** — и затова правилото е кандидат.
    """

    _цикъл(entities=_чертеж("А", легенда=57), drawing="проект-групово",
           сха="1" * 64)
    състояние = _цикъл(entities=_чертеж("А", легенда=57, допълнителни=30),
                       drawing="проект-групово-препотвърден", сха="2" * 64)

    правила = _правила_по_име(памет)
    assert правила
    правило = правила[0]
    подкрепи = sorted({int(п.get("support") or 0) for п in правило.positives})
    assert подкрепи == [57], "подкрепата е 57 позиции"
    assert len(правило.positives) == 2, "два реда доказателства"
    assert състояние.independent_sources == 1, "но ЕДИН независим източник"
    assert правило.validation["independent_sources"] == 1
    assert правило.state == CANDIDATE


