def test_podmnozhestvo_NE_dava_priemane(памет) -> None:
    """Поднабор не е второ свидетелство — случаят ``s-8`` ⊂ ``s-9``.

    Измерено: всичките надписи на ``s-8`` са в ``s-9`` — вложеност **1,0000** —
    докато покритието е само 0,5974. Старата порта пускаше двойката и приемаше
    **3 правила**, а в режим „Б" на предишния опит един от двата донора беше
    самата цел.

    Тук малкият чертеж има 19 надписа, големият — същите 19 плюс 30 нови:
    покритие 19/49 = **0,3878** (ПОД прага 0,50), вложеност **1,0000**. Тоест
    само вложеността хваща случая; ако тя се махне, тестът пада.
    """

    малък = _чертеж("А")
    голям = _чертеж("А", допълнителни=30)

    _цикъл(entities=малък, drawing="проект-малък", сха="c" * 64)
    състояние = _цикъл(entities=голям, drawing="проект-голям", сха="d" * 64)

    assert състояние.observations == 2
    assert състояние.independent_sources == 1, (
        "поднаборът не е второ свидетелство — вложеност 1,0000")
    правила = _правила_по_име(памет)
    assert правила and all(п.state == CANDIDATE for п in правила)


