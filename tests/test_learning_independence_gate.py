def test_reshenie_za_poziciya_ne_se_uchi() -> None:
    """Конкретно количество, дължина или изключение не става правило.

    § 5 от заданието: „Конкретно количество, дължина или изключение в един проект
    не става общо правило." Затова ``POSITION_DECISION`` е най-тесното стъпало на
    стълбата и НЕ е приложимо, колкото и източника да го подкрепят.
    """

    присъда = scopes.scope_for(independent_sources=9, per_position=True)
    assert присъда["scope"] == scopes.ОБХВАТ_ПОЗИЦИЯ
    assert not scopes.is_applicable(scopes.ОБХВАТ_ПОЗИЦИЯ)
    assert not scopes.is_applicable(scopes.ОБХВАТ_ПРОЕКТ)
    assert scopes.is_applicable(scopes.ОБХВАТ_СЕМЕЙСТВО)
    assert scopes.is_applicable(scopes.ОБХВАТ_ОБЩ)
    assert scopes.narrower(scopes.ОБХВАТ_ОБЩ, scopes.ОБХВАТ_ПРОЕКТ) == (
        scopes.ОБХВАТ_ПРОЕКТ)


