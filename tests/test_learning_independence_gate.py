def test_dva_nezavisimi_v_edno_semeystvo_davat_ADAPTACIYA(памет) -> None:
    """Два независими проекта в ЕДНО семейство дават адаптация, не общо правило.

    Случаят в корпуса: ``d-1`` и ``тест-004`` са РАЗЛИЧНИ чертежи (покритие на
    надписите 0,3444, вложеност 0,5487 — и двете под праговете), но диалектите им
    съвпадат (покритие на образците **0,7308**, праг 0,50), тоест едно стилово
    семейство А.

    Изкуствените чертежи тук повтарят същото устройство: покритие на надписите
    **0,1515**, вложеност **0,2632** (независими), покритие на образците
    **1,0000** (едно семейство).

    Очакваното: правилото се приема, но с обхват ``FAMILY_CONVENTION`` —
    обозначено като адаптация в семейството, с записан диалект на донорите.
    Пренос МЕЖДУ семейства не е доказан и не се твърди.
    """

    _цикъл(entities=_чертеж("А1"), drawing="проект-1", сха="e" * 64)
    състояние = _цикъл(entities=_чертеж("А2"), drawing="проект-2", сха="f" * 64)

    assert състояние.independent_sources == 2
    приети = [п for п in _правила_по_име(памет) if п.state == ACCEPTED]
    assert приети, "два независими източника приемат правилото"
    правило = приети[0]
    assert правило.scope["learning_scope"] == scopes.ОБХВАТ_СЕМЕЙСТВО
    assert not scopes.crosses_families(правило.scope["learning_scope"]), (
        "адаптация в семейство НЕ е пренос между семейства")
    assert правило.scope["donor_styles"], (
        "обхватът е проверим само ако правилото носи диалекта на донорите")
    assert "адаптация" in правило.scope["scope_verdict"]


def test_semeynoto_pravilo_NE_se_prilaga_vurhu_drugo_semeystvo(памет) -> None:
    """Извън доказания обхват отговорът е ОТКАЗ, не най-близкото.

    Правило, доказано в два независими проекта на семейство А (диалект от 14
    образеца), се прилага върху чертеж от семейство Б (покритие на образците
    **0,0345**, вложеност 0,0667 — под праговете 0,50 и 0,85). Старият код нямаше
    обхват и го прилагаше —
    това е пренос между семейства без доказателство.
    """

    from lion_rebar.learning.policy_bridge import learned_declarations

    _цикъл(entities=_чертеж("А1"), drawing="проект-1", сха="e" * 64)
    _цикъл(entities=_чертеж("А2"), drawing="проект-2", сха="f" * 64)
    store = KnowledgeStore.load(памет)
    assert any(п.state == ACCEPTED for п in store.all_rules())

    # Целта е в СЪЩОТО семейство -> правилото важи.
    свои = learned_declarations(_чертеж("А3"), policy=DEFAULT_RECOGNITION_POLICY,
                                store=store, drawing="цел-А")
    assert свои["authorized"], "вътре в семейството правилото важи"

    # Целта е в ДРУГО семейство -> отказ, с причина „извън обхвата".
    чужди = learned_declarations(_чертеж("Б1", диалект=ДИАЛЕКТ_Б),
                                 policy=DEFAULT_RECOGNITION_POLICY,
                                 store=store, drawing="цел-Б")
    assert not чужди["authorized"] and not чужди["resolved"], (
        "друго семейство НЕ получава семейното правило")


