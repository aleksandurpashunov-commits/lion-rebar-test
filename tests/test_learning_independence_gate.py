# --------------------------------------------------------------------------- #
# Изкуствени чертежи. Съдържанието е избрано така, че ``full_profile`` да даде
# точно едно учимо предложение (``POSITION_KEY_SPEC`` върху слой ``ARMTXT1``,
# прочетено от ``_parse_legend_spec`` — функцията на самата програма), а
# диалектът да е над ``МИН_ОБРАЗЦИ``.
# --------------------------------------------------------------------------- #

#: Четиринайсет образеца — диалектът на семейство „А" в тези тестове.
ДИАЛЕКТ_А = (
    "Гр.%d s=20", "К.%d x 30", "стр. %dN12/s=20", "%d бр.стр.", "Ш%d - 12/20",
    "поз.%d", "%dxN14", "%d см", "L=%d общо", "s=%d/пълнеж", "%d N16 x 40",
    "фиби %d", "плоча %d горе", "ребро %d долу",
)

#: Съвсем друг диалект — семейство „Б". Нула общи образеца с „А".
ДИАЛЕКТ_Б = (
    "\\U+%d Bars", "%dx200 distribution", "\\L%dx150", "%d-%d spacing",
    "Slab top %d", "Slab bottom %d", "Mesh %d", "Edge %d", "Stirrup %d",
    "Cover %d mm", "Splice %d", "Anchor %d", "Chair %d", "Lap %d",
)


def _текст(handle: str, слой: str, стойност: str, x: float, y: float):
    return DxfEntityRecord(handle=handle, entity_type="TEXT", layer=слой,
                           geometry={"insert": [x, y], "height": 2.5},
                           text=стойност)


def _чертеж(белег: str, *, легенда: int = 5, диалект=ДИАЛЕКТ_А,
            допълнителни: int = 0) -> list[DxfEntityRecord]:
    """Изкуствен чертеж: легенда на позиционните ключове + диалект + зони.

    ``белег`` влиза във всеки надпис ОСВЕН легендните, затова два чертежа с
    различен белег имат общи само петте легендни надписа: покритие 0,1515,
    вложеност 0,2632 — доказано различни източници. ``диалект`` решава стиловото
    семейство. ``допълнителни`` добавя надписи, без да маха стари — така се прави
    ПОДМНОЖЕСТВО (вложеност 1,0000).
    """

    редове: list[DxfEntityRecord] = []
    for и in range(легенда):
        # Легендата НЕ носи белега: тя трябва да мине през ``_parse_legend_spec``
        # — функцията, с която самата програма чете легендата. Затова легендните
        # надписи са общи за всички чертежи тук, а различието идва от диалекта.
        редове.append(_текст("L%s%d" % (белег, и), "ARMTXT1",
                             "N%d L=%d" % (10 + и * 2, 200 + и * 37),
                             и * 10.0, 0.0))
    for и, шаблон in enumerate(диалект):
        стойност = (шаблон % (и + 1, и + 2) if шаблон.count("%d") == 2
                    else шаблон % (и + 1))
        редове.append(_текст("G%s%d" % (белег, и), "ARM_TXT",
                             "%s %s" % (стойност, белег), и * 7.0, 20.0))
    for и in range(допълнителни):
        редове.append(_текст("X%s%d" % (белег, и), "Dopulnitelni",
                             "%s допълнение %d" % (белег, и), и * 3.0, 60.0))
    return редове


@pytest.fixture()
def памет(tmp_path, monkeypatch):
    """Празна, но СЪЩЕСТВУВАЩА памет в ``tmp_path`` + включен цикъл."""

    monkeypatch.delenv("LION_REBAR_LEARNING", raising=False)
    monkeypatch.delenv("LION_REBAR_AUTOCYCLE", raising=False)
    път = tmp_path / "naucheno.json"
    KnowledgeStore.load(път).save()
    monkeypatch.setenv("LION_REBAR_NAUCHENO", str(път))
    return път


def _цикъл(*, entities, drawing: str, сха: str) -> LearningStatus:
    състояние = run_cycle_after_analysis(
        status=LearningStatus(enabled=True), bridge_report={},
        entities=entities, drawing=drawing, family=drawing, source_sha256=сха)
    # Без тази проверка тестът може да мине „успешно" при паднал цикъл: грешката
    # се лапа нарочно, за да не вали анализа.
    assert състояние.error == "", състояние.error
    return състояние


def _правила_по_име(път):
    store = KnowledgeStore.load(път)
    return [п for п in store.all_rules()
            if п.signature.get("match_mode") == "NAME_TOKEN"
            and п.role == "POSITION_KEY_SPEC"]


