def test_pragovete_sa_izmerenite() -> None:
    """Праговете стоят в измерения ров и не се донастройват мълчаливо.

    ``PREDI.json``: вложеност при ЕДИН чертеж 0,9469 и 1,0000; най-високата
    вложеност между различни чертежи 0,8011. Покритие при един чертеж 0,5974 и
    0,8560; най-високото между различни 0,4393.
    """

    from lion_rebar.learning import source_identity as си

    assert си.ПРАГ_ВЛОЖЕНОСТ == 0.90
    assert 0.8011 < си.ПРАГ_ВЛОЖЕНОСТ < 0.9469, "прагът е В измерения ров"
    assert си.ПРАГ_ПОКРИТИЕ == 0.50
    assert 0.4393 < си.ПРАГ_ПОКРИТИЕ < 0.5974
    # Семейството по диалект — преписано от `izmereno.py`, не избрано наново.
    assert (си.СЕМЕЙСТВО_ПОКРИТИЕ, си.СЕМЕЙСТВО_ВЛОЖЕНОСТ) == (0.50, 0.85)
    assert scopes.МИН_НЕЗАВИСИМИ == 2
