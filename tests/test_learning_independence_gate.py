def test_dva_fayla_na_edin_chertezh_NE_davat_priemane(памет) -> None:
    """Два файла на ЕДИН чертеж не дават приемане — случаят ``d-1`` / ``s-10``.

    Измерено: ``d-1`` и ``s-10`` са един чертеж с РАЗЛИЧНИ sha
    (``4dc59ff2ba35`` срещу ``c41de772a8fd``) и различни имена на проект;
    вложеността на надписите им е **0,9469**, покритието **0,8560**. Старата
    порта (``family`` ИЛИ ``source_sha256``) ги пускаше за две доказателства и
    приемаше **6 правила** от един чертеж, подаден двукратно.

    Тук вторият файл е същият чертеж с един нов надпис: покритие 19/20 = 0,9500,
    вложеност 1,0000.
    Очакваното: ЕДНО свидетелство, тоест ``CANDIDATE``, не ``ACCEPTED``.
    """

    основен = _чертеж("А")
    втори_файл = _чертеж("А") + [
        _текст("НОВ", "Dopulnitelni", "А допълнителен надпис", 1.0, 99.0)]

    _цикъл(entities=основен, drawing="проект-А", сха="a" * 64)
    състояние = _цикъл(entities=втори_файл, drawing="проект-А-под-друго-име",
                       сха="b" * 64)

    assert състояние.observations == 2, "и двата файла се записват"
    assert състояние.independent_sources == 1, (
        "но са ЕДИН независим източник — различно име и различен sha не "
        "доказват различен източник")
    правила = _правила_по_име(памет)
    assert правила, "правилото се образува с доказателствата си"
    assert [п.state for п in правила] == [CANDIDATE] * len(правила)
    assert правила[0].scope["learning_scope"] == scopes.ОБХВАТ_ПРОЕКТ
    assert правила[0].scope["independent_sources"] == 1


