"""Черновите се подреждат по ВЕРСИЯ, не по име на файл.

Намерено 22.09.2026 при истинска употреба: собственикът роди форма от отказан
случай, черновата `0.3.16` се записа вярно с новата форма вътре, а MASTER
Studio отвори **0.3.7** и формата „я нямаше“.

Причината е сортиране на низове: при десетте чернови в папката му редът беше
0.3.1, 0.3.12, 0.3.15, 0.3.16, 0.3.2, 0.3.3 … 0.3.7 — знакът „7“ е след „1“.
``EngineStudio`` отваря ``list_drafts()[-1]``, тоест последната, и хващаше
най-СТАРАТА от последните.
"""
import json

import pytest

from lion_rebar.engine.repository import EngineRepository


@pytest.fixture()
def хранилище(tmp_path):
    return EngineRepository(tmp_path / "engine_registry")


def _чернова(хранилище, версия: str) -> None:
    """Записва минимална чернова направо на диска."""

    хранилище.drafts_dir.mkdir(parents=True, exist_ok=True)
    път = хранилище.drafts_dir / f"lion-rebar-master_v{версия}.draft.json"
    път.write_text(json.dumps({
        "engine_id": "lion-rebar-master",
        "title": "MASTER",
        "version": версия,
        "state": "DRAFT",
        "shapes": [],
    }, ensure_ascii=False), encoding="utf-8")


def test_последната_чернова_е_най_новата(хранилище):
    """Точните десет версии от папката на собственика."""

    for версия in ("0.3.1", "0.3.12", "0.3.15", "0.3.16",
                   "0.3.2", "0.3.3", "0.3.4", "0.3.5", "0.3.6", "0.3.7"):
        _чернова(хранилище, версия)

    редът = [info.version for info in хранилище.list_drafts()]

    assert редът[-1] == "0.3.16", "EngineStudio отваря последната — тя трябва да е най-новата"
    assert редът == ["0.3.1", "0.3.2", "0.3.3", "0.3.4", "0.3.5",
                     "0.3.6", "0.3.7", "0.3.12", "0.3.15", "0.3.16"]


def test_двуцифреното_бие_едноцифреното(хранилище):
    _чернова(хранилище, "0.3.9")
    _чернова(хранилище, "0.3.10")

    assert [i.version for i in хранилище.list_drafts()] == ["0.3.9", "0.3.10"]


def test_нечислова_версия_не_чупи_подредбата(хранилище):
    """Чернова с име извън образеца остава накрая, но не хвърля."""

    _чернова(хранилище, "0.3.2")
    _чернова(хранилище, "0.4.0-rc1")

    редът = [i.version for i in хранилище.list_drafts()]
    assert "0.3.2" in редът and "0.4.0-rc1" in редът
    assert редът.index("0.3.2") < редът.index("0.4.0-rc1")
