# -*- coding: utf-8 -*-
"""Голо число на надписния слой не е размер на пръта.

Възпроизведено от `d-2` (AutoCAD Structural Detailing), четири позиции. ASD пише
описанието на разпределението като ДВА MTEXT-а на един слой — брой и позиционен
надпис — със съседни handle-и:

| поз. | надпис | начертано | ведомост на проектанта | програмата даваше |
|---|---|---|---|---|
| 9 | `2015` Ø14x610 | 14,3 + 594,3 | **15 + 595** | **[601, 9]** от `2014`=„9" |
| 24 | `2A7B` Ø8x360 | 349,5 + 9,6 | **350 + 10** | **[24, 336]** от `2A7A`=„24" |
| 25 | `2AB5` Ø12x220 | 208,9 + 9,4 | **210 + 10** | **[25, 195]** от `2AB4`=„25" |
| 35 | `2C1B` Ø8x460 | 9,6 + 449,1 | **10 + 450** | **[425, 35]** от `2C1A`=„35" |

Стратегията `A_E_TOTAL_MINUS_PRINTED` приемаше голото число за един участък и
досмяташе другия като Δ = обявена обща − отпечатано, затова сборът винаги
излизаше точен, а стойностите не отговаряха нито на чертежа, нито на ведомостта.

Тестовете тук са СИНТЕТИЧНИ: проверяват правилото, не конкретния чертеж. В кода
няма име на слой, handle или размер от `d-2`.
"""
from __future__ import annotations

from lion_rebar.dxf.dimension_resolver import dimension_evidence_for_shape
from lion_rebar.dxf.models import DxfEntityRecord
from lion_rebar.engine.models import SegmentDefinition, ShapeDefinition

НАДПИСЕН_СЛОЙ = "Описание на разпределението"
КОТЕН_СЛОЙ = "koti"


def _форма() -> ShapeDefinition:
    """Прът с един винкел: два участъка, всеки със свой размерен код."""

    return ShapeDefinition(
        code="F004",
        name="ПРЪТ С ЕДИН ВИНКЕЛ",
        state="APPROVED",
        active=True,
        mirror_allowed=True,
        segments=[
            SegmentDefinition(index=1, length_code="L1", bend_after_deg=90.0,
                              bend_direction="RIGHT"),
            SegmentDefinition(index=2, length_code="L2"),
        ],
        recognition={"reference_segment_lengths_cm": [15.0, 595.0]},
    )


#: Начертаният прът: къс винкел 15 и основна част 595 — както в оригинала.
ТОЧКИ = ((0.0, 15.0), (0.0, 0.0), (595.0, 0.0))
ОБЯВЕНА = 610.0


def _текст(handle: str, слой: str, текст: str, точка, rotation: float = 0.0):
    return DxfEntityRecord(handle=handle, entity_type="MTEXT", layer=слой,
                           text=текст,
                           geometry={"insert": list(точка), "rotation": rotation})


def _разчети(записи, *, allowed=None):
    return dimension_evidence_for_shape(
        ТОЧКИ, _форма(), записи,
        declared_length_cm=ОБЯВЕНА,
        excluded_handles=("НАДПИС",),
        allowed_handles=allowed,
        annotation_layer=НАДПИСЕН_СЛОЙ,
    )


# --- дефектът --------------------------------------------------------------


def test_golo_chislo_na_nadpisniya_sloy_ne_e_razmer() -> None:
    """Число до пръта, но на слоя на самия надпис, не дава размери.

    Без правилото стратегията `A_E_TOTAL_MINUS_PRINTED` приема „9" за участък и
    досмята 601 = 610 − 9. Сборът излиза точен, а нито едно от двете числа не е
    размер на този прът.
    """

    записи = [
        _текст("НАДПИС", НАДПИСЕН_СЛОЙ, " 22N14x610/10", (5.0, 5.0)),
        _текст("БРОЙ", НАДПИСЕН_СЛОЙ, "9", (4.0, 8.0)),
    ]
    решения = _разчети(записи)
    assert решения == (), (
        "голо число на надписния слой не бива да става производствен размер")


def test_bez_praviloto_sluchayat_e_reshim() -> None:
    """Контрола за самия тест: без надписния слой същото число минава.

    Показва, че случаят наистина е в обхвата на резолвера и че отказът идва от
    новото правило, а не от друга причина.
    """

    записи = [
        _текст("НАДПИС", НАДПИСЕН_СЛОЙ, " 22N14x610/10", (5.0, 5.0)),
        _текст("БРОЙ", КОТЕН_СЛОЙ, "9", (4.0, 8.0)),
    ]
    решения = dimension_evidence_for_shape(
        ТОЧКИ, _форма(), записи,
        declared_length_cm=ОБЯВЕНА,
        excluded_handles=("НАДПИС",),
        allowed_handles=None,
        annotation_layer="",          # правилото е изключено
    )
    assert решения, "без правилото резолверът стига до решение"
    assert any("TOTAL_MINUS_PRINTED" in р.strategy for р in решения)


# --- истинските коти продължават да работят --------------------------------


def test_koti_na_koten_sloy_se_polzvat() -> None:
    """Истински размери на отделен слой дават верния вектор."""

    записи = [
        _текст("НАДПИС", НАДПИСЕН_СЛОЙ, " 22N14x610/10", (5.0, 5.0)),
        _текст("K1", КОТЕН_СЛОЙ, "15", (-8.0, 7.5), rotation=90.0),
        _текст("K2", КОТЕН_СЛОЙ, "595", (297.5, -8.0)),
    ]
    решения = _разчети(записи)
    assert решения, "котите на отделен слой трябва да се четат"
    най = решения[0]
    assert sorted(round(с, 1) for с in най.segment_lengths_cm) == [15.0, 595.0]
    assert set(най.text_handles) == {"K1", "K2"}


def test_izrichno_obyavena_kota_stoi_nad_praviloto() -> None:
    """Операторът може да обяви кота дори на надписния слой."""

    записи = [
        _текст("НАДПИС", НАДПИСЕН_СЛОЙ, " 22N14x610/10", (5.0, 5.0)),
        _текст("РЪЧНА", НАДПИСЕН_СЛОЙ, "15", (-8.0, 7.5), rotation=90.0),
        _текст("K2", КОТЕН_СЛОЙ, "595", (297.5, -8.0)),
    ]
    решения = _разчети(записи, allowed={"РЪЧНА", "K2"})
    assert решения, "изрично обявената кота се ползва"
    assert sorted(round(с, 1) for с in решения[0].segment_lengths_cm) == [15.0, 595.0]


