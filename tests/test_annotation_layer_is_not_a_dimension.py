# --- контрапримерът, който стесни правилото --------------------------------


def test_DIMENSION_na_nadpisniya_sloy_SE_chete() -> None:
    """Обект DIMENSION е размер по устройство — и на надписния слой.

    Контрапример от `Тест-003`, позиция `69F9B3` = `10N12x480`: истинските
    DIMENSION обекти `69F9B1` и `69F9B2` стоят на слой `Text ARM.2` — същия, на
    който е и надписът. Първата редакция на правилото ги изключи заедно с шума и
    верният вектор [50, 430] се загуби. Затова правилото важи само за СВОБОДЕН
    ТЕКСТ.
    """

    def _kota(handle, слой, мярка, точка, ot, do, rotation=0.0):
        # Празен DIMENSION се чете само когато двете му опорни точки лежат
        # върху самия контур — иначе близкият текст не е доказателство за
        # принадлежност.
        return DxfEntityRecord(
            handle=handle, entity_type="DIMENSION", layer=слой, text=None,
            geometry={"measurement": мярка, "text_midpoint": list(точка),
                      "rotation": rotation,
                      "defpoint2": list(ot), "defpoint3": list(do)})

    записи = [
        _текст("НАДПИС", НАДПИСЕН_СЛОЙ, " 22N14x610/10", (5.0, 5.0)),
        _kota("K1", НАДПИСЕН_СЛОЙ, 15.0, (-8.0, 7.5), (0.0, 15.0), (0.0, 0.0),
              rotation=90.0),
        _kota("K2", НАДПИСЕН_СЛОЙ, 595.0, (297.5, -8.0), (0.0, 0.0), (595.0, 0.0)),
    ]
    решения = _разчети(записи)
    assert решения, "DIMENSION на надписния слой трябва да се чете"
    assert sorted(round(с, 1) for с in решения[0].segment_lengths_cm) == [15.0, 595.0]


def test_dosmetnatoto_iska_potvurzhdenie_ot_chertezha() -> None:
    """Досметнатата стойност се сверява с начертания участък.

    Отпечатаната стойност е доказателство и стои над чертежа. Досметнатата е
    аритметика: ако не отговаря на нито един участък, който описва, решението
    пада. Измерено на d-2: точно това спира [601, 9] и [24, 336].
    """

    # Начертано е [15, 595]; кота „200" би дала досметнато 410 — нито едното.
    записи = [
        _текст("НАДПИС", НАДПИСЕН_СЛОЙ, " 22N14x610/10", (5.0, 5.0)),
        _текст("K1", КОТЕН_СЛОЙ, "200", (-8.0, 7.5), rotation=90.0),
    ]
    assert _разчети(записи) == (), "досметнато 410 при начертани 15 и 595 е отказ"

    # Същият път с вярната кота минава.
    записи_добри = [
        _текст("НАДПИС", НАДПИСЕН_СЛОЙ, " 22N14x610/10", (5.0, 5.0)),
        _текст("K1", КОТЕН_СЛОЙ, "15", (-8.0, 7.5), rotation=90.0),
    ]
    решения = _разчети(записи_добри)
    assert решения, "досметнато 595 при начертани 595 минава"
    assert sorted(round(с, 1) for с in решения[0].segment_lengths_cm) == [15.0, 595.0]
