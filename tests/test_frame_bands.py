"""Чертожната рамка има граница, не само котва (rc44).

Собственик, 2026-09-15: „Чете първо главния лист от DXf-а, след това гледа
рамките и експорта отива в този лист." И: „няма как да има рамка с детайли
в чертежа с гредите."

КАКВО БЕШЕ КРИВО
----------------
``DrawingFrame`` нямаше правоъгълник — само котвата на заглавния щемпел.
``assign_point_to_frame`` връщаше най-близката котва, тоест режеше по
средата между два съседни щемпела.

Това работи само ако щемпелът стои в средата на своя чертеж. В ``s-9`` той
е в ДЕСНИЯ край: всичките 32 заглавия на греди са в ``x 112 886..118 424``,
а котвата ГРЕДИ е на ``119 978``. Средата с ДЕТАЙЛИ (котва ``106 653``)
пада на ``113 315`` и открадва левия край на гредовия чертеж — шест греди
и армировката им отиваха в лист „детайли".

Операторската рамка не можеше да го поправи: нейният ``frame_index`` се
решава по същото правило и по същото заглавие. И петте записани области в
``s-9`` носят ``frame_index=5`` (ДЕТАЙЛИ).

ЗАЩО НЯМА ПРАГ
--------------
Реже се по най-широката празнина и толкова пъти, колкото е нужно всяка
лента да съдържа точно един щемпел. Броят на щемпелите калибрира рязането
сам. Праг, нагоден по един чертеж, се чупи на следващия: в ``s-9`` вярната
стойност е между 3 736 и 5 689.
"""
from __future__ import annotations

import pytest

from lion_rebar.dxf.models import DxfEntityRecord
from lion_rebar.export.frame_detection import (
    DrawingFrame,
    _frame_bands,
    assign_point_to_frame,
)


def _обект(x: float, y: float = 1000.0) -> DxfEntityRecord:
    return DxfEntityRecord(
        handle=f"H{x:.0f}",
        entity_type="TEXT",
        layer="ARMTXT",
        geometry={"insert": (x, y, 0.0)},
        text="4N16x200",
    )


def _рамка(index: int, anchor_x: float, code: str, **още) -> DrawingFrame:
    return DrawingFrame(
        index=index,
        marker_handle=f"M{index}",
        anchor_x=anchor_x,
        anchor_y=1750.0,
        title_text=code,
        supporting_text="",
        category_code=code,
        suggested_sheet_name=code.lower(),
        confidence="HIGH",
        **още,
    )


#: Два чертежа в редица, всеки с щемпел в ДЕСНИЯ си край — както е в ``s-9``.
#:
#: ДЕТАЙЛИ заема 1000..2400 с щемпел на 2400; ГРЕДИ заема 3200..5000 с щемпел
#: на 4800. Празнината между тях (800) е по-широка от всяка вътрешна (400).
#: Средата между двата щемпела пада на 3600 — тоест левите 400 единици на
#: гредовия чертеж са по-близо до ЧУЖДИЯ щемпел. Точно това местеше шестте
#: греди в ``s-9``.
_СЪДЪРЖАНИЕ = [_обект(x) for x in (1000, 1200, 1400, 1600, 1800, 2000, 2400)]
_СЪДЪРЖАНИЕ += [_обект(x) for x in (3200, 3400, 3600, 3800, 4000, 4400, 4800, 5000)]
_ДЕТАЙЛИ = _рамка(1, 2400.0, "DETAILS")
_ГРЕДИ = _рамка(2, 4800.0, "BEAMS")


class TestЛентите:
    def test_разделят_се_в_празнината(self) -> None:
        ленти = _frame_bands(_СЪДЪРЖАНИЕ, [_ДЕТАЙЛИ, _ГРЕДИ])
        assert ленти is not None
        assert ленти[1] == pytest.approx((1000.0, 2800.0))
        assert ленти[2] == pytest.approx((2800.0, 5000.0))

    def test_една_рамка_взима_всичко(self) -> None:
        ленти = _frame_bands(_СЪДЪРЖАНИЕ, [_ГРЕДИ])
        assert ленти == {2: (1000.0, 5000.0)}

    def test_без_съдържание_няма_ленти(self) -> None:
        assert _frame_bands([], [_ДЕТАЙЛИ, _ГРЕДИ]) is None

    def test_отказва_когато_щемпелите_са_в_една_група(self) -> None:
        """Два щемпела в един чертеж не могат да се разделят честно."""

        съдържание = [_обект(x) for x in (1000, 1100, 1200, 1300)]
        ленти = _frame_bands(съдържание, [_рамка(1, 1050.0, "DETAILS"), _рамка(2, 1250.0, "BEAMS")])
        # Празнините вътре са равни; ако не може да се раздели с точно един
        # щемпел на лента, се връща None и остава старото правило.
        assert ленти is None or set(ленти) == {1, 2}


class TestДефектътОтS9:
    """Щемпелът в десния край — точно случаят, който местеше гредите."""

    def test_най_близката_котва_бърка(self) -> None:
        """Без ленти точка от левия край на гредовия чертеж отива в ДЕТАЙЛИ."""

        # 3200 е в чертежа на ГРЕДИ, но е по-близо до котвата на ДЕТАЙЛИ.
        assert abs(3200 - 2400) < abs(3200 - 4800)
        assert assign_point_to_frame(3200.0, 1000.0, [_ДЕТАЙЛИ, _ГРЕДИ]) == 1

    def test_лентата_поправя_същата_точка(self) -> None:
        ленти = _frame_bands(_СЪДЪРЖАНИЕ, [_ДЕТАЙЛИ, _ГРЕДИ])
        с_ленти = [
            _рамка(1, 2400.0, "DETAILS", x_min=ленти[1][0], x_max=ленти[1][1]),
            _рамка(2, 4800.0, "BEAMS", x_min=ленти[2][0], x_max=ленти[2][1]),
        ]
        assert assign_point_to_frame(3200.0, 1000.0, с_ленти) == 2

    def test_останалите_точки_не_мърдат(self) -> None:
        ленти = _frame_bands(_СЪДЪРЖАНИЕ, [_ДЕТАЙЛИ, _ГРЕДИ])
        с_ленти = [
            _рамка(1, 2400.0, "DETAILS", x_min=ленти[1][0], x_max=ленти[1][1]),
            _рамка(2, 4800.0, "BEAMS", x_min=ленти[2][0], x_max=ленти[2][1]),
        ]
        for x, очаквана in ((1000.0, 1), (2400.0, 1), (3600.0, 2), (5000.0, 2)):
            assert assign_point_to_frame(x, 1000.0, с_ленти) == очаквана


class TestПадаОбратно:
    def test_без_ленти_остава_старото_правило(self) -> None:
        """Рамка без лента не бива да променя поведението си."""

        assert not _ДЕТАЙЛИ.contains_x
        assert assign_point_to_frame(2000.0, 1000.0, [_ДЕТАЙЛИ, _ГРЕДИ]) == 1

    def test_точка_извън_всички_ленти_пада_на_котвата(self) -> None:
        с_лента = _рамка(2, 4800.0, "BEAMS", x_min=3200.0, x_max=5000.0)
        assert assign_point_to_frame(100.0, 1000.0, [с_лента]) == 2
