def test_dagata_e_ogavka_ne_ramo():
    """Полилиния с bulge: правите са рамена, дъгата между тях е огъвка."""

    # 100 надясно, дъга 90° наляво, после 50 нагоре.
    bulge_90 = 0.41421356237309503          # tan(90°/4)
    обекти = [
        _дъгова_полилиния("P1", "ARM", [
            (0.0, 0.0, 0.0), (100.0, 0.0, bulge_90), (110.0, 10.0, 0.0),
            (110.0, 60.0, 0.0)]),
        _текст("T1", "ARM_TXT", "100", (50.0, 6.0), 10.0, 0.0),
        _текст("T2", "ARM_TXT", "50", (116.0, 35.0), 10.0, 90.0),
    ]
    ук = верига.ВериженУказател(обекти)
    дневник: list = []
    р = верига.присъда(["P1"], ук, 150.0, дневник=дневник)
    assert р is not None, причина(дневник)
    assert list(р.участъци_cm) == [100.0, 50.0]
    assert [о.вид for о in р.огъвки] == [верига.ДЪГА]
    assert р.огъвки[0].завой_deg == pytest.approx(90.0, abs=0.01)
    assert р.огъвки[0].радиус_cm is not None and р.огъвки[0].радиус_cm > 0.0


