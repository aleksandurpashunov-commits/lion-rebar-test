# Две неща се научиха, докато се строеше този пример, и двете са ЗА пазене:
#
# 1. надписът „40" в първата редакция беше на 2,1 височини от СЪСЕДНОТО рамо,
#    тоест в обхвата на две рамена наведнъж, и правилото отказа с `MALAK_ZAPAS`.
#    Вярно поведение върху зле построен пример — поправи се примерът;
# 2. втората редакция сложи обърнатата отсечка НА ЕДНА ЛИНИЯ със съседа ѝ и
#    веригата даде две рамена вместо три. Причината е, че
#    ``рамена_на_веригата`` слива колинеарните съседни прави — две отсечки на
#    една линия СА едно рамо на пръта. Затова тук обърнатата отсечка е отвесна.
ОБЪРНАТ = [
    # Средната отсечка е начертана в ОБРАТНАТА посока спрямо съседите си.
    _права("A1", "ARM", (0.0, 0.0), (300.0, 0.0)),
    _права("A2", "ARM", (300.0, 90.0), (300.0, 0.0)),     # обърната и отвесна
    _права("A3", "ARM", (300.0, 90.0), (420.0, 90.0)),
    _текст("T1", "ARM_TXT", "300", (150.0, 10.0), 10.0, 0.0),
    _текст("T2", "ARM_TXT", "90", (312.0, 45.0), 10.0, 90.0),
    _текст("T3", "ARM_TXT", "120", (360.0, 100.0), 10.0, 0.0),
]


def test_obarnat_obhod_se_poema():
    """Отсечка, начертана наопаки, се преобръща и веригата се затваря."""

    ук = верига.ВериженУказател(ОБЪРНАТ)
    дневник: list = []
    р = верига.присъда(["A1"], ук, 510.0, дневник=дневник)
    assert р is not None, причина(дневник)
    assert list(р.участъци_cm) == [300.0, 90.0, 120.0]
    assert дневник == []


def test_obarnat_obhod_zapazva_reda_na_ramenata():
    """Преобръщането не разбърква реда: обхожда се от единия свободен край."""

    подредени = верига.подреди_веригата(
        верига.събери_веригата(["A1"], верига.ВериженУказател(ОБЪРНАТ))[0])
    assert подредени is not None
    краища = [(о.начало, о.край) for о in подредени]
    for предишна, следваща in zip(краища, краища[1:]):
        assert предишна[1] == pytest.approx(следваща[0], abs=1e-6)


def test_kolinearnite_otsechki_sa_EDNO_ramo():
    """Две прави на една линия са едно рамо, независимо от посоката им.

    Това не е закръгляне, а определение: рамото на пръта е правият участък, а
    не обектът в DXF. Чертожник, който го е начертал на две парчета, не му
    добавя огъвка.
    """

    обекти = [
        _права("K1", "ARM", (0.0, 0.0), (300.0, 0.0)),
        _права("K2", "ARM", (420.0, 0.0), (300.0, 0.0)),   # колинеарна, обърната
        _права("K3", "ARM", (420.0, 0.0), (420.0, 90.0)),
    ]
    отсечки, _слой = верига.събери_веригата(
        ["K1"], верига.ВериженУказател(обекти))
    рамена = верига.рамена_на_веригата(верига.подреди_веригата(отсечки))
    assert [round(р.дължина, 2) for р in рамена] == [420.0, 90.0]
    assert рамена[0].handles == ("K1", "K2")


