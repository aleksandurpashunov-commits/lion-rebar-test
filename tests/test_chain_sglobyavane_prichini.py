"""F2.1: кои случаи при сглобяването на целия прът се поемат и кои се отказват.

Петте случая от заданието, всеки със свой тест:

| случай | поведение |
|---|---|
| **дъги** | поемат се — `bulge` дава завой, хорда и радиус |
| **обърнат обход** | поема се — отсечката се преобръща с `-bulge` |
| прекъсвания | отказ `PREKASVANE_ILI_PRIMKA` |
| пресичания | отказ `RAZKLONENIE` |
| разклонения | отказ `RAZKLONENIE` |

Отказът при последните три е НАРОЧЕН и тестовете го пазят: клон или пресичане
значи, че „прътът" не е един прът, а подреждането по най-близко би било догадка.
„Нула или две съвпадения е отказ, не най-близкото."

Новото тук е, че отказът вече **не е мълчалив**. Досега двайсетина различни
причини изглеждаха еднакво отвън — едно ``None``. Всеки тест проверява и КОДА
на причината, за да не може утре един отказ да се маскира като друг.
"""
from __future__ import annotations

import pytest

from lion_rebar.dxf import chain_printed_dimensions as верига
from lion_rebar.dxf.models import DxfEntityRecord


def _права(handle: str, слой: str, начало, край) -> DxfEntityRecord:
    return DxfEntityRecord(
        handle=handle, entity_type="LINE", layer=слой,
        geometry={"start": [начало[0], начало[1], 0.0],
                  "end": [край[0], край[1], 0.0]},
    )


def _текст(handle: str, слой: str, текст: str, точка, височина=10.0,
           ротация=0.0) -> DxfEntityRecord:
    return DxfEntityRecord(
        handle=handle, entity_type="TEXT", layer=слой, text=текст,
        geometry={"insert": [точка[0], точка[1], 0.0], "height": височина,
                  "rotation": ротация},
    )


def _дъгова_полилиния(handle: str, слой: str, върхове) -> DxfEntityRecord:
    """Върховете са (x, y, bulge); bulge = tan(θ/4) на дъгата ПОСЛЕ върха."""

    return DxfEntityRecord(
        handle=handle, entity_type="LWPOLYLINE", layer=слой,
        geometry={"points": [[в[0], в[1], 0.0] for в in върхове],
                  "bulges": [в[2] for в in върхове], "closed": False},
    )


def причина(дневник) -> str:
    return дневник[0]["code"] if дневник else ""


