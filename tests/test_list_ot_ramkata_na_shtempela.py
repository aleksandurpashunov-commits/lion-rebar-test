# -*- coding: utf-8 -*-
"""Листът е начертаната рамка, в която стои щемпелът му — не най-близкият щемпел.

Собственик, 23.10.2026, върху ``Тест-002`` (S-SR+27,82): „това е Горна
армировка плоча на кота +27.82, най-горният чертеж е кофражен“ и „това е
долна скара“. Трите листа стоят един над друг, щемпелът е долу вдясно на
своя лист.

Щемпели един над друг не се делят по x (``_frame_bands`` връща ``None``) и
дотук позицията отиваше към НАЙ-БЛИЗКИЯ щемпел. Горната част на всеки лист е
по-близо до щемпела на листа НАД него. Измерено на 22.10.2026: 59 позиции от
горната армировка в кофража (UNKNOWN), 88 от долната скара — в горната.

Всеки лист обаче е НАЧЕРТАН: затворен правоъгълник (двоен, на слоеве
``STANDARD`` и ``S-DETL``), вътре в който е точно един щемпел. Това е
проектантска граница, не разстояние. В корпуса правилото мести точно тези
147 позиции и нищо друго — в останалите 10 чертежа листовете се делят по x.

Отказът остава отказ: щемпел без своя рамка, рамка с два щемпела или
застъпени рамки — правилото не се прилага и остава старото поведение.
"""
from __future__ import annotations

from lion_rebar.dxf.models import DxfEntityRecord
from lion_rebar.export.frame_detection import assign_point_to_frame, detect_drawing_frames

#: Щемпелите на Тест-002 (котвата на „ЧЕРТЕЖ:“) и заглавията им.
ЩЕМПЕЛИ = (
    ("K", 50100.0, 65692.0, "КОФРАЖЕН ПЛАН НА ПЛОЧА НА КОТА +27.82"),
    ("G", 50270.0, 61714.0, "ГОРНА АРМИРОВКА ПЛОЧА НА КОТА +27.82"),
    ("D", 50564.0, 58220.0, "ДОЛНА АРМИРОВКА ПЛОЧА И ГРЕДИ НА КОТА +27.82"),
)

#: Външните рамки на листовете, както са начертани в Тест-002.
РАМКИ = (
    ("RK", "S-DETL", 42771.0, 50887.0, 65502.0, 68472.0),
    ("RG", "STANDARD", 43017.0, 51057.0, 61524.0, 64494.0),
    ("RD", "STANDARD", 42956.0, 51351.0, 58030.0, 61000.0),
)


def _щемпели() -> list[DxfEntityRecord]:
    записи = []
    for ключ, x, y, заглавие in ЩЕМПЕЛИ:
        записи.append(DxfEntityRecord(
            "M" + ключ, "MTEXT", "STANDARD", {"insert": [x, y, 0], "char_height": 20.0}, "ЧЕРТЕЖ:"))
        записи.append(DxfEntityRecord(
            "T" + ключ, "TEXT", "STANDARD", {"insert": [x + 150.0, y, 0], "height": 20.0}, заглавие))
    return записи


def _рамка(handle: str, слой: str, x0: float, x1: float, y0: float, y1: float) -> DxfEntityRecord:
    return DxfEntityRecord(handle, "LWPOLYLINE", слой, {
        "points": [[x0, y0], [x1, y0], [x1, y1], [x0, y1]], "closed": True})


def _лист(точка, рамки) -> str:
    индекс = assign_point_to_frame(точка[0], точка[1], рамки)
    рамка = next((р for р in рамки if р.index == индекс), None)
    return "" if рамка is None else рамка.category_code


#: Позиции от Тест-002: горната част на горната армировка, горната част на
#: долната скара и една точка под котвата на долния щемпел, но в листа му.
ГОРЕ_В_ГОРНАТА = (45838.0, 64000.0)      # 15N10x300/20 и съседите
ГОРЕ_В_ДОЛНАТА = (44447.0, 60247.0)      # 2N12x200 около отвора
ПОД_ДОЛНИЯ_ЩЕМПЕЛ = (44447.0, 58150.0)


def test_kontrola_bez_ramki_e_nai_blizkiyat_shtempel():
    """Положителна контрола: без начертаните рамки грешката се вижда."""

    рамки = detect_drawing_frames(_щемпели())

    assert _лист(ГОРЕ_В_ГОРНАТА, рамки) == "UNKNOWN"
    assert _лист(ГОРЕ_В_ДОЛНАТА, рамки) == "TOP"


def test_listat_e_ramkata_na_shtempela():
    рамки = detect_drawing_frames(_щемпели() + [_рамка(*р) for р in РАМКИ])

    assert _лист(ГОРЕ_В_ГОРНАТА, рамки) == "TOP"
    assert _лист(ГОРЕ_В_ДОЛНАТА, рамки) == "BOTTOM"
    assert _лист(ПОД_ДОЛНИЯ_ЩЕМПЕЛ, рамки) == "BOTTOM"


def test_dvoynata_ramka_ne_prechi():
    """Тест-002 чертае всяка рамка двойно: външна и вътрешна на 50 единици."""

    вътрешни = [
        _рамка(h + "i", с, x0 + 50, x1 - 50, y0 + 50, y1 - 50)
        for h, с, x0, x1, y0, y1 in РАМКИ
    ]
    рамки = detect_drawing_frames(_щемпели() + [_рамка(*р) for р in РАМКИ] + вътрешни)

    assert _лист(ГОРЕ_В_ГОРНАТА, рамки) == "TOP"
    assert _лист(ГОРЕ_В_ДОЛНАТА, рамки) == "BOTTOM"


def test_shtempel_bez_svoya_ramka_vrashta_staroto():
    """Ако дори един щемпел няма рамка, правилото не се прилага изобщо."""

    рамки = detect_drawing_frames(_щемпели() + [_рамка(*р) for р in РАМКИ[1:]])

    assert _лист(ГОРЕ_В_ГОРНАТА, рамки) == "UNKNOWN"
    assert all(р.y_min is None for р in рамки)


def test_ramka_s_dva_shtempela_ne_e_list():
    """Обща рамка около два листа не казва кой лист е чий."""

    обща = _рамка("RX", "STANDARD", 42900.0, 51400.0, 58000.0, 64600.0)
    рамки = detect_drawing_frames(_щемпели() + [обща, _рамка(*РАМКИ[0])])

    assert all(р.y_min is None for р in рамки)


def test_listove_edin_do_drug_ne_se_promenyat():
    """Чертежи с листове по x (останалите 10 в корпуса) остават същите."""

    записи = [
        DxfEntityRecord("M1", "MTEXT", "STANDARD", {"insert": [9000, 0, 0], "char_height": 20.0}, "ЧЕРТЕЖ:"),
        DxfEntityRecord("T1", "TEXT", "STANDARD", {"insert": [9150, 0, 0], "height": 20.0}, "ГОРНА АРМИРОВКА ПЛОЧА"),
        DxfEntityRecord("M2", "MTEXT", "STANDARD", {"insert": [19000, 0, 0], "char_height": 20.0}, "ЧЕРТЕЖ:"),
        DxfEntityRecord("T2", "TEXT", "STANDARD", {"insert": [19150, 0, 0], "height": 20.0}, "ДОЛНА АРМИРОВКА ПЛОЧА"),
        DxfEntityRecord("P1", "TEXT", "s-Text", {"insert": [2000, 3000, 0], "height": 12.0}, "2N12x200"),
        DxfEntityRecord("P2", "TEXT", "s-Text", {"insert": [12000, 3000, 0], "height": 12.0}, "2N12x200"),
        _рамка("R1", "STANDARD", 0, 9900, -200, 6000),
        _рамка("R2", "STANDARD", 10000, 19900, -200, 6000),
    ]

    рамки = detect_drawing_frames(записи)

    assert all(р.contains_x and р.y_min is None for р in рамки)
