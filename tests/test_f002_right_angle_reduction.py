"""Редукция под прав ъгъл не изписва размер „0 cm“ (rc44).

Собственик, 2026-09-14, за реалната позиция „134N18x410" в проект ``s-10``
— [260, 40, 110] cm: „виждаш ли този дефект в желязото с редукция, трябва да
го оправим да изглежда както на DWG."

Прътът в чертежа върви 260 cm хоризонтално, качва се 40 cm под ПРЯВ ЪГЪЛ и
продължава 110 cm. Хоризонталното отместване на редукцията е нула — но
рисунката въпреки това изписваше четвърти размер „0 cm" над него. В описа
това изглежда като пропуснат размер, а не като липсващ.

``DX2``/``DY2`` остават производствените параметри на F002: при истинско
наклонено снаждане и двата са смислени и двата се показват. Скрива се само
този, който го няма.
"""
from __future__ import annotations

import re

import pytest

from lion_rebar.export.master_engine_v031 import (
    parameters_from_segments,
    render_master_svg,
)

_ПРАВ = {"L1": 260.0, "DX2": 0.0, "DY2": 40.0, "L3": 110.0}
_НАКЛОНЕН = {"L1": 310.0, "DX2": 18.19, "DY2": 10.5, "L3": 150.0}


def _размери(values) -> list[str]:
    return re.findall(r">([\d.,]+) cm<", render_master_svg("F002", values))


class TestПравЪгъл:
    def test_нулевото_отместване_не_се_изписва(self) -> None:
        размери = _размери(_ПРАВ)

        assert "0" not in размери
        assert размери == ["260", "40", "110"]

    def test_същото_и_при_изчислена_нула(self) -> None:
        """``cos(90°)`` дава 2.4e-15, не кръгла нула — прагът го хваща."""

        parameters = parameters_from_segments(
            "F002", (260.0, 40.0, 110.0),
            production_length_cm=410.0, turn_angles_deg=(90.0, 90.0),
        )

        assert parameters.values["DX2"] < 1e-9
        assert "0" not in _размери(parameters.values)

    def test_формата_върви_нагоре_под_прав_ъгъл(self) -> None:
        """Силуетът трябва да съвпада с чертежа: ⌐ обърнато."""

        svg = render_master_svg("F002", _ПРАВ)
        points = re.search(r'points="([^"]+)"', svg)
        assert points is not None
        върхове = [
            tuple(float(v) for v in двойка.split(","))
            for двойка in points.group(1).split()
        ]

        assert len(върхове) == 4
        # Първото рамо е хоризонтално, качването е строго вертикално.
        assert върхове[0][1] == върхове[1][1]
        assert върхове[1][0] == pytest.approx(върхове[2][0], abs=0.01)
        assert върхове[1][1] != върхове[2][1]
        # Последното рамо пак е хоризонтално.
        assert върхове[2][1] == върхове[3][1]


class TestНаклоненаРедукция:
    def test_истинското_снаждане_показва_и_двете_проекции(self) -> None:
        """Защитата: поправката не скрива смислен размер."""

        размери = _размери(_НАКЛОНЕН)

        assert "310" in размери
        assert "150" in размери
        assert len(размери) == 4

    @pytest.mark.parametrize("dx", [0.05, 0.5, 5.0, 18.19])
    def test_отместване_над_прага_се_показва(self, dx: float) -> None:
        values = dict(_НАКЛОНЕН, DX2=dx)

        assert len(_размери(values)) == 4

    @pytest.mark.parametrize("dx", [0.0, 0.001, 0.049])
    def test_отместване_под_прага_се_скрива(self, dx: float) -> None:
        """Под половин милиметър няма отместване нито в чертежа, нито в цеха."""

        values = dict(_НАКЛОНЕН, DX2=dx)

        assert len(_размери(values)) == 3
