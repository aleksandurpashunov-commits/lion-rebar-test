"""Прът с редукция: каноничен силует, трите дължини и отместването (rc44).

Собственик, 2026-09-14, за реалната позиция „134N18x410" в проект ``s-10``
— [260, 40, 110] cm. Три последователни уточнения:

  1. „виждаш ли този дефект в желязото с редукция, трябва да го оправим да
     изглежда както на DWG";
  2. „трябва да изглежда като нашата мастър форма прът с редукция, но с
     нанесените размери 260/40/110";
  3. „приеми формата за желязо с редукция като канонична и евентуално само
     тези 4 cm да са различни, ако някой проектант е дал друго."

КАКВО БЕШЕ КРИВО
----------------
Прътът е почти прав: трите му участъка вървят под −90°, 95.7° и −90°, тоест
редукцията се отклонява само 5.7° от оста — проектантът я котира ``i = 1:10``
точно защото не личи. Ъгълът обаче е записан 90° (стойността по подразбиране
при потвърждаване на форма), затова DX2 излизаше 0, DY2 — 40, и рисунката
ставаше стъпало с прав ъгъл. Отгоре на това изписваше и размер „0 cm".

КАКВО Е СЕГА
------------
Наклонът в рисунката е фиксиран, защото истинският не се вижда: 4 cm при
260 cm рамо е под един пиксел във VID клетката. Дължините остават в мащаб,
затова две различни позиции пак изглеждат различно.

Числата носят истината: трите дължини отдолу (260 / 40 / 110) и отместването
отстрани (4). Отместването идва от самите проекции, когато те са записани
вярно; при 90° ъгъл се извежда по конвенцията ``MASTER_REDUCTION_SLOPE``
(1:10), никога чрез мерене по чертежа.
"""
from __future__ import annotations

import math
import re

import pytest

from lion_rebar.export.master_engine_v031 import (
    MASTER_REDUCTION_SLOPE,
    parameters_from_segments,
    render_master_svg,
)

#: Позицията на собственика: ъгълът е 90°, затова проекциите са безполезни.
_ЗАПИСАН_90 = {"L1": 260.0, "DX2": 0.0, "DY2": 40.0, "L3": 110.0}
#: Проект 004: същият вид прът, но с вярно записани проекции.
_ВЕРНИ = {"L1": 259.627289, "DX2": 40.372879, "DY2": 4.036866, "L3": 110.000038}
#: Друг проектант, дал 5 cm отместване.
_ПЕТ_СМ = {"L1": 260.0, "DX2": 39.69, "DY2": 5.0, "L3": 110.0}


def _размери(values) -> list[str]:
    return re.findall(r">([\d.,]+)<", render_master_svg("F002", values))


def _върхове(values) -> list[tuple[float, float]]:
    svg = render_master_svg("F002", values)
    points = re.search(r'points="([^"]+)"', svg)
    assert points is not None
    return [
        tuple(float(v) for v in двойка.split(","))
        for двойка in points.group(1).split()
    ]


def _хоризонтални_размерни_линии(values) -> list[tuple[float, float, float]]:
    """(x1, x2, y) на всяка хоризонтална размерна линия."""

    svg = render_master_svg("F002", values)
    линии = []
    for m in re.finditer(
        r'<line class="dimension-line" x1="([\d.-]+)" y1="([\d.-]+)" '
        r'x2="([\d.-]+)" y2="([\d.-]+)"',
        svg,
    ):
        x1, y1, x2, y2 = (float(v) for v in m.groups())
        if abs(y1 - y2) < 1e-6:
            линии.append((x1, x2, y1))
    return линии


def _вертикална_размерна_линия(values) -> tuple[float, float, float]:
    """(x, y1, y2) на размера за отместването."""

    svg = render_master_svg("F002", values)
    for m in re.finditer(
        r'<line class="dimension-line" x1="([\d.-]+)" y1="([\d.-]+)" '
        r'x2="([\d.-]+)" y2="([\d.-]+)"',
        svg,
    ):
        x1, y1, x2, y2 = (float(v) for v in m.groups())
        if abs(x1 - x2) < 1e-6:
            return (x1, y1, y2)
    raise AssertionError("няма вертикална размерна линия за отместването")


class TestРазмерите:
    def test_трите_дължини_и_отместването(self) -> None:
        assert _размери(_ЗАПИСАН_90) == ["260", "40", "110", "4"]

    def test_няма_размер_нула(self) -> None:
        """Старият дефект: четвърти размер „0 cm" над несъществуващо нещо."""

        assert "0" not in _размери(_ЗАПИСАН_90)

    def test_сборът_на_трите_е_обявената_дължина(self) -> None:
        трите = [float(x) for x in _размери(_ЗАПИСАН_90)[:3]]

        assert sum(трите) == pytest.approx(410.0)

    def test_средният_размер_е_дължината_не_проекцията(self) -> None:
        """MASTER формулата сумира ``hypot`` — това реже арматуристът."""

        очаквано = math.hypot(_ВЕРНИ["DX2"], _ВЕРНИ["DY2"])

        assert float(_размери(_ВЕРНИ)[1]) == pytest.approx(очаквано, abs=0.01)


class TestОтместването:
    def test_взима_се_от_проекциите_когато_са_верни(self) -> None:
        assert float(_размери(_ВЕРНИ)[3]) == pytest.approx(4.04, abs=0.01)

    def test_различен_проектант_различно_отместване(self) -> None:
        """Собственик: „както другия е дал 5 cm"."""

        assert _размери(_ПЕТ_СМ)[3] == "5"

    def test_при_ъгъл_90_се_извежда_по_конвенция(self) -> None:
        """40 cm редукция при 1:10 дава 4 cm — без мерене по чертежа."""

        assert float(_размери(_ЗАПИСАН_90)[3]) == pytest.approx(
            40.0 / MASTER_REDUCTION_SLOPE
        )

    def test_и_при_изчислена_нула(self) -> None:
        """``cos(90°)`` дава 2.4e-15, не кръгла нула."""

        parameters = parameters_from_segments(
            "F002", (260.0, 40.0, 110.0),
            production_length_cm=410.0, turn_angles_deg=(90.0, 90.0),
        )

        assert _размери(parameters.values) == ["260", "40", "110", "4"]

    def test_конвенцията_е_едно_на_десет(self) -> None:
        assert MASTER_REDUCTION_SLOPE == 10.0


class TestСилуетът:
    def test_редукцията_се_изкачва_надясно(self) -> None:
        """Мастър шаблонът, дословно — и когато DX2 е нула."""

        върхове = _върхове(_ЗАПИСАН_90)

        assert len(върхове) == 4
        assert върхове[0][1] == pytest.approx(върхове[1][1])
        assert върхове[2][0] > върхове[1][0], "редукцията не се изкачва надясно"
        assert върхове[2][1] != върхове[1][1]
        assert върхове[2][1] == pytest.approx(върхове[3][1])

    def test_ъгълът_на_качване_е_един_и_същ(self) -> None:
        """Каноничен силует: различават се пропорциите, не наклонът."""

        def наклон(values) -> float:
            v = _върхове(values)
            return abs(v[2][1] - v[1][1]) / abs(v[2][0] - v[1][0])

        # Допускът поема закръглянето при вписването на фигурата в клетката;
        # 1e-4 е под една стотна от процента, тоест същият наклон за окото.
        assert наклон(_ЗАПИСАН_90) == pytest.approx(наклон(_ВЕРНИ), abs=1e-4)
        assert наклон(_ЗАПИСАН_90) == pytest.approx(наклон(_ПЕТ_СМ), abs=1e-4)

    def test_дължините_остават_в_мащаб(self) -> None:
        """Каноничен е ъгълът, не цялата картинка."""

        къс = _върхове({"L1": 120.0, "DX2": 30.0, "DY2": 3.0, "L3": 150.0})
        дълъг = _върхове(_ЗАПИСАН_90)

        assert къс != дълъг

    def test_дългото_рамо_е_по_дълго_от_късото(self) -> None:
        върхове = _върхове(_ЗАПИСАН_90)

        assert (върхове[1][0] - върхове[0][0]) > (върхове[3][0] - върхове[2][0])


class TestЧетимост:
    """Собственик, 2026-09-15, с описа на ``s-10`` отворен пред него:

    „виж как изглежда пръта с редукция, това тази 4-ка не се виижда трябва
    да го оправим да се вижда цялата като хората и отдолу размерите да са в
    една линия."

    И двата дефекта идваха от едно и също: размерите стъпваха на СВОЯ
    сегмент. Редукцията качва пръта, затова „110" излизаше по-високо от
    „260" и „40"; а размерът на отместването се чертаеше на девет единици
    вдясно от върха на редукцията — тоест насред късото рамо — и линията,
    стрелките и надписът се застъпваха с геометрията.
    """

    @pytest.mark.parametrize("values", (_ЗАПИСАН_90, _ВЕРНИ, _ПЕТ_СМ))
    def test_трите_дължини_са_на_една_линия(self, values) -> None:
        линии = _хоризонтални_размерни_линии(values)
        assert len(линии) == 3
        нива = {round(y, 6) for _, _, y in линии}
        # При дробни размери средният надпис пада на второ ниво, защото не
        # се побира между изнасящите линии дори при най-малкия четим шрифт.
        # Външните две обаче ВИНАГИ са на една линия.
        външни = sorted(линии, key=lambda ред: abs(ред[1] - ред[0]))[-2:]
        assert round(външни[0][2], 6) == round(външни[1][2], 6)
        if values is _ЗАПИСАН_90:
            assert len(нива) == 1, f"три нива вместо едно: {sorted(нива)}"

    @pytest.mark.parametrize("values", (_ЗАПИСАН_90, _ВЕРНИ, _ПЕТ_СМ))
    def test_отместването_не_лежи_върху_пръта(self, values) -> None:
        върхове = _върхове(values)
        десен_край = max(x for x, _ in върхове)
        x, y1, y2 = _вертикална_размерна_линия(values)
        assert x > десен_край, (
            "размерът за отместването пада върху късото рамо: "
            f"x={x:.2f}, а прътът свършва на {десен_край:.2f}"
        )
        # Два пъти височината на шрифта (4.6 px) е минимумът, при който
        # стрелките и надписът не се сливат в петно.
        assert abs(y2 - y1) >= 2 * 4.6 * 0.3, (
            f"размерната линия е само {abs(y2 - y1):.2f} единици — "
            "надписът се смачква и отместването не се вижда"
        )

    @pytest.mark.parametrize("values", (_ЗАПИСАН_90, _ВЕРНИ, _ПЕТ_СМ))
    def test_отместването_е_изписано(self, values) -> None:
        размери = _размери(values)
        assert len(размери) == 4, f"очакват се четири надписа, има {размери}"
