# -*- coding: utf-8 -*-
"""Едно описание на формата управлява проверката, изображението и експорта.

## Веригата, която този файл пази

    chain_printed_dimensions   → участъци и огъвки от чертежа
        ↓
    proven_form.реши           → ПРИСЪДА: откъде идва всеки ъгъл
        ↓
    canonical_turn_angles_deg  → ЕДНО поле на реда
        ↓                ↓
    shape_image          excel_export
    (какво се рисува)    (какво се изнася)

Изображението и експортът четат ЕДНО И СЪЩО поле, а то се пълни само когато
присъдата е доказана. Затова не може картинката да казва едно, а числата друго.

## Измерено върху изнесения файл

`d-1`, позиция „325N6x40": `image1.png` в `d-1_СПЕЦИФИКАЦИЯ.xlsx` съвпада
**байт в байт** (SHA-256 `158f1a1a945ed1b88127…`, 15992 байта) с рисунката по
НАЧЕРТАНИТЕ завои −135°/+135°. Шаблонът на F007 е −90°/−135° и дава друга
рисунка (20002 байта). Тоест Excel носи Z-то, не C-то.

Тестовете тук пазят правилото, не конкретния файл: рисувачът тръгва по
доказаните завои точно когато те се разминават с шаблона, и по шаблона — когато
не се разминават или когато нищо не е доказано.
"""
from __future__ import annotations

import pytest

from lion_rebar.dxf.chain_printed_dimensions import ДЪГА, ОСТЪР
from lion_rebar.export import proven_form as форма
from lion_rebar.export.shape_image import (
    _turns_contradict_shape, shape_turn_angles_deg,
)


class Сегмент:
    def __init__(self, индекс, завой=None, посока="L"):
        self.index = индекс
        self.bend_after_deg = завой
        self.bend_direction = посока


class Шаблон:
    """Колкото от ``ShapeDefinition`` ползва рисувачът."""

    def __init__(self, код, завои):
        self.code = код
        self.segments = [Сегмент(и, abs(з), "L" if з >= 0 else "R")
                         for и, з in enumerate(завои)]
        self.segments.append(Сегмент(len(завои)))


F007 = Шаблон("F007", [-90.0, -135.0])          # C-образна, както е в ENGINE
F004 = Шаблон("F004", [90.0])                   # прът с един винкел


def дъга(завой, радиус=1.5):
    return {"kind": ДЪГА, "turn_deg": завой, "radius_cm": радиус}


def остър(завой):
    return {"kind": ОСТЪР, "turn_deg": завой, "radius_cm": None}


# --------------------------------------------------------------------------
# Шаблонът се чете от ДЕФИНИЦИЯТА, не от таблица в кода
# --------------------------------------------------------------------------

def test_shablonat_idva_ot_definiciyata():
    assert shape_turn_angles_deg(F007) == (-90.0, -135.0)
    assert shape_turn_angles_deg(F004) == (90.0,)


# --------------------------------------------------------------------------
# Едната присъда решава и за рисунката
# --------------------------------------------------------------------------

def test_dokazanata_Z_forma_kara_risuvacha_da_ne_polzva_shablona():
    """d-1 „Есове": доказани −135/135 срещу шаблон −90/−135 → рисува се Z."""

    присъда = форма.реши(
        участъци_cm=(10.0, 20.0, 10.0),
        начертани_cm=(10.3829, 24.3, 9.924),
        огъвки=(дъга(-135.0), дъга(135.0)),
        шаблонни_ъгли_deg=(-90.0, -135.0),
        диаметър_mm=6.0,
    )
    assert присъда.доказана is True
    assert присъда.ъгли_deg == (-135.0, 135.0)
    # СЪЩИТЕ ъгли отиват в полето, което чете рисувачът.
    assert _turns_contradict_shape(F007, list(присъда.ъгли_deg)) is True


def test_sagvashtashtata_forma_ostava_na_shablona():
    """Доказани ъгли, които СЪВПАДАТ с шаблона → нищо не се променя."""

    присъда = форма.реши(
        участъци_cm=(100.0, 30.0),
        начертани_cm=(100.0, 30.0),
        огъвки=(остър(90.0),),
        шаблонни_ъгли_deg=(90.0,),
        диаметър_mm=10.0,
    )
    assert присъда.доказана is True
    assert присъда.ъгли_deg == (90.0,)
    assert _turns_contradict_shape(F004, list(присъда.ъгли_deg)) is False


def test_nedokazanata_forma_ne_dava_agli_i_risuva_shablona():
    """Куката: рамо извън мащаб → няма ъгли → рисувачът ползва шаблона.

    Това е и границата на твърдението: при недоказана форма картинката показва
    шаблона, а редът НЕ носи ъгли. Разминаването е записано в бележките, не
    скрито — вж. `tools/roadmap_f110_konflikti.py`.
    """

    присъда = форма.реши(
        участъци_cm=(1035.0, 35.0),
        начертани_cm=(1035.0, 26.0),
        огъвки=(остър(90.0),),
        шаблонни_ъгли_deg=(90.0,),
        диаметър_mm=10.0,
    )
    assert присъда.доказана is False
    assert присъда.ъгли_deg == ()
    assert _turns_contradict_shape(F004, list(присъда.ъгли_deg)) is False


