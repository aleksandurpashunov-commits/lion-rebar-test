@pytest.mark.parametrize("ъгли,противоречи", [
    ((-135.0, 135.0), True),        # Z срещу C
    ((-90.0, -135.0), False),       # точно шаблонът
    ((90.0, 135.0), False),         # същите по модул
    ((-92.0, -137.0), False),       # в рамките на 5°
    ((-99.0, -135.0), True),        # 9° разлика
    ((), False),                    # нищо доказано
    ((-135.0,), False),             # друг БРОЙ завои — няма какво да се сравни
])
def test_granicata_e_pet_gradusa_po_modul(ъгли, противоречи):
    """Сравнява се по МОДУЛ: огледалната форма не е друга форма."""

    assert _turns_contradict_shape(F007, list(ъгли)) is противоречи


def test_as_dict_nosi_i_dvete_strani_na_sravnenieto():
    """Записът на реда носи и доказаното, и шаблона, и разликата."""

    д = форма.реши(
        участъци_cm=(10.0, 20.0, 10.0),
        начертани_cm=(10.3829, 24.3, 9.924),
        огъвки=(дъга(-135.0), дъга(135.0)),
        шаблонни_ъгли_deg=(-90.0, -135.0),
        диаметър_mm=6.0,
    ).as_dict()
    assert д["turn_angles_deg"] == [-135.0, 135.0]
    assert д["template_turn_angles_deg"] == [-90.0, -135.0]
    assert д["template_disagreement_deg"] == pytest.approx(45.0)
    assert any("SHABLONAT_NE_SAVPADA" in str(б) for б in д["notes"])
