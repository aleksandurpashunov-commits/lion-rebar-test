def test_две_заглавия_на_един_слой_дават_два_листа_с_имена() -> None:
    записи = [
        _text("T1", "Долна армировка на кота +6,68", (1000.0, 0.0), layer="ANTETKA"),
        _text("T2", "Горна армировка на кота +6,68", (8000.0, 0.0), layer="ANTETKA"),
        *_позиции("A", (500.0, 500.0)),
        *_позиции("B", (7500.0, 500.0)),
    ]

    рамки = detect_drawing_frames(записи)

    assert len(рамки) == 2
    assert [рамка.resolution_reason for рамка in рамки] == ["TITLE_ONLY_BAND"] * 2
    assert {рамка.category_code for рамка in рамки} == {"BOTTOM", "TOP"}
    assert {рамка.suggested_sheet_name for рамка in рамки} == {"долна", "горна"}
    # лентите делят чертежа и всяка съдържа своите надписи
    долна = next(рамка for рамка in рамки if рамка.category_code == "BOTTOM")
    горна = next(рамка for рамка in рамки if рамка.category_code == "TOP")
    assert долна.x_max <= горна.x_min + 1e-6


