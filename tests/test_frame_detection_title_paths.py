"""Щемпел в един обект и листове, познати само по заглавията си.

Два измерени случая от 2026-09-20, върху чертежи от два непознати офиса:

* „KOFR_B“ пише целия щемпел в ЕДИН MTEXT — „ЧЕРТЕЖ: ФУНДАМЕНТНА ПЛОЧА НА
  КОТА-6,34“ — и затова рамките бяха нула, а портата отказваше всичките 2974
  позиции;
* „тест-01“ няма щемпел, но носи „Долна армировка на кота +6,68“ и „Горна
  армировка на кота +6,68“ на слой ANTETKA. Резервният път за ЕДИН лист вижда
  две заглавия и правилно отказва, затова 137 позиции стояха, макар 120 да са
  силни по геометрия. Собственик: „да си направи рамка и да и даде име като
  разпознае името както в тест-01“.

Случаите са построени синтетично — проверява се образецът, не конкретен файл.
"""
from __future__ import annotations

from lion_rebar.dxf.models import DxfEntityRecord
from lion_rebar.export.frame_detection import detect_drawing_frames


def _text(
    handle: str,
    текст: str,
    at: tuple[float, float],
    *,
    layer: str = "щемпел",
    height: float = 13.0,
) -> DxfEntityRecord:
    return DxfEntityRecord(
        handle=handle,
        entity_type="TEXT",
        layer=layer,
        geometry={"insert": [at[0], at[1], 0.0], "height": height},
        text=текст,
    )


def _позиции(
    префикс: str,
    at: tuple[float, float],
    брой: int = 6,
    *,
    layer: str = "надписи",
) -> list[DxfEntityRecord]:
    """Армировъчни надписи, за да има какво да съдържа лентата."""

    return [
        _text(
            f"{префикс}{индекс}",
            f"{10 + индекс}N12x{300 + индекс}",
            (at[0] + индекс * 20.0, at[1]),
            layer=layer,
            height=10.0,
        )
        for индекс in range(брой)
    ]


def test_щемпел_в_един_обект_дава_рамка_със_заглавието_си() -> None:
    записи = [
        _text("M1", "ЧЕРТЕЖ: ДОЛНА АРМИРОВКА НА КОТА +5.90", (0.0, 0.0)),
        *_позиции("A", (100.0, 200.0)),
    ]

    рамки = detect_drawing_frames(записи)

    assert len(рамки) == 1
    рамка = рамки[0]
    assert рамка.category_code == "BOTTOM"
    assert рамка.resolution_reason == "INLINE_TITLE"
    assert рамка.title_text == "ДОЛНА АРМИРОВКА НА КОТА +5.90"
    assert "ЧЕРТЕЖ" not in рамка.title_text


