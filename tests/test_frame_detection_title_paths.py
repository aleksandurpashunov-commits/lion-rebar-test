def test_обявената_рамка_бие_изведената_по_заглавие() -> None:
    """Решението на оператора е по-силно от извод по заглавие."""

    записи = [
        _text("T1", "Долна армировка на кота +6,68", (1000.0, 0.0), layer="ANTETKA"),
        _text("T2", "Горна армировка на кота +6,68", (8000.0, 0.0), layer="ANTETKA"),
        *_позиции("A", (500.0, 500.0)),
        *_позиции("B", (7500.0, 500.0)),
        DxfEntityRecord(
            handle="R1",
            entity_type="LWPOLYLINE",
            layer="Горна армировка",
            geometry={
                "points": [
                    [7000.0, 400.0, 0.0],
                    [8500.0, 400.0, 0.0],
                    [8500.0, 600.0, 0.0],
                    [7000.0, 600.0, 0.0],
                ]
            },
        ),
    ]

    рамки = detect_drawing_frames(записи)

    assert len(рамки) == 1
    assert рамки[0].resolution_reason == "DECLARED_AREA_LAYER"
    assert рамки[0].category_code == "TOP"
