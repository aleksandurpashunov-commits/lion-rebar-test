def test_щемпели_един_над_друг_не_се_режат_по_x() -> None:
    """Измерен случай: „S-SR+27,82 горна и долна“ (21.09.2026).

    Трите щемпела стоят на 464 единици един от друг по x и на 7472 по y.
    Рязането по x даде безсмислени ленти — една от 168 единици — и ВСИЧКИТЕ 337
    надписа паднаха в първата, която е неопределената рамка. Тоест вярно
    разпознатите ГОРНА и ДОЛНА останаха без нито една позиция.

    Тогава е по-честно да няма ленти: остава подреждането по най-близка котва,
    по което вече минават чертежите в решетка.
    """

    записи = [
        _text("M1", "ЧЕРТЕЖ:", (50100.0, 65692.0)),
        _text("T1", "ГОРНА АРМИРОВКА ПЛОЧА НА КОТА +27.82", (50300.0, 65692.0)),
        _text("M2", "ЧЕРТЕЖ:", (50270.0, 61714.0)),
        _text("T2", "ДОЛНА АРМИРОВКА ПЛОЧА И ГРЕДИ НА КОТА +27.82", (50470.0, 61714.0)),
        *_позиции("A", (50000.0, 65000.0)),
        *_позиции("B", (50200.0, 61000.0)),
    ]

    рамки = detect_drawing_frames(записи)

    assert len(рамки) == 2
    assert {рамка.category_code for рамка in рамки} == {"TOP", "BOTTOM"}
    # лентите по x биха били безсмислени -> не се изчисляват
    assert all(рамка.x_min is None and рамка.x_max is None for рамка in рамки)


