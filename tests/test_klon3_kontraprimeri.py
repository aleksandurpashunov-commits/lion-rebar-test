def test_stesnenie_g_odobrenoto_pravilo_e_pred_nachertaniya_ostar_agal():
    """(г) поотделно: правило в обхват изпреварва начертания остър ъгъл.

    Входът е нарочно такъв, че (б) и (д) да НЕ се намесват: завоите 45° и 135°
    са производствени ъгли, а начертаните рамена съвпадат с отпечатаните в
    рамките на относителния допуск. Тоест единственото, което държи присъдата,
    е новият ред на клоновете.

    Измерено срещу стария код: същият вход даваше ``ИЗВЛЕЧЕНА`` (45,0°; 135,0°)
    и изхвърляше `BEAM_ENGINEERING_90_F003` без бележка. Пази изискването, че
    одобрено инженерно правило в своя обхват не се отменя от чертожен символ.
    """

    резултат = форма.реши(
        участъци_cm=(15.0, 405.0, 15.0),
        начертани_cm=(15.0, 404.7813, 15.0),
        огъвки=(остър(45.0), остър(135.0)),
        диаметър_mm=8.0,
        правило="BEAM_ENGINEERING_90_F003",
        ъгли_по_правило_deg=(90.0, 90.0),
    )

    assert резултат.в_мащаб == (True, True, True)
    assert all(форма.завоят_е_производствен(з) for з in (45.0, 135.0))
    assert резултат.състояние == форма.ПО_ПРАВИЛО
    assert резултат.ъгли_deg == (90.0, 90.0)
    assert all(п.правило == "BEAM_ENGINEERING_90_F003" for п in резултат.огъвки)
    assert any("PRAVILO_V_OBHVAT" in б for б in резултат.бележки)


