# -*- coding: utf-8 -*-
"""Контрапримери срещу клон 3 на ``proven_form.класифицирай_огъвка`` — и
какво остана от тях СЛЕД стеснението.

## Клонът, преди и сега

Преди стеснението клон 3 гласеше:

    if вид != ДЪГА and съседните_рамена_са_в_мащаб:
        return ОгъвкаПрисъда(индекс, ИЗВЛЕЧЕНА, начертан, начертан, ...)

и стоеше ПРЕД клона за одобрено правило. Сега са приложени три стеснения:

* **(г)** одобреното правило се произнася ПРЕД начертания остър ъгъл;
  начертаната ДЪГА остава над правилото — тя е доказаната проектна форма;
* **(б)** ъглов прозорец: ``завоят_е_производствен`` иска начертаният завой да
  е до ``ПРОЗОРЕЦ_DEG`` = 1,0° от производствен ъгъл. ``за_реда`` подава
  ЖИВИЯ набор от заключените форми на engine-а; константата
  ``ПРОИЗВОДСТВЕНИ_ЪГЛИ`` = (29,0; 45,0; 90,0; 135,0) е резервата;
* **(д)** ``рамото_удостоверява_посока``: и двете съседни рамена трябва да са
  начертани в рамките на ЕДИН и същ ОТНОСИТЕЛЕН допуск (``ДОПУСК_МАЩАБ`` = 8 %)
  при всяка дължина. ``в_мащаб`` остава непроменен — той отговаря на другия
  въпрос, „в мащаб ли е чертежът тук", и затова под ``КЪСО_РАМО_CM`` минава на
  абсолютен под ±1 cm. Посоката не се удостоверява по-леко там, където
  геометрията е по-малка.

  Първият вид на (д) беше праг по дължина (12 cm) и беше СГРЕШЕН: отне 5 реални
  позиции с отклонение 0,0000 cm. Хлабината е в мярката, не в дължината.

## Защо тестовете тук изглеждат така

Входовете на контрапримерите **не са пипани** — те са доказателството.
Сменени са само очакванията, и при всяко сменено очакване докстрингът казва
какво се твърдеше, кое число го обори и кое изискване пази новото.

Два теста бяха ``xfail(strict=True)`` — твърдяха желаното поведение и падаха
срещу стария код. Сега минават и маркерът е махнат:
``test_kp2_shematichnata_kuka_v_mashtab_ne_e_izmervane`` и
``test_kp5_neravnomerno_mashtabirane_ne_dava_izmervane``.

## Какво остава ограничение

* **КП-1** — мащабът пак няма разделителна сила по ъгъла. Прозорецът сви
  набора от 7 доказани форми на 3 от един и същ вход; не му даде сила да
  различава верен от невярен ъгъл;
* **КП-2б** — 45° Е производствен ъгъл. Схематична кука под 45° без одобрено
  правило все още излиза ИЗВЛЕЧЕНА. Затваря я само (г);
* **измерената граница на клон 3** — при единния относителен допуск от 8 %
  неравномерно мащабиране може да мести истински 90° с до 10,28° (прозорецът я
  хваща), а истински 45° — с до 26,18°. За 45° това е повече от дупка: при
  k = 0,62 завоят се начертава 28,9946°, тоест СЯДА върху производствения ъгъл
  29° и прозорецът няма как да го види. Записано в
  ``test_izmerenata_granica_45_moje_da_sedne_varhu_29``.
"""
from __future__ import annotations

import math

import pytest

from lion_rebar.dxf.chain_printed_dimensions import ДЪГА, ОСТЪР
from lion_rebar.export import proven_form as форма


def остър(завой: float) -> dict:
    return {"kind": ОСТЪР, "turn_deg": завой, "radius_cm": None}


def дъга(завой: float, радиус: float = 1.5) -> dict:
    return {"kind": ДЪГА, "turn_deg": завой, "radius_cm": радиус}


def верига_след_мащабиране(
    дължини: tuple[float, ...],
    посоки_deg: tuple[float, ...],
    *,
    sx: float = 1.0,
    sy: float = 1.0,
) -> tuple[tuple[float, ...], tuple[float, ...]]:
    """Начертаните дължини и завои след мащабиране (sx, sy) на чертежа.

    Неравномерното мащабиране е реален чертожен ход — разтягане на копиран
    детайл. То мени ъглите, но може да остави дължините привидно в мащаб.
    """

    вектори = [(д * math.cos(math.radians(п)), д * math.sin(math.radians(п)))
               for д, п in zip(дължини, посоки_deg)]
    мащабирани = [(в[0] * sx, в[1] * sy) for в in вектори]
    нови_дължини = tuple(math.hypot(*в) for в in мащабирани)
    нови_посоки = [math.degrees(math.atan2(в[1], в[0])) for в in мащабирани]
    завои = tuple((b - a + 180.0) % 360.0 - 180.0
                  for a, b in zip(нови_посоки, нови_посоки[1:]))
    return нови_дължини, завои


#: Реалният `s-9/14723`: отпечатани [25; 405; 25], начертани [25,0; 404,78;
#: 25,0]. Това е позицията, с която докстрингът на модула обосновава клона.
S9_14723 = dict(участъци_cm=(25.0, 405.0, 25.0),
                начертани_cm=(25.0, 404.7813, 25.0))

#: Реалният `s-9/14736`: двете куки са начертани като остри ъгли при 27,2357° и
