def test_stesnenie_b_uglov_prozorec_otsyava_neproizvodstveniya_zavoy():
    """(б) поотделно: завой извън прозореца не е посока.

    Двата входа се различават САМО по завоя; дължините са едни и същи, в мащаб,
    и двете рамена са над 12 cm, така че (д) не се намесва, а правило няма, така
    че (г) не се намесва.

    * 90,00° — на 0° от производствен ъгъл → ``ИЗВЛЕЧЕНА``;
    * 94,7719° — на 4,77° → ``НЕРАЗРЕШЕН``.

    Пази изискването, че се произвежда само ъгъл, който заключената библиотека
    познава; „най-близкото" не е приемане.
    """

    производствен = форма.реши(участъци_cm=(100.0, 100.0),
                               начертани_cm=(100.0, 100.0),
                               огъвки=(остър(90.0),))
    извън = форма.реши(участъци_cm=(100.0, 100.0),
                       начертани_cm=(100.0, 100.0),
                       огъвки=(остър(94.7719),))

    assert производствен.в_мащаб == извън.в_мащаб == (True, True)
    assert производствен.състояние == форма.ИЗВЛЕЧЕНА
    assert производствен.ъгли_deg == (90.0,)

    assert форма.завоят_е_производствен(94.7719) is False
    assert извън.състояние == форма.НЕРАЗРЕШЕН
    assert извън.ъгли_deg == ()
    assert any("FORMA_ZA_PREGLED" in б for б in извън.бележки)


def test_stesnenie_b_naborat_idva_ot_zaklyuchenite_formi_ne_ot_konstanta():
    """(б): прозорецът следва библиотеката, а не обратното.

    ``за_реда`` смята живия набор от завоите на заключените форми на активния
    engine и го подава на ``реши``. Измерено на engine 0.3.15: наборът е точно
    (29,0; 45,0; 90,0; 135,0) — съвпада с резервната константа.

    Тестът проверява механиката, без да зависи от инсталиран engine: подаден
    по-тесен набор наистина стеснява преценката.
    """

    assert форма.ПРОЗОРЕЦ_DEG == 1.0
    # резервният набор приема и трите
    assert форма.завоят_е_производствен(90.0) is True
    assert форма.завоят_е_производствен(45.0) is True
    assert форма.завоят_е_производствен(29.0) is True
    # подаден набор само с 90° отхвърля останалите
    assert форма.завоят_е_производствен(90.0, (90.0,)) is True
    assert форма.завоят_е_производствен(45.0, (90.0,)) is False
    assert форма.завоят_е_производствен(29.0, (90.0,)) is False
    # знакът не участва — 135° и −135° са един ъгъл
    assert форма.завоят_е_производствен(-135.0, (135.0,)) is True

    стеснено = форма.реши(участъци_cm=(100.0, 100.0),
                          начертани_cm=(100.0, 100.0),
                          огъвки=(остър(45.0),),
                          производствени_ъгли=(90.0,))
    assert стеснено.състояние == форма.НЕРАЗРЕШЕН


def test_stesnenie_d_kasoto_ramo_se_meri_sas_sashtiya_otnositelen_dopusk():
    """(д) поотделно, в поправения си вид — и какво обори първия.

    Старото твърдение: рамена 5 и 8 cm НЕ удостоверяват посока, дори начертани
    точно, защото под ``КЪСО_РАМО_CM`` допускът е абсолютен ±1 cm (до 20 %).

    Кое го обори: измерено на корпуса, прагът по дължина отне 5 реални позиции
    `F009` в `тест-006` — рамо 10 cm, начертано с отклонение **0,0000 cm**,
    завои точно ±90,00°, в_мащаб (True,)×5. Основанието „допускът пропуска 34°
    при завъртян чертеж" е твърдение за онова, което тестът ДОПУСКА, не за
    начертаното: там хлабина не е изразходвана изобщо. В целия корпус късите
    рамена са пет и всичките минават и относителния допуск.

    Новото: хлабината е в мярката, не в дължината. (д) иска ЕДИН и същ
    ОТНОСИТЕЛЕН допуск при всяка дължина. Пази изискването „не избирай ново
    число": допускът не е нов, а вече решеният за дългото рамо.
    """

    точно = форма.реши(участъци_cm=(5.0, 8.0, 5.0),
                       начертани_cm=(5.0, 8.0, 5.0),
                       огъвки=(остър(-90.0), остър(-90.0)))

    assert точно.в_мащаб == (True, True, True)
    assert форма.завоят_е_производствен(-90.0) is True
    assert точно.състояние == форма.ИЗВЛЕЧЕНА       # начертано точно — минава
    assert точно.ъгли_deg == (-90.0, -90.0)

    # ... същите къси рамена, но начертани В ХЛАБИНАТА на абсолютния под
    хлабаво = форма.реши(участъци_cm=(5.0, 8.0, 5.0),
                         начертани_cm=(4.05, 8.0, 4.05),
                         огъвки=(остър(-90.0), остър(-90.0)))

    assert хлабаво.в_мащаб == (True, True, True)     # ±1 cm абсолютно ги пуска
    assert форма.рамото_удостоверява_посока(4.05, 5.0) is False   # 19 % > 8 %
    assert хлабаво.състояние == форма.НЕРАЗРЕШЕН     # относителният ги спира
    assert хлабаво.ъгли_deg == ()


def test_stesnenie_d_granicata_e_edna_i_sashta_pri_vsyaka_dalzhina():
    """(д): границата е ОТНОСИТЕЛНА и не зависи от дължината на рамото.

    Старото твърдение: прагът е 12 cm по отпечатания размер — 11,99 пада,
    12,00 минава. Кое го обори: границата по дължина няма измерено основание
    и отсече пет безупречно начертани позиции (виж теста над този). Тук се
    проверява, че 11,99 cm вече минава, когато е начертано точно.

    Пази изискването границата да е ЕДНА: същият процент при 5 cm и при 500 cm.
    """

    assert форма.ДОПУСК_МАЩАБ == 0.08

    for отпечатано in (5.0, 10.0, 11.99, 12.0, 100.0, 500.0):
        вътре = отпечатано * (1.0 + 0.9 * форма.ДОПУСК_МАЩАБ)
        извън = отпечатано * (1.0 + 1.1 * форма.ДОПУСК_МАЩАБ)
        assert форма.рамото_удостоверява_посока(вътре, отпечатано) is True
        assert форма.рамото_удостоверява_посока(извън, отпечатано) is False
        # и в двете посоки — начертано по-късо се мери със същия процент
        assert форма.рамото_удостоверява_посока(
            отпечатано * (1.0 - 0.9 * форма.ДОПУСК_МАЩАБ), отпечатано) is True
        assert форма.рамото_удостоверява_посока(
            отпечатано * (1.0 - 1.1 * форма.ДОПУСК_МАЩАБ), отпечатано) is False

    # старият праг вече не отсича: 11,99 cm, начертано точно, минава
    под_стария_праг = форма.реши(участъци_cm=(11.99, 405.0, 11.99),
                                 начертани_cm=(11.99, 405.0, 11.99),
                                 огъвки=(остър(-90.0), остър(-90.0)))

    assert под_стария_праг.състояние == форма.ИЗВЛЕЧЕНА
    assert под_стария_праг.ъгли_deg == (-90.0, -90.0)


