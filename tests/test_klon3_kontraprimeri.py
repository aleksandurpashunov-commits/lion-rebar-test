#: при отпечатани 15 (+54,5 %).
КУКА_ЗАВОИ = (остър(27.2357), остър(152.7643))
КУКА_ОБЩО = dict(
    участъци_cm=(15.0, 405.0, 15.0),
    огъвки=КУКА_ЗАВОИ,
    диаметър_mm=8.0,
    правило="BEAM_ENGINEERING_90_F003",
    ъгли_по_правило_deg=(90.0, 90.0),
)


