def test_bez_odobreno_pravilo_nishto_ne_se_vzima():
    """24-те F004 куки без правило остават неразрешени. Това е случай Б."""

    р = форма.за_реда(ред(contextual_rule_code=None, master_shape_code="F004",
                          chain_printed_dimensions={
                              "status": "CONFIRMED",
                              "segments_cm": [1035.0, 35.0],
                              "drawn_lengths_cm": [1035.0, 26.0],
                              "bends": [{"kind": ОСТЪР, "turn_deg": 90.0,
                                         "radius_cm": None}]}),
                      форми=ФОРМИ)
    assert р is not None
    assert р.състояние == форма.НЕРАЗРЕШЕН
    assert р.ъгли_deg == ()


def test_dvusmislena_forma_ne_vzima_nishto():
    """MASTER двусмислие е истинска несигурност — правилото не я разчиства."""

    р = форма.за_реда(ред(master_ambiguous_shape_codes=["F003", "F005"]),
                      форми=ФОРМИ)
    assert р.състояние == форма.НЕРАЗРЕШЕН


def test_konflikt_na_formata_ne_vzima_nishto():
    р = форма.за_реда(ред(master_conflict=True), форми=ФОРМИ)
    assert р.състояние == форма.НЕРАЗРЕШЕН


def test_izteglena_forma_ne_dava_agli():
    """RETIRED форма не е основание за нищо, дори с правило на реда."""

    assert форма.ъгли_на_заключената_форма("F009", ФОРМИ) == []
    р = форма.за_реда(ред(master_shape_code="F009",
                          contextual_rule_code="НЯКАКВО_ПРАВИЛО"), форми=ФОРМИ)
    assert р.състояние == форма.НЕРАЗРЕШЕН


def test_drug_broy_zavoi_ne_se_razteglya():
    """Форма с един завой не покрива верига с два. Отказ, не разтягане."""

    р = форма.за_реда(ред(master_shape_code="F004"), форми=ФОРМИ)
    assert р.състояние == форма.НЕРАЗРЕШЕН


def test_nepoznat_kod_ne_dava_agli():
    assert форма.ъгли_на_заключената_форма("F999", ФОРМИ) == []
    assert форма.ъгли_на_заключената_форма("", ФОРМИ) == []


def test_sobstvenite_kanonichni_agli_imat_predimstvo():
    """Когато редът си носи ъгли, те се ползват — формата не ги замества."""

    р = форма.за_реда(ред(canonical_turn_angles_deg=[80.0, 100.0]), форми=ФОРМИ)
    assert р.състояние == форма.ПО_ПРАВИЛО
    assert р.ъгли_deg == (80.0, 100.0)
    # Формата казва 90/90; редът казва 80/100. Взима се редът.
    assert форма.ъгли_на_заключената_форма("F003", ФОРМИ) == [90.0, 90.0]


