# -*- coding: utf-8 -*-
"""Одобрено правило взима ъглите си от ЗАКЛЮЧЕНАТА форма, не от празно поле.

## Дефектът

``proven_form.за_реда`` четеше ъглите, които правилото налага, от самия ред::

    шаблонни = row["canonical_turn_angles_deg"]
    по_правило = шаблонни if (правило and len(шаблонни) == len(огъвки)) else []

Измерено върху корпуса: **24 от 48** позиции с неудостоверен ъгъл НОСЯТ одобрено
правило (`U_PROPORTION_F003` × 21, `U_PROPORTION_F005` × 3) и еднозначна
ЗАКЛЮЧЕНА форма, но `canonical_turn_angles_deg` е празно. Тогава `по_правило`
излизаше празно, правилото нямаше какво да наложи и присъдата падаше на
``UNRESOLVED``.

Тоест параметърът е определен — правилото е одобрено, формата е заключена — а
записът остава празен. Това е непопълнен запис, не неизвестен ъгъл.

## Границата, която тестовете пазят

Това НЕ е разрешение MASTER да замени проектната геометрия. Прилага се само
когато **одобрено правило вече е решило коя е формата**. Без правило нищо не се
взима — 24-те позиции без правило (F004 куки с рамо извън мащаб) остават
неразрешени и тестовете го пазят изрично.
"""
from __future__ import annotations

import pytest

from lion_rebar.dxf.chain_printed_dimensions import ДЪГА, ОСТЪР
from lion_rebar.export import proven_form as форма


class Сегмент:
    def __init__(self, индекс, завой=None, посока="L"):
        self.index = индекс
        self.bend_after_deg = завой
        self.bend_direction = посока


class Форма:
    def __init__(self, код, завои, state="LOCKED"):
        self.code = код
        self.state = state
        self.segments = [Сегмент(и, abs(з), "L" if з >= 0 else "R")
                         for и, з in enumerate(завои)]
        self.segments.append(Сегмент(len(завои)))


F003 = Форма("F003", [90.0, 90.0])
F004 = Форма("F004", [90.0])
F009_RETIRED = Форма("F009", [-90.0, -90.0], state="RETIRED")
ФОРМИ = [F003, F004, F009_RETIRED]


def ред(**промени) -> dict:
    """Ред като `s-9` U-образна позиция: правило има, канонични ъгли няма."""

    основа = {
        "annotation_handle": "AAA::BJ-FI-L",
        "annotation_text": "10N10x300",
        "declared_length_cm": 300.0,
        "diameter_mm": 10.0,
        "master_shape_code": "F003",
        "contextual_rule_code": "U_PROPORTION_F003",
        "canonical_turn_angles_deg": [],          # ← празно
        "chain_printed_dimensions": {
            "status": "CONFIRMED",
            "segments_cm": [100.0, 100.0, 100.0],
            "drawn_lengths_cm": [74.0, 74.0, 74.0],   # всички извън мащаб
            "bends": [
                {"kind": ОСТЪР, "turn_deg": 90.0, "radius_cm": None},
                {"kind": ОСТЪР, "turn_deg": 90.0, "radius_cm": None},
            ],
        },
    }
    основа.update(промени)
    return основа


# --------------------------------------------------------------------------
# Същината
# --------------------------------------------------------------------------

def test_pravilo_bez_kanonichni_agli_vzima_ot_formata():
    """Одобрено правило + заключена форма + празно поле → ъглите са от формата."""

    р = форма.за_реда(ред(), форми=ФОРМИ)
    assert р is not None
    assert р.състояние == форма.ПО_ПРАВИЛО
    assert р.ъгли_deg == (90.0, 90.0)
    assert all(о.правило == "U_PROPORTION_F003" for о in р.огъвки)


def test_odobrenoto_pravilo_pokriva_I_ogavkata_v_mashtab():
    """Правилото се произнася ПРЕД начертания остър ъгъл — и за двете огъвки.

    ОЧАКВАНЕТО Е ПРОМЕНЕНО. Този тест твърдеше смесена присъда:
    `[ИЗВЛЕЧЕНА, ПО_ПРАВИЛО]` — първата огъвка между рамена в мащаб се вземаше
    от чертежа, втората от правилото.

    ЗАЩО Е ОСТАРЯЛО. Възпроизведено на `s-9/14736`: куки с ИСТИНСКИ 90°,
    начертани схематично под 27,24°/152,76°. При начертана кука 16,21 cm
    присъдата беше `APPROVED_RULE` 90°/90°; при **16,20 cm** — `DERIVED_DIRECTION`
    **27,24°/152,76°**. Една десета от милиметъра начертана дължина местеше
    производствения ъгъл с 62,76° и мълчаливо изхвърляше одобрено инженерно
    правило.

    КОЕ ИЗИСКВАНЕ ПАЗИ НОВОТО. „Одобрено правило важи в доказания си обхват" и
    „не произвеждай предполагаеми ъгли". Символ не бива да изпреварва правило.
    Начертаната ДЪГА остава над правилото — тя е доказаната проектна форма,
    а правилото е обобщение (`test_nachertanata_daga_bie_praviloto`).
    """

    р = форма.за_реда(ред(chain_printed_dimensions={
        "status": "CONFIRMED",
        "segments_cm": [100.0, 100.0, 100.0],
        "drawn_lengths_cm": [100.0, 100.0, 74.0],    # само третото извън мащаб
        "bends": [{"kind": ОСТЪР, "turn_deg": 90.0, "radius_cm": None},
                  {"kind": ОСТЪР, "turn_deg": 90.0, "radius_cm": None}]}),
        форми=ФОРМИ)
    assert [о.състояние for о in р.огъвки] == [форма.ПО_ПРАВИЛО, форма.ПО_ПРАВИЛО]
    assert all(о.правило == "U_PROPORTION_F003" for о in р.огъвки)
    assert р.ъгли_deg == (90.0, 90.0)


def test_bez_formi_nishto_ne_se_vzima():
    """Без подадени дефиниции поведението е старото — неразрешена."""

    р = форма.за_реда(ред(), форми=None)
    assert р is not None
    assert р.състояние == форма.НЕРАЗРЕШЕН
    assert р.ъгли_deg == ()


