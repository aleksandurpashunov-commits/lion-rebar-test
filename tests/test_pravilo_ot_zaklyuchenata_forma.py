def test_nachertanata_daga_bie_praviloto():
    """Доказаното от чертежа не се заменя, дори когато правило казва друго."""

    р = форма.за_реда(ред(
        master_shape_code="F003", contextual_rule_code="U_PROPORTION_F003",
        chain_printed_dimensions={
            "status": "CONFIRMED",
            "segments_cm": [10.0, 20.0, 10.0],
            "drawn_lengths_cm": [10.0, 20.0, 10.0],
            "bends": [{"kind": ДЪГА, "turn_deg": -135.0, "radius_cm": 1.5},
                      {"kind": ДЪГА, "turn_deg": 135.0, "radius_cm": 1.5}]}),
        форми=ФОРМИ)
    assert р.състояние == форма.ИЗВЛЕЧЕНА
    assert р.ъгли_deg == (-135.0, 135.0)
