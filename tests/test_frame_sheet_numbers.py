"""Номерът на листа в антетката като доказателство за рамка.

ЗАЩО. Измерено 2026-09-21 върху истинския чертеж `ARM.2.R02.dxf`
(„К-С-ПРОЕКТ ИНЖЕНЕРИНГ“ ООД, същият офис като `тест-01`): цялата сграда е на
един файл — седем нива по две скари, **14 листа**. Всеки лист носи в антетката

    „ЧЕРТ. :17/31“   и   „Долна армировка на кота +6,68“

на слой ``ANTETKA``, височина 13,0. Пътят „няколко листа само по заглавия“
отказваше, защото изисква толкова РАЗЛИЧНИ категории, колкото са заглавията, а
тук 14 заглавия дават само две категории (7 долни + 7 горни). Изискването е
вярно и остава: то пази `h03_3902` от два листа „детайли“ и 39 позиции на чужд
лист. Затова тук НЕ се разхлабва проверка, а се добавя **по-силно, независимо
доказателство** — номерът на листа.

ДОКАЗАТЕЛСТВОТО: числото „n/d“ с ЕДИН общ знаменател за целия чертеж (чертежът
сам обявява колко листа има), сдвоено по близост със заглавие, което се
класифицира еднозначно, и то с ЯСЕН ПРЕВЕС над второто по близост.

Измереното в `ARM.2.R02`: 15 номера, всичките с знаменател 31; 14 от тях се
сдвояват на ~280–306 единици, а второто най-близко заглавие е **19–26 пъти
по-далеч**. Петнадесетият номер („2/31“) няма свое заглавие — най-близкото е на
5 703 единици — и затова се отказва по разстояние, а не се досдвоява по догадка.

ОБХВАТ (измерен върху осемте други чужди чертежа): правилото не дава НИТО ЕДНА
лъжлива рамка. При `S-SR-WALL_7_8_9` намира 24 числа „n/852“ (размери на
колони), при `Тест-002` — 138 с „/300“ (отвори): нула от тях се сдвояват със
заглавие и всички се отказват.
"""
from __future__ import annotations

from lion_rebar.dxf.models import DxfEntityRecord
from lion_rebar.export.frame_detection import detect_drawing_frames, unresolved_frames

СЛОЙ = "ANTETKA"
ВИСОЧИНА = 13.0
# Измерените отстояния: номерът стои под заглавието си в същата антетка.
НОМЕР_DX = -280.0
НОМЕР_DY = -26.0
# Листовете са разстлани хоризонтално; измереното в чертежа е ~6 500 единици.
СТЪПКА_ЛИСТ = 6500.0


def _текст(handle: str, text: str, *, insert, layer: str = СЛОЙ,
           height: float = ВИСОЧИНА) -> DxfEntityRecord:
    return DxfEntityRecord(
        handle=handle,
        entity_type="TEXT",
        layer=layer,
        geometry={"insert": list(insert), "height": height},
        text=text,
    )


def _армировъчен(handle: str, *, insert) -> DxfEntityRecord:
    """Позиционен надпис — рамка върху празно място не е лист."""

    return _текст(handle, "24N12x455", insert=insert, layer="Text ARM.1", height=12.0)


def _лист(индекс: int, *, заглавие: str, номер: int, знаменател: int = 31,
          x: float | None = None) -> list[DxfEntityRecord]:
    ax = СТЪПКА_ЛИСТ * индекс if x is None else x
    ay = 0.0
    return [
        _текст(f"T{индекс}", заглавие, insert=(ax, ay, 0.0)),
        _текст(
            f"N{индекс}",
            f"ЧЕРТ. :{номер:02d}/{знаменател}",
            insert=(ax + НОМЕР_DX, ay + НОМЕР_DY, 0.0),
            height=10.0,
        ),
        _армировъчен(f"A{индекс}", insert=(ax + 100.0, ay + 2000.0, 0.0)),
    ]


ЗАГЛАВИЯ = (
    "Долна армировка на кота -0,10",
    "Горна армировка на кота -0,10",
    "Долна армировка на кота +2,58",
    "Горна армировка на кота +2,58",
)


def test_sheet_numbers_resolve_repeated_categories() -> None:
    """Четири листа, само две категории — номерът на листа ги разделя."""

    entities: list[DxfEntityRecord] = []
    for индекс, заглавие in enumerate(ЗАГЛАВИЯ):
        entities.extend(_лист(индекс, заглавие=заглавие, номер=9 + индекс))

    frames = detect_drawing_frames(entities)

    assert len(frames) == 4
    assert [frame.title_text for frame in frames] == list(ЗАГЛАВИЯ)
    assert [frame.category_code for frame in frames] == ["BOTTOM", "TOP", "BOTTOM", "TOP"]
    assert [frame.resolution_reason for frame in frames] == ["SHEET_NUMBER_BAND"] * 4
    # Различните листове получават различни имена, макар категорията да се
    # повтаря — иначе Excel би слял две коти в един лист.
    assert len({frame.suggested_sheet_name for frame in frames}) == 4
    assert not unresolved_frames(frames)


def test_sheet_number_without_a_title_becomes_unresolved() -> None:
    """Петнадесетият номер в истинския чертеж няма свое заглавие.

    Той не се досдвоява към чуждо заглавие — измереното разстояние е 5 703
    единици, тоест 20 пъти повече от честните ~280 — но и НЕ се изхвърля.
    Изхвърлянето би оставило неговата площ без котва и позициите му биха легнали
    на съседния лист: точно дефектът, който `h03_3902` вече показа (39 позиции
    на чужд лист). Затова става неопределена рамка и спира СВОИТЕ позиции, както
    прави портата от `7608b0f`.
    """

    entities: list[DxfEntityRecord] = []
    for индекс, заглавие in enumerate(ЗАГЛАВИЯ):
        entities.extend(_лист(индекс, заглавие=заглавие, номер=9 + индекс))
    # Самотен номер далеч от всяко заглавие.
    entities.append(
        _текст("NX", "ЧЕРТ. :02/31", insert=(-9000.0, 0.0, 0.0), height=10.0)
    )

    frames = detect_drawing_frames(entities)

    assert len(frames) == 5
    озаглавени = [frame for frame in frames if frame.title_text]
    неопределени = unresolved_frames(frames)
    assert len(озаглавени) == 4
    assert [frame.title_text for frame in озаглавени] == list(ЗАГЛАВИЯ)
    assert len(неопределени) == 1
    самотен = неопределени[0]
    assert самотен.marker_handle == "NX"
    assert самотен.category_code == "UNKNOWN"
    assert самотен.resolution_reason == "SHEET_NUMBER_NO_TITLE"
    # Той има своя лента, тоест площта му не е поета от съседен лист.
    assert самотен.contains_x


def test_mixed_denominators_are_not_sheet_numbers() -> None:
    """Размерите „n/d“ в чертежа нямат общ знаменател и не правят листове.

    Измерено: `S-SR-WALL_7_8_9` носи 24 числа „n/852“ (размери на колони),
    `Тест-002` — 138 с „/300“ (отвори). Без сдвояване със заглавие те не са
    доказателство за лист.
    """

    entities = [
        _текст("D1", "15/300", insert=(0.0, 0.0, 0.0), layer="Otvori", height=10.0),
        _текст("D2", "20/300", insert=(500.0, 0.0, 0.0), layer="Otvori", height=10.0),
        _текст("D3", "35/852", insert=(1000.0, 0.0, 0.0), layer="S-Col-Text", height=10.0),
    ]

    assert detect_drawing_frames(entities) == []


def test_sheet_numbers_do_not_override_a_stamp() -> None:
    """Щемпелът „ЧЕРТЕЖ:“ остава по-силен — редът на доказателствата не се мени."""

    entities = [
        _текст("M1", "ЧЕРТЕЖ", insert=(0.0, 0.0, 0.0), layer="STANDARD", height=7.5),
        _текст("T1", "ДОЛНА АРМИРОВКА", insert=(211.0, -10.0, 0.0),
               layer="STANDARD", height=15.0),
        _текст("N1", "ЧЕРТ. :17/31", insert=(-280.0, -26.0, 0.0), height=10.0),
    ]

    frames = detect_drawing_frames(entities)

    assert len(frames) == 1
    assert frames[0].resolution_reason == "PRIMARY_WINDOW"


def test_grid_layout_keeps_the_sheets_without_bands() -> None:
    """Листовете в решетка остават листове, макар лентите по x да отказват.

    Измерено в `ARM.2.R02`: петнадесетте листа са седем коти по y (разстлан
    72 686) по две скари по x (разстлан 15 061) — отношение 4,83 при праг 2,0,
    затова ``_frame_bands`` връща ``None``. Отказът на лентите е честен, но не
    бива да отменя доказателството за листове: остава подреждането по най-близка
    котва, както при `KOFR_B` (43 рамки) и `ARM HUS 2,3` (26).
    """

    entities: list[DxfEntityRecord] = []
    # Две скари на четири коти: решетка, не редица.
    for ниво in range(4):
        for скара, (дума, категория) in enumerate((("Долна", "BOTTOM"), ("Горна", "TOP"))):
            индекс = ниво * 2 + скара
            entities.extend(
                _лист(
                    индекс,
                    заглавие=f"{дума} армировка на кота +{ниво},58",
                    номер=9 + индекс,
                    x=скара * 7000.0,
                )
            )
            # Котвите се разнасят по y — това прави решетката.
            entities[-3] = _текст(
                f"T{индекс}",
                f"{дума} армировка на кота +{ниво},58",
                insert=(скара * 7000.0, -ниво * 24000.0, 0.0),
            )
            entities[-2] = _текст(
                f"N{индекс}",
                f"ЧЕРТ. :{9 + индекс:02d}/31",
                insert=(скара * 7000.0 + НОМЕР_DX, -ниво * 24000.0 + НОМЕР_DY, 0.0),
                height=10.0,
            )
            entities[-1] = _армировъчен(
                f"A{индекс}", insert=(скара * 7000.0 + 100.0, -ниво * 24000.0 + 2000.0, 0.0)
            )

    frames = detect_drawing_frames(entities)

    assert len(frames) == 8
    assert all(frame.resolution_reason == "SHEET_NUMBER_BAND" for frame in frames)
    # Лентите отказват -> няма граници по x, остава най-близката котва.
    assert all(not frame.contains_x for frame in frames)
    assert not unresolved_frames(frames)


def test_две_заглавия_на_еднакво_разстояние_не_чупят_анализа():
    """Равно разстояние е ОТКАЗ, не срив.

    Намерено при преглед 2026-09-22. Сдвояването подреждаше кортежи
    ``(разстояние, запис, текст, категория)`` без ключ; при ТОЧНО равни
    разстояния Python стига до втория член, а ``DxfEntityRecord`` не е
    подреждаем и целият ``detect_drawing_frames`` падаше с ``TypeError``.
    Това не е измислен случай: припокриващи се дублирани надписи и симетрична
    антетка дават точно равенство, а сривът идва СЛЕД цял час анализ.

    Вярното поведение е вече написаното отдолу в същата функция: равенството
    не минава превеса над второто и номерът остава неопределена рамка, която
    спира своите позиции и чака оператора.
    """

    entities = [
        _текст("N1", "ЧЕРТ. :01/02", insert=(0.0, 0.0, 0.0)),
        _текст("N2", "ЧЕРТ. :02/02", insert=(5000.0, 0.0, 0.0)),
        # симетрични спрямо N1 -> ТОЧНО еднакво разстояние
        _текст("T1", "Долна армировка на кота +6,68", insert=(-300.0, 0.0, 0.0)),
        _текст("T2", "Горна армировка на кота +6,68", insert=(300.0, 0.0, 0.0)),
        _текст("T3", "Долна армировка на кота +9,68", insert=(5300.0, 0.0, 0.0)),
        _армировъчен("A1", insert=(-280.0, 50.0, 0.0)),
        _армировъчен("A2", insert=(5280.0, 50.0, 0.0)),
    ]

    frames = detect_drawing_frames(entities)

    причини = {frame.marker_handle: frame.resolution_reason for frame in frames}
    assert причини["N1"] == "SHEET_NUMBER_NO_TITLE"
    assert [f.category_code for f in frames if f.marker_handle == "N1"] == ["UNKNOWN"]
    # другият номер е еднозначен и се решава
    assert причини["N2"] == "SHEET_NUMBER_BAND"
