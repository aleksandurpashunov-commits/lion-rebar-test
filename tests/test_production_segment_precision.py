"""Производственият размер влиза в описа без шум от обхождането.

ЗАЩО. Собственик, 23.09.2026, при одита на „Тест-003“: „тук трябва да ги
оправим да са точен размер, както е записано в енджина“.

Четиринайсет от 137 позиции носеха числа с по шест знака. Числата тук са
СЪЩИТЕ, прочетени от `final_integrity_ledger.csv` на неговия експорт от
23.09.2026, 09:43 — не са измислени за теста.
"""
from __future__ import annotations

import pytest

from lion_rebar.export.batch_auto_output import (
    PRODUCTION_SEGMENT_DECIMALS,
    production_segment_precision,
)


#: Каквото беше в описа -> каквото проектантът е начертал.
ОТ_ОПИСА = [
    ("109N14x395", [374.999942, 17.0], [375.0, 17.0]),
    ("3N16x620", [599.999859, 17.0], [600.0, 17.0]),
    ("28N12x455", [440.000022, 13.0], [440.0, 13.0]),
    ("34N8x115", [99.999942, 13.0], [100.0, 13.0]),
    ("44N8x165", [149.999942, 13.0], [150.0, 13.0]),
    ("38N10x760", [749.50007, 10.0], [749.5, 10.0]),
    ("9N10x770", [759.5, 10.0], [759.5, 10.0]),
    ("28N12x465", [12.750176, 70.0, 379.499915], [12.75, 70.0, 379.5]),
]


@pytest.mark.parametrize("надпис, преди, след", ОТ_ОПИСА)
def test_шумът_пада_а_размерът_остава(надпис, преди, след):
    assert list(production_segment_precision(преди)) == след


def test_наистина_неточното_НЕ_се_приглажда():
    """``22N12x390``: 374,93 не е шум — толкова е начертано.

    Разликата до 375 е 0,7 mm, тоест седемдесет пъти над прага. Приглаждането
    ѝ би било измисляне на размер.
    """

    assert list(production_segment_precision([374.931063, 12.0])) == [374.93, 12.0]


def test_точността_е_една_десета_от_милиметъра():
    """Два знака в сантиметри. Под всеки допуск за арматура."""

    assert PRODUCTION_SEGMENT_DECIMALS == 2
    assert production_segment_precision([1.005])[0] == pytest.approx(1.0, abs=0.011)
    assert production_segment_precision([1.0049])[0] == 1.0


def test_сборът_не_се_мени_осезаемо():
    """Закръглянето не бива да мести общата дължина.

    При осем участъка най-лошият случай е 8 x 0,005 = 0,04 cm — сто пъти под
    допуска 0,51, с който ``segments_match_total`` сверява сбора.
    """

    сурови = [374.999942, 17.0, 99.999942, 13.0, 440.000022, 12.750176, 379.499915, 70.0]
    закръглени = production_segment_precision(сурови)

    assert abs(sum(сурови) - sum(закръглени)) < 0.01


def test_негодните_стойности_отпадат():
    assert production_segment_precision([]) == ()
    assert production_segment_precision(None) == ()
    assert production_segment_precision([float("nan"), 5.0, float("inf")]) == (5.0,)
    assert production_segment_precision(["не е число", 3.0]) == (3.0,)


def test_вече_кръглите_не_се_пипат():
    цели = [50.0, 17.0, 60.0, 17.0, 50.0]
    assert list(production_segment_precision(цели)) == цели
